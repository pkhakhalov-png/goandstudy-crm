// Наблюдение за источником: robots.txt и различение исходов (E6.3–E6.5).
//
//   npx tsx scripts/content-observe-test.ts
//   npx tsx scripts/content-observe-test.ts --без-сети
//
// Проверяется главное правило этапа: недоступность источника — пробел
// наблюдения, а не «изменений нет». И что одиночный 404 не считается
// удалением.
import { config } from 'dotenv'; import path from 'path'
config({ path: path.resolve(process.cwd(), '.env.local') })
import { разобратьRobots, путьРазрешён, правилаДомена, __сброситьКэшRobots } from '../lib/content/robots'
import { наблюдать, выводИзИстории, подтверждает, ПРОБЕЛ, ПОДРЯД_ДЛЯ_ВЫВОДА, type Исход } from '../lib/content/observe'

let passed = 0, failed = 0
function ok(name: string, cond: boolean, note = '') {
  if (cond) { passed++; console.log(`✓ ${name}${note ? ' — ' + note : ''}`) }
  else { failed++; console.log(`✗ ${name}${note ? ' — ' + note : ''}`) }
}

const ПРИМЕР = `
User-agent: *
Disallow: /admin/
Disallow: /private
Allow: /private/public-page
Crawl-delay: 2

User-agent: goandstudy-seo-bot
Disallow: /only-for-us/
`

async function main() {
  /* ── robots.txt ───────────────────────────────────────────────────────── */

  const п = разобратьRobots(ПРИМЕР, 'goandstudy-seo-bot')
  ok('правила общей и своей группы складываются',
    п.запрещено.includes('/admin/') && п.запрещено.includes('/only-for-us/'),
    `запретов ${п.запрещено.length}`)
  ok('задержка прочитана', п.задержкаСек === 2)

  ok('запрещённый путь закрыт', !путьРазрешён('/admin/users', п))
  ok('разрешённый открыт', путьРазрешён('/blog/article', п))
  ok('более длинное разрешение сильнее запрета',
    путьРазрешён('/private/public-page', п),
    'так делают исключения внутри закрытого раздела')
  ok('остальное в закрытом разделе закрыто', !путьРазрешён('/private/secret', п))

  const звёздочка = разобратьRobots('User-agent: *\nDisallow: /*.pdf$', 'x')
  ok('шаблон со звёздочкой и концом строки работает',
    !путьРазрешён('/files/doc.pdf', звёздочка) && путьРазрешён('/files/doc.pdf.html', звёздочка))

  // Чужой агент: правило для конкретного бота нас не касается.
  const чужой = разобратьRobots('User-agent: GPTBot\nDisallow: /\n', 'goandstudy-seo-bot')
  ok('запрет для чужого агента нас не касается', путьРазрешён('/', чужой))

  /* ── История наблюдений ───────────────────────────────────────────────── */

  ok('свежий успех — источник жив', выводИзИстории(['изменилось']).что === 'источник_жив')
  ok('успех после неудач — источник жив', выводИзИстории(['не_изменилось', 'не_найдено', 'не_найдено']).что === 'источник_жив')

  const один404 = выводИзИстории(['не_найдено'])
  ok('одиночный 404 не считается удалением', один404.что === 'ждём',
    один404.что === 'ждём' ? один404.почему : '')

  const три404 = выводИзИстории(Array(ПОДРЯД_ДЛЯ_ВЫВОДА).fill('не_найдено'))
  ok(`${ПОДРЯД_ДЛЯ_ВЫВОДА} подряд — вывод об исчезновении`, три404.что === 'источник_исчез')

  const закрыт = выводИзИстории(Array(ПОДРЯД_ДЛЯ_ВЫВОДА).fill('запрещено_сервером'))
  ok('403 подряд — закрылся, а не исчез', закрыт.что === 'источник_закрылся',
    'страница на месте, просто не для нас')

  const прервано = выводИзИстории(Array(ПОДРЯД_ДЛЯ_ВЫВОДА).fill('таймаут'))
  ok('таймауты подряд — прерванное наблюдение', прервано.что === 'наблюдение_прервано')
  ok('и сказано, что это НЕ «изменений нет»',
    прервано.что === 'наблюдение_прервано' && /НЕ «изменений нет»/.test(прервано.почему),
    'иначе годность факта продлевается молча')

  ok('смешанная история считает только подряд идущие',
    (выводИзИстории(['таймаут', 'не_изменилось', 'таймаут', 'таймаут']) as any).подряд === 1)

  /* ── Что подтверждает факт ────────────────────────────────────────────── */

  const все: Исход['вид'][] = ['впервые', 'изменилось', 'не_изменилось', 'не_найдено',
    'запрещено_сервером', 'запрещено_robots', 'таймаут', 'недоступно']
  const подтв = все.filter((в) => подтверждает({ вид: в } as Исход))
  ok('подтверждают факт только три исхода',
    подтв.length === 3 && подтв.every((в) => !ПРОБЕЛ.has(в)),
    подтв.join(', '))
  ok('пробелов наблюдения пять', ПРОБЕЛ.size === 5)

  /* ── Живые запросы ────────────────────────────────────────────────────── */

  if (!process.argv.includes('--без-сети')) {
    __сброситьКэшRobots()

    const свои = await правилаДомена('https://goandstudy.com')
    ok('robots.txt сайта прочитан', свои.источник === 'файл', `запретов ${свои.запрещено.length}`)
    ok('админка закрыта самим сайтом', !путьРазрешён('/wp-admin/', свои))
    ok('блог открыт', путьРазрешён('/blog/', свои))

    const первый = await наблюдать('https://goandstudy.com/robots.txt')
    ok('первое наблюдение — «впервые»', первый.вид === 'впервые', первый.вид)

    if (первый.вид === 'впервые') {
      const второй = await наблюдать('https://goandstudy.com/robots.txt', { хеш: первый.хеш })
      ok('повтор с тем же содержимым — «не изменилось»',
        второй.вид === 'не_изменилось', второй.вид === 'не_изменилось' ? второй.как : второй.вид)

      const третий = await наблюдать('https://goandstudy.com/robots.txt', { хеш: 'заведомо-другой' })
      ok('другой прошлый хеш — «изменилось»', третий.вид === 'изменилось', третий.вид)
    }

    const нет = await наблюдать('https://goandstudy.com/такой-страницы-точно-нет-98765/')
    ok('несуществующая страница — «не найдено», а не «недоступно»',
      нет.вид === 'не_найдено', нет.вид)

    const запрет = await наблюдать('https://goandstudy.com/wp-admin/options.php')
    ok('запрещённый robots путь НЕ запрашивается',
      запрет.вид === 'запрещено_robots',
      запрет.вид === 'запрещено_robots' ? `правило ${запрет.правило}` : запрет.вид)

    const частный = await наблюдать('http://169.254.169.254/latest/meta-data/')
    ok('адрес метаданных облака не запрашивается', частный.вид === 'недоступно',
      частный.вид === 'недоступно' ? частный.причина : частный.вид)
    ok('и причина названа настоящая, а не «запрещено robots»',
      частный.вид === 'недоступно' && /blocked host/.test(частный.причина),
      'первая версия выдавала защиту от приватных адресов за правило robots.txt')
  }

  console.log(`\n${passed} пройдено, ${failed} провалено`)
  process.exit(failed ? 1 : 0)
}
main()
