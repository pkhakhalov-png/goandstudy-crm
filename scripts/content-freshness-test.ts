// Свежесть фактов: расписание, следствия исхода и план правки (E6.1, E6.2, E6.6, E6.7).
//
//   npx tsx scripts/content-freshness-test.ts
//   npx tsx scripts/content-freshness-test.ts --живой-прогон
//
// Без флага проверяется расчёт и согласие с базой: те же числа расписания в SQL
// и в коде, те же выводы из истории. С флагом шаг наблюдения выполняется по-
// настоящему: он ходит на сайты и пишет снимки, а при исчезновении факта ставит
// утверждению «stale» и блокирует запланированное. Поэтому это отдельный флаг.
import { config } from 'dotenv'; import path from 'path'
config({ path: path.resolve(process.cwd(), '.env.local') })
import { createClient } from '@supabase/supabase-js'
import {
  часыПерепроверки, пораСмотреть, видИзСтроки, историяВидов, следствия,
  нуженЧеловек, правкаНаПлощадке, планПравки, ЧАСЫ_КРИТИЧНЫЕ, ЧАСЫ_ПРОЧИЕ,
} from '../lib/content/freshness'
import type { Исход } from '../lib/content/observe'
import { runStep, hasStep } from '../lib/seo/steps'
import '../lib/seo/steps-freshness'

let passed = 0, failed = 0, skipped = 0
function ok(name: string, cond: boolean, note = '') {
  if (cond) { passed++; console.log(`✓ ${name}${note ? ' — ' + note : ''}`) }
  else { failed++; console.log(`✗ ${name}${note ? ' — ' + note : ''}`) }
}
function skip(name: string, why: string) { skipped++; console.log(`· ${name} — пропущено: ${why}`) }

const ЖИВОЙ = process.argv.includes('--живой-прогон')
const seo = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.SUPABASE_SERVICE_ROLE_KEY!,
  { auth: { persistSession: false } },
).schema('seo')

const час = 3_600_000

async function main() {
  /* ── Расписание ───────────────────────────────────────────────────────── */

  ok('критичный источник смотрится каждые шесть часов', часыПерепроверки(true) === ЧАСЫ_КРИТИЧНЫЕ)
  ok('прочий — раз в неделю', часыПерепроверки(false) === ЧАСЫ_ПРОЧИЕ)
  ok('заданное вручную сильнее критичности', часыПерепроверки(true, 24) === 24,
    'сезонность задаётся полем, а не календарём в коде: сезоны у стран разные')
  ok('ноль и отрицательное игнорируются', часыПерепроверки(true, 0) === 6 && часыПерепроверки(false, -5) === 168)

  const сейчас = new Date('2026-09-18T12:00:00Z')
  ok('ни разу не наблюдали — пора', пораСмотреть(null, false, null, сейчас).пора)
  ok('критичный через три часа — ещё не пора',
    !пораСмотреть(new Date(сейчас.getTime() - 3 * час), true, null, сейчас).пора)
  ok('критичный через семь часов — пора',
    пораСмотреть(new Date(сейчас.getTime() - 7 * час), true, null, сейчас).пора)
  ok('прочий через три дня — ещё не пора',
    !пораСмотреть(new Date(сейчас.getTime() - 72 * час), false, null, сейчас).пора)
  ok('прочий через восемь дней — пора',
    пораСмотреть(new Date(сейчас.getTime() - 192 * час), false, null, сейчас).пора)

  /* ── Исход из строки снимка ───────────────────────────────────────────── */

  ok('имя исхода из базы берётся как есть',
    видИзСтроки({ outcome: 'запрещено_robots', http_status: null }) === 'запрещено_robots')
  ok('старая строка с 404 — «не найдено»', видИзСтроки({ http_status: 404 }) === 'не_найдено')
  ok('старая строка с 403 — «запрещено сервером»', видИзСтроки({ http_status: 403 }) === 'запрещено_сервером')
  ok('старая строка с таймаутом — «таймаут»',
    видИзСтроки({ http_status: null, fetch_error: 'The operation was aborted' }) === 'таймаут')
  ok('успех с changed=false — «не изменилось»',
    видИзСтроки({ http_status: 200, changed: false }) === 'не_изменилось')
  ok('успех с changed=true — «изменилось»',
    видИзСтроки({ http_status: 200, changed: true }) === 'изменилось')
  ok('успех без changed — «впервые»', видИзСтроки({ http_status: 200, changed: null }) === 'впервые')
  ok('непонятная строка считается пробелом, а не подтверждением',
    видИзСтроки({ http_status: 500 }) === 'недоступно',
    'гадать в безопасную сторону: неизвестное не продлевает годность факта')

  ok('история читается от новой строки к старой',
    JSON.stringify(историяВидов([{ http_status: 404 }, { http_status: 200, changed: false }]))
      === JSON.stringify(['не_найдено', 'не_изменилось']))

  /* ── Следствия исхода ─────────────────────────────────────────────────── */

  const неизм: Исход = { вид: 'не_изменилось', хеш: 'a', как: 'по_ответу_304', статус: 304 }
  const с1 = следствия(неизм, ['не_найдено', 'не_найдено'])
  ok('успех обнуляет счётчик пробелов', с1.пробелов(2) === 0)
  ok('«не изменилось» не требует перепроверки фактов', !с1.перепроверитьФакты)
  ok('и вывод — источник жив', с1.вывод.что === 'источник_жив')

  const с2 = следствия({ вид: 'таймаут' }, ['таймаут', 'таймаут'])
  ok('пробел прибавляется к счётчику', с2.пробелов(2) === 3)
  ok('пробел не считается подтверждением',
    /пробел наблюдения/.test(с2.почему) && !с2.перепроверитьФакты,
    'недоступность источника — пробел, а НЕ «изменений нет»')

  const с3 = следствия(
    { вид: 'изменилось', хеш: 'b', текст: 'x', статус: 200, финальныйАдрес: 'u', etag: null, изменено: null },
    ['не_изменилось'],
  )
  ok('изменение страницы требует перепроверки фактов по новому тексту', с3.перепроверитьФакты,
    'само изменение хеша фактом не является: у вузов меняются новости и баннеры')

  /* ── Когда звать человека ─────────────────────────────────────────────── */

  ok('одиночный 404 человека не зовёт',
    !нуженЧеловек(следствия({ вид: 'не_найдено', статус: 404 }, []).вывод, true).нужен,
    'сайты переезжают: один 404 — наблюдение, а не вывод')

  const исчез = следствия({ вид: 'не_найдено', статус: 404 }, ['не_найдено', 'не_найдено']).вывод
  const зовКрит = нуженЧеловек(исчез, true)
  const зовПроч = нуженЧеловек(исчез, false)
  ok('три 404 подряд зовут человека', зовКрит.нужен && зовПроч.нужен)
  ok('критичный источник весит больше', зовКрит.вес === 'high' && зовПроч.вес === 'medium',
    'неделя молчания визовых правил и неделя молчания страницы про столовую стоят разного')
  ok('в тексте сказано, что это не «изменений нет»',
    /не подтверждены и не опровергнуты/.test(зовКрит.текст))

  const закрылся = нуженЧеловек(следствия({ вид: 'запрещено_сервером', статус: 403 }, ['запрещено_сервером', 'запрещено_сервером']).вывод, false)
  ok('403 подряд — «источник закрылся», а не «исчез»',
    закрылся.нужен && /закрылся от нас/.test(закрылся.текст),
    'страница на месте, нас на неё не пускают')

  /* ── Правка на площадке ───────────────────────────────────────────────── */

  const tg = правкаНаПлощадке('telegram')
  ok('метод правки в Telegram назван', tg.метод === 'editMessageText')
  ok('но возможность не объявлена проверенной', tg.доверие === 'не_проверяли',
    'документация описывает намерение авторов площадки, а не поведение нашего токена')
  ok('у VK свой метод', правкаНаПлощадке('vk').метод === 'wall.edit')
  ok('неизвестная площадка — способ неизвестен', правкаНаПлощадке(null).метод === null)

  /* ── План правки ──────────────────────────────────────────────────────── */

  const факт = {
    id: 42, kind: 'tuition_fee', statement: 'Стоимость программы — 76 000 THB за семестр',
    было: '…tuition fee 76,000 THB per semester…', подтверждаетсяСейчас: false, стало: null,
  }
  const вышло = планПравки({
    факт,
    источник: { url: 'https://www.chula.ac.th/fees', наблюдёнВ: '2026-09-18 09:00' },
    публикация: { id: 7, статус: 'published', платформа: 'telegram', адрес: 'https://t.me/c/1/55' },
    вариант: { версияId: 3, пакетId: 1 },
  })
  ok('вышедший пост — высокий вес', вышло.вес === 'high', 'его читают прямо сейчас')
  ok('в плане есть адрес поста', вышло.текст.includes('https://t.me/c/1/55'))
  ok('в плане есть прежняя выдержка', вышло.текст.includes('76,000 THB'))
  ok('сказано, что прежней формулировки на странице больше нет',
    /больше нет/.test(вышло.текст))
  ok('правка поста предложена, но помечена непроверенной',
    вышло.действия.some((д) => /поправить текст поста/.test(д.что) && д.доступно === 'не_проверяли'))
  ok('оговорка отдельной публикацией — то, что мы точно умеем',
    вышло.действия.some((д) => /оговорку/.test(д.что) && д.доступно === 'да'))

  const заблокировано = планПравки({
    факт: { ...факт, подтверждаетсяСейчас: true, стало: '…tuition fee 82,000 THB per semester…' },
    источник: { url: 'https://www.chula.ac.th/fees', наблюдёнВ: '2026-09-18 09:00' },
    публикация: { id: 8, статус: 'blocked', платформа: 'vk', адрес: null },
    вариант: null,
  })
  ok('заблокированная публикация — средний вес', заблокировано.вес === 'medium', 'наружу она не ушла')
  ok('для неё предложено поправить вариант и перепланировать',
    заблокировано.действия.some((д) => /перепланировать/.test(д.что) && д.доступно === 'да'))
  ok('нынешнее состояние страницы попало в план', заблокировано.текст.includes('82,000 THB'))

  /* ── Шаги зарегистрированы ────────────────────────────────────────────── */

  ok('шаг наблюдения зарегистрирован', hasStep('content_freshness_check'))
  ok('шаг плана правки зарегистрирован', hasStep('content_correction_plan'))

  /* ── Согласие с базой ─────────────────────────────────────────────────── */

  const { data: очередь, error } = await seo.rpc('sources_due', { p_limit: 50 })
  if (error) {
    skip('расписание в SQL и в коде совпадает',
      /schema cache|does not exist|Could not find/i.test(error.message)
        ? 'миграция 20260918000000_freshness.sql не применена'
        : error.message)
    skip('шаг наблюдения выполняется', 'та же миграция')
  } else {
    const ids = (очередь ?? []).map((r: any) => r.out_id)
    const { data: все } = await seo.from('sources')
      .select('id, url, critical, recheck_hours, last_observed_at, active, source_type')
      .eq('active', true).eq('source_type', 'web')

    const расхождения = (все ?? []).filter((s: any) => {
      const наш = пораСмотреть(s.last_observed_at, Boolean(s.critical), s.recheck_hours).пора
      return наш !== ids.includes(s.id)
    })
    ok('расписание в SQL и в коде совпадает', расхождения.length === 0,
      расхождения.length
        ? `разошлись на ${расхождения.length}: ${расхождения.slice(0, 3).map((s: any) => s.id).join(', ')}`
        : `источников ${(все ?? []).length}, в очереди ${ids.length}`)

    const критСначала = (очередь ?? []).every((r: any, i: number, a: any[]) =>
      i === 0 || !(r.out_critical && !a[i - 1].out_critical))
    ok('критичные источники стоят в очереди первыми', критСначала)

    if (ЖИВОЙ) {
      const job: any = { id: 0, step: 'content_freshness_check', lane: 'local', payload: { limit: 2 }, run_id: null, run_item_id: null, article_id: null, topic_id: null }
      const res = await runStep(job, seo as any)
      ok('шаг наблюдения выполняется', res.outcome === 'done', JSON.stringify(res.result))
    } else {
      skip('шаг наблюдения выполняется', 'нужен --живой-прогон: он ходит на сайты и пишет снимки')
    }
  }

  console.log(`\n${passed} пройдено, ${failed} провалено${skipped ? `, ${skipped} пропущено` : ''}`)
  process.exit(failed ? 1 : 0)
}
main()
