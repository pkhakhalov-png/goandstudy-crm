// Экран подключений: чего он не должен путать.
//
//   npx tsx scripts/content-connections-test.ts
//
// Проверяется ровно то, на чём такой экран врёт в первую очередь: заданный
// токен выдаётся за рабочий, неудачная проверка выглядит как её отсутствие,
// ручная площадка требует токена, а список площадок в коде расходится с
// проверкой в схеме — и канал не заводится с ошибкой из базы.
import { config } from 'dotenv'; import path from 'path'
config({ path: path.resolve(process.cwd(), '.env.local') })
import fs from 'node:fs'
import {
  ПЛОЩАДКИ, ПУБЛИКАЦИЯ, площадка, естьСекрет, состояниеПо, требуетсяДля, подключения,
} from '../lib/content/platforms'
import { проверить, секретДля } from '../lib/content/probe'

let ошибок = 0
function так(что: string, условие: boolean, почему = '') {
  console.log(`${условие ? '✓' : '✗'} ${что}${условие ? '' : ` — ${почему}`}`)
  if (!условие) ошибок++
}

async function main() {
  const tg = площадка('telegram')!
  const dzen = площадка('dzen')!

  /* ── Состояния ────────────────────────────────────────────────────────── */

  так('заданный токен без проверки — это «не проверено», а не «подключено»',
    состояниеПо(tg, { секретЕсть: true, проверено: null, действия: [] }) === 'не_проверено')

  так('проверка без доказанной публикации — «частично», а не «подключено»',
    состояниеПо(tg, { секретЕсть: true, проверено: '2026-09-21T10:00:00Z', действия: ['auth'] }) === 'частично')

  так('проверка с доказанной публикацией — «подключено»',
    состояниеПо(tg, { секретЕсть: true, проверено: '2026-09-21T10:00:00Z', действия: ['auth', ПУБЛИКАЦИЯ] }) === 'подключено')

  так('неудачная проверка отличается от её отсутствия',
    состояниеПо(tg, { секретЕсть: true, проверено: '2026-09-21T10:00:00Z', действия: [] }) === 'нет_доступа')

  так('без секрета — «нет секрета», и это не «не проверено»',
    состояниеПо(tg, { секретЕсть: false, проверено: null, действия: [] }) === 'нет_секрета')

  так('ручная площадка не требует токена ни в одном состоянии',
    состояниеПо(dzen, { секретЕсть: false, проверено: null, действия: [] }) === 'руками')

  так('ручной площадке не предлагается задать секрет',
    !требуетсяДля(dzen, 'руками', 1).some((т) => /задать/i.test(т)),
    требуетсяДля(dzen, 'руками', 1).join('; '))

  так('площадке без канала предлагается его завести',
    требуетсяДля(tg, 'подключено', 0).some((т) => /завести канал/i.test(т)))

  /* ── Секреты ──────────────────────────────────────────────────────────── */

  так('пустая строка в переменной не считается заданным секретом',
    !естьСекрет(tg, { TELEGRAM_CHANNEL_BOT_TOKEN: '   ', TELEGRAM_BOT_TOKEN: '' }))

  так('любого из перечисленных секретов достаточно',
    естьСекрет(tg, { TELEGRAM_BOT_TOKEN: 'x' }))

  так('площадка без секретов считается обеспеченной',
    естьСекрет(dzen, {}))

  так('секрет ручной площадки не ищется вовсе', секретДля(dzen, {}) === null)

  /* ── Проверка не публикует и не раскрывает секрет ─────────────────────── */

  const ручная = await проверить(dzen, { секрет: null, аккаунты: ['goandstudy'] })
  так('проверка ручной площадки не падает и ничего не доказывает',
    ручная.ок && ручная.действия.length === 0)

  const безТокена = await проверить(tg, { секрет: null, аккаунты: [] })
  так('без токена проверка не ходит в сеть и объясняет, чего не хватает',
    !безТокена.ок && /секрет не задан/i.test(безТокена.след))

  const плохой = await проверить(tg, { секрет: 'ЗАВЕДОМО-НЕ-ТОКЕН:123', аккаунты: [] })
  так('дохлый токен даёт отказ, а не исключение', !плохой.ок, плохой.след)
  так('в следе проверки нет самого токена',
    !JSON.stringify(плохой).includes('ЗАВЕДОМО-НЕ-ТОКЕН'),
    'секрет утёк в результат проверки')

  /* ── Реестр и схема ───────────────────────────────────────────────────── */

  const sql = fs.readFileSync('supabase/migrations/20260921000000_platforms.sql', 'utf8')
  const разрешено = [...sql.matchAll(/'([a-z]+)'/g)].map((m) => m[1])
  const лишние = ПЛОЩАДКИ.map((п) => п.код).filter((к) => !разрешено.includes(к))
  так('каждая площадка реестра разрешена проверкой в схеме', лишние.length === 0,
    `в схеме нет: ${лишние.join(', ')} — канал на них не заведётся`)

  так('коды площадок не повторяются',
    new Set(ПЛОЩАДКИ.map((п) => п.код)).size === ПЛОЩАДКИ.length)

  так('у каждой ручной площадки написано, почему руками',
    ПЛОЩАДКИ.filter((п) => п.доставка === 'manual').every((п) => Boolean(п.почемуРуками)))

  так('у каждой площадки с API есть ссылка на документацию',
    ПЛОЩАДКИ.filter((п) => п.доставка === 'api').every((п) => Boolean(п.док)))

  /* ── Сборка экрана на живой базе ──────────────────────────────────────── */

  if (process.env.SUPABASE_SERVICE_ROLE_KEY) {
    const { createClient } = await import('@supabase/supabase-js')
    const content = createClient(
      process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.SUPABASE_SERVICE_ROLE_KEY!,
      { auth: { persistSession: false } },
    ).schema('content' as any)

    const карточки = await подключения(content)
    так('экран собирается на живой базе и покрывает весь реестр',
      карточки.length === ПЛОЩАДКИ.length)
    так('ни одна карточка не осталась без объяснения состояния',
      карточки.every((к) => к.строка.length > 10))
    так('секреты не уезжают на экран значениями',
      карточки.every((к) => Object.values(к.секретЗадан).every((v) => typeof v === 'boolean')))

    console.log('\nчто увидит человек:')
    for (const к of карточки) console.log(`  ${к.площадка.имя}: ${к.состояние} — ${к.строка}`)
  } else {
    console.log('— ключа сервисной роли нет: сборка экрана на живой базе пропущена')
  }

  console.log(ошибок ? `\n${ошибок} проверок не прошло` : '\nвсе проверки прошли')
  process.exit(ошибок ? 1 : 0)
}

main().catch((e) => { console.error(e); process.exit(1) })
