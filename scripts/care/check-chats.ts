// Можем ли мы написать клиентам — проверка без единого сообщения.
//
//   npx tsx scripts/care/check-chats.ts
//
// ЗАЧЕМ. Перед первым живым напоминанием надо знать не «работает ли Телеграм»,
// а «дойдёт ли оно до вот этого клиента». Бота могли удалить из группы, группу
// переделать в канал, права урезать. Узнать об этом в момент отправки значит
// узнать слишком поздно.
//
// Ничего не отправляет: спрашивает у Bot API состояние чата и своё членство в
// нём. Результат пишется в care.connections — кабинет показывает его в ленте
// внимания, а не только здесь.
import { config } from 'dotenv'
import path from 'path'

config({ path: path.resolve(process.cwd(), '.env.local') })

async function main() {
  const { проверитьКаналы } = await import('../../lib/care/channels')
  const итог = await проверитьКаналы()

  console.log(`\nПроверено чатов: ${итог.проверено}`)
  console.log(`  писать можем:   ${итог.доступны}`)
  console.log(`  писать нельзя:  ${итог.недоступны}`)
  console.log(`  дел без чата:   ${итог.безЧата}`)

  if (итог.строки.some((с) => !с.можемПисать)) {
    console.log('\nНедоступные:')
    for (const с of итог.строки.filter((x) => !x.можемПисать)) {
      console.log(`  ✗ ${с.название ?? с.chatId}: ${с.почему}`)
    }
  }

  if (итог.причины.length && !итог.проверено) {
    console.log('\n' + итог.причины.join('\n'))
  }

  // Дело без чата — не поломка канала, а незаконченная настройка. Названо
  // отдельно, чтобы одно не прятало другое.
  if (итог.безЧата) {
    console.log(`\nУ ${итог.безЧата} дел на новом кабинете чат не привязан — им написать нечем.`)
    console.log('Привязать: npx tsx scripts/care/link-chats.ts --дело <id> --применить')
  }
}

main().catch((e) => {
  console.error(`\n✗ ${e instanceof Error ? e.message : String(e)}`)
  process.exit(1)
})
