// Правка опубликованного архива (E3.5).
//
//   npx tsx scripts/content-legacy-fix-test.ts
//   npx tsx scripts/content-legacy-fix-test.ts --прикидка      # выбор страницы, без модели
//   npx tsx scripts/content-legacy-fix-test.ts --живой-прогон  # с моделью, пишет версию
//
// Главное, что проверяется: закрытой считается только исчезнувшая находка.
// Смягчение — не исправление, и тест это фиксирует прямо: фраза, обёрнутая в
// «обычно», по-прежнему находится в тексте.
import { config } from 'dotenv'; import path from 'path'
config({ path: path.resolve(process.cwd(), '.env.local') })
import { createClient } from '@supabase/supabase-js'
import { проза, встречается, блоки, заменить } from '../lib/seo/steps-legacy'
import { runStep, hasStep } from '../lib/seo/steps'
import { RISK_ORDER } from '../lib/seo/legacy-audit'
import '../lib/seo/steps-legacy'

let passed = 0, failed = 0, skipped = 0
function ok(name: string, cond: boolean, note = '') {
  if (cond) { passed++; console.log(`✓ ${name}${note ? ' — ' + note : ''}`) }
  else { failed++; console.log(`✗ ${name}${note ? ' — ' + note : ''}`) }
}
function skip(name: string, why: string) { skipped++; console.log(`· ${name} — пропущено: ${why}`) }

const seo = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.SUPABASE_SERVICE_ROLE_KEY!,
  { auth: { persistSession: false } },
).schema('seo')

const ПРИКИДКА = process.argv.includes('--прикидка')
const ЖИВОЙ = process.argv.includes('--живой-прогон')

async function main() {
  /* ── Текст без разметки ───────────────────────────────────────────────── */

  ok('теги выбрасываются', проза('<p>Стоимость <b>4000</b> евро</p>') === 'стоимость 4000 евро')
  ok('скрипт не попадает в прозу',
    !проза('<p>цена</p><script>var x = "виза не нужна"</script>').includes('виза'),
    'иначе строка из кода сошла бы за утверждение статьи')
  ok('пробелы и регистр не важны', проза('  ЦЕНА\n\n  4000  ') === 'цена 4000')

  /* ── Что считается закрытой находкой ──────────────────────────────────── */

  const текст = '<p>Виза оформляется за две недели, стоимость обучения 4000 евро в год.</p>'

  ok('находка на месте — видим её', встречается(текст, 'стоимость обучения 4000 евро'))
  ok('разметка внутри фразы не мешает',
    встречается('<p>стоимость обучения <b>4000</b> евро</p>', 'стоимость обучения 4000 евро'),
    'статья могла сменить теги — находка от этого никуда не делась')
  ok('удалённая находка исчезает', !встречается('<p>Виза оформляется за две недели.</p>', 'стоимость обучения 4000 евро'))

  ok('смягчение НЕ считается исправлением',
    встречается('<p>Обычно стоимость обучения 4000 евро в год.</p>', 'стоимость обучения 4000 евро'),
    'проверить утверждение от слова «обычно» не станет чем, а читатель примет за факт')

  ok('слишком короткая фраза не ищется', !встречается(текст, 'виза'),
    'иначе любое слово считалось бы находкой и правка не заканчивалась бы никогда')

  /* ── Разбор на блоки ──────────────────────────────────────────────────── */

  const статья = [
    '<!-- wp:paragraph -->', '<p>Первый абзац.</p>', '<!-- /wp:paragraph -->', '',
    '<!-- wp:heading {"level":2} -->', '<h2>Раздел</h2>', '<!-- /wp:heading -->', '',
    '<!-- wp:paragraph -->', '<p>Стоимость обучения 4000 евро в год.</p>', '<!-- /wp:paragraph -->',
  ].join('\n')

  const б = блоки(статья)
  ok('разметка редактора даёт точные границы блоков', б.length === 3, `блоков ${б.length}`)
  ok('блок содержит и комментарии, и тег', б[0].html.includes('wp:paragraph') && б[0].html.includes('<p>'))

  const найден = б.findIndex((x) => встречается(x.html, 'стоимость обучения 4000 евро'))
  ok('находка привязывается к своему блоку', найден === 2)

  const после = заменить(статья, [{ блок: б[найден], на: '<!-- wp:paragraph -->\n<p>Стоимость зависит от страны и программы.</p>\n<!-- /wp:paragraph -->' }])
  ok('правленый блок заменён', !встречается(после, 'стоимость обучения 4000 евро'))
  ok('соседние блоки остались побайтово теми же',
    после.includes('<p>Первый абзац.</p>') && после.includes('<h2>Раздел</h2>')
      && после.slice(0, после.indexOf('<h2>')) === статья.slice(0, статья.indexOf('<h2>')),
    'ради этого правка и идёт по блокам: остальной текст к модели не попадает вовсе')

  const пустой = заменить(статья, [{ блок: б[найден], на: '' }])
  ok('пустая замена убирает блок целиком, не оставляя комментариев',
    !пустой.includes('4000') && (пустой.match(/wp:paragraph/g) ?? []).length === 2,
    'от абзаца с одной непроверяемой цифрой после удаления может не остаться содержания')

  const безРазметки = '<p>Абзац раз.</p>\n<ul><li>пункт</li></ul>\n<h3>Заголовок</h3>'
  ok('статья без разметки редактора разбирается по элементам', блоки(безРазметки).length === 3,
    'иначе правка одной цифры снова означала бы переписывание целого')

  ok('порядок риска — от дорогого к дешёвому',
    RISK_ORDER[0] === 'критично' && RISK_ORDER[RISK_ORDER.length - 1] === 'низко')

  ok('шаг зарегистрирован', hasStep('content_legacy_fix'))

  /* ── Материал в базе ──────────────────────────────────────────────────── */

  const { data: находки, error } = await seo.from('claims')
    .select('id, page_id, qualifiers, statement').eq('status', 'unverified').not('page_id', 'is', null)

  if (error) {
    skip('находки ревизии лежат в реестре',
      /page_id|column/i.test(error.message) ? 'не применена docs/sql/утверждения-из-архива.sql' : error.message)
  } else {
    ok('находки ревизии лежат в реестре', (находки?.length ?? 0) > 0, `${находки?.length ?? 0} утверждений`)

    const крит = (находки ?? []).filter((c: any) => c.qualifiers?.risk === 'критично')
    ok('у находок проставлен риск', крит.length > 0, `критичных ${крит.length}`)
    ok('у находки есть дословная цитата',
      (находки ?? []).every((c: any) => typeof c.statement === 'string' && c.statement.length >= 8),
      'утверждение без цитаты нельзя ни найти в тексте, ни проверить, что оно ушло')

    const страницы = new Set((находки ?? []).map((c: any) => c.page_id))
    ok('находки размечены по страницам', страницы.size > 1, `страниц ${страницы.size}`)
  }

  /* ── Живые прогоны ────────────────────────────────────────────────────── */

  const job = (payload: any) => ({
    id: 0, step: 'content_legacy_fix', lane: 'local', payload,
    run_id: null, run_item_id: null, article_id: null, topic_id: null,
  })

  if (ПРИКИДКА || ЖИВОЙ) {
    const res = await runStep(job({ dry: true }) as any, seo as any)
    ok('прикидка выбирает страницу и считает находки',
      res.outcome === 'done' && Boolean((res.result as any)?.slug),
      JSON.stringify(res.result))
  } else {
    skip('прикидка выбирает страницу и считает находки', 'нужен --прикидка: ходит по ssh в тему сайта')
  }

  if (ЖИВОЙ) {
    const res = await runStep(job({}) as any, seo as any)
    const r: any = res.result ?? {}
    ok('правка проходит и ложится предложением',
      (res.outcome === 'done' || res.outcome === 'awaiting_human') && Boolean(r.version_id || r.ухудшение),
      `${res.outcome}: ${JSON.stringify(r)}`)
    if (r.version_id) {
      ok('правка не ухудшила гейт фактов', (r.факты_после ?? 0) <= (r.факты_до ?? 0),
        `было ${r.факты_до}, стало ${r.факты_после}`)
      ok('что-то действительно закрыто', (r.закрыто ?? 0) > 0, `закрыто ${r.закрыто} из ${r.находок}`)
    }
  } else {
    skip('правка проходит и ложится предложением', 'нужен --живой-прогон: зовёт модель и пишет версию')
  }

  console.log(`\n${passed} пройдено, ${failed} провалено${skipped ? `, ${skipped} пропущено` : ''}`)
  process.exit(failed ? 1 : 0)
}
main()
