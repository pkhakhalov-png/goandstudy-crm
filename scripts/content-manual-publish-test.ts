// Ручная выкладка: метки, подготовка текста и проверка выхода (E5, ручные площадки).
//
//   npx tsx scripts/content-manual-publish-test.ts
//   npx tsx scripts/content-manual-publish-test.ts --без-сети
//
// Главное, что проверяется: «не смогли прочитать пост» не превращается в «пост
// не вышел», а «в посте нет метки» — не превращается в ноль переходов. Первое
// оставляет кликабельность неизвестной, второе прямо говорит, что приписывать
// переходы нечем.
import { config } from 'dotenv'; import path from 'path'
config({ path: path.resolve(process.cwd(), '.env.local') })
import { метки, ссылкаДляПоста, подготовить, проверитьВыход, следствиеВыхода } from '../lib/content/manual-publish'

let passed = 0, failed = 0
function ok(name: string, cond: boolean, note = '') {
  if (cond) { passed++; console.log(`✓ ${name}${note ? ' — ' + note : ''}`) }
  else { failed++; console.log(`✗ ${name}${note ? ' — ' + note : ''}`) }
}

const БЕЗ_СЕТИ = process.argv.includes('--без-сети')

async function main() {
  /* ── Метки ────────────────────────────────────────────────────────────── */

  const m = метки({ платформа: 'vc', публикацияId: 42, пакетId: 7 })
  ok('площадка, пакет и публикация попадают в метки',
    m.utm_source === 'vc' && m.utm_campaign === '7' && m.utm_content === '42')
  ok('без пакета метка кампании не выдумывается',
    !('utm_campaign' in метки({ платформа: 'vc', публикацияId: 42 })))

  const с = ссылкаДляПоста('https://goandstudy.com/polnoe-soprovozhdenie/', m)
  ok('метки дописываются к адресу', с.includes('utm_content=42') && с.includes('utm_source=vc'))

  const сХвостом = ссылкаДляПоста('https://goandstudy.com/a?ref=old', m)
  ok('чужие параметры адреса не теряются', сХвостом.includes('ref=old') && сХвостом.includes('utm_content=42'))

  /* ── Подготовка текста ────────────────────────────────────────────────── */

  const исходный = 'Стоимость магистратуры в Италии — разбор.\nПодробно: https://goandstudy.com/blog/italy/ — записывайтесь.'
  const { текст, ссылка } = подготовить({ текст: исходный, платформа: 'dzen', публикацияId: 99, пакетId: 3 })
  ok('ссылка в тексте пересобрана с меткой публикации',
    текст.includes('utm_content=99') && Boolean(ссылка?.includes('utm_content=99')),
    'при сборке поста публикации ещё нет, её номер появляется только здесь')
  ok('остальной текст не тронут', текст.startsWith('Стоимость магистратуры') && текст.includes('записывайтесь'))
  ok('тире после ссылки не съедено',
    текст.includes(' — записывайтесь'),
    'знак препинания за ссылкой не должен уезжать внутрь адреса')

  const безСсылки = подготовить({ текст: 'Пост без ссылки', платформа: 'vc', публикацияId: 1 })
  ok('пост без ссылки не ломается', безСсылки.ссылка === null && безСсылки.текст === 'Пост без ссылки')

  /* ── Следствия проверки выхода ────────────────────────────────────────── */

  const сМеткой = следствиеВыхода({ вид: 'виден_с_меткой', адрес: 'https://vc.ru/x/1' })
  ok('пост с меткой — переходы считаются', сМеткой.link_clickable === true && Boolean(сМеткой.last_verified_at))

  const безМетки = следствиеВыхода({ вид: 'виден_без_метки', почему: 'метки нет' })
  ok('пост без метки — переходы не приписываются', безМетки.link_clickable === false)
  ok('и проверка при этом засчитана', Boolean(безМетки.last_verified_at),
    'страницу мы прочитали — это факт, даже если метки в ней нет')

  const неПрочитали = следствиеВыхода({ вид: 'не_проверить', почему: 'не пустили' })
  ok('не прочитали — кликабельность остаётся неизвестной',
    неПрочитали.link_clickable === null && неПрочитали.last_verified_at === null,
    '«не смотрели» это не «нет»: записать false значило бы соврать')

  /* ── Живая проверка выхода ────────────────────────────────────────────── */

  if (!БЕЗ_СЕТИ) {
    const чужая = await проверитьВыход('https://goandstudy.com/robots.txt', 12345)
    ok('страница без нашей метки читается как «виден без метки»',
      чужая.вид === 'виден_без_метки', чужая.вид)

    const нет = await проверитьВыход('https://goandstudy.com/такой-страницы-нет-98765/', 1)
    ok('несуществующая страница — «не проверить», а не «не вышел»',
      нет.вид === 'не_проверить', нет.вид === 'не_проверить' ? нет.почему : нет.вид)

    const частный = await проверитьВыход('http://169.254.169.254/latest/meta-data/', 1)
    ok('адрес метаданных облака не запрашивается', частный.вид === 'не_проверить',
      частный.вид === 'не_проверить' ? частный.почему : частный.вид)
  }

  console.log(`\n${passed} пройдено, ${failed} провалено`)
  process.exit(failed ? 1 : 0)
}
main()
