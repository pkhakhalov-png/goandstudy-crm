async function main() {
  console.log('Обновляем регламент куратора...\n')

  // 1) Update stages (subtitle, badge, description)
  for (const s of STAGES) {
    const { error } = await sb
      .from('curator_stages')
      .update({ subtitle: s.subtitle, badge: s.badge, description: s.description })
      .eq('code', s.code)
    if (error) {
      console.error(`stage ${s.code}:`, error.message)
      process.exit(1)
    }
    console.log(`stage ${s.code} ✓`)
  }

  // 2) Load all stages to get UUIDs
  const { data: dbStages } = await sb.from('curator_stages').select('id, code')
  const stageIdByCode = new Map<string, string>(dbStages?.map(s => [s.code, s.id]) ?? [])

  // 3) Wipe old checklist & insert new
  await sb.from('curator_stage_checklist').delete().neq('id', '00000000-0000-0000-0000-000000000000')
  console.log('\nстарые чек-листы удалены\n')

  let total = 0
  for (const s of STAGES) {
    const stageId = stageIdByCode.get(s.code)
    if (!stageId) {
      console.error(`stage ${s.code} not found — пропускаем checklist`)
      continue
    }
    const rows = s.checklist.map((c, idx) => ({
      stage_id: stageId,
      text: c.text,
      section: c.section || null,
      external_link: c.external_link || null,
      position: idx + 1,
    }))
    const { error } = await sb.from('curator_stage_checklist').insert(rows)
    if (error) {
      console.error(`checklist for ${s.code}:`, error.message)
      process.exit(1)
    }
    total += rows.length
    console.log(`  ${s.code}: +${rows.length} пунктов`)
  }

  console.log(`\n✅ Готово. Этапов: ${STAGES.length}, пунктов: ${total}`)
  console.log('Открыть: https://crm.goandstudy.com/curator/guide')
}

main().catch(e => { console.error(e); process.exit(1) })
