// Приём вебхуков и политика повторов (E5.13).
//
//   npx tsx scripts/content-webhook-test.ts
//
// Три защиты проверяются по отдельности: подпись, срок, уникальность. Каждая
// закрывает свою дыру, и подменить одну другой нельзя — проверяется и это.
import { config } from 'dotenv'; import path from 'path'
config({ path: path.resolve(process.cwd(), '.env.local') })
import { createClient } from '@supabase/supabase-js'
import {
  разобратьTelegram, разобратьVk, секретыСовпали, ключСобытия, секретГодится,
  принятьОдинРаз, решитьПоИсходу, ОКНО_СВЕЖЕСТИ_СЕК, МАКС_ПОПЫТОК,
} from '../lib/content/webhooks'

const seo = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.SUPABASE_SERVICE_ROLE_KEY!, { auth: { persistSession: false } })
const content = seo.schema('content' as any)

let passed = 0, failed = 0
function ok(name: string, cond: boolean, note = '') {
  if (cond) { passed++; console.log(`✓ ${name}${note ? ' — ' + note : ''}`) }
  else { failed++; console.log(`✗ ${name}${note ? ' — ' + note : ''}`) }
}

// Секрет только латиницей: телеграм передаёт его заголовком, а туда
// кириллица не помещается. Это не придирка теста — это ограничение HTTP.
const СЕКРЕТ = 'proverka-vebhukov-7f3a'
const СЕЙЧАС = new Date('2026-09-18T10:00:00Z')
const метка = (сдвигСек: number) => Math.floor(СЕЙЧАС.getTime() / 1000) + сдвигСек

const шапка = (v: string | null) => new Headers(v ? { 'x-telegram-bot-api-secret-token': v } : {})

async function main() {
  /* ── Подпись ──────────────────────────────────────────────────────────── */

  ok('пустой секрет не совпадает ни с чем',
    !секретыСовпали(null, СЕКРЕТ) && !секретыСовпали(СЕКРЕТ, null) && !секретыСовпали('', ''))
  ok('разные секреты не совпадают', !секретыСовпали(СЕКРЕТ, СЕКРЕТ + 'х'))
  ok('одинаковые совпадают', секретыСовпали(СЕКРЕТ, СЕКРЕТ))

  // Ограничение, на котором споткнулась первая версия этой проверки.
  ok('секрет с кириллицей не годится',
    !секретГодится('секрет-по-русски').ok,
    'в заголовок HTTP кириллица не помещается — секрет не уйдёт вовсе')
  ok('и сказано почему, а не просто «нет»',
    /кириллица/.test(секретГодится('секрет-по-русски').почему ?? ''))
  ok('латинский секрет годится', секретГодится(СЕКРЕТ).ok)
  ok('пустой не годится', !секретГодится('').ok)
  ok('слишком длинный не годится', !секретГодится('a'.repeat(257)).ok)

  const безПодписи = разобратьTelegram(шапка(null), { update_id: 1 }, СЕКРЕТ, СЕЙЧАС)
  ok('без подписи не принимается', !безПодписи.ok && безПодписи.статус === 401)

  const чужаяПодпись = разобратьTelegram(шапка('chuzhoy-sekret'), { update_id: 1 }, СЕКРЕТ, СЕЙЧАС)
  ok('с чужой подписью не принимается', !чужаяПодпись.ok && чужаяПодпись.статус === 401)

  /* ── Срок ─────────────────────────────────────────────────────────────── */

  const свежее = разобратьTelegram(шапка(СЕКРЕТ), { update_id: 2, message: { date: метка(-10) } }, СЕКРЕТ, СЕЙЧАС)
  ok('свежее событие принимается', свежее.ok && свежее.срок === 'свежее', `возраст ${свежее.ok ? свежее.возраст : '—'} с`)

  const старое = разобратьTelegram(шапка(СЕКРЕТ), { update_id: 3, message: { date: метка(-ОКНО_СВЕЖЕСТИ_СЕК - 60) } }, СЕКРЕТ, СЕЙЧАС)
  ok('старое событие с верной подписью отклоняется', !старое.ok,
    'подписанное остаётся подписанным навсегда — подпись от повтора не защищает')

  const безВремени = разобратьTelegram(шапка(СЕКРЕТ), { update_id: 4, my_chat_member: {} }, СЕКРЕТ, СЕЙЧАС)
  ok('событие без времени принимается, но срок помечен как непроверяемый',
    безВремени.ok && безВремени.срок === 'нечем',
    'не всякое обновление несёт время — притворяться, что проверили, нельзя')

  const изБудущего = разобратьTelegram(шапка(СЕКРЕТ), { update_id: 5, message: { date: метка(30) } }, СЕКРЕТ, СЕЙЧАС)
  ok('событие из будущего не отклоняется', изБудущего.ok,
    'разошлись часы; наши могут быть неправы ровно так же, как чужие')

  /* ── VK ───────────────────────────────────────────────────────────────── */

  const vkЧужой = разобратьVk({ secret: 'не тот', event_id: 'e1', group_id: 7 }, СЕКРЕТ, 7)
  ok('VK без верного секрета не принимается', !vkЧужой.ok && vkЧужой.статус === 401)

  const vkЧужаяГруппа = разобратьVk({ secret: СЕКРЕТ, event_id: 'e1', group_id: 999 }, СЕКРЕТ, 7)
  ok('VK от чужой группы не принимается', !vkЧужаяГруппа.ok,
    'секрет верный, а группа не наша — значит секрет утёк')

  const vkОк = разобратьVk({ secret: СЕКРЕТ, event_id: 'e1', group_id: 7 }, СЕКРЕТ, 7)
  ok('VK со своим секретом и группой принимается', vkОк.ok)
  ok('у VK срок проверить нечем — и это сказано, а не замазано',
    vkОк.ok && vkОк.срок === 'нечем',
    'Callback API не передаёт времени события вовсе')

  /* ── Уникальность ─────────────────────────────────────────────────────── */

  ok('ключ события устойчив', ключСобытия('telegram', 'x') === ключСобытия('telegram', 'x'))
  ok('ключ различает площадки', ключСобытия('telegram', 'x') !== ключСобытия('vk', 'x'))

  const есть = !(await content.from('event_receipts').select('event_id').limit(1)).error
  if (есть) {
    const id = `проверка-${СЕЙЧАС.getTime()}`
    try {
      const первый = await принятьОдинРаз(content, 'telegram', id)
      const второй = await принятьОдинРаз(content, 'telegram', id)
      ok('первая доставка принимается', первый === true)
      ok('повторная доставка отбрасывается', второй === false,
        'площадки повторяют доставку пачками — это их штатное поведение')
    } finally {
      await content.from('event_receipts').delete().eq('event_id', ключСобытия('telegram', id))
    }
  } else {
    console.log('  (схема content недоступна — проверка уникальности пропущена)')
  }

  /* ── Политика повторов ────────────────────────────────────────────────── */

  ok('успех — готово', решитьПоИсходу({ kind: 'опубликовано' }, 1).что === 'готово')

  const отказ = решитьПоИсходу({ kind: 'отказано', reason: 'слишком длинно' }, 1)
  ok('отказ по существу — сдаться сразу', отказ.что === 'сдаться',
    'пять раз получить «слишком длинно» — это не настойчивость, а трата слота')

  const токен = решитьПоИсходу({ kind: 'нужна_авторизация', reason: 'токен отозван' }, 1)
  ok('отзыв токена останавливает канал, а не повторяет', токен.что === 'остановить_канал')

  const часто = решитьПоИсходу({ kind: 'повторить_позже', reason: '429', retryAfterSec: 17 }, 1)
  ok('срок от площадки главнее нашей оценки',
    часто.что === 'повторить' && часто.черезСек === 17)

  const безСрока = решитьПоИсходу({ kind: 'повторить_позже', reason: '502' }, 3)
  ok('без срока задержка растёт', безСрока.что === 'повторить' && безСрока.черезСек === 240,
    `третья попытка → ${безСрока.что === 'повторить' ? безСрока.черезСек : '—'} с`)

  const исчерпано = решитьПоИсходу({ kind: 'повторить_позже', reason: '502' }, МАКС_ПОПЫТОК)
  ok('после предела попыток — сдаться', исчерпано.что === 'сдаться')

  const неизвестно = решитьПоИсходу({ kind: 'исход_неизвестен', reason: 'таймаут' }, 1)
  ok('неизвестный исход НЕ повторяется', неизвестно.что === 'разобрать_вручную',
    'слепой повтор здесь даёт второй пост')
  ok('и причина названа человеку', неизвестно.что === 'разобрать_вручную' && /второй пост/.test(неизвестно.почему))

  console.log(`\n${passed} пройдено, ${failed} провалено`)
  process.exit(failed ? 1 : 0)
}
main()
