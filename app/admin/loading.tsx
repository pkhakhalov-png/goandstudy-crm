/**
 * Заглушка на время загрузки страницы админки.
 *
 * Рисует только правую часть: сайдбар живёт в оболочке (`layout.tsx`) и при
 * переходах не перерисовывается — меню серым не становится.
 *
 * Почему она снова здесь и чем отличается от прежней. Прежняя подставляла
 * серые прямоугольники сразу, на каждый переход: экран мигал даже там, где
 * страница приезжала за треть секунды, и мельканий было больше, чем ожидания.
 * Эта молчит первые 250 мс — короткий переход проходит целиком и остаётся
 * незамеченным, — а потом показывает кружок с подписью. Молчать дольше и
 * рисовать бледнее пробовали: тогда непонятно, идёт ли загрузка вообще.
 *
 * Всё поведение — в стилях (`.load` в globals.css), а не в коде: заглушку
 * монтирует Next в момент нажатия, и своего состояния под таймер у неё нет.
 */
export default function AdminLoading() {
  return (
    <div className="main">
      <div className="load">
        <span className="load-spin" aria-hidden />
        <span className="load-text">Загрузка</span>
      </div>
      <span className="sr-only" role="status">Загружается</span>
    </div>
  )
}
