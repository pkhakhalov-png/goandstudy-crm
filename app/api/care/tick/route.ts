/**
 * Воркер очереди care.
 *
 * Зовётся расписанием базы раз в минуту (`care.dispatch_tick()`), берёт
 * несколько заданий и выполняет их, пока не кончится отведённое время.
 *
 * Бюджет времени, а не «сколько успеем». Vercel обрывает функцию на 300
 * секундах без предупреждения, и задание, оборванное посередине, остаётся
 * взятым до истечения аренды. Поэтому тик сам останавливается заранее и
 * возвращает недоделанное в очередь честно — со следующей попыткой и
 * сохранённым прогрессом.
 *
 * Своя авторизация заголовком, потому что расписание зовёт маршрут без сессии,
 * а `middleware.ts` пропускает `/api/care` как публичный путь.
 */
import { NextRequest, NextResponse } from 'next/server'
import { взятьЗадания, закрытьЗадание, сохранитьПрогресс, type Задание } from '@/lib/care/jobs/claim'
import { подготовитьНапоминания } from '@/lib/care/jobs/reminders'
import { отправитьОчередь } from '@/lib/care/jobs/send'
import { разобратьПереписку } from '@/lib/care/jobs/extract'
import { разобратьВходящие } from '@/lib/care/jobs/triage'
import { закрытьЗависшие } from '@/lib/care/jobs/sweep'
import { проверитьКаналы } from '@/lib/care/channels'
import { необязательна } from '@/lib/care/env'
import { секретГодится, секретыСовпали } from '@/lib/care/secret'

export const dynamic = 'force-dynamic'
export const runtime = 'nodejs'
export const maxDuration = 300

/** Останавливаемся заранее: нужен запас, чтобы успеть закрыть взятое задание. */
const БЮДЖЕТ_МС = 240_000
const ЗАДАНИЙ_ЗА_ТИК = 5

/**
 * Обработчики по виду задания.
 *
 * На этапе 0 здесь только `echo` — он существует ради проверки, что цепочка
 * «расписание → маршрут → очередь → результат» работает целиком, до того как в
 * неё добавлена хоть одна настоящая работа. Проверять очередь одновременно с
 * первым содержательным заданием значит не знать, что именно сломалось.
 */
const ОБРАБОТЧИКИ: Record<string, (з: Задание, воркер: string) => Promise<Record<string, unknown>>> = {
  async echo(задание) {
    return { echo: задание.payload, at: new Date().toISOString() }
  },

  /** Подготовить напоминания. Ничего не отправляет — создаёт предложения. */
  async prepare_reminders() {
    const итог = await подготовитьНапоминания()
    return { ...итог, at: new Date().toISOString() }
  },

  /**
   * Можем ли мы написать клиентам.
   *
   * Модель не зовёт и денег не стоит: два запроса Bot API на чат. Раз в сутки
   * достаточно — бота из группы удаляют не каждую минуту, — но знать об этом
   * надо до отправки, а не в момент, когда напоминание со сроком не ушло.
   */
  async check_channels() {
    const итог = await проверитьКаналы()
    return { ...итог, строки: итог.строки.length, at: new Date().toISOString() }
  },

  /**
   * Разобрать входящие: чем было каждое сообщение клиента.
   *
   * Дешевле разбора фактов на порядок — ярлыки, а не извлечение, — и потому
   * ставится при каждом проходе расписания, а не раз в сутки. Вопрос клиента,
   * пролежавший сутки, это сутки молчания в ответ на прямой вопрос.
   */
  async triage_messages(задание) {
    const дело = (задание.payload as { case_id?: string }).case_id
    const итог = await разобратьВходящие(дело)
    return { ...итог, at: new Date().toISOString() }
  },

  /**
   * Разобрать переписку в факты.
   *
   * Самое дорогое задание контура — около десяти центов на дело, потому что
   * модель читает переписку целиком. Поэтому оно ставится раз в сутки, берёт
   * только то, что пришло с прошлого разбора, и останавливается, упёршись в
   * дневной потолок, а не доедает его до дна.
   */
  async extract_facts(задание) {
    const дело = (задание.payload as { case_id?: string }).case_id
    const итог = await разобратьПереписку(дело)
    return { ...итог, at: new Date().toISOString() }
  },

  /**
   * Отправить то, что куратор принял и что прошло ворота.
   *
   * Отдельным заданием от подготовки: готовить можно всегда, отправлять —
   * только когда решение принято человеком. Смешать их значит потерять этот
   * рубеж.
   */
  async send_outbound() {
    const итог = await отправитьОчередь()
    return { ...итог, at: new Date().toISOString() }
  },
}

function авторизован(req: NextRequest): { ok: true } | { ok: false; код: 401 | 500; причина: string } {
  const секрет = необязательна('CARE_TICK_SECRET')
  if (!секрет) return { ok: false, код: 500, причина: 'CARE_TICK_SECRET не задан' }
  const годность = секретГодится(секрет)
  if (!годность.ok) return { ok: false, код: 500, причина: `секрет не годится: ${годность.почему}` }
  if (!секретыСовпали(req.headers.get('x-care-tick-secret'), секрет)) {
    return { ok: false, код: 401, причина: 'заголовок с секретом не сошёлся' }
  }
  return { ok: true }
}

/** Имя воркера уникально на запуск: по нему определяется, чей результат принимать. */
function имяВоркера(): string {
  return `tick-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`
}

export async function POST(req: NextRequest) {
  const доступ = авторизован(req)
  if (!доступ.ok) {
    console.warn(`[care tick] запрос отклонён: ${доступ.причина}`)
    return NextResponse.json({ ok: false }, { status: доступ.код })
  }

  const началоМс = Date.now()
  const воркер = имяВоркера()
  const итог = { взято: 0, сделано: 0, ошибок: 0, отложено: 0, пропущено: 0, прибрано: 0 }

  // Уборка идёт до заданий и не зависит от очереди: поручения помощника в ней
  // не лежат, а оборваться они могут ровно так же. Падение уборки не должно
  // мешать работе — это гигиена, а не работа.
  try {
    const уборка = await закрытьЗависшие()
    итог.прибрано = уборка.закрыто
    for (const п of уборка.причины) console.warn(`[care tick] ${п}`)
  } catch (err) {
    console.error('[care tick] уборка не прошла:', err)
  }

  let задания: Задание[]
  try {
    задания = await взятьЗадания(воркер, ЗАДАНИЙ_ЗА_ТИК)
  } catch (err) {
    console.error('[care tick] очередь недоступна:', err)
    return NextResponse.json({ ok: false, error: 'очередь недоступна' }, { status: 503 })
  }

  итог.взято = задания.length

  for (const задание of задания) {
    // Время вышло — остальное возвращаем в очередь сразу, не начиная.
    // Начать и быть оборванным хуже: задание провисит до истечения аренды.
    if (Date.now() - началоМс > БЮДЖЕТ_МС) {
      await закрытьЗадание(задание.id, воркер, false, {}, 'время тика вышло до начала работы')
        .catch((e) => console.error('[care tick] не вернулось в очередь:', e))
      итог.отложено += 1
      continue
    }

    const обработчик = ОБРАБОТЧИКИ[задание.kind]
    if (!обработчик) {
      // Неизвестный вид — не ошибка воркера, а задание из будущего этапа.
      // Закрываем как неуспешное с внятной причиной, повторять бессмысленно.
      await закрытьЗадание(задание.id, воркер, false, {}, `нет обработчика для вида «${задание.kind}»`)
        .catch((e) => console.error('[care tick] не закрыто:', e))
      итог.пропущено += 1
      continue
    }

    try {
      const результат = await обработчик(задание, воркер)
      const принят = await закрытьЗадание(задание.id, воркер, true, результат)
      if (принят) итог.сделано += 1
      // принят === false означает, что аренда истекла и задание отобрали.
      // Это не наша ошибка и не успех — просто наш результат опоздал.
      else итог.отложено += 1
    } catch (err) {
      const текст = err instanceof Error ? err.message : String(err)
      // Прогресс сохраняем даже при ошибке: следующая попытка начнёт не с нуля.
      await сохранитьПрогресс(задание.id, воркер, { last_failure: текст }).catch(() => {})
      await закрытьЗадание(задание.id, воркер, false, {}, текст)
        .catch((e) => console.error('[care tick] не закрыто после ошибки:', e))
      итог.ошибок += 1
    }
  }

  return NextResponse.json({ ok: true, воркер, мс: Date.now() - началоМс, ...итог })
}
