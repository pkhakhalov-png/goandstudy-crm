'use client'

/**
 * Панель помощника.
 *
 * Чего здесь нет намеренно (раздел 1.2 дизайн-документа): аватара, имени,
 * эмодзи, речи от первого лица. Это инструмент, а не собеседник.
 *
 * ПРО «ДУМАЕТ». Анимация хода работы — не «печатает…»: там выдуманная
 * человечность, здесь настоящие шаги. «Ищу программы в вебе» появляется тогда,
 * когда вызван поиск, и ровно столько раз, сколько он вызван. Куратор ждёт
 * полторы минуты и должен видеть, работает помощник или завис; строка «идёт
 * работа», которая не меняется девяносто секунд, не отличима от зависшей.
 *
 * ПРО ПЕРЕЗАГРУЗКУ. Разговор живёт в базе, а не в этом компоненте. Панель
 * спрашивает состояние по номеру поручения, поэтому обновление страницы,
 * закрытая вкладка и переход в другое дело работу не обрывают: вернулся —
 * видишь ход с того места, где он сейчас, или готовый ответ.
 *
 * Область ограничивается чипом рядом с полем ввода — «Все мои клиенты» или
 * конкретное дело. Это параметр запроса, а не текст в промпте: написать
 * «покажи всех» в поле ввода не расширит область, потому что инструменты
 * помощника её не принимают.
 */
import { useCallback, useEffect, useRef, useState } from 'react'
import {
  начатьВопрос,
  ходРазговоров,
  незаконченные,
  type Реплика as РепликаИзБазы,
  type ХодРазговора,
} from './assistant-actions'

type Реплика = {
  id: string
  вопрос: string
  статус: 'идёт' | 'готово' | 'сорвалось'
  шаги: string[]
  ответ: string | null
  долларов: number | null
}

function изИстории(история: РепликаИзБазы[]): Реплика[] {
  return история.map((р) => ({
    id: р.id,
    вопрос: р.вопрос,
    статус: 'готово' as const,
    шаги: [],
    ответ: р.ответ,
    долларов: р.долларов,
  }))
}

/** Как часто спрашивать состояние, пока хоть один разговор идёт. */
const ОПРОС_МС = 1500

export function AssistantPanel({
  caseId,
  областьПодпись,
  доступен,
  подсказки,
  история = [],
}: {
  caseId: string | null
  областьПодпись: string
  доступен: boolean
  подсказки: string[]
  /** Что уже спрашивали — чтобы разговор пережил обновление страницы. */
  история?: РепликаИзБазы[]
}) {
  const [диалог, установитьДиалог] = useState<Реплика[]>(() => изИстории(история))
  const [ввод, установитьВвод] = useState('')
  const [ошибка, установитьОшибку] = useState<string | null>(null)
  const [широко, установитьШирину] = useState(false)
  const низ = useRef<HTMLDivElement | null>(null)
  const поле = useRef<HTMLTextAreaElement | null>(null)

  const идущие = диалог.filter((р) => р.статус === 'идёт')
  // Строкой, а не массивом: массив новый на каждой отрисовке, и эффект ниже
  // пересоздавал бы опрос каждый раз, так ни разу до него и не дойдя.
  const ждущие = идущие.map((р) => р.id).join(',')

  const влить = useCallback((ходы: ХодРазговора[]) => {
    if (!ходы.length) return
    установитьДиалог((д) => {
      const по = new Map(д.map((р) => [р.id, р]))
      for (const х of ходы) по.set(х.id, х)
      return [...по.values()]
    })
  }, [])

  // Подхватываем работу, начатую до перезагрузки. Без этого обновление
  // страницы во время подбора показывало бы пустоту — а подбор идёт.
  useEffect(() => {
    if (!доступен) return
    let живо = true
    незаконченные(caseId).then((х) => {
      if (живо) влить(х)
    })
    return () => {
      живо = false
    }
  }, [caseId, доступен, влить])

  // Опрос идёт, только пока есть что ждать: лишний запрос раз в полторы
  // секунды в пустой панели — это запрос в базу на каждого открытого куратора.
  useEffect(() => {
    if (!ждущие) return
    const ждут = ждущие.split(',')
    const таймер = setInterval(() => {
      ходРазговоров(ждут).then(влить)
    }, ОПРОС_МС)
    return () => clearInterval(таймер)
  }, [ждущие, влить])

  useEffect(() => {
    низ.current?.scrollIntoView({ behavior: 'smooth', block: 'end' })
  }, [диалог])

  if (!доступен) {
    return (
      <div className="care-ai-panel">
        <div className="ds-label" style={{ marginBottom: 10 }}>
          <span className="care-ai-dot" />
          Помощник
        </div>
        <p style={{ fontSize: 13, color: 'var(--ds-muted)', margin: 0, lineHeight: 1.6 }}>
          Вам ещё не включён. Он умеет отвечать по данным дел: кто давно молчит, что
          горит, чего не хватает.
        </p>
      </div>
    )
  }

  const спросить = async (вопрос: string) => {
    const текст = вопрос.trim()
    if (!текст) return
    установитьОшибку(null)
    установитьВвод('')
    if (поле.current) поле.current.style.height = 'auto'

    const запуск = await начатьВопрос(текст, caseId)
    if (!запуск.ok) {
      установитьОшибку(запуск.ошибка)
      установитьВвод(текст)
      return
    }
    установитьДиалог((д) => [
      ...д,
      { id: запуск.id, вопрос: текст, статус: 'идёт', шаги: [], ответ: null, долларов: null },
    ])
  }

  return (
    <div className="care-ai-panel" data-wide={широко ? '1' : '0'}>
      <div className="care-ai-top">
        <div className="ds-label" style={{ margin: 0 }}>
          <span className="care-ai-dot" />
          Помощник
        </div>
        <span className="ds-chip ds-chip-neutral" style={{ fontSize: 11 }}>
          {областьПодпись}
        </span>
        <button
          type="button"
          className="care-ai-wide"
          onClick={() => установитьШирину((ш) => !ш)}
          title={широко ? 'Свернуть к колонке' : 'Развернуть пошире'}
          aria-label={широко ? 'Свернуть панель' : 'Развернуть панель'}
        >
          {широко ? '⤡' : '⤢'}
        </button>
      </div>

      <div className="care-ai-lenta">
        {диалог.length === 0 && (
          <p className="care-ai-пусто">
            Отвечает по данным ваших дел и переписки. Что скажете — сделает: «утверждаем
            Францию», «закрой задачу про диплом», «добавь TU Dortmund», «перенеси срок на
            пятницу». Соберёт подборку и напишет стратегию. Отправить что-либо клиенту
            он не может.
          </p>
        )}

        {диалог.map((р) => (
          <div key={р.id} className="care-ai-пара">
            <div className="care-ai-вопрос">{р.вопрос}</div>

            {р.статус === 'идёт' ? (
              <Progress шаги={р.шаги} />
            ) : (
              <div className="care-ai-ответ" data-сорвалось={р.статус === 'сорвалось' ? '1' : '0'}>
                {р.ответ}
                {р.долларов != null && (
                  <div className="care-ai-цена">
                    {/* Расход показывается человеку, а не только пишется в базу:
                        цену вопроса видно до того, как она станет строкой в отчёте. */}
                    {р.долларов < 0.01 ? 'меньше цента' : `${р.долларов.toFixed(2)} $`}
                  </div>
                )}
              </div>
            )}
          </div>
        ))}

        <div ref={низ} />
      </div>

      {ошибка && <p className="care-ai-беда">{ошибка}</p>}

      {диалог.length === 0 && подсказки.length > 0 && (
        <div className="care-ai-подсказки">
          {подсказки.map((п) => (
            <button key={п} className="ds-btn ds-btn-ghost ds-btn-sm" onClick={() => спросить(п)}>
              {п}
            </button>
          ))}
        </div>
      )}

      <form
        className="care-ai-форма"
        onSubmit={(e) => {
          e.preventDefault()
          спросить(ввод)
        }}
      >
        <textarea
          ref={поле}
          className="care-ai-поле"
          placeholder="Спросить или поручить"
          rows={1}
          value={ввод}
          onChange={(e) => {
            установитьВвод(e.target.value)
            // Поле растёт под текст: поручение в три строки не должно
            // набираться в щель высотой в одну.
            e.target.style.height = 'auto'
            e.target.style.height = `${Math.min(e.target.scrollHeight, 180)}px`
          }}
          onKeyDown={(e) => {
            // Enter отправляет, Shift+Enter — перенос строки. Так во всех
            // чатах, и рука уже знает.
            if (e.key === 'Enter' && !e.shiftKey) {
              e.preventDefault()
              спросить(ввод)
            }
          }}
        />
        <button
          className="care-ai-отправить"
          type="submit"
          disabled={!ввод.trim()}
          aria-label="Отправить"
        >
          ↑
        </button>
      </form>

      {/* Новый вопрос можно задать, не дожидаясь прошлого: работа идёт на
          сервере, и ждать её, глядя в заблокированное поле, незачем. */}
      {идущие.length > 0 && (
        <div className="care-ai-внизу">
          {идущие.length === 1 ? 'Один ответ готовится' : `${идущие.length} ответа готовятся`} ·
          можно спрашивать дальше
        </div>
      )}
    </div>
  )
}

/**
 * Ход работы.
 *
 * Последний шаг — крупно и с бегущим бликом, предыдущие — тускло и мелко. Так
 * видно и то, на чём помощник сейчас, и то, что он уже прошёл: подбор с
 * проверкой требований идёт полторы минуты, и эти полторы минуты должны
 * выглядеть как работа, а не как зависание.
 */
// Имя латиницей: правило react-hooks/rules-of-hooks считает компонентом
// только то, что начинается с заглавной латинской буквы, и кириллическое имя
// отвергает вместе с хуками внутри.
function Progress({ шаги }: { шаги: string[] }) {
  const [секунд, установитьСекунды] = useState(0)

  useEffect(() => {
    const т = setInterval(() => установитьСекунды((с) => с + 1), 1000)
    return () => clearInterval(т)
  }, [])

  const последний = шаги[шаги.length - 1]
  const прежние = шаги.slice(0, -1).slice(-3)

  return (
    <div className="care-ai-ход">
      {прежние.map((ш, и) => (
        <div key={и} className="care-ai-шаг-было">
          ✓ {ш}
        </div>
      ))}
      <div className="care-ai-шаг">
        <span className="care-ai-пульс" aria-hidden />
        <span className="care-ai-блик">{последний ?? 'думаю'}</span>
        <span className="care-ai-таймер">{секунд} с</span>
      </div>
    </div>
  )
}
