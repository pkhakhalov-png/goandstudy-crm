'use client'

/**
 * Профиль клиента компактной сеткой.
 *
 * ЧТО БЫЛО НЕ ТАК. Одиннадцать фактов занимали два экрана: у каждого своя
 * строка со значением, зелёной подписью «подтверждено» и цитатой. Чтобы
 * добраться до работы, куратор пролистывал анкету — а анкета меняется раз в
 * месяц и читается один раз.
 *
 * ПОЧЕМУ НЕТ «ПОДТВЕРЖДЕНО» У КАЖДОГО ЗНАЧЕНИЯ. Подтверждённое — это норма, а
 * норма не должна кричать. Когда зелёным помечено всё, зелёное перестаёт
 * значить что-либо, и неподтверждённое теряется среди него. Теперь наоборот:
 * нормальное выглядит нейтрально, а отмечено только то, с чем надо что-то
 * делать.
 *
 * ПОЧЕМУ ЦИТАТА ПО ЗАПРОСУ. Она нужна, когда значению не веришь, — то есть
 * редко и по одному полю. Постоянно открытая, она превращает сетку обратно в
 * анкету. Первоисточник остаётся в двух нажатиях: «источник» → цитата.
 *
 * ЧТО ОСТАЁТСЯ ВИДНЫМ ВСЕГДА. Неподтверждённое и намерение. Это не украшение
 * статуса, а разница между «клиент решил» и «клиент подумывает»: по первому
 * собирают подборку, по второму нельзя.
 */
import { useState } from 'react'

export type Пара = {
  id: string
  имя: string
  значение: string
  период: string | null
  цитата: string | null
  подтверждён: boolean
  намерение: boolean
}

export function FactGrid({ пары, действия }: { пары: Пара[]; действия?: Record<string, React.ReactNode> }) {
  const [открыт, открыть] = useState<string | null>(null)

  if (!пары.length) {
    return (
      <p style={{ fontSize: 13, color: 'var(--ds-muted)', margin: 0 }}>
        Пока ничего не записано. Сведения появятся, когда помощник разберёт встречу.
      </p>
    )
  }

  return (
    <div className="care-профиль">
      {пары.map((п) => (
        <div key={п.id} className="care-пара">
          <div className="care-пара-имя">
            {п.имя}
            {п.период ? ` · ${п.период}` : ''}
          </div>

          <div className="care-пара-знач">
            {п.значение}
            {/* Не подтверждено и намерение — видны всегда: по ним принимают
                другие решения, чем по подтверждённому факту. */}
            {!п.подтверждён && (
              <span className="ds-chip ds-chip-neutral" style={{ marginLeft: 8, fontSize: 11 }}>
                не подтверждено
              </span>
            )}
            {п.намерение && (
              <span className="ds-chip ds-chip-warning" style={{ marginLeft: 8, fontSize: 11 }}>
                намерение
              </span>
            )}
          </div>

          {п.цитата && (
            <button
              type="button"
              className="care-пара-ещё"
              onClick={() => открыть(открыт === п.id ? null : п.id)}
              aria-expanded={открыт === п.id}
            >
              {открыт === п.id ? 'скрыть источник' : 'источник'}
            </button>
          )}
          {открыт === п.id && п.цитата && <div className="care-пара-цитата">«{п.цитата}»</div>}

          {действия?.[п.id]}
        </div>
      ))}
    </div>
  )
}
