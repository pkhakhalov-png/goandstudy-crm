/**
 * Переменные окружения контура care.
 *
 * Зачем отдельный файл. Обращение вида `process.env.CARE_DB_KEY!` с
 * восклицательным знаком обманывает: если переменной нет, до ошибки дойдёт не
 * здесь, а глубоко внутри клиента базы, и в журнале окажется «Invalid API key»
 * вместо «не задан CARE_DB_KEY». Разница в том, сколько времени займёт
 * разобраться — минуту или час.
 *
 * Переменные намеренно не имеют значений по умолчанию. Умолчание для секрета
 * означает, что забытая переменная не мешает запуску, а тихо делает проверку
 * бессмысленной.
 */

/** Обязательная переменная. Нет — исключение с внятным текстом. */
export function требуется(имя: string): string {
  const значение = process.env[имя]
  if (!значение || !значение.trim()) {
    throw new Error(
      `Не задана переменная ${имя}. Контур care без неё не работает. ` +
        `Окружение Preview в Vercel, scope — ветка feat/curator-v2.`
    )
  }
  return значение.trim()
}

/** Необязательная переменная: null вместо пустой строки, чтобы проверять одним способом. */
export function необязательна(имя: string): string | null {
  const значение = process.env[имя]
  return значение && значение.trim() ? значение.trim() : null
}

/**
 * Готов ли контур принимать запросы.
 *
 * Возвращает список недостающего, а не первое недостающее: владелец заводит
 * переменные пачкой, и узнавать о них по одной за деплой — потерянный день.
 */
export function чегоНеХватает(имена: string[]): string[] {
  return имена.filter((имя) => {
    const значение = process.env[имя]
    return !значение || !значение.trim()
  })
}

