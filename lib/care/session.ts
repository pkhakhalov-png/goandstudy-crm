/**
 * Кто смотрит кабинет v2.
 *
 * Собирает в одном месте три вопроса, на которые нужен ответ каждой странице:
 * кто это, заведён ли он в контуре и открыт ли ему интерфейс. Обёрнуто в
 * `cache` из React — оболочка раздела и сама страница рисуются в одном
 * запросе, и без этого каждая задавала бы те же вопросы базе заново.
 *
 * Кеш живёт ровно один запрос. Между запросами не сохраняется ничего: это
 * защита от повторного вопроса, а не кеш данных.
 */
import { cache } from 'react'
import { viewer } from '@/lib/auth/viewer'
import { участникПоПользователю, type Участник } from './access'
import { флагВключён } from './flags'

export type СессияКонтура = {
  userId: string
  имя: string | null
  рольCRM: string | null
  участник: Участник | null
  интерфейсОткрыт: boolean
}

export const сессияКонтура = cache(async (): Promise<СессияКонтура | null> => {
  const { user, profile } = await viewer()
  if (!user) return null

  const участник = await участникПоПользователю(user.id)

  // Флаг спрашиваем по сотруднику контура. Нет записи в контуре — нет и
  // флага: включать интерфейс тому, у кого нет дел, нечему.
  const интерфейсОткрыт = участник
    ? await флагВключён('ui', { memberId: участник.id })
    : false

  return {
    userId: user.id,
    имя: profile?.name ?? null,
    рольCRM: profile?.role ?? null,
    участник,
    интерфейсОткрыт,
  }
})
