/**
 * Уборка за умершими: поручения, которые навсегда остались «идёт».
 *
 * ОТКУДА ОНИ БЕРУТСЯ. Работа помощника идёт после ответа браузеру, вне
 * запроса. Её может оборвать что угодно, о чём некому сообщить: предел времени
 * функции, выкладка новой версии, падение площадки. Поручение при этом остаётся
 * со статусом «идёт» — и так навсегда.
 *
 * ЧЕМ ЭТО ПЛОХО. Панель крутит ход работы над мёртвым разговором: куратор ждёт
 * ответ, которого не будет, и не узнаёт об этом, пока не устанет ждать. Хуже
 * того, он спросит заново — и заплатит второй раз за то, что уже оплачено.
 *
 * ПОЧЕМУ ПЯТНАДЦАТЬ МИНУТ. Самый долгий настоящий разговор — подбор с проверкой
 * требований — укладывается в три. Пятнадцать выбраны с запасом: убить живую
 * работу хуже, чем лишние десять минут показывать её идущей. Граница должна
 * быть заведомо недостижимой для здоровой работы, иначе уборка сама станет
 * источником обрывов.
 *
 * ПОЧЕМУ В ТИКЕ, А НЕ ПРИ ОТКРЫТИИ ПАНЕЛИ. При открытии убрались бы только те,
 * на чьё дело кто-то зашёл. Остальные висели бы в журнале и в расходах как
 * незавершённые — и считались бы работой, которой не было.
 *
 * ВТОРАЯ УБОРКА — ЗАДАНИЯ, УПАВШИЕ ДО ПОЯВЛЕНИЯ ОБРАБОТЧИКА. Расписание в базе
 * обновляется миграцией, а код — выкладкой, и между ними проходят минуты. В
 * этот промежуток задание нового вида падает трижды с «нет обработчика» и
 * остаётся `failed` навсегда, хотя через десять минут то же самое проходит.
 * Один такой труп уже закрывали миграцией 024 — но это повторяется при каждом
 * новом виде работы, значит закрывать надо правилом, а не разовой правкой.
 */
import { базаCare } from '../db'

/** Сколько поручение может честно идти, прежде чем считать его мёртвым. */
const ПРЕДЕЛ_МИНУТ = 15

export const ПРИЧИНА_ОБРЫВА =
  'Работа оборвалась — сервер перезапустился или истекло время. Спросите заново.'

/**
 * Закрыть падения «нет обработчика» по видам, которые код уже умеет.
 *
 * Условие именно такое: вид должен быть в списке обработчиков **сейчас**. Если
 * обработчика по-прежнему нет, задание остаётся красным — это настоящая
 * недоделка, и прятать её нельзя.
 */
export async function закрытьДогнанные(известныеВиды: string[]): Promise<{
  закрыто: number
  причины: string[]
}> {
  if (!известныеВиды.length) return { закрыто: 0, причины: [] }

  const { data, error } = await базаCare()
    .from('jobs')
    .update({
      status: 'cancelled',
      last_error: 'закрыто уборкой: обработчик появился позже, задание устарело',
    })
    .eq('status', 'failed')
    .in('kind', известныеВиды)
    .like('last_error', 'нет обработчика для вида%')
    .select('id, kind')

  if (error) return { закрыто: 0, причины: [`уборка догнанных не прошла: ${error.message}`] }

  const закрыто = (data ?? []).length
  return {
    закрыто,
    причины: закрыто
      ? [`закрыто падений «нет обработчика», которые код уже догнал: ${закрыто}`]
      : [],
  }
}

export async function закрытьЗависшие(пределМинут = ПРЕДЕЛ_МИНУТ): Promise<{
  закрыто: number
  причины: string[]
}> {
  const граница = new Date(Date.now() - пределМинут * 60_000).toISOString()

  const { data, error } = await базаCare()
    .from('assignments')
    .update({
      status: 'failed',
      // Ответ, а не только статус: панель показывает человеку текст, и «идёт»,
      // сменившееся на пустоту, читается как потерянный ответ.
      answer: ПРИЧИНА_ОБРЫВА,
    })
    .eq('status', 'running')
    .lt('created_at', граница)
    .select('id')

  if (error) return { закрыто: 0, причины: [`уборка не прошла: ${error.message}`] }

  const закрыто = (data ?? []).length
  return {
    закрыто,
    // Молча закрывать не годится: если такое начнёт случаться часто, это
    // видно только отсюда — в журнале останутся отдельные записи, а не
    // закономерность.
    причины: закрыто ? [`закрыто зависших поручений: ${закрыто}`] : [],
  }
}
