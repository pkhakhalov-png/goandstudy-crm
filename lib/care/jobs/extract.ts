/**
 * Разбор переписки в факты — задание очереди.
 *
 * Читает то, что пришло с прошлого разбора, отдаёт модели, складывает
 * проверенные факты **черновиками** и отмечает, до какого момента прочитано.
 *
 * ПОЧЕМУ ЧЕРНОВИКАМИ И НИКАК ИНАЧЕ. Извлечение ошибается не грубо и не всегда,
 * а тихо и иногда: перепутает бюджет родителя с бюджетом на год, примет
 * «хотелось бы» за решение. Такие ошибки ловятся только глазами человека,
 * который знает клиента. Автоматически подтверждать нечего — даже когда
 * цитата на месте и всё выглядит очевидным.
 *
 * ЧТО ДЕЛАЕМ С РАСХОЖДЕНИЕМ. Если по полю уже есть подтверждённый факт с
 * другим значением, черновик не просто ложится рядом: заводится запись в
 * `care.fact_conflicts` и предложение `kind = 'fact_update'`. Куратор видит
 * «было → стало» с обеими цитатами и решает. Молча положить рядом два
 * противоречащих факта — худшее из возможного: оба выглядят одинаково
 * настоящими.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Ни одного изменения в старой CRM и ни одного сообщения
 * наружу. Разбор переписки — операция чтения; всё, что он производит, это
 * строки на проверку человеку.
 */
import { базаCare } from '../db'
import { извлечьФакты, type Сообщение } from '../ai/extract'
import { можноТратить, записатьРасход } from '../ai/budget'
import { клиентыПоId } from '../cases'

/** Сколько сообщений отдаём модели за один разбор. */
const СООБЩЕНИЙ_ЗА_РАЗ = 200

export type ИтогРазбора = {
  дел: number
  фактов: number
  конфликтов: number
  отброшено: number
  долларов: number
  причины: string[]
}

/**
 * Разобрать переписку всех дел, где появилось что-то новое.
 *
 * `толькоДело` ограничивает разбор одним делом — так его зовут из кабинета,
 * когда куратор нажал «разобрать переписку» по конкретному человеку.
 */
export async function разобратьПереписку(толькоДело?: string): Promise<ИтогРазбора> {
  const итог: ИтогРазбора = { дел: 0, фактов: 0, конфликтов: 0, отброшено: 0, долларов: 0, причины: [] }

  const потолок = await можноТратить('extraction')
  if (!потолок.можно) {
    итог.причины.push(потолок.почему)
    return итог
  }

  let запрос = базаCare()
    .from('cases')
    .select('id, client_id, is_synthetic, synthetic_name, facts_extracted_at')
    .eq('automation_owner', 'v2')
    .eq('status', 'active')
  if (толькоДело) запрос = запрос.eq('id', толькоДело)

  const { data: дела, error } = await запрос
  if (error) {
    итог.причины.push(`не удалось прочитать дела: ${error.message}`)
    return итог
  }
  if (!дела?.length) {
    итог.причины.push('нет дел на v2')
    return итог
  }

  const имена = await клиентыПоId(дела.filter((д) => !д.is_synthetic).map((д) => д.client_id))

  for (const дело of дела) {
    // Потолок проверяем перед каждым делом, а не один раз на прогон: разбор
    // стоит около десяти центов, и десяток дел подряд способен упереться в
    // него по дороге.
    const осталось = await можноТратить('extraction')
    if (!осталось.можно) {
      итог.причины.push(`остановились на середине: ${осталось.почему}`)
      break
    }

    let сообщения = базаCare()
      .from('case_messages')
      .select('message_id, created_at, sender_name, content')
      .eq('case_id', дело.id)
      .order('created_at')
      .limit(СООБЩЕНИЙ_ЗА_РАЗ)
    if (дело.facts_extracted_at) сообщения = сообщения.gt('created_at', дело.facts_extracted_at)

    const { data: список } = await сообщения
    if (!список?.length) continue

    const клиент = дело.is_synthetic
      ? (дело.synthetic_name ?? 'тестовое дело')
      : (имена.get(дело.client_id) ?? `клиент #${дело.client_id}`)

    const разбор = await извлечьФакты(список as Сообщение[], клиент)

    if (разбор.расход) {
      await записатьРасход('extraction', разбор.расход, {
        caseId: дело.id,
        пометка: `разбор переписки, ${список.length} сообщ.`,
      })
      итог.долларов += разбор.расход.долларов
    }

    if (разбор.ошибка) {
      итог.причины.push(`${клиент}: ${разбор.ошибка}`)
      continue
    }

    итог.дел += 1
    итог.отброшено += разбор.отброшено.length

    for (const { факт, messageId } of разбор.факты) {
      const записано = await записатьФакт(дело.id, факт, messageId)
      if (записано === 'новый') итог.фактов += 1
      if (записано === 'конфликт') {
        итог.фактов += 1
        итог.конфликтов += 1
      }
    }

    // Отметку ставим по последнему прочитанному сообщению, а не по «сейчас»:
    // между чтением и записью могли прийти новые, и они не должны молча
    // считаться разобранными.
    const последнее = список[список.length - 1].created_at
    await базаCare().from('cases').update({ facts_extracted_at: последнее }).eq('id', дело.id)
  }

  return итог
}

type Исход = 'новый' | 'конфликт' | 'уже было'

/**
 * Положить один факт — с оглядкой на то, что по этому полю уже известно.
 *
 * Три случая, и в каждом своё поведение:
 *   · такого значения по этому полю ещё не заводили — кладём черновик;
 *   · ровно это уже есть (хоть черновиком, хоть подтверждённым, хоть
 *     отклонённым) — молчим. Повторно предлагать отклонённое значит спорить
 *     с человеком, который уже ответил;
 *   · есть подтверждённое, но другое — черновик плюс конфликт плюс
 *     предложение. Это единственный случай, где куратора зовут явно.
 */
async function записатьФакт(
  caseId: string,
  факт: { field: string; value: string | number; currency?: string | null; period?: string | null; speaker: string; quote: string; is_plan: boolean },
  messageId: string
): Promise<Исход> {
  const { data: было } = await базаCare()
    .from('facts')
    .select('id, value, status')
    .eq('case_id', caseId)
    .eq('field', факт.field)

  const тоЖе = (было ?? []).find(
    (ф) => String(ф.value) === String(факт.value) && ф.status !== 'superseded'
  )
  if (тоЖе) return 'уже было'

  const подтверждённый = (было ?? []).find((ф) => ф.status === 'confirmed')

  // Источник — конкретное сообщение, а не «переписка вообще». Цитата без
  // точного адреса проверяется пересказом, то есть не проверяется.
  const { data: источник } = await базаCare()
    .from('sources')
    .insert({
      case_id: caseId,
      kind: 'message',
      ref: { message_id: messageId },
      note: 'разбор переписки помощником',
    })
    .select('id')
    .single()

  const { data: новый, error } = await базаCare()
    .from('facts')
    .insert({
      case_id: caseId,
      field: факт.field,
      value: факт.value,
      currency: факт.currency ?? null,
      period: факт.period ?? null,
      is_plan: факт.is_plan,
      speaker: факт.speaker,
      quote: факт.quote,
      source_id: источник?.id ?? null,
      status: 'draft',
    })
    .select('id')
    .single()

  if (error || !новый) {
    console.warn('[care разбор] факт не записан:', error?.message)
    return 'уже было'
  }

  if (!подтверждённый) return 'новый'

  await базаCare().from('fact_conflicts').insert({
    case_id: caseId,
    field: факт.field,
    fact_a: подтверждённый.id,
    fact_b: новый.id,
  })

  await базаCare().from('proposals').insert({
    case_id: caseId,
    kind: 'fact_update',
    payload: {
      field: факт.field,
      было: подтверждённый.value,
      стало: факт.value,
      цитата: факт.quote,
      источник_сообщение: messageId,
    },
    payload_hash: `${факт.field}:${факт.value}`.slice(0, 32),
    data_version: String(подтверждённый.id),
    status: 'pending',
  })

  return 'конфликт'
}
