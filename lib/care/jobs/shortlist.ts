/**
 * Подборка программ по делу — от фактов до строк на проверку куратору.
 *
 * ТРИ СЛОЯ, КАК В ПЛАНЕ, И ПОРЯДОК ВАЖЕН:
 *
 *   1. **Кандидаты.** По базе вузов, если по этой стране в ней есть что искать,
 *      и веб-поиском, если нет. Отбор механический, модель здесь ничего не
 *      решает — она не должна придумывать вуз, которого не существует.
 *   2. **Применимость.** Сверка с подтверждёнными фактами клиента: бюджет,
 *      уровень, страна. Считается кодом, а не моделью.
 *   3. **Объяснение.** Модель пишет, почему программа подходит именно этому
 *      человеку, — по уже посчитанному, а не вместо счёта.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Процентов соответствия: они создают уверенность, которой у
 * нас нет. Вместо них у каждой строки список «что проверить» — и он честно
 * непустой, потому что требования к поступающим ни в одной нашей базе не лежат.
 *
 * Всё ложится в `care.shortlists` со статусом `curator_review`. Клиенту ничего
 * не уходит: подборку отдаёт куратор, руками, и это записано в плане как
 * временное устройство пилота.
 */
import { базаCare, базаPublic } from '../db'
import { искатьПрограммы, уровеньПоНазванию } from '../programs'
import { искатьВВебе, type НайденнаяПрограмма } from '../ai/search'
import { можноТратить, записатьРасход } from '../ai/budget'
import { подписьПоля, подписьЗначения } from '../labels'

/** Страны, по которым в базе парсера лежат настоящие программы, а не категории. */
const СТРАНЫ_В_БАЗЕ = new Set(['us', 'gb', 'ca', 'ae', 'au'])

export type ИтогПодборки = {
  shortlistId: string | null
  программ: number
  откуда: 'база' | 'веб' | 'пусто'
  долларов: number
  причины: string[]
}

/**
 * Собрать подборку по делу.
 *
 * Возвращает причины отказа словами: «подбор не вышел» без объяснения
 * заставляет куратора гадать, а он и так пришёл сюда не от хорошей жизни.
 */
export async function собратьПодборку(caseId: string): Promise<ИтогПодборки> {
  const итог: ИтогПодборки = { shortlistId: null, программ: 0, откуда: 'пусто', долларов: 0, причины: [] }

  const { data: дело } = await базаCare()
    .from('cases')
    .select('id, client_id, is_synthetic, synthetic_name, intake_year')
    .eq('id', caseId)
    .maybeSingle()
  if (!дело) {
    итог.причины.push('дело не найдено')
    return итог
  }

  const { data: факты } = await базаCare()
    .from('facts')
    .select('field, value, currency, is_plan, status')
    .eq('case_id', caseId)
    .eq('status', 'confirmed')

  const поПолю = new Map((факты ?? []).map((ф) => [ф.field as string, ф]))
  const страна = String(поПолю.get('country.target')?.value ?? '').trim()
  const направление = String(поПолю.get('program.field')?.value ?? '').trim()
  const уровеньТекст = String(поПолю.get('education.level_target')?.value ?? '').trim()
  const бюджетФакт = поПолю.get('budget.tuition.max')
  const бюджет = бюджетФакт ? Number(бюджетФакт.value) : null
  const валюта = (бюджетФакт?.currency as string | null) ?? null

  // Без страны и направления подбор — это гадание. Лучше сказать, чего не
  // хватает, чем принести список наугад: его всё равно выбросят, но сначала
  // потратят на него полчаса.
  const нет: string[] = []
  if (!страна) нет.push('страна')
  if (!направление) нет.push('направление')
  if (нет.length) {
    итог.причины.push(`не подтверждено: ${нет.join(', ')} — подбирать не по чему`)
    return итог
  }

  const оКлиенте: Record<string, string> = {}
  for (const ф of факты ?? []) {
    if (ф.is_plan) continue
    const значение = подписьЗначения(ф.field as string, ф.value)
    оКлиенте[подписьПоля(ф.field as string)] = ф.currency ? `${значение} ${ф.currency}` : значение
  }

  const коды = кодыСтран(страна)
  const изБазы = коды.some((к) => СТРАНЫ_В_БАЗЕ.has(к))

  let строки: СтрокаПодборки[] = []

  if (изБазы) {
    const найдено = await искатьПрограммы({
      страны: коды,
      бюджет,
      направление: первоеСлово(направление),
      уровень: уровеньИзТекста(уровеньТекст),
      сколько: 10,
    })
    строки = найдено.программы.map((п) => ({
      вуз: п.вуз,
      программа: п.название,
      страна: п.страна ?? страна,
      город: п.город,
      стоимость: п.стоимость,
      валюта: п.валюта ?? валюта,
      ссылка: п.ссылка,
      почему: `${п.уровень === 'неизвестно' ? 'Уровень на странице не указан' : `Уровень: ${п.уровень} (определён по названию)`}.`,
      проверить: найдено.непроверено,
    }))
    итог.откуда = 'база'
    if (!строки.length) итог.причины.push('в базе вузов по этому запросу ничего не нашлось')
  }

  // Веб-поиск: либо страна не покрыта базой, либо база ничего не дала.
  if (!строки.length) {
    const потолок = await можноТратить('research')
    if (!потолок.можно) {
      итог.причины.push(потолок.почему)
      return итог
    }

    const поиск = await искатьВВебе({
      страны: страна,
      направление,
      уровень: уровеньТекст || 'не указан',
      бюджетВГод: бюджет ? `до ${бюджет} ${валюта ?? ''}`.trim() : 'не указан',
      оКлиенте,
      сколько: 8,
    })

    if (поиск.расход) {
      await записатьРасход('research', поиск.расход, { caseId, пометка: 'подбор программ' })
      итог.долларов += поиск.расход.долларов
    }
    if (поиск.ошибка) {
      итог.причины.push(`поиск не прошёл: ${поиск.ошибка}`)
      return итог
    }
    for (const о of поиск.отброшено) итог.причины.push(`отброшено «${о.программа}»: ${о.почему}`)

    строки = поиск.программы.map((п: НайденнаяПрограмма) => ({
      вуз: п.вуз,
      программа: п.программа,
      страна: п.страна,
      город: п.город,
      стоимость: п.стоимость_в_год,
      валюта: п.валюта ?? валюта,
      ссылка: п.ссылка,
      почему: п.почему_подходит,
      проверить: п.что_проверить.length ? п.что_проверить : ['требования к поступающим не проверены'],
    }))
    итог.откуда = 'веб'
  }

  if (!строки.length) {
    итог.причины.push('ничего не нашлось — стоит пересмотреть бюджет или страну')
    return итог
  }

  // Бюджет — второй слой: сверка уже найденного с подтверждённым фактом.
  // Дороже бюджета не выбрасываем, а помечаем: иногда разница в двести евро,
  // и решает это человек, а не мы.
  for (const с of строки) {
    if (бюджет && с.стоимость != null && с.стоимость > бюджет) {
      с.проверить = [`дороже бюджета: ${с.стоимость} ${с.валюта ?? ''} против ${бюджет} ${валюта ?? ''}`.trim(), ...с.проверить]
    }
  }

  const { data: прежние } = await базаCare()
    .from('shortlists')
    .select('version')
    .eq('case_id', caseId)
    .order('version', { ascending: false })
    .limit(1)
  const версия = ((прежние ?? [])[0]?.version ?? 0) + 1

  const { data: подборка, error } = await базаCare()
    .from('shortlists')
    .insert({ case_id: caseId, version: версия, status: 'curator_review' })
    .select('id')
    .single()

  if (error || !подборка) {
    итог.причины.push(`подборка не записалась: ${error?.message}`)
    return итог
  }

  const { error: ошибкаСтрок } = await базаCare().from('shortlist_items').insert(
    строки.map((с, i) => ({
      shortlist_id: подборка.id,
      program_ref: {
        вуз: с.вуз,
        программа: с.программа,
        страна: с.страна,
        город: с.город,
        ссылка: с.ссылка,
        проверено: new Date().toISOString().slice(0, 10),
      },
      tuition_amount: с.стоимость,
      currency: с.валюта,
      fit_notes: { почему: с.почему },
      unresolved: с.проверить,
      position: i,
    }))
  )
  if (ошибкаСтрок) итог.причины.push(`строки не записались: ${ошибкаСтрок.message}`)

  await базаCare().from('events').insert({
    actor_kind: 'assistant',
    case_id: caseId,
    action: 'shortlist_built',
    after: { shortlist_id: подборка.id, программ: строки.length, откуда: итог.откуда },
    source: { job: 'lib/care/jobs/shortlist.ts' },
    reason: `подборка версии ${версия}`,
  })

  итог.shortlistId = подборка.id
  итог.программ = строки.length
  return итог
}

type СтрокаПодборки = {
  вуз: string
  программа: string
  страна: string
  город: string | null
  стоимость: number | null
  валюта: string | null
  ссылка: string | null
  почему: string
  проверить: string[]
}

/** Коды стран из того, как страну записал куратор: «Европа», «Германия, Италия». */
export function кодыСтран(текст: string): string[] {
  const т = текст.toLowerCase()
  const словарь: Record<string, string> = {
    герман: 'de', австри: 'at', чехи: 'cz', итали: 'it', испан: 'es', венгри: 'hu',
    франц: 'fr', нидерланд: 'nl', польш: 'pl', португал: 'pt',
    сша: 'us', америк: 'us', британ: 'gb', англи: 'gb', канад: 'ca',
    оаэ: 'ae', эмират: 'ae', кипр: 'cy', коре: 'kr', австрал: 'au',
  }
  const коды = new Set<string>()
  for (const [ключ, код] of Object.entries(словарь)) if (т.includes(ключ)) коды.add(код)
  // «Европа» и «ЕС» без уточнения — берём те страны, куда возят чаще всего.
  if (!коды.size && /европ|\bес\b|\beu\b/.test(т)) ['de', 'at', 'it', 'es', 'hu', 'cz'].forEach((к) => коды.add(к))
  return [...коды]
}

function первоеСлово(направление: string): string {
  return направление.split(/[,/]|\s+и\s+/)[0].trim().slice(0, 24)
}

function уровеньИзТекста(текст: string): ReturnType<typeof уровеньПоНазванию> | null {
  const т = текст.toLowerCase()
  if (/магистр|master/.test(т)) return 'магистратура'
  if (/бакалавр|bachelor/.test(т)) return 'бакалавриат'
  return null
}

/** Клиент по делу — для подписи в интерфейсе. Вынесено, чтобы не дублировать. */
export async function имяКлиентаДела(caseId: string): Promise<string> {
  const { data: дело } = await базаCare()
    .from('cases')
    .select('client_id, is_synthetic, synthetic_name')
    .eq('id', caseId)
    .maybeSingle()
  if (!дело) return 'дело не найдено'
  if (дело.is_synthetic) return дело.synthetic_name ?? 'тестовое дело'
  const { data: клиент } = await базаPublic()
    .from('clients')
    .select('name')
    .eq('id', дело.client_id)
    .maybeSingle()
  return (клиент?.name as string | null) ?? `клиент #${дело.client_id}`
}
