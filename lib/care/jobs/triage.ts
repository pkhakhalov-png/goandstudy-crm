/**
 * Разбор входящих сообщений — задание очереди.
 *
 * ЧТО ДЕЛАЕТ. Берёт сообщения клиента, которых мы ещё не разбирали, спрашивает
 * модель, чем они были, и на вопросы и документы заводит задачи куратору.
 *
 * ПОЧЕМУ ЗАДАЧА, А НЕ ПОМЕТКА. Пометка «тут был вопрос» ничего не меняет: её
 * надо где-то увидеть. Задача попадает в список дел, в счётчик на странице и в
 * сводку «что горит» — то есть в места, куда куратор смотрит и так.
 *
 * ПОЧЕМУ ЗАДАЧА НА НАС, А НЕ НА КЛИЕНТА. `waiting_on = 'specialist'`: это мы
 * задолжали ответ. Поставь мы «ждём клиента» — по ней начали бы готовиться
 * напоминания, и человек получил бы напоминание о собственном вопросе.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Ответов клиенту. Модель говорит, что вопрос был, и приводит
 * слова; отвечает куратор. Отправлять наружу это задание не умеет вовсе.
 */
import { базаCare } from '../db'
import { разобратьСообщения, ПОДПИСЬ_ВИДА, type ВидСообщения } from '../ai/triage'
import type { Сообщение } from '../ai/extract'
import { можноТратить, записатьРасход } from '../ai/budget'
import { клиентыПоId } from '../cases'

/** Сколько сообщений отдаём модели за один разбор. */
const СООБЩЕНИЙ_ЗА_РАЗ = 100

/**
 * Как названы направления в `care.case_messages`.
 *
 * Именно так, а не `in`/`out`. Первая версия фильтровала по сокращённым, и
 * задание молча не находило ни одного сообщения: ошибки нет, работа есть,
 * результат ноль. Проверка ниже в `tests/care/triage.test.ts` спрашивает
 * значения у самой базы — чтобы разойтись второй раз было нельзя.
 */
const ВХОДЯЩЕЕ = 'incoming'
const ИСХОДЯЩЕЕ = 'outgoing'

/**
 * Сколько ждём ответа куратора, прежде чем считать вопрос неотвеченным.
 *
 * Куратор часто отвечает сразу, в ту же минуту. Заводить задачу на такой
 * вопрос — засыпать его работой, которую он уже сделал; а список дел, где
 * половина строк уже не нужна, перестают читать.
 */
const ОТВЕТИЛИ_В_ТЕЧЕНИЕ_МИНУТ = 30

export type ИтогРазбораВходящих = {
  дел: number
  сообщений: number
  вопросов: number
  документов: number
  задач: number
  отброшено: number
  долларов: number
  причины: string[]
}

/** Задачи заводим только на то, на что человек должен ответить. */
const ТРЕБУЕТ_ОТВЕТА: Record<ВидСообщения, boolean> = {
  question: true,
  document: true,
  terms: false,
  other: false,
}

function заголовокЗадачи(вид: ВидСообщения, оЧём: string): string {
  const начало = вид === 'question' ? 'Ответить' : 'Проверить присланное'
  return `${начало}: ${оЧём}`.slice(0, 180)
}

export async function разобратьВходящие(толькоДело?: string): Promise<ИтогРазбораВходящих> {
  const итог: ИтогРазбораВходящих = {
    дел: 0,
    сообщений: 0,
    вопросов: 0,
    документов: 0,
    задач: 0,
    отброшено: 0,
    долларов: 0,
    причины: [],
  }

  const потолок = await можноТратить('extraction')
  if (!потолок.можно) {
    итог.причины.push(потолок.почему)
    return итог
  }

  let запрос = базаCare()
    .from('cases')
    .select('id, client_id, is_synthetic, synthetic_name, owner_member_id, switched_at')
    .eq('automation_owner', 'v2')
    .eq('status', 'active')
  if (толькоДело) запрос = запрос.eq('id', толькоДело)

  const { data: дела, error } = await запрос
  if (error) {
    итог.причины.push(`не удалось прочитать дела: ${error.message}`)
    return итог
  }
  if (!дела?.length) {
    итог.причины.push('нет дел на v2')
    return итог
  }

  const имена = await клиентыПоId(дела.filter((д) => !д.is_synthetic).map((д) => д.client_id))

  for (const дело of дела) {
    const осталось = await можноТратить('extraction')
    if (!осталось.можно) {
      итог.причины.push(`остановились на середине: ${осталось.почему}`)
      break
    }

    // Только то, что пришло после передачи дела на новый кабинет. В переписке
    // лежат месяцы истории; завести сегодня задачу «Ответить» на вопрос,
    // заданный в июне и давно закрытый, значит засыпать куратора работой,
    // которой нет. Без даты передачи берём неделю — дальше вопрос либо
    // отвечен, либо уже не актуален.
    const граница =
      (дело.switched_at as string | null) ??
      new Date(Date.now() - 7 * 86_400_000).toISOString()

    const { data: все } = await базаCare()
      .from('case_messages')
      .select('message_id, created_at, sender_name, content, direction')
      .eq('case_id', дело.id)
      .gte('created_at', граница)
      .order('created_at', { ascending: false })
      .limit(СООБЩЕНИЙ_ЗА_РАЗ * 2)

    const входящие = (все ?? []).filter((с) => с.direction === ВХОДЯЩЕЕ)
    if (!входящие.length) continue

    // Уже разобранные пропускаем. Не ради экономии: без этого каждый прогон
    // заводил бы новую задачу на тот же вопрос.
    const { data: было } = await базаCare()
      .from('message_triage')
      .select('message_id')
      .eq('case_id', дело.id)
      .in('message_id', входящие.map((с) => с.message_id as string))

    const разобрано = new Set((было ?? []).map((с) => с.message_id as string))
    const новые = входящие.filter((с) => !разобрано.has(с.message_id as string)).slice(0, СООБЩЕНИЙ_ЗА_РАЗ)
    if (!новые.length) continue

    const клиент = дело.is_synthetic
      ? (дело.synthetic_name ?? 'тестовое дело')
      : (имена.get(дело.client_id)?.name ?? `клиент #${дело.client_id}`)

    const разбор = await разобратьСообщения(новые as Сообщение[], клиент)

    if (разбор.расход) {
      await записатьРасход('extraction', разбор.расход, {
        caseId: дело.id,
        пометка: `разбор входящих, ${новые.length} сообщ.`,
      })
      итог.долларов += разбор.расход.долларов
    }
    if (разбор.ошибка) {
      итог.причины.push(`${клиент}: ${разбор.ошибка}`)
      continue
    }

    итог.дел += 1
    итог.сообщений += новые.length
    итог.отброшено += разбор.отброшено.length
    for (const о of разбор.отброшено) итог.причины.push(`${клиент}: отброшено — ${о.почему}`)

    for (const р of разбор.разобрано) {
      const сообщение = новые.find((с) => с.message_id === р.messageId)
      if (!сообщение) continue

      if (р.вид === 'question') итог.вопросов += 1
      if (р.вид === 'document') итог.документов += 1

      let taskId: string | null = null

      if (ТРЕБУЕТ_ОТВЕТА[р.вид]) {
        // Куратор мог ответить сразу. Задача на отвеченный вопрос — мусор в
        // списке дел, а список, где половина строк не нужна, перестают читать.
        const порог = new Date(
          new Date(сообщение.created_at as string).getTime() + ОТВЕТИЛИ_В_ТЕЧЕНИЕ_МИНУТ * 60_000
        ).toISOString()
        const ответили = (все ?? []).some(
          (с) =>
            с.direction === ИСХОДЯЩЕЕ &&
            String(с.created_at) > String(сообщение.created_at) &&
            String(с.created_at) <= порог
        )

        if (!ответили) {
          const { data: задача } = await базаCare()
            .from('tasks')
            .insert({
              case_id: дело.id,
              title: заголовокЗадачи(р.вид, р.оЧём),
              // Точные слова в задаче: куратор отвечает, не открывая чат, и не
              // по нашему пересказу.
              details: `${ПОДПИСЬ_ВИДА[р.вид]}: «${р.цитата}»`,
              waiting_on: 'specialist',
              status: 'todo',
              // Срок — завтра. Без срока задача не попадает ни в «горит», ни в
              // сводку, то есть не отличается от пометки в углу.
              due_on: new Date(Date.now() + 86_400_000).toISOString().slice(0, 10),
              assignee_member_id: дело.owner_member_id,
            })
            .select('id')
            .single()

          taskId = (задача?.id as string) ?? null
          if (taskId) итог.задач += 1
        }
      }

      const { error: ошибка } = await базаCare().from('message_triage').insert({
        case_id: дело.id,
        message_id: р.messageId,
        kind: р.вид,
        about: р.оЧём,
        quote: р.цитата,
        task_id: taskId,
      })
      // Запись разбора обязана состояться: без неё следующий прогон заведёт
      // вторую задачу на тот же вопрос.
      if (ошибка) {
        итог.причины.push(`${клиент}: разбор не записался — ${ошибка!.message}`)
      }
    }
  }

  return итог
}
