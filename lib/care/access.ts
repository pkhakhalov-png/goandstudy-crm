/**
 * Кто какие дела видит.
 *
 * Единственное место, где это решается. Не «рекомендуется использовать» —
 * любой запрос к делам обязан пройти отсюда, иначе однажды появится страница,
 * которая показывает всё, и заметят это не разработчики.
 *
 * Почему не через RLS в базе. Политика в Postgres знает роль подключения
 * (`care_app`), но не знает, какой именно куратор смотрит: контур ходит одним
 * ключом на всех. Передавать личность через `set_config` в каждом запросе
 * можно, но пул соединений PostgREST делает это ненадёжным — настройка
 * пережила бы запрос и утекла к соседу. Поэтому область считается здесь, а
 * база остаётся вторым рубежом: писать в `public` роль всё равно не может.
 *
 * ПРАВИЛА (раздел «Этап 1» плана сборки):
 *
 *   curator     — свои дела (owner_member_id = я) плюс те, куда меня позвали
 *   lead        — всё вышеперечисленное плюс дела своей команды
 *   deputy      — только то, куда позвали, и только пока позвали
 *   specialist  — то же самое
 *
 * «Пока позвали» — не формальность. Помощь на две недели должна сама
 * закончиться: доступ, который забыли снять, — это доступ навсегда.
 */
import { базаCare } from './db'

export type РольВКонтуре = 'curator' | 'lead' | 'deputy' | 'specialist'

export type Участник = {
  id: string
  user_id: string
  care_role: РольВКонтуре
  team_lead_id: string | null
  active: boolean
}

/** Область видимости: какие дела и почему именно эти. */
export type Область = {
  дела: string[]
  /** Пусто — не ошибка: у нового куратора дел может ещё не быть. */
  пусто: boolean
  объяснение: string
}

/**
 * Найти сотрудника контура по пользователю CRM.
 *
 * `null` означает «в контуре v2 такого сотрудника нет» — не «нет прав».
 * Разница важна: первое чинится заведением записи, второе не чинится вовсе.
 */
export async function участникПоПользователю(userId: string): Promise<Участник | null> {
  const { data, error } = await базаCare()
    .from('members')
    .select('id, user_id, care_role, team_lead_id, active')
    .eq('user_id', userId)
    .maybeSingle()

  if (error) throw new Error(`не удалось найти сотрудника контура: ${error.message}`)
  if (!data) return null
  // Выключенный сотрудник — как отсутствующий. Не оставляем половинчатого
  // состояния «есть запись, но неизвестно что можно».
  if (!data.active) return null
  return data as Участник
}

/** Дела, куда участника позвали и позвали до сих пор. */
async function деларазделённые(участникId: string): Promise<string[]> {
  const сейчас = new Date().toISOString()
  const { data, error } = await базаCare()
    .from('case_members')
    .select('case_id, valid_from, valid_to')
    .eq('member_id', участникId)
    .lte('valid_from', сейчас)
    // `valid_to is null` — бессрочно; иначе срок ещё не истёк.
    .or(`valid_to.is.null,valid_to.gt.${сейчас}`)

  if (error) throw new Error(`не удалось прочитать участие в делах: ${error.message}`)
  return (data ?? []).map((с) => с.case_id as string)
}

/** Дела, где участник — ведущий. */
async function делаСвои(участникId: string): Promise<string[]> {
  const { data, error } = await базаCare()
    .from('cases')
    .select('id')
    .eq('owner_member_id', участникId)

  if (error) throw new Error(`не удалось прочитать свои дела: ${error.message}`)
  return (data ?? []).map((с) => с.id as string)
}

/** Дела всех, у кого этот участник — руководитель. */
async function делаКоманды(руководительId: string): Promise<string[]> {
  const { data: люди, error: ошибкаЛюдей } = await базаCare()
    .from('members')
    .select('id')
    .eq('team_lead_id', руководительId)

  if (ошибкаЛюдей) throw new Error(`не удалось прочитать команду: ${ошибкаЛюдей.message}`)
  const идентификаторы = (люди ?? []).map((ч) => ч.id as string)
  if (!идентификаторы.length) return []

  const { data: дела, error: ошибкаДел } = await базаCare()
    .from('cases')
    .select('id')
    .in('owner_member_id', идентификаторы)

  if (ошибкаДел) throw new Error(`не удалось прочитать дела команды: ${ошибкаДел.message}`)
  return (дела ?? []).map((д) => д.id as string)
}

/**
 * Область видимости участника.
 *
 * Возвращает список идентификаторов, а не готовый запрос: список можно
 * проверить в тесте и показать в журнале, а запрос — нет.
 */
export async function видимыеДела(участник: Участник): Promise<Область> {
  let дела: string[]
  let объяснение: string

  switch (участник.care_role) {
    case 'lead': {
      const [свои, команды, позвали] = await Promise.all([
        делаСвои(участник.id),
        делаКоманды(участник.id),
        деларазделённые(участник.id),
      ])
      дела = [...свои, ...команды, ...позвали]
      объяснение = `свои (${свои.length}), команды (${команды.length}), по приглашению (${позвали.length})`
      break
    }
    case 'curator': {
      const [свои, позвали] = await Promise.all([
        делаСвои(участник.id),
        деларазделённые(участник.id),
      ])
      дела = [...свои, ...позвали]
      объяснение = `свои (${свои.length}), по приглашению (${позвали.length})`
      break
    }
    case 'deputy':
    case 'specialist': {
      // Заместитель и специалист своих дел не ведут: только то, куда позвали.
      // Если такой человек окажется владельцем дела, это ошибка заведения, и
      // чинить её надо там, а не расширением прав здесь.
      const позвали = await деларазделённые(участник.id)
      дела = позвали
      объяснение = `по приглашению (${позвали.length})`
      break
    }
  }

  const уникальные = [...new Set(дела)]
  return { дела: уникальные, пусто: уникальные.length === 0, объяснение }
}

/**
 * Доступно ли участнику одно конкретное дело.
 *
 * Отдельной функцией, а не `видимыеДела().includes()`: страница дела
 * спрашивает про одно дело, и тянуть ради этого весь список руководителя —
 * это лишний обход базы на каждый заход.
 */
export async function делоДоступно(участник: Участник, caseId: string): Promise<boolean> {
  // Свои и командные — одним запросом к делу.
  const { data: дело, error } = await базаCare()
    .from('cases')
    .select('id, owner_member_id')
    .eq('id', caseId)
    .maybeSingle()

  if (error) throw new Error(`не удалось прочитать дело: ${error.message}`)
  if (!дело) return false

  const владелец = дело.owner_member_id as string | null

  if (владелец && владелец === участник.id) {
    // Заместитель и специалист владельцами быть не должны, но если так
    // случилось — дело всё равно своё, прятать его от владельца бессмысленно.
    return true
  }

  if (участник.care_role === 'lead' && владелец) {
    const { data: подчинённый, error: ошибка } = await базаCare()
      .from('members')
      .select('id')
      .eq('id', владелец)
      .eq('team_lead_id', участник.id)
      .maybeSingle()
    if (ошибка) throw new Error(`не удалось проверить команду: ${ошибка.message}`)
    if (подчинённый) return true
  }

  // Осталось приглашение — и оно обязано быть действующим сейчас.
  const позвали = await деларазделённые(участник.id)
  return позвали.includes(caseId)
}

/**
 * Проверка для серверных действий: либо участник с доступом, либо исключение.
 *
 * Бросает, а не возвращает `false`, намеренно. Действие, продолжившееся после
 * `false`, — это действие без прав; выбор «а что если забудут проверить»
 * должен вести к остановке, а не к тихому выполнению.
 */
export async function требуетсяДоступ(участник: Участник | null, caseId: string): Promise<Участник> {
  if (!участник) throw new Error('Нет доступа: пользователь не заведён в контуре v2')
  if (!(await делоДоступно(участник, caseId))) {
    throw new Error('Нет доступа к этому делу')
  }
  return участник
}
