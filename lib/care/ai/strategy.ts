/**
 * Стратегия поступления — связный документ по делу.
 *
 * ЧТО ЭТО. Не пересказ карточки и не список задач. Ответ на четыре вопроса,
 * на которые куратор отвечает клиенту каждый раз заново: куда мы целимся и
 * почему именно туда, что уже есть, чего не хватает и к какому сроку, что
 * делаем в ближайший месяц.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Выдуманных дат подачи, требований и стоимостей. Всё, что
 * попадает в документ, приходит из подтверждённых фактов, задач и подборки —
 * то есть из того, что кто-то уже проверил. Если чего-то нет, документ пишет
 * «неизвестно», а не правдоподобное число: клиент строит по этому планы, и
 * ошибка здесь стоит года.
 *
 * ПОЧЕМУ ЧЕРНОВИКОМ. Стратегия — это обещание клиенту от лица компании.
 * Подписывает её куратор, а не помощник: документ ложится в предложения и
 * ждёт решения человека, как и всё остальное в этом контуре.
 */
import { модель, МОДЕЛЬ_ПО_УМОЛЧАНИЮ, расход, type Расход } from './client'

export type ДанныеСтратегии = {
  клиент: string
  факты: { поле: string; значение: string; намерение: boolean }[]
  задачи: { название: string; срок: string | null; ждём: string; статус: string }[]
  подборка: { вуз: string; программа: string; страна: string; стоимость: string; ссылка: string }[]
  /** О чём договаривались в переписке — своими словами, коротко. */
  изПереписки: string[]
}

export type Стратегия = {
  текст: string
  расход: Расход | null
  ошибка?: string
}

/**
 * Проверить, что в тексте нет выдуманной конкретики.
 *
 * Самое опасное в стратегии — правдоподобная дата подачи, которой никто не
 * проверял. Поэтому: даты, которых нет во входных данных, запрещены. Проверка
 * грубая и намеренно строгая — пропустить выдуманный дедлайн хуже, чем
 * заставить модель переписать абзац.
 */
export function проверитьСтратегию(
  текст: string,
  д: ДанныеСтратегии
): { ok: true } | { ok: false; почему: string } {
  const т = текст.trim()
  if (т.length < 200) return { ok: false, почему: 'слишком коротко для стратегии' }
  if (/(\*\*|^#{1,6}\s)/m.test(т)) return { ok: false, почему: 'в тексте разметка Markdown' }

  // Все даты и годы, которые контур действительно знает.
  const известные = new Set<string>()
  for (const з of д.задачи) if (з.срок) известные.add(з.срок.slice(0, 4))
  for (const ф of д.факты) {
    const годы = ф.значение.match(/\b20\d{2}\b/g) ?? []
    for (const г of годы) известные.add(г)
  }
  for (const с of д.изПереписки) {
    for (const г of с.match(/\b20\d{2}\b/g) ?? []) известные.add(г)
  }

  const годаВТексте = т.match(/\b20\d{2}\b/g) ?? []
  const чужой = годаВТексте.find((г) => !известные.has(г))
  if (чужой) return { ok: false, почему: `в тексте год ${чужой}, которого нет в данных дела` }

  return { ok: true }
}

export async function написатьСтратегию(д: ДанныеСтратегии): Promise<Стратегия> {
  const вход = {
    клиент: д.клиент,
    подтверждено: д.факты.filter((ф) => !ф.намерение).map((ф) => `${ф.поле}: ${ф.значение}`),
    намерения: д.факты.filter((ф) => ф.намерение).map((ф) => `${ф.поле}: ${ф.значение}`),
    задачи: д.задачи.map((з) => `${з.название} — ${з.статус}, ждём ${з.ждём}${з.срок ? `, срок ${з.срок}` : ', срока нет'}`),
    подборка: д.подборка.map((п) => `${п.вуз} (${п.страна}) — ${п.программа}, ${п.стоимость}`),
    из_переписки: д.изПереписки,
  }

  try {
    const ответ = await модель().messages.create({
      model: МОДЕЛЬ_ПО_УМОЛЧАНИЮ,
      max_tokens: 3000,
      // Здесь есть что решать: связать разрозненные сведения в один план и
      // увидеть, чего не хватает. Глубина окупается.
      output_config: { effort: 'medium' },
      system:
        'Ты пишешь стратегию поступления для клиента goandstudy. Читает её куратор, ' +
        'правит и показывает клиенту. Пиши для человека, а не для отчёта.\n\n' +
        'СТРУКТУРА — четыре части, каждая абзацем, без заголовков и списков:\n' +
        '1. Куда целимся и почему именно туда — по подтверждённым сведениям о клиенте.\n' +
        '2. Что уже есть: образование, язык, документы, решения.\n' +
        '3. Чего не хватает и к какому сроку. Только сроки из задач — своих не придумывай.\n' +
        '4. Что делаем в ближайший месяц: два-три конкретных шага.\n\n' +
        'ЖЁСТКИЕ ПРАВИЛА:\n' +
        '— Обычный текст. Никакой разметки: ни звёздочек, ни заголовков, ни списков.\n' +
        '— Ни одной даты, срока подачи, требования или стоимости, которых нет во входных данных. ' +
        'Не знаешь — так и пиши: «сроки подачи ещё не проверены».\n' +
        '— Намерения не выдавай за результат: «планирует сдать IELTS» — это не «есть IELTS».\n' +
        '— Не обещай поступление и не оценивай шансы в процентах.\n' +
        '— Если данных мало, скажи прямо, чего не хватает, чтобы стратегия была полной. ' +
        'Короткий честный документ полезнее длинного и додуманного.',
      messages: [{ role: 'user', content: JSON.stringify(вход, null, 1) }],
    })

    const р = расход(ответ.model, ответ.usage.input_tokens, ответ.usage.output_tokens)
    if (ответ.stop_reason === 'refusal') return { текст: '', расход: р, ошибка: 'модель отказалась' }

    const текст = ответ.content
      .map((б) => (б.type === 'text' ? б.text : ''))
      .filter(Boolean)
      .join('\n')
      .trim()

    const проверка = проверитьСтратегию(текст, д)
    if (!проверка.ok) return { текст: '', расход: р, ошибка: проверка.почему }

    return { текст, расход: р }
  } catch (e) {
    return { текст: '', расход: null, ошибка: e instanceof Error ? e.message : String(e) }
  }
}
