/**
 * Напоминание, написанное под конкретное дело.
 *
 * ПОЧЕМУ НЕ ШАБЛОН. Шаблон экономил внимание куратора: тридцать одинаковых
 * сообщений читаются по диагонали. Но он же означал, что все клиенты получают
 * одну и ту же фразу — а у каждого свой случай, свой этап и своя причина
 * задержки. Решение владельца от 30.09.2026: пишем индивидуально.
 *
 * ЧТО ОСТАЁТСЯ ОТ ШАБЛОНА. Он — запасной путь. Модель может не ответить,
 * ответить плохо или упереться в дневной потолок; напоминание при этом должно
 * уйти, потому что срок не подвинется. Шаблон хуже индивидуального текста и
 * лучше молчания.
 *
 * ЧТО МОДЕЛИ НЕ ДАЮТ РЕШАТЬ. Ни срок, ни имя, ни то, какой документ ждём —
 * всё это приходит из базы готовым и проверяется в тексте после. Модель
 * подбирает слова, а не факты. Проверки ниже — не украшение: сообщение уходит
 * живому человеку от имени компании, и выдуманная дата в нём дороже любой
 * экономии.
 */
import { модель, МОДЕЛЬ_ПО_УМОЛЧАНИЮ, глубина, расход, type Расход } from './client'

/** Всё, что нужно знать, чтобы написать одно напоминание. */
export type ДелоДляНапоминания = {
  имя: string
  документ: string
  датаСловами: string
  просрочено: boolean
  /** Сколько раз по этой задаче уже напоминали. Второе письмо звучит иначе. */
  напоминалиРаз: number
  /** Подтверждённые сведения о клиенте: страна, уровень, услуга. Без цитат. */
  оКлиенте: Record<string, string>
}

export type ИтогТекста =
  | { ok: true; текст: string }
  | { ok: false; почему: string }

const МЕСЯЦЫ =
  'январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр'

/**
 * Проверить, что написанное можно отправить человеку.
 *
 * Каждая проверка ловит свою беду, и ни одна не придумана «на всякий случай»:
 *
 *   · плейсхолдер — модель повторила шаблон вместо того, чтобы написать;
 *   · нет имени — сообщение читается как рассылка;
 *   · нет срока — напоминание без даты не напоминание;
 *   · **лишняя дата** — самая дорогая ошибка: «пришлите до 5 октября», когда
 *     срок десятого, сдвигает клиенту дедлайн, и заметит это только он;
 *   · ссылка — модель не знает наших адресов и придумает их;
 *   · разметка — уйдёт в Телеграм звёздочками как есть;
 *   · длина — короче трёх строк не бывает вежливо, длиннее абзаца не читают.
 */
export function проверитьТекст(текст: string, д: ДелоДляНапоминания): ИтогТекста {
  const т = текст.trim()

  if (!т) return { ok: false, почему: 'пустой ответ' }

  const плейсхолдер = т.match(/\{[а-яёa-z_]+\}/i)
  if (плейсхолдер) return { ok: false, почему: `в тексте остался ${плейсхолдер[0]}` }

  const имя = д.имя.split(/\s+/)[0]
  if (!т.includes(имя)) return { ok: false, почему: 'в тексте нет имени' }

  if (!т.includes(д.датаСловами)) return { ok: false, почему: `в тексте нет срока «${д.датаСловами}»` }

  // Любая дата, кроме нашей, — выдумка. Ищем и словесные, и цифровые.
  //
  // Знаки препинания отрезаем: `\S*` захватывает точку в конце предложения,
  // и «10 октября.» переставало совпадать с «до 10 октября». Текст при этом
  // был верный — отвергалась правильная подстановка, напоминание молча
  // скатывалось в шаблон, а вызов модели оплачивался впустую. В журнале это
  // выглядело бы как «шаблон», и причину пришлось бы искать в коде.
  const безЗнаков = (строка: string) => строка.replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, '')
  const наша = безЗнаков(д.датаСловами)

  const словесные = т.match(new RegExp(`\\d{1,2}\\s+(?:${МЕСЯЦЫ})\\S*`, 'gi')) ?? []
  const цифровые = т.match(/\b\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?\b/g) ?? []
  const лишняя = [...словесные, ...цифровые]
    .map(безЗнаков)
    .find((д2) => !наша.includes(д2) && !д2.includes(наша))
  if (лишняя) return { ok: false, почему: `в тексте чужая дата «${лишняя}» — срок только ${д.датаСловами}` }

  if (/https?:\/\/|www\.|t\.me\//i.test(т)) return { ok: false, почему: 'в тексте ссылка' }

  if (/(\*\*|__|^#{1,6}\s|^[-*]\s)/m.test(т)) return { ok: false, почему: 'в тексте разметка Markdown' }

  if (т.length < 40) return { ok: false, почему: 'слишком коротко' }
  if (т.length > 600) return { ok: false, почему: 'слишком длинно' }

  return { ok: true, текст: т }
}

/** Как обращаться, когда напоминаем не в первый раз. */
function тон(д: ДелоДляНапоминания): string {
  if (д.напоминалиРаз === 0) {
    return 'Это первое напоминание. Пиши спокойно и коротко, без нажима.'
  }
  if (д.просрочено) {
    return (
      `Напоминаем уже ${д.напоминалиРаз + 1}-й раз, и срок прошёл. Скажи об этом прямо и спроси, ` +
      'что мешает, — не упрекая. Человек скорее молчит потому, что застрял, чем потому, что забыл.'
    )
  }
  return `Напоминаем уже ${д.напоминалиРаз + 1}-й раз. Не повторяй прежнюю формулировку дословно, спроси, нужна ли помощь.`
}

export type Написанное = {
  текст: string
  расход: Расход | null
  /** Чем написано: моделью по этому делу или общим шаблоном. */
  чем: 'модель' | 'шаблон'
  /** Почему не моделью, если не ею. Попадает в журнал, а не к клиенту. */
  почемуНеМодель?: string
}

/**
 * Написать напоминание по делу.
 *
 * Возвращает `null`, если модель не дала годного текста. Решение, что делать
 * дальше, принимает вызывающий: у правила напоминаний это шаблон.
 */
export async function написатьНапоминание(
  д: ДелоДляНапоминания
): Promise<{ текст: string; расход: Расход } | { ошибка: string; расход: Расход | null }> {
  const имя = д.имя.split(/\s+/)[0]

  const условия = [
    `Имя, как обращаться: ${имя}`,
    `Что ждём: ${д.документ}`,
    `Срок, писать ровно так и только так: ${д.датаСловами}`,
    д.просрочено ? 'Срок уже прошёл.' : 'Срок ещё не наступил.',
    Object.keys(д.оКлиенте).length
      ? `Что мы о нём знаем: ${Object.entries(д.оКлиенте).map(([к, з]) => `${к} — ${з}`).join('; ')}`
      : 'Больше о нём ничего подтверждённого нет.',
  ].join('\n')

  try {
    const ответ = await модель().messages.create({
      model: МОДЕЛЬ_ПО_УМОЛЧАНИЮ,
      max_tokens: 500,
      ...глубина(МОДЕЛЬ_ПО_УМОЛЧАНИЮ, 'low'),
      system:
        'Ты пишешь короткое сообщение клиенту от лица куратора goandstudy — компании, которая помогает поступать в зарубежные вузы. ' +
        'Сообщение уходит в Телеграм от живого человека, а не от робота.\n\n' +
        'ЖЁСТКИЕ ПРАВИЛА:\n' +
        '— Только обычный текст. Никакой разметки: ни звёздочек, ни списков, ни заголовков.\n' +
        '— Никаких дат, кроме названного срока. Не пересчитывай его и не уточняй «осталось N дней».\n' +
        '— Никаких ссылок, адресов, телефонов и имён сотрудников.\n' +
        '— Ничего не обещай от имени компании и не выдумывай подробностей о клиенте.\n' +
        '— Обратись по имени. Две-четыре фразы, не больше.\n' +
        '— Без подписи и без «с уважением».\n\n' +
        `ТОН: ${тон(д)}\n\n` +
        'Верни только текст сообщения, без пояснений и без кавычек вокруг.',
      messages: [{ role: 'user', content: условия }],
    })

    const р = расход(ответ.model, ответ.usage.input_tokens, ответ.usage.output_tokens)

    if (ответ.stop_reason === 'refusal') return { ошибка: 'модель отказалась отвечать', расход: р }

    const текст = ответ.content
      .map((б) => (б.type === 'text' ? б.text : ''))
      .filter(Boolean)
      .join('\n')
      .trim()
      // Модель любит обрамлять сообщение кавычками, хотя её просили не делать
      // этого. Снимаем сами — это дешевле, чем выбрасывать годный текст.
      .replace(/^[«"']|[»"']$/g, '')
      .trim()

    const проверка = проверитьТекст(текст, д)
    if (!проверка.ok) return { ошибка: проверка.почему, расход: р }

    return { текст: проверка.текст, расход: р }
  } catch (e) {
    return { ошибка: e instanceof Error ? e.message : String(e), расход: null }
  }
}
