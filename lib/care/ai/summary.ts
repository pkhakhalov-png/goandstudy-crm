/**
 * Сводка «что сегодня требует внимания».
 *
 * УСТРОЙСТВО, КОТОРОЕ НЕЛЬЗЯ МЕНЯТЬ: числа считает база, модель пишет к ним
 * две фразы. Счётчики на экране рендерятся из запроса, а не из текста ответа.
 *
 * Почему так. Если бы модель возвращала и числа, и текст, подменённый или
 * просто неточный ответ менял бы то, что куратор считает фактом — а проверить
 * он это может только открыв двадцать карточек. Разделение делает подмену
 * безвредной: текст может оказаться любым, счётчики останутся верными.
 *
 * Проверяется это прямо: тест подменяет ответ модели и убеждается, что числа
 * на экране те же.
 */
import { модель, МОДЕЛЬ_ПО_УМОЛЧАНИЮ, расход, type Расход } from './client'
import { склонение } from '../labels'
import type { Главная } from '../cases'

export type Сводка = {
  фраза: string
  расход: Расход | null
  /** Модель не ответила — экран всё равно рисуется по числам. */
  безМодели: boolean
}

/**
 * Сухая формулировка на случай, когда модель недоступна.
 *
 * Не заглушка «сервис временно недоступен»: куратору нужна сводка, а не
 * сообщение об ошибке. Числа у нас есть, значит одну фразу мы составим и без
 * модели — просто без связного объяснения.
 */
export function безПомощника(д: Главная): string {
  if (д.всегоДел === 0) return 'Дел пока нет.'
  if (д.требуютВас === 0) return `${д.всегоДел} ${склонение(д.всегоДел, 'дело', 'дела', 'дел')} в работе, ничего не горит.`
  const части: string[] = []
  if (д.просроченныхЗадач) {
    части.push(`${д.просроченныхЗадач} ${склонение(д.просроченныхЗадач, 'просроченная задача', 'просроченные задачи', 'просроченных задач')}`)
  }
  if (д.предложений) {
    части.push(`${д.предложений} ${склонение(д.предложений, 'запись ждёт', 'записи ждут', 'записей ждут')} проверки`)
  }
  if (д.дедлайновЗа14Дней) {
    части.push(`${д.дедлайновЗа14Дней} ${склонение(д.дедлайновЗа14Дней, 'срок', 'срока', 'сроков')} в ближайшие две недели`)
  }
  return части.length ? `Требуют внимания: ${части.join(', ')}.` : 'Есть дела, требующие вашего внимания.'
}

export async function сводка(д: Главная, имя: string | null): Promise<Сводка> {
  if (д.всегоДел === 0) {
    return { фраза: безПомощника(д), расход: null, безМодели: true }
  }

  // Модели отдаём только уже посчитанные числа — ни одного запроса к базе она
  // при этом не делает. Считать нечего, остаётся сформулировать.
  const числа = {
    всего_дел: д.всегоДел,
    требуют_внимания: д.требуютВас,
    записей_на_проверку: д.предложений,
    просроченных_задач: д.просроченныхЗадач,
    сроков_за_14_дней: д.дедлайновЗа14Дней,
    первые_в_ленте: д.лента.slice(0, 3).map((с) => ({
      клиент: с.имя,
      почему: с.причины.map((п) => п.текст),
    })),
  }

  try {
    const ответ = await модель().messages.create({
      model: МОДЕЛЬ_ПО_УМОЛЧАНИЮ,
      max_tokens: 400,
      // Работа простая — сформулировать по готовым числам. Высокая глубина
      // здесь только добавит задержку на экране, который открывают утром.
      output_config: { effort: 'low' },
      system:
        'Ты помощник куратора в goandstudy. По готовым числам напиши ДВЕ фразы: что сегодня важнее всего и с чего начать. ' +
        'Числа не пересчитывай и не выдумывай — бери как есть. Без вступлений, без списков, без обращения по имени. ' +
        'Если всё спокойно — так и скажи одной фразой.',
      messages: [
        {
          role: 'user',
          content: `Числа на сегодня:\n${JSON.stringify(числа, null, 1)}${имя ? `\n\nКуратор: ${имя}` : ''}`,
        },
      ],
    })

    if (ответ.stop_reason === 'refusal') {
      return { фраза: безПомощника(д), расход: null, безМодели: true }
    }

    const текст = ответ.content
      .map((б) => (б.type === 'text' ? б.text : ''))
      .filter(Boolean)
      .join(' ')
      .trim()

    return {
      фраза: текст || безПомощника(д),
      расход: расход(ответ.model, ответ.usage.input_tokens, ответ.usage.output_tokens),
      безМодели: !текст,
    }
  } catch (e) {
    // Экран важнее сводки: молча падаем на сухую формулировку, а причину
    // оставляем в журнале сервера.
    console.warn('[care сводка] модель недоступна:', e instanceof Error ? e.message : e)
    return { фраза: безПомощника(д), расход: null, безМодели: true }
  }
}
