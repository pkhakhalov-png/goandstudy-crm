/**
 * Вопрос в интернет — для всего, что не подбор программ.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ ПОДБОРА. Подбор ищет программы и возвращает их строками с
 * ценой и ссылкой; его ответ ложится в подборку. А куратору по десять раз в
 * день нужно другое: «когда дедлайн в TUM на осень», «нужен ли APS в этом
 * году», «сколько стоит студенческая виза в Нидерланды». Это не программы, это
 * ответ на вопрос — и класть его в подборку некуда.
 *
 * ПОЧЕМУ ОТВЕТ ВСЕГДА СО ССЫЛКАМИ. Куратор перескажет это клиенту, а клиент
 * построит на этом планы. «Дедлайн 15 января» без источника и «дедлайн 15
 * января, вот страница вуза» — разные вещи: первое невозможно проверить, когда
 * через месяц окажется, что дедлайн другой. Ответ без ни одной ссылки мы не
 * отдаём вовсе.
 *
 * ЧЕГО ОН НЕ ДЕЛАЕТ. Не пишет в базу. Это чтение из интернета, и всё, что с
 * ответом произойдёт дальше, решает куратор: захочет — скажет записать фактом.
 */
import { модель, МОДЕЛЬ_ПО_УМОЛЧАНИЮ, расход, вебРазрешён, type Расход } from './client'

export type ИтогСправки = {
  ответ: string
  /** Адреса, на которые модель ссылалась. Пустой список — ответ не отдаём. */
  источники: string[]
  расход: Расход | null
  ошибка?: string
}

/** Поисковая выдача и агрегаторы: ссылаться на них — всё равно что не ссылаться. */
const НЕ_ИСТОЧНИК = [
  'google.',
  'bing.',
  'duckduckgo.',
  'yandex.',
  'mastersportal',
  'bachelorsportal',
  'studyportals',
  'topuniversities',
  'timeshighereducation',
]

export function годныйИсточник(адрес: string): boolean {
  try {
    const u = new URL(адрес)
    if (u.protocol !== 'https:' && u.protocol !== 'http:') return false
    const хост = u.hostname.toLowerCase()
    return !НЕ_ИСТОЧНИК.some((п) => хост.includes(п))
  } catch {
    return false
  }
}

/**
 * Собрать адреса из блоков ответа.
 *
 * Серверный поиск возвращает результаты отдельными блоками, а не текстом, и
 * вытаскивать их регулярками из ответа модели — значит верить тому, что она
 * написала. Берём из блоков: там адреса настоящие.
 */
function источникиИзБлоков(блоки: unknown[]): string[] {
  const найдено = new Set<string>()
  const обойти = (значение: unknown): void => {
    if (!значение || typeof значение !== 'object') return
    if (Array.isArray(значение)) {
      for (const э of значение) обойти(э)
      return
    }
    for (const [ключ, э] of Object.entries(значение as Record<string, unknown>)) {
      if (ключ === 'url' && typeof э === 'string' && годныйИсточник(э)) найдено.add(э)
      else обойти(э)
    }
  }
  обойти(блоки)
  return [...найдено]
}

const ПРАВИЛА = `
Ты отвечаешь на вопрос куратора goandstudy, который ведёт клиентов в зарубежные
вузы. Ищешь в вебе и отвечаешь по найденному.

Правила:
— Отвечай по страницам вузов, министерств, консульств и официальных служб.
Агрегаторы и рейтинги не источник: там устаревает молча.
— Называй дату, на которую сведения верны, если она есть на странице. Сроки
подачи и визовые правила меняются каждый год, и ответ без года бесполезен.
— Чего не нашёл — так и скажи. «На странице вуза этого нет» — это ответ.
Достроенный по общему смыслу срок хуже отсутствующего: по нему подают.
— Если нашёл разное в разных местах, скажи об этом и назови оба, а не выбирай
за куратора.
— Коротко: три-пять фраз. Куратор читает это между делами.
— Обычным текстом, без разметки. Ни **, ни ##, ни таблиц.
`.trim()

/** Спросить интернет. Пишет только ответ — в базу ничего. */
export async function справкаИзИнтернета(вопрос: string, оДеле?: string): Promise<ИтогСправки> {
  const веб = вебРазрешён()
  if (!веб.можно) return { ответ: '', источники: [], расход: null, ошибка: веб.почему }

  const блоки: unknown[] = []

  try {
    const бегун = модель().beta.messages.toolRunner({
      model: МОДЕЛЬ_ПО_УМОЛЧАНИЮ,
      max_tokens: 8000,
      output_config: { effort: 'medium' },
      tools: [{ type: 'web_search_20260209', name: 'web_search', max_uses: 8 }],
      system: ПРАВИЛА,
      messages: [
        {
          role: 'user',
          content: оДеле ? `${вопрос}\n\nКонтекст дела: ${оДеле}` : вопрос,
        },
      ],
      max_iterations: 10,
    })

    let вход = 0
    let выход = 0
    let модельId = МОДЕЛЬ_ПО_УМОЛЧАНИЮ
    let текст = ''

    for await (const сообщение of бегун) {
      вход += сообщение.usage.input_tokens
      выход += сообщение.usage.output_tokens
      модельId = сообщение.model
      блоки.push(...сообщение.content)

      const свой = сообщение.content
        .map((б: { type: string; text?: string }) => (б.type === 'text' ? (б.text ?? '') : ''))
        .filter(Boolean)
        .join('\n')
        .trim()
      if (свой) текст = свой

      // Поиск отработал круги и просит продолжения. Не вернуть ход — значит
      // оборвать на середине, молча и без ошибки.
      if (сообщение.stop_reason === 'pause_turn') {
        бегун.pushMessages({ role: 'assistant', content: сообщение.content })
      }
    }

    const источники = источникиИзБлоков(блоки)
    const р = расход(модельId, вход, выход)

    if (!текст) return { ответ: '', источники, расход: р, ошибка: 'модель не ответила текстом' }
    if (!источники.length) {
      // Ответ без единого годного источника выглядит так же уверенно, как
      // ответ со ссылкой, и проверить его нельзя. Такой не отдаём.
      return {
        ответ: '',
        источники: [],
        расход: р,
        ошибка: 'ответ не опирается ни на одну страницу вуза или ведомства',
      }
    }

    return { ответ: текст, источники, расход: р }
  } catch (e) {
    return {
      ответ: '',
      источники: [],
      расход: null,
      ошибка: e instanceof Error ? e.message : String(e),
    }
  }
}
