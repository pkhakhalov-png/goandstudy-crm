/**
 * Подбор программ веб-поиском — там, где базы вузов не хватает.
 *
 * ПОЧЕМУ ЭТО ВООБЩЕ ПОНАДОБИЛОСЬ. В базе парсера 80 995 программ, но уровень
 * заполнен у четырёх записей, язык и даты набора — у четырёхсот. По Европе это
 * вообще не программы, а категории направлений: «Образование», «Инженерия» со
 * стоимостью 200. Отбирать по такому нечем, и притворяться, что можно, значит
 * выдать куратору подборку из воздуха.
 *
 * Поэтому по странам, где база пуста, программы ищутся в вебе — поиск делает
 * сама модель серверным инструментом, а мы требуем от неё ссылку на страницу
 * программы. Ссылка здесь — то же, чем цитата была при разборе переписки:
 * единственное, что отличает найденное от придуманного.
 *
 * ЧТО МЫ НЕ УТВЕРЖДАЕМ. Что требования проверены. Модель прочитала страницу
 * сегодня — это всё, что мы знаем, и так и записывается: ссылка и дата
 * проверки. Куратор открывает и смотрит. Проценты соответствия не считаем:
 * они создают уверенность, которой нет.
 */
import { betaTool } from '@anthropic-ai/sdk/helpers/beta/json-schema'
import { модель, МОДЕЛЬ_ПО_УМОЛЧАНИЮ, расход, type Расход } from './client'

export type НайденнаяПрограмма = {
  вуз: string
  город: string | null
  страна: string
  программа: string
  уровень: string
  язык: string | null
  стоимость_в_год: number | null
  валюта: string | null
  ссылка: string
  почему_подходит: string
  что_проверить: string[]
}

export type ИтогПоиска = {
  программы: НайденнаяПрограмма[]
  отброшено: { программа: string; почему: string }[]
  расход: Расход | null
  ошибка?: string
}

/**
 * Проверить одну найденную программу.
 *
 * Ссылка обязательна и должна быть похожа на страницу вуза, а не на поисковую
 * выдачу или агрегатор: подборка, где половина ссылок ведёт на рейтинги, не
 * экономит куратору ни минуты — он всё равно пойдёт искать сам.
 */
export function проверитьПрограмму(
  п: НайденнаяПрограмма
): { ok: true } | { ok: false; почему: string } {
  if (!п.программа?.trim() || !п.вуз?.trim()) return { ok: false, почему: 'нет названия вуза или программы' }

  const ссылка = (п.ссылка ?? '').trim()
  if (!/^https?:\/\//i.test(ссылка)) return { ok: false, почему: 'нет ссылки на страницу программы' }

  let хост = ''
  try {
    хост = new URL(ссылка).hostname.toLowerCase()
  } catch {
    return { ok: false, почему: 'ссылка не разбирается' }
  }

  // Агрегаторы и поисковики. Не потому что они плохие, а потому что куратору
  // нужна страница программы, а не ещё один список, который надо разбирать.
  const посредники = [
    'google.', 'bing.', 'duckduckgo.', 'yandex.',
    'wikipedia.org', 'mastersportal.com', 'bachelorsportal.com', 'studyportals.',
    'keystoneacademic', 'educations.com', 'topuniversities.com', 'timeshighereducation',
    'unipage.net', 'studyineurope', 'hotcoursesabroad',
  ]
  if (посредники.some((п2) => хост.includes(п2))) {
    return { ok: false, почему: `ссылка на посредника (${хост}), а не на страницу вуза` }
  }

  if (п.стоимость_в_год != null && !п.валюта) return { ok: false, почему: 'сумма без валюты' }

  return { ok: true }
}

export type ЗапросПоиска = {
  страны: string
  направление: string
  уровень: string
  бюджетВГод: string
  оКлиенте: Record<string, string>
  сколько: number
}

/**
 * Найти программы в вебе под запрос куратора.
 *
 * Модель ищет сама — серверный инструмент поиска. Наше дело: задать рамки,
 * потребовать ссылку и выбросить всё, что ссылкой не подтверждено.
 */
export async function искатьВВебе(з: ЗапросПоиска): Promise<ИтогПоиска> {
  const собрано: НайденнаяПрограмма[] = []

  const запись = betaTool({
    // Латиницей: API отвергает кириллицу и в имени инструмента, и в ключах схемы.
    name: 'record_programs',
    description:
      'Записать найденные программы. Вызови один раз, когда собрал список. ' +
      'Каждая программа — с прямой ссылкой на её страницу на сайте вуза.',
    inputSchema: {
      type: 'object',
      properties: {
        programs: {
          type: 'array',
          items: {
            type: 'object',
            properties: {
              вуз: { type: 'string' },
              город: { type: ['string', 'null'] },
              страна: { type: 'string' },
              программа: { type: 'string', description: 'Полное название программы' },
              уровень: { type: 'string', description: 'бакалавриат, магистратура, подготовка' },
              язык: { type: ['string', 'null'], description: 'Язык обучения, если указан на странице' },
              стоимость_в_год: { type: ['number', 'null'], description: 'Число без валюты' },
              валюта: { type: ['string', 'null'], description: 'EUR, USD — обязательно, если есть сумма' },
              ссылка: {
                type: 'string',
                description:
                  'Прямая ссылка на страницу программы на сайте вуза. Не на рейтинг, ' +
                  'не на агрегатор, не на поисковую выдачу.',
              },
              почему_подходит: {
                type: 'string',
                description: 'Одна-две фразы по сведениям о клиенте. Без общих слов про качество образования.',
              },
              что_проверить: {
                type: 'array',
                items: { type: 'string' },
                description: 'Чего на странице не нашлось: сроки подачи, требования к языку, стоимость.',
              },
            },
            required: ['вуз', 'страна', 'программа', 'уровень', 'ссылка', 'почему_подходит', 'что_проверить'],
            additionalProperties: false,
          },
        },
      },
      required: ['programs'],
      additionalProperties: false,
    },
    run: async ({ programs }) => {
      собрано.push(...((programs ?? []) as НайденнаяПрограмма[]))
      return 'записано'
    },
  })

  const условия = [
    `Страны: ${з.страны}`,
    `Направление: ${з.направление}`,
    `Уровень: ${з.уровень}`,
    `Бюджет на обучение: ${з.бюджетВГод}`,
    Object.keys(з.оКлиенте).length
      ? `Что подтверждено о клиенте: ${Object.entries(з.оКлиенте).map(([к, з2]) => `${к} — ${з2}`).join('; ')}`
      : 'Больше ничего подтверждённого о клиенте нет.',
    `Нужно программ: ${з.сколько}`,
  ].join('\n')

  try {
    const бегун = модель().beta.messages.toolRunner({
      model: МОДЕЛЬ_ПО_УМОЛЧАНИЮ,
      max_tokens: 16000,
      // Работа исследовательская: найти, сверить с бюджетом, отсеять неподходящее.
      // Здесь глубина окупается — в отличие от формулировки напоминания.
      output_config: { effort: 'medium' },
      tools: [
        // Серверный поиск: выполняется на стороне модели, своего обработчика не
        // требует. Отдельный инструмент выполнения кода рядом не объявляем —
        // в этой версии поиска фильтрация встроена, и второй он только путает.
        { type: 'web_search_20260209', name: 'web_search', max_uses: 12 },
        запись,
      ],
      system:
        'Ты подбираешь программы зарубежных вузов для клиента goandstudy. Ищешь в вебе и ' +
        'записываешь найденное инструментом record_programs.\n\n' +
        'ЖЁСТКИЕ ПРАВИЛА:\n' +
        '— У каждой программы прямая ссылка на её страницу на сайте вуза. Не на рейтинг, ' +
        'не на агрегатор (mastersportal, studyportals и подобные), не на поисковую выдачу. ' +
        'Программа без такой ссылки не записывается вовсе.\n' +
        '— Стоимость и язык бери со страницы. Не нашёл — ставь null и пиши об этом в «что_проверить». ' +
        'Выдуманная стоимость хуже отсутствующей: по ней клиент строит планы.\n' +
        '— Не превышай бюджет. Если под бюджет почти ничего нет, запиши что нашлось и скажи об этом ' +
        'в ответе — это полезнее, чем подобрать дорогое и промолчать.\n' +
        '— «почему_подходит» пиши по сведениям о клиенте, а не общими словами о вузе.\n' +
        '— Проценты соответствия и рейтинги не приводи.\n\n' +
        'После вызова инструмента напиши куратору две-три фразы: что получилось, чего не хватает, ' +
        'на что обратить внимание. Обычным текстом, без разметки.',
      messages: [{ role: 'user', content: условия }],
      max_iterations: 12,
    })

    let вход = 0
    let выход = 0
    let модельId = МОДЕЛЬ_ПО_УМОЛЧАНИЮ

    for await (const сообщение of бегун) {
      вход += сообщение.usage.input_tokens
      выход += сообщение.usage.output_tokens
      модельId = сообщение.model

      // Серверный инструмент отработал десять кругов и попросил продолжения.
      // Возвращаем ход модели обратно — иначе поиск обрывается на середине,
      // молча и без ошибки.
      if (сообщение.stop_reason === 'pause_turn') {
        бегун.pushMessages({ role: 'assistant', content: сообщение.content })
      }
    }

    const р = расход(модельId, вход, выход)

    const годные: НайденнаяПрограмма[] = []
    const отброшено: { программа: string; почему: string }[] = []
    for (const п of собрано) {
      const проверка = проверитьПрограмму(п)
      if (проверка.ok) годные.push(п)
      else отброшено.push({ программа: `${п.вуз} — ${п.программа}`, почему: проверка.почему })
    }

    return { программы: годные, отброшено, расход: р }
  } catch (e) {
    return {
      программы: [],
      отброшено: [],
      расход: null,
      ошибка: e instanceof Error ? e.message : String(e),
    }
  }
}
