/**
 * Чем было входящее сообщение.
 *
 * ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ ИЗВЛЕЧЕНИЯ ФАКТОВ. Разбор переписки ищет в сообщениях
 * сведения о клиенте: страну, бюджет, сроки. Но клиент пишет не только о себе.
 * «А когда дедлайн в Мюнхене?» — тут нет ни одного факта, и разбор проходит
 * мимо. Вопрос остаётся в чате, куратор его не видит, клиент ждёт.
 *
 * ЧЕТЫРЕ ВИДА, И БОЛЬШЕ НЕ НАДО. Вопрос, документ, изменение условий, прочее.
 * Дробить мельче — значит заставлять модель выбирать между близкими ярлыками,
 * а разница между ними всё равно не меняет того, что мы делаем.
 *
 * ЦИТАТА ОБЯЗАНА НАЙТИСЬ ДОСЛОВНО. Та же проверка, что у фактов, и по той же
 * причине: перефразировать можно что угодно, процитировать — только то, что
 * было написано. Без цитаты «клиент спрашивал про сроки» нельзя ни проверить,
 * ни показать.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Ответа клиенту. Модель не пишет ответов и не решает, что
 * сказать: она говорит, что вопрос был, и приводит слова. Отвечает человек.
 */
import { betaTool } from '@anthropic-ai/sdk/helpers/beta/json-schema'
import { модель, МОДЕЛЬ_МЕХАНИКИ, глубина, расход, type Расход } from './client'
import { длясверки, type Сообщение } from './extract'

export const ВИДЫ = ['question', 'document', 'terms', 'other'] as const
export type ВидСообщения = (typeof ВИДЫ)[number]

export const ПОДПИСЬ_ВИДА: Record<ВидСообщения, string> = {
  question: 'вопрос клиента',
  document: 'прислал документ',
  terms: 'изменение условий',
  other: 'прочее',
}

export type РазборСообщения = {
  messageId: string
  вид: ВидСообщения
  оЧём: string
  цитата: string
}

export type ИтогРазбораВходящих = {
  разобрано: РазборСообщения[]
  /** Что модель предложила, но мы не приняли, — с номером сообщения. */
  отброшено: { messageId: string | null; почему: string }[]
  расход: Расход | null
  ошибка?: string
}

/**
 * Проверка одного разбора.
 *
 * Отбрасываем молча только то, что нельзя показать человеку: выдуманную
 * цитату, неизвестный вид, пустое «о чём». Всё отброшенное считается и
 * называется — молчаливая потеря хуже видимой.
 */
export function проверитьРазбор(
  р: { message_id?: string; kind?: string; about?: string; quote?: string },
  сообщения: Сообщение[]
): { ok: true; разбор: РазборСообщения } | { ok: false; почему: string } {
  if (!(ВИДЫ as readonly string[]).includes(р.kind ?? '')) {
    return { ok: false, почему: `вид «${р.kind}» не из словаря` }
  }

  const сообщение = сообщения.find((с) => с.message_id === р.message_id)
  if (!сообщение) return { ok: false, почему: 'сообщения с таким номером не было' }

  const оЧём = (р.about ?? '').trim()
  if (!оЧём) return { ok: false, почему: 'пустое «о чём»' }

  const цитата = (р.quote ?? '').trim()
  if (цитата.length < 8) return { ok: false, почему: 'цитата слишком короткая, проверить нечем' }
  // Цитата ищется в том самом сообщении, а не в переписке вообще: иначе
  // вопрос из одного сообщения приписался бы другому.
  if (!длясверки(сообщение.content).includes(длясверки(цитата))) {
    return { ok: false, почему: 'цитаты нет в сообщении дословно' }
  }

  return {
    ok: true,
    разбор: { messageId: сообщение.message_id, вид: р.kind as ВидСообщения, оЧём, цитата },
  }
}

const ПРАВИЛА = `
Ты разбираешь входящие сообщения клиентов компании goandstudy, которая ведёт
людей в зарубежные вузы. По каждому сообщению отвечаешь на один вопрос: что это
было.

Виды:
— question: клиент о чём-то спрашивает и ждёт ответа. «Когда дедлайн?», «А
  общежитие дают?», «Что с моими документами?»
— document: клиент прислал или говорит, что прислал документ — диплом,
  справку, паспорт, сертификат.
— terms: клиент сообщает, что изменились условия — бюджет, страна, сроки,
  состав семьи, планы. Не вопрос, а новое обстоятельство.
— other: всё остальное. Благодарность, приветствие, «хорошо», «понял».

Правила:
— Сообщения от куратора и от нас не разбирай вовсе: они размечены именем
  отправителя. Нас интересует только то, что пишет клиент.
— Цитата обязана быть дословной частью того самого сообщения. Не пересказ.
— «О чём» пиши одной короткой фразой по-русски, так, чтобы куратор понял, не
  открывая чат: «спрашивает про сроки подачи в TUM», «прислал скан диплома».
— Сомневаешься между question и other — ставь question. Пропущенный вопрос
  дороже лишней задачи: лишнюю куратор закроет за секунду, а пропущенный
  обнаружится, когда клиент уйдёт.
— Сомневаешься между terms и other — ставь other. Ложное «изменение условий»
  поднимает разбор фактов и отнимает время на расхождении, которого нет.
— Одно сообщение — не больше одной записи. Если в нём и вопрос, и документ,
  выбирай вопрос: на него ждут ответа.
`.trim()

/** Разобрать пачку входящих сообщений. */
export async function разобратьСообщения(
  сообщения: Сообщение[],
  клиент: string
): Promise<ИтогРазбораВходящих> {
  const собрано: { message_id?: string; kind?: string; about?: string; quote?: string }[] = []

  const запись = betaTool({
    // Латиницей: API отвергает кириллицу и в имени инструмента, и в ключах схемы.
    name: 'record_triage',
    description: 'Записать, чем оказалось каждое сообщение клиента',
    inputSchema: {
      type: 'object',
      properties: {
        items: {
          type: 'array',
          items: {
            type: 'object',
            properties: {
              message_id: { type: 'string', description: 'Номер сообщения из списка' },
              kind: { type: 'string', enum: [...ВИДЫ] },
              about: { type: 'string', description: 'О чём, одной короткой фразой по-русски' },
              quote: { type: 'string', description: 'Дословная часть этого сообщения' },
            },
            required: ['message_id', 'kind', 'about', 'quote'],
            additionalProperties: false,
          },
        },
      },
      required: ['items'],
      additionalProperties: false,
    },
    run: async ({ items }) => {
      собрано.push(...(items ?? []))
      return `принято записей: ${(items ?? []).length}`
    },
  })

  const текст = сообщения
    .map((с) => `[${с.message_id}] ${с.sender_name ?? 'без имени'}: ${с.content}`)
    .join('\n')

  try {
    const бегун = модель().beta.messages.toolRunner({
      model: МОДЕЛЬ_МЕХАНИКИ,
      max_tokens: 8000,
      ...глубина(МОДЕЛЬ_МЕХАНИКИ, 'low'),
      system: ПРАВИЛА,
      tools: [запись],
      messages: [{ role: 'user', content: `Клиент: ${клиент}\n\nСообщения:\n${текст}` }],
      max_iterations: 4,
    })

    let вход = 0
    let выход = 0
    let модельId = МОДЕЛЬ_МЕХАНИКИ
    for await (const сообщение of бегун) {
      вход += сообщение.usage.input_tokens
      выход += сообщение.usage.output_tokens
      модельId = сообщение.model
    }

    const годные: РазборСообщения[] = []
    const отброшено: { messageId: string | null; почему: string }[] = []
    const видели = new Set<string>()

    for (const р of собрано) {
      const проверка = проверитьРазбор(р, сообщения)
      if (!проверка.ok) {
        отброшено.push({ messageId: р.message_id ?? null, почему: проверка.почему })
        continue
      }
      // Одно сообщение — одна запись: иначе по нему заведётся две задачи.
      if (видели.has(проверка.разбор.messageId)) continue
      видели.add(проверка.разбор.messageId)
      годные.push(проверка.разбор)
    }

    return { разобрано: годные, отброшено, расход: расход(модельId, вход, выход) }
  } catch (e) {
    return {
      разобрано: [],
      отброшено: [],
      расход: null,
      ошибка: e instanceof Error ? e.message : String(e),
    }
  }
}
