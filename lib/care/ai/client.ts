/**
 * Клиент модели для контура care.
 *
 * Свой, а не общий `lib/ai.ts`: тот тянет большой продажный системный промпт
 * про пакеты и цены, и помощник куратора начал бы отвечать в его тоне.
 * Импорт оттуда запрещён правилом ESLint — здесь объяснение, почему.
 *
 * ПАРАМЕТРЫ, КОТОРЫХ ЗДЕСЬ НЕТ И НЕ БУДЕТ. На claude-opus-5 сняты
 * `temperature`, `top_p`, `top_k` и `budget_tokens` — запрос с любым из них
 * отвергается с 400. Глубина рассуждения задаётся `effort`, а не токенным
 * бюджетом. Размышление включено по умолчанию, отдельно включать не нужно.
 */
import Anthropic from '@anthropic-ai/sdk'
import { требуется } from '../env'

/** Модель по умолчанию. Меняется через care.settings, не правкой кода. */
export const МОДЕЛЬ_ПО_УМОЛЧАНИЮ = 'claude-opus-5'

/**
 * Модель для механической работы: разбор входящих по ярлыкам, извлечение
 * фактов с дословной цитатой, подстановка в шаблон напоминания.
 *
 * ПОЧЕМУ НЕ ОПУС. Эти три вызова ничего не решают и ничего не сочиняют: ярлык
 * виден из самого сообщения, факт обязан найтись цитатой дословно, напоминание
 * собирается из шаблона и проверяется регулярками. За двое суток они съели
 * полтора доллара на Опусе — впятеро дороже, чем нужно, и дорожать будут с
 * каждым клиентом пилота.
 *
 * ЧЕМ ЭТО БЕЗОПАСНО. Качество здесь ловится не моделью, а проверками после
 * неё: цитата, которой нет в переписке, отбрасывается; подстановка, не
 * совпавшая с датой и именем, не проходит; ярлык не из словаря не принимается.
 * Модель послабее найдёт меньше, но не придумает лишнего.
 */
export const МОДЕЛЬ_МЕХАНИКИ = 'claude-haiku-4-5'

/**
 * Параметры глубины для модели.
 *
 * `effort` принимают не все: Haiku 4.5 отвечает на него четырёхсотым. Поэтому
 * спрашивать надо здесь, а не помнить в каждом вызове — забытое правило
 * ломается не при сборке и не в типах, а при первом же обращении к модели.
 */
export function глубина(
  модельId: string,
  уровень: 'low' | 'medium' | 'high'
): { output_config?: { effort: 'low' | 'medium' | 'high' } } {
  return модельId === МОДЕЛЬ_МЕХАНИКИ ? {} : { output_config: { effort: уровень } }
}

/**
 * Цена за миллион токенов. Нужна, чтобы записывать расход в деньгах, а не в
 * токенах: «потратили 40 тысяч токенов» никому ничего не говорит.
 */
export const ЦЕНА: Record<string, { вход: number; выход: number }> = {
  'claude-opus-5': { вход: 5, выход: 25 },
  'claude-sonnet-5': { вход: 3, выход: 15 },
  'claude-haiku-4-5': { вход: 1, выход: 5 },
}

/**
 * Можно ли сейчас ходить в веб за деньги.
 *
 * ПОЧЕМУ ЗАПРЕТ, А НЕ ФЛАГ В ВЫЗОВЕ. Поиск в сети стоит около тридцати центов
 * за вызов. В прогоне проверок он шёл каждый раз — 51 вызов и 16.58 $ за двое
 * суток, всё проверками, ни одного по работе. Я закрыл это флагом в том
 * вызове, который нашёл; но флаг надо помнить при каждом новом месте, а
 * забытый флаг не ломается — он просто стоит денег, и узнают об этом по счёту.
 *
 * Правило в одном месте помнить не надо. Прогону проверок веб закрыт; если он
 * правда нужен — включается явно и шумно:
 *
 *     CARE_TEST_ALLOW_WEB=1 npm run test:care
 */
export function вебРазрешён(): { можно: true } | { можно: false; почему: string } {
  const проверки = process.env.CARE_TEST_RUN === '1'
  if (!проверки) return { можно: true }
  if (process.env.CARE_TEST_ALLOW_WEB === '1') return { можно: true }
  return {
    можно: false,
    почему:
      'прогону проверок поиск в сети закрыт: он стоит около тридцати центов за вызов. ' +
      'Нужен по-настоящему — CARE_TEST_ALLOW_WEB=1',
  }
}

let клиент: Anthropic | null = null

export function модель(): Anthropic {
  if (!клиент) {
    клиент = new Anthropic({ apiKey: требуется('ANTHROPIC_API_KEY') })
  }
  return клиент
}

export type Расход = {
  модель: string
  вход: number
  выход: number
  долларов: number
}

/**
 * Цена по имени модели, которое вернул API.
 *
 * Имя приходит с датой выпуска: `claude-haiku-4-5-20251001`. Точный ключ его
 * не ловит, и первая версия просто брала цену по умолчанию — то есть считала
 * Haiku по цене Опуса, впятеро дороже. Расход при этом выглядел правдой и
 * показывался в кабинете.
 *
 * Поэтому ищем по началу имени, а неизвестную модель считаем по самой дорогой:
 * ошибиться в сторону «дороже, чем на самом деле» безопаснее — потолок
 * сработает раньше, а не позже.
 */
export function ценаМодели(модельId: string): { вход: number; выход: number } {
  const точная = ЦЕНА[модельId]
  if (точная) return точная

  const поНачалу = Object.keys(ЦЕНА).find((имя) => модельId.startsWith(имя))
  if (поНачалу) return ЦЕНА[поНачалу]

  const самая = Object.values(ЦЕНА).reduce((а, б) => (б.вход > а.вход ? б : а))
  console.warn(`[care цена] модель «${модельId}» не в прайсе — считаю по самой дорогой`)
  return самая
}

/** Расход одного вызова. Округление до цента вниз врёт в нашу пользу — не округляем. */
export function расход(модельId: string, вход: number, выход: number): Расход {
  const цена = ценаМодели(модельId)
  return {
    модель: модельId,
    вход,
    выход,
    долларов: (вход * цена.вход + выход * цена.выход) / 1_000_000,
  }
}
