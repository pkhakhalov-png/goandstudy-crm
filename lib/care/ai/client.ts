/**
 * Клиент модели для контура care.
 *
 * Свой, а не общий `lib/ai.ts`: тот тянет большой продажный системный промпт
 * про пакеты и цены, и помощник куратора начал бы отвечать в его тоне.
 * Импорт оттуда запрещён правилом ESLint — здесь объяснение, почему.
 *
 * ПАРАМЕТРЫ, КОТОРЫХ ЗДЕСЬ НЕТ И НЕ БУДЕТ. На claude-opus-5 сняты
 * `temperature`, `top_p`, `top_k` и `budget_tokens` — запрос с любым из них
 * отвергается с 400. Глубина рассуждения задаётся `effort`, а не токенным
 * бюджетом. Размышление включено по умолчанию, отдельно включать не нужно.
 */
import Anthropic from '@anthropic-ai/sdk'
import { требуется } from '../env'

/** Модель по умолчанию. Меняется через care.settings, не правкой кода. */
export const МОДЕЛЬ_ПО_УМОЛЧАНИЮ = 'claude-opus-5'

/**
 * Цена за миллион токенов. Нужна, чтобы записывать расход в деньгах, а не в
 * токенах: «потратили 40 тысяч токенов» никому ничего не говорит.
 */
export const ЦЕНА: Record<string, { вход: number; выход: number }> = {
  'claude-opus-5': { вход: 5, выход: 25 },
  'claude-sonnet-5': { вход: 3, выход: 15 },
  'claude-haiku-4-5': { вход: 1, выход: 5 },
}

let клиент: Anthropic | null = null

export function модель(): Anthropic {
  if (!клиент) {
    клиент = new Anthropic({ apiKey: требуется('ANTHROPIC_API_KEY') })
  }
  return клиент
}

export type Расход = {
  модель: string
  вход: number
  выход: number
  долларов: number
}

/** Расход одного вызова. Округление до цента вниз врёт в нашу пользу — не округляем. */
export function расход(модельId: string, вход: number, выход: number): Расход {
  const цена = ЦЕНА[модельId] ?? ЦЕНА[МОДЕЛЬ_ПО_УМОЛЧАНИЮ]
  return {
    модель: модельId,
    вход,
    выход,
    долларов: (вход * цена.вход + выход * цена.выход) / 1_000_000,
  }
}
