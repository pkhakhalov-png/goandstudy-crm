/**
 * Извлечение фактов из переписки.
 *
 * Модель читает сообщения дела и возвращает список полей со значениями. Всё,
 * что она вернёт, ложится **черновиками**: подтверждает человек. Это правило
 * этапа 4 и оно не обсуждается — извлечение ошибается не грубо и не всегда, а
 * тихо и иногда, и такие ошибки ловятся только глазами.
 *
 * ТРИ ЗАЩИТЫ, И КАЖДАЯ НУЖНА ОТ СВОЕГО:
 *
 *   1. **Словарь полей.** Модель выбирает из списка, а не придумывает имена.
 *      Иначе в базе заведётся `бюджет_обучения` рядом с `budget.tuition.max`,
 *      и половина фактов станет невидимой для всего остального кода.
 *
 *   2. **Цитата обязана найтись в переписке дословно.** Не «похоже на», а
 *      найтись. Это единственная проверка, которая ловит выдумку: перефразировать
 *      можно что угодно, а процитировать — только то, что было написано.
 *      Факт без такой цитаты выбрасывается, даже если выглядит верным.
 *
 *   3. **Намерение отделено от результата.** «Буду сдавать C1» и «у меня C1» —
 *      разные вещи, и вторая идёт в подбор программ, а первая нет. Модель
 *      обязана помечать `is_plan`, и сомнительное считается намерением.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Никаких решений о клиенте: модель не пишет «стоит
 * рассмотреть Германию» и не оценивает шансы. Она отвечает на один вопрос —
 * что человек про себя сообщил и какими словами.
 */
import { betaTool } from '@anthropic-ai/sdk/helpers/beta/json-schema'
import { модель, МОДЕЛЬ_ПО_УМОЛЧАНИЮ, расход, type Расход } from './client'

/**
 * Поля, которые умеет извлекать контур.
 *
 * Список короче словаря подписей намеренно: сюда входит только то, что
 * действительно встречается в переписке словами клиента. `profile.notes` и
 * прочее свободное — не извлекается: это место, куда стекается всё, что
 * модель не сумела разложить, и оно быстро становится свалкой.
 */
export const ПОЛЯ_ИЗВЛЕЧЕНИЯ = [
  'budget.tuition.max',
  'budget.living.max',
  'intake.year',
  'intake.term',
  'country.target',
  'language.ielts.overall',
  'language.toefl.overall',
  'language.german.level',
  'language.english.level',
  'gpa.value',
  'education.current',
  'education.level_target',
  'program.field',
] as const

export type ИзвлечённыйФакт = {
  field: string
  value: string | number
  currency?: string | null
  period?: string | null
  speaker: 'student' | 'parent' | 'curator' | 'other'
  quote: string
  is_plan: boolean
}

export type Сообщение = {
  message_id: string
  created_at: string
  sender_name: string | null
  content: string
}

/**
 * Нормализация для сверки цитаты.
 *
 * Модель почти наверняка вернёт цитату с другими кавычками, схлопнутыми
 * переносами строк или без эмодзи — и это не выдумка, а нормальное
 * цитирование. Сверять посимвольно значит выбрасывать годные факты; сверять
 * «по смыслу» значит не сверять вовсе. Середина: убираем то, что не несёт
 * смысла, и требуем точного совпадения оставшегося.
 */
function длясверки(т: string): string {
  return т
    .toLowerCase()
    .replace(/[«»"'`„“”]/g, '')
    .replace(/[\s ]+/g, ' ')
    .replace(/[^\p{L}\p{N} .,:;%+\-/()]/gu, '')
    .trim()
}

export type ПроверкаФакта =
  | { ok: true; факт: ИзвлечённыйФакт; messageId: string }
  | { ok: false; почему: string }

/**
 * Проверить один извлечённый факт против самой переписки.
 *
 * Возвращает и сообщение, в котором цитата нашлась: без него факт нельзя
 * привязать к источнику, а факт без источника в этом контуре не факт.
 */
export function проверитьФакт(факт: ИзвлечённыйФакт, сообщения: Сообщение[]): ПроверкаФакта {
  if (!(ПОЛЯ_ИЗВЛЕЧЕНИЯ as readonly string[]).includes(факт.field)) {
    return { ok: false, почему: `поле «${факт.field}» не из словаря` }
  }

  const значение = typeof факт.value === 'string' ? факт.value.trim() : факт.value
  if (значение === '' || значение === null || значение === undefined) {
    return { ok: false, почему: 'пустое значение' }
  }

  if (факт.field.startsWith('budget.') && !факт.currency) {
    return { ok: false, почему: 'сумма без валюты' }
  }

  const цитата = (факт.quote ?? '').trim()
  if (цитата.length < 8) return { ok: false, почему: 'цитата слишком короткая, проверить нечем' }

  const искомое = длясверки(цитата)
  const источник = сообщения.find((с) => длясверки(с.content).includes(искомое))
  if (!источник) return { ok: false, почему: 'цитаты нет в переписке дословно' }

  return { ok: true, факт: { ...факт, value: значение, quote: цитата }, messageId: источник.message_id }
}

export type ИтогИзвлечения = {
  факты: { факт: ИзвлечённыйФакт; messageId: string }[]
  отброшено: { поле: string; почему: string }[]
  расход: Расход | null
  ошибка?: string
}

/**
 * Прочитать переписку и вернуть проверенные факты.
 *
 * Сообщения отдаются с номерами и именами отправителей: без имени модель не
 * отличит слова студента от слов куратора, а `speaker` решает, чьё это
 * утверждение. Слова куратора — не факт о клиенте, и такие мы отбросим сами.
 */
export async function извлечьФакты(
  сообщения: Сообщение[],
  клиент: string
): Promise<ИтогИзвлечения> {
  if (!сообщения.length) {
    return { факты: [], отброшено: [], расход: null, ошибка: 'сообщений нет' }
  }

  const собрано: ИзвлечённыйФакт[] = []

  const инструмент = betaTool({
    // Имя инструмента латиницей: API принимает только [a-zA-Z0-9_-] и
    // отвергает кириллицу четырёхсотым. Описание и поля — по-русски.
    name: 'record_facts',
    description:
      'Записать факты, которые клиент или его родитель сообщили о себе в переписке. ' +
      'Вызови ровно один раз, даже если фактов ноль.',
    inputSchema: {
      type: 'object',
      properties: {
        facts: {
          type: 'array',
          items: {
            type: 'object',
            properties: {
              field: { type: 'string', enum: [...ПОЛЯ_ИЗВЛЕЧЕНИЯ] },
              value: {
                anyOf: [{ type: 'string' }, { type: 'number' }],
                description: 'Значение. Для сумм — число без валюты, валюта отдельным полем.',
              },
              currency: { type: ['string', 'null'], description: 'EUR, USD, RUB — обязательно для сумм' },
              period: { type: ['string', 'null'], description: 'год или месяц, если сказано' },
              speaker: { type: 'string', enum: ['student', 'parent', 'curator', 'other'] },
              quote: {
                type: 'string',
                description:
                  'ДОСЛОВНАЯ фраза из переписки, на которой стоит вывод. Копируй, не пересказывай. ' +
                  'Одно предложение целиком.',
              },
              is_plan: {
                type: 'boolean',
                description: 'true — это намерение («буду сдавать»), false — уже имеющийся результат',
              },
            },
            required: ['field', 'value', 'speaker', 'quote', 'is_plan'],
            additionalProperties: false,
          },
        },
      },
      required: ['facts'],
      additionalProperties: false,
    },
    run: async ({ facts }) => {
      собрано.push(...((facts ?? []) as ИзвлечённыйФакт[]))
      return 'записано'
    },
  })

  const переписка = сообщения
    .map((с, i) => `[${i + 1}] ${с.created_at.slice(0, 10)} ${с.sender_name ?? 'без имени'}: ${с.content}`)
    .join('\n')

  try {
    const бегун = модель().beta.messages.toolRunner({
      model: МОДЕЛЬ_ПО_УМОЛЧАНИЮ,
      max_tokens: 4000,
      // Работа разборчивая: понять, кто что сказал и чем отличается намерение
      // от результата. Здесь глубина окупается — в отличие от формулировки
      // напоминания, где решать нечего.
      output_config: { effort: 'medium' },
      tools: [инструмент],
      system:
        `Ты разбираешь переписку куратора с клиентом goandstudy (${клиент}) и выписываешь факты о клиенте.\n\n` +
        'ЖЁСТКИЕ ПРАВИЛА:\n' +
        '— Цитата дословная. Копируй фразу из переписки целиком, не пересказывай и не сокращай. ' +
        'Факт без точной цитаты будет выброшен.\n' +
        '— Только то, что сказал сам клиент или его родитель о себе. Слова куратора и общие пояснения — не факты.\n' +
        '— Намерение отличай от результата. «Планирую сдать IELTS» — is_plan true. «Сдал на 7.0» — false. ' +
        'Сомневаешься — считай намерением.\n' +
        '— Не выводи из косвенного. «Хочу в Берлин» — это не подтверждённая страна, если прямо не сказано.\n' +
        '— Одно поле — один самый свежий факт. Если клиент менял мнение, бери последнее и процитируй именно его.\n' +
        '— Ничего не додумывай. Пусто — верни пустой список, это нормальный ответ.',
      messages: [{ role: 'user', content: `Переписка:\n\n${переписка}` }],
      max_iterations: 4,
    })

    // Считаем расход по каждому шагу, а не по последнему ответу: вызов
    // инструмента — это ещё один запрос с полной перепиской во входе, и он
    // стоит столько же, сколько первый.
    let потрачено = { вход: 0, выход: 0, модельId: МОДЕЛЬ_ПО_УМОЛЧАНИЮ }
    for await (const сообщение of бегун) {
      потрачено = {
        вход: потрачено.вход + сообщение.usage.input_tokens,
        выход: потрачено.выход + сообщение.usage.output_tokens,
        модельId: сообщение.model,
      }
    }
    const р = расход(потрачено.модельId, потрачено.вход, потрачено.выход)

    const годные: { факт: ИзвлечённыйФакт; messageId: string }[] = []
    const отброшено: { поле: string; почему: string }[] = []

    for (const факт of собрано) {
      // Слова куратора отбрасываем здесь, а не промптом: промпт — просьба,
      // а это правило.
      if (факт.speaker === 'curator') {
        отброшено.push({ поле: факт.field, почему: 'это слова куратора, а не клиента' })
        continue
      }
      const проверка = проверитьФакт(факт, сообщения)
      if (проверка.ok) годные.push({ факт: проверка.факт, messageId: проверка.messageId })
      else отброшено.push({ поле: факт.field, почему: проверка.почему })
    }

    return { факты: годные, отброшено, расход: р }
  } catch (e) {
    return {
      факты: [],
      отброшено: [],
      расход: null,
      ошибка: e instanceof Error ? e.message : String(e),
    }
  }
}
