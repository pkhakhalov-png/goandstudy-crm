/**
 * Дневной потолок расхода на модель — и учёт того, что уже потрачено.
 *
 * ПОЧЕМУ ПРОВЕРКА ЗДЕСЬ, А НЕ В БАЗЕ. Ограничение в базе умеет отказать во
 * вставке, но не умеет не делать вызов: деньги тратятся до того, как что-то
 * записывается. Проверять надо перед обращением к модели, то есть в коде.
 *
 * ПОЧЕМУ ПОТОЛОК — ЭТО ПРЕДОХРАНИТЕЛЬ, А НЕ БЮДЖЕТ. Упереться в дневной
 * потолок при нормальной работе нельзя: одно напоминание стоит около полутора
 * центов, а потолок на них — три доллара. Если он сработал, значит что-то
 * зациклилось, и правильная реакция — остановиться и показать это человеку, а
 * не тратить дальше.
 *
 * ЧТО ПРОИСХОДИТ ПРИ ОТКАЗЕ. Работа не срывается: тот, кто зовёт модель,
 * обязан иметь запасной путь без неё. У напоминаний это шаблон. Отказ потолка
 * — повод написать проще, а не повод не написать.
 *
 * ПРОВЕРКИ СЧИТАЮТСЯ ОТДЕЛЬНО. Прогон проверок зовёт модель по-настоящему —
 * иначе он ничего не проверяет, — и однажды съел дневной потолок подбора
 * целиком: до полуночи куратор не мог собрать ни одной подборки. Поэтому у
 * проверок свой вид и свой потолок: он так же останавливает зацикленную
 * проверку, но останавливает её, а не работу кабинета. Расход при этом пишется
 * весь: деньги потрачены настоящие, и не видеть их хуже всего.
 */
import { базаCare } from '../db'
import type { Расход } from './client'

/**
 * Идёт ли сейчас прогон проверок.
 *
 * Переменную выставляет только `tests/care/setup.ts`. Читается на сервере, где
 * исполняется вызов модели, — из браузера её не подставить.
 */
function этоПроверки(): boolean {
  return process.env.CARE_TEST_RUN === '1'
}

/** Вид, под которым считается расход проверок. */
const ВИД_ПРОВЕРОК = 'tests'

export type РешениеПотолка =
  | { можно: true; осталось: number }
  | { можно: false; почему: string; потрачено: number; потолок: number }

/**
 * Можно ли звать модель по этому виду работы прямо сейчас.
 *
 * Ноль в потолке означает «не расходовать вовсе» — так заведены все виды до
 * решения владельца. Это не ошибка настройки, и текст отказа говорит именно
 * это, а не «превышен лимит».
 */
export async function можноТратить(вид: string): Promise<РешениеПотолка> {
  // Словарь видов проверяется всегда, и в прогоне проверок тоже. Опечатка в
  // названии вида не должна открывать расход без потолка ни при каких
  // обстоятельствах — а если подменять вид целиком, именно это и выходит.
  const { data: свой, error } = await базаCare()
    .from('job_kinds_budget')
    .select('daily_budget_usd')
    .eq('kind', вид)
    .maybeSingle()

  if (error) {
    // Не знаем потолка — не тратим. Молча продолжить значило бы, что сбой
    // чтения настройки снимает ограничение.
    return { можно: false, почему: `не удалось прочитать потолок: ${error.message}`, потрачено: 0, потолок: 0 }
  }
  if (!свой) {
    return { можно: false, почему: `вид работы «${вид}» не заведён в потолках`, потрачено: 0, потолок: 0 }
  }
  if (Number(свой.daily_budget_usd) <= 0) {
    // Ноль означает «не расходовать вовсе» — и в прогоне проверок тоже: иначе
    // проверки ходили бы туда, куда работе ходить запрещено.
    return {
      можно: false,
      почему: `по виду «${вид}» модель не зовём: дневной потолок ноль`,
      потрачено: 0,
      потолок: 0,
    }
  }

  // А вот счёт и потолок, по которым решаем, — свои у прогона проверок.
  // Иначе исчерпанный рабочий потолок красил бы проверки, а исчерпанный
  // проверками — останавливал бы куратора.
  const считаем = этоПроверки() ? ВИД_ПРОВЕРОК : вид

  let потолок = Number(свой.daily_budget_usd)
  if (считаем !== вид) {
    const { data: строка } = await базаCare()
      .from('job_kinds_budget')
      .select('daily_budget_usd')
      .eq('kind', считаем)
      .maybeSingle()
    потолок = Number(строка?.daily_budget_usd ?? 0)
    if (потолок <= 0) {
      return {
        можно: false,
        почему: `потолок прогона проверок «${считаем}» не заведён или равен нулю`,
        потрачено: 0,
        потолок,
      }
    }
  }

  const { data: потрачено } = этоПроверки()
    ? await базаCare().rpc('spent_today_test')
    : await базаCare().rpc('spent_today', { p_kind: вид })
  const сегодня = Number(потрачено ?? 0)

  if (сегодня >= потолок) {
    return {
      можно: false,
      почему: `дневной потолок по виду «${считаем}» исчерпан: ${сегодня.toFixed(2)} из ${потолок.toFixed(2)} $`,
      потрачено: сегодня,
      потолок,
    }
  }

  return { можно: true, осталось: потолок - сегодня }
}

/**
 * Записать расход вызова.
 *
 * Пишется всегда, даже когда ответ модели не пригодился и его выбросили:
 * деньги за него уже уплачены. Журнал, в котором видны только удачные вызовы,
 * показывает расход меньше настоящего — и именно в тот момент, когда что-то
 * идёт не так и вызовы уходят впустую.
 */
export async function записатьРасход(
  вид: string,
  р: Расход,
  привязка: { caseId?: string | null; jobId?: string | null; пометка?: string } = {}
): Promise<void> {
  const { error } = await базаCare().from('ai_spend').insert({
    kind: вид,
    // Вид остаётся настоящим: по нему видно, на что ушли деньги. Отдельно
    // стоит только признак — чтобы расход проверок не закрывал работу.
    is_test: этоПроверки(),
    model: р.модель,
    tokens_in: р.вход,
    tokens_out: р.выход,
    usd: р.долларов,
    case_id: привязка.caseId ?? null,
    job_id: привязка.jobId ?? null,
    note: привязка.пометка ?? null,
  })

  // Не бросаем: несохранённая строка учёта — плохо, но сорванная из-за этого
  // работа хуже. Причина остаётся в журнале сервера.
  if (error) console.warn('[care расход] не записан:', error.message)
}
