/**
 * Проверка требований программы на сайте вуза.
 *
 * ЗАЧЕМ. Подборка приходит со списком «что проверить»: язык обучения,
 * стоимость, сроки подачи, требования к языку и документам. Этот список
 * честный, но его кто-то должен закрыть — иначе он просто перекладывает работу
 * на куратора, и подборка экономит меньше, чем кажется.
 *
 * ЧТО СЧИТАЕТСЯ ПРОВЕРЕННЫМ. Только то, под чем есть цитата со страницы и
 * адрес этой страницы. Не «обычно в Италии взнос по ISEE», а конкретная
 * фраза с конкретного сайта. Остальное остаётся `not_found` — и это тоже
 * ответ, причём полезный: куратор видит, что на сайте этого нет, и не ищет
 * второй раз.
 *
 * ЧЕГО МОДЕЛЬ НЕ ДЕЛАЕТ. Не решает, подходит ли программа. Она отвечает на
 * четыре узких вопроса по странице и приносит цитаты. Вывод делает человек.
 */
import { betaTool } from '@anthropic-ai/sdk/helpers/beta/json-schema'
import { модель, МОДЕЛЬ_ПО_УМОЛЧАНИЮ, расход, type Расход } from './client'

/** Что именно спрашиваем у страницы. Список закрытый: иначе ответы не сложить. */
export const ВИДЫ_ТРЕБОВАНИЙ = [
  'language_of_instruction',
  'tuition_per_year',
  'application_deadline',
  'language_certificate',
  'documents',
  'entrance_exam',
] as const

export type ВидТребования = (typeof ВИДЫ_ТРЕБОВАНИЙ)[number]

export const ПОДПИСЬ_ТРЕБОВАНИЯ: Record<ВидТребования, string> = {
  language_of_instruction: 'язык обучения',
  tuition_per_year: 'стоимость за год',
  application_deadline: 'срок подачи',
  language_certificate: 'языковой сертификат',
  documents: 'документы',
  entrance_exam: 'вступительные испытания',
}

export type НайденноеТребование = {
  requirement_type: ВидТребования
  value: string
  excerpt: string
  source_url: string
  found: boolean
}

export type ИтогПроверки = {
  требования: НайденноеТребование[]
  отброшено: { вид: string; почему: string }[]
  расход: Расход | null
  ошибка?: string
}

/**
 * Проверить одно требование перед записью.
 *
 * Цитата обязательна и должна быть не короче фразы: по трём словам совпадёт
 * что угодно, а проверять потом будет куратор. Адрес обязателен и должен
 * вести на сайт — без него требование нельзя перепроверить через полгода,
 * когда вуз поменяет правила.
 */
export function проверитьТребование(
  т: НайденноеТребование
): { ok: true } | { ok: false; почему: string } {
  if (!(ВИДЫ_ТРЕБОВАНИЙ as readonly string[]).includes(т.requirement_type)) {
    return { ok: false, почему: `вид «${т.requirement_type}» не из словаря` }
  }

  // «Не нашлось» — полноценный ответ, и цитата ему не нужна.
  if (!т.found) return { ok: true }

  if (!т.value?.trim()) return { ok: false, почему: 'пустое значение при found = true' }
  if ((т.excerpt ?? '').trim().length < 15) {
    return { ok: false, почему: 'цитата короче фразы — проверить по ней нельзя' }
  }

  try {
    const u = new URL(т.source_url)
    if (u.protocol !== 'https:' && u.protocol !== 'http:') {
      return { ok: false, почему: 'адрес источника не http' }
    }
  } catch {
    return { ok: false, почему: 'нет разбираемого адреса источника' }
  }

  return { ok: true }
}

/**
 * Прочитать страницу программы и ответить на вопросы по ней.
 *
 * Страница передаётся адресом: модель открывает её сама серверным поиском.
 * Своего обхода страниц мы не делаем — чужой сайт может отдать что угодно, и
 * разбирать это надёжнее модели, чем регулярками.
 */
export async function проверитьПрограмму(
  ссылка: string,
  подпись: string
): Promise<ИтогПроверки> {
  const собрано: НайденноеТребование[] = []

  const запись = betaTool({
    name: 'record_requirements',
    description:
      'Записать то, что нашлось на странице программы. Вызови один раз, когда прочитал страницу. ' +
      'По каждому вопросу — отдельная запись, даже если ответа на странице нет.',
    inputSchema: {
      type: 'object',
      properties: {
        requirements: {
          type: 'array',
          items: {
            type: 'object',
            properties: {
              requirement_type: { type: 'string', enum: [...ВИДЫ_ТРЕБОВАНИЙ] },
              found: { type: 'boolean', description: 'Нашлось ли это на странице' },
              value: { type: 'string', description: 'Коротко, как на странице. Пусто, если не нашлось.' },
              excerpt: {
                type: 'string',
                description:
                  'ДОСЛОВНАЯ фраза со страницы, на которой стоит ответ. Копируй, не пересказывай. ' +
                  'Пусто, если не нашлось.',
              },
              source_url: { type: 'string', description: 'Адрес страницы, где это написано' },
            },
            required: ['requirement_type', 'found', 'value', 'excerpt', 'source_url'],
            additionalProperties: false,
          },
        },
      },
      required: ['requirements'],
      additionalProperties: false,
    },
    run: async ({ requirements }) => {
      собрано.push(...((requirements ?? []) as НайденноеТребование[]))
      return 'записано'
    },
  })

  try {
    const бегун = модель().beta.messages.toolRunner({
      model: МОДЕЛЬ_ПО_УМОЛЧАНИЮ,
      max_tokens: 8000,
      output_config: { effort: 'low' },
      tools: [
        { type: 'web_search_20260209', name: 'web_search', max_uses: 6 },
        запись,
      ],
      system:
        'Ты читаешь страницу программы вуза и отвечаешь на шесть вопросов по ней: язык обучения, ' +
        'стоимость за год, срок подачи, требования к языковому сертификату, список документов, ' +
        'вступительные испытания.\n\n' +
        'ЖЁСТКИЕ ПРАВИЛА:\n' +
        '— Отвечай только по странице и соседним страницам того же сайта. Общие знания о стране ' +
        'или вузе — не ответ: их нельзя перепроверить.\n' +
        '— Цитата дословная, целой фразой. Факт без цитаты будет выброшен.\n' +
        '— Не нашёл — так и напиши: found = false. Это нормальный и полезный ответ, ' +
        'а выдуманная стоимость хуже отсутствующей: по ней клиент считает бюджет.\n' +
        '— Для стоимости указывай валюту и за какой период. Для срока — дату как на странице.\n' +
        '— Запиши ровно по одной записи на каждый из шести вопросов.',
      messages: [
        {
          role: 'user',
          content: `Программа: ${подпись}\nСтраница: ${ссылка}\n\nПрочитай её и запиши, что нашлось.`,
        },
      ],
      max_iterations: 8,
    })

    let вход = 0
    let выход = 0
    let модельId = МОДЕЛЬ_ПО_УМОЛЧАНИЮ
    for await (const сообщение of бегун) {
      вход += сообщение.usage.input_tokens
      выход += сообщение.usage.output_tokens
      модельId = сообщение.model
      if (сообщение.stop_reason === 'pause_turn') {
        бегун.pushMessages({ role: 'assistant', content: сообщение.content })
      }
    }

    const годные: НайденноеТребование[] = []
    const отброшено: { вид: string; почему: string }[] = []
    for (const т of собрано) {
      const проверка = проверитьТребование(т)
      if (проверка.ok) годные.push(т)
      else отброшено.push({ вид: т.requirement_type, почему: проверка.почему })
    }

    return { требования: годные, отброшено, расход: расход(модельId, вход, выход) }
  } catch (e) {
    return {
      требования: [],
      отброшено: [],
      расход: null,
      ошибка: e instanceof Error ? e.message : String(e),
    }
  }
}
