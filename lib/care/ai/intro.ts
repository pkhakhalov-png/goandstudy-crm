/**
 * Вступление к подборке — две-три фразы клиенту.
 *
 * ЧТО МОДЕЛИ ОТДАЮТ. Список программ: вуз, страна, стоимость, что осталось
 * уточнить. Ни имени клиента, ни бюджета, ни сведений из дела — вступление
 * читает человек, которому мы и так всё это знаем, а на странице этого быть
 * не должно: ссылку могут переслать.
 *
 * ЧТО МОДЕЛЬ НЕ ДЕЛАЕТ. Не называет программы и цены — они подставляются в
 * страницу из строк подборки. Её дело — объяснить, что это за список и что с
 * ним делать дальше.
 */
import { модель, МОДЕЛЬ_ПО_УМОЛЧАНИЮ, расход, type Расход } from './client'

export type СтрокаДляВступления = {
  вуз: string
  программа: string
  страна: string
  стоимость: string | null
  проверить: string[]
}

export type Вступление = { текст: string; расход: Расход | null; ошибка?: string }

/**
 * Проверить вступление перед тем, как показать его клиенту.
 *
 * Главное — чтобы оно не обещало того, чего мы не проверяли, и не называло
 * цифр: цифры на странице приходят из строк, и второе их появление в тексте
 * однажды разойдётся с первым.
 */
export function проверитьВступление(текст: string): { ok: true } | { ok: false; почему: string } {
  const т = текст.trim()
  if (т.length < 60) return { ok: false, почему: 'слишком коротко' }
  if (т.length > 700) return { ok: false, почему: 'слишком длинно для вступления' }
  if (/(\*\*|^#{1,6}\s|^[-*]\s)/m.test(т)) return { ok: false, почему: 'в тексте разметка' }
  if (/https?:\/\//i.test(т)) return { ok: false, почему: 'в тексте ссылка' }

  // Цифры стоимости и годов в тексте запрещены: они уже есть в карточках
  // программ, и две версии одного числа рано или поздно разойдутся.
  if (/\b\d{3,}\b/.test(т)) return { ok: false, почему: 'в тексте числа — они должны быть только в карточках' }

  // Обещания. Поступление не гарантирует никто, и страница — не место, где
  // компания впервые это пообещает.
  if (/гарантиру|обязательно поступ|точно поступ|100%/i.test(т)) {
    return { ok: false, почему: 'в тексте обещание поступления' }
  }

  return { ok: true }
}

export async function написатьВступление(строки: СтрокаДляВступления[]): Promise<Вступление> {
  if (!строки.length) return { текст: '', расход: null, ошибка: 'подборка пуста' }

  try {
    const ответ = await модель().messages.create({
      model: МОДЕЛЬ_ПО_УМОЛЧАНИЮ,
      max_tokens: 600,
      output_config: { effort: 'low' },
      system:
        'Ты пишешь вступление к подборке программ, которую клиент goandstudy откроет по ссылке. ' +
        'Две-три фразы перед списком.\n\n' +
        'ЖЁСТКИЕ ПРАВИЛА:\n' +
        '— Обычный текст: ни разметки, ни списков, ни заголовков.\n' +
        '— Никаких чисел, цен, годов и ссылок — они уже есть в карточках программ ниже.\n' +
        '— Ничего не обещай: ни поступления, ни сроков, ни стипендий.\n' +
        '— Скажи, по какому принципу собран список и что требует уточнения — ' +
        'клиент должен понимать, что стоимость и требования ещё проверяются.\n' +
        '— Без обращения по имени: страницу может открыть родитель.\n' +
        '— Без «мы рады» и «с удовольствием представляем».',
      messages: [
        {
          role: 'user',
          content: JSON.stringify(
            строки.map((с) => ({
              вуз: с.вуз,
              страна: с.страна,
              программа: с.программа,
              стоимость_известна: с.стоимость != null,
              осталось_уточнить: с.проверить,
            })),
            null,
            1
          ),
        },
      ],
    })

    const р = расход(ответ.model, ответ.usage.input_tokens, ответ.usage.output_tokens)
    if (ответ.stop_reason === 'refusal') return { текст: '', расход: р, ошибка: 'модель отказалась' }

    const текст = ответ.content
      .map((б) => (б.type === 'text' ? б.text : ''))
      .filter(Boolean)
      .join('\n')
      .trim()

    const проверка = проверитьВступление(текст)
    if (!проверка.ok) return { текст: '', расход: р, ошибка: проверка.почему }

    return { текст, расход: р }
  } catch (e) {
    return { текст: '', расход: null, ошибка: e instanceof Error ? e.message : String(e) }
  }
}
