/**
 * Сравнение секретов.
 *
 * Почему не `===`. Обычное сравнение строк останавливается на первом
 * несовпавшем символе, и время ответа зависит от того, сколько символов
 * совпало. По этой разнице секрет подбирается посимвольно. Разница
 * микроскопическая, но вебхук можно звать сколько угодно раз, а усреднение
 * шума — вопрос терпения.
 *
 * Отдельный файл, а не импорт `lib/webhook-secret.ts`: правило границ контура
 * (п. 0.3 плана) разрешает из `lib/care/**` импортировать строго
 * перечисленное, и общий модуль секретов в этот список не входит.
 */
import { timingSafeEqual } from 'crypto'

/**
 * Годится ли секрет как секрет.
 *
 * Пустая строка и «changeme» — не секреты. Проверка нужна, чтобы негодное
 * значение отвергалось явно, а не притворялось работающей защитой.
 */
export function секретГодится(секрет: string | null | undefined): { ok: true } | { ok: false; почему: string } {
  if (!секрет || !секрет.trim()) return { ok: false, почему: 'пустой' }
  const s = секрет.trim()
  if (s.length < 16) return { ok: false, почему: `короче 16 символов (${s.length})` }
  if (/^(changeme|secret|password|test)$/i.test(s)) return { ok: false, почему: 'значение-заглушка' }
  return { ok: true }
}

/**
 * Совпали ли секреты. Время работы не зависит от того, где именно расхождение.
 *
 * Разная длина — сразу false: `timingSafeEqual` на буферах разной длины
 * бросает исключение, и длину всё равно не скрыть.
 */
export function секретыСовпали(пришедший: string | null | undefined, ожидаемый: string): boolean {
  if (!пришедший) return false
  const a = Buffer.from(пришедший, 'utf8')
  const b = Buffer.from(ожидаемый, 'utf8')
  if (a.length !== b.length) return false
  return timingSafeEqual(a, b)
}
