/**
 * Знак вуза: буквы в круге, нарисованные нами.
 *
 * ПОЧЕМУ НЕ НАСТОЯЩИЙ ЛОГОТИП. В справочнике вузов под видом логотипов лежат
 * ссылки на чужие сервисы фавиконок — Google и DuckDuckGo. На странице,
 * которую открывает клиент, это недопустимо дважды: она не грузит ничего
 * снаружи по построению, и такая картинка сообщает Google, что этот человек её
 * открыл. Настоящие логотипы появятся, когда мы начнём хранить их у себя;
 * колонка `image_url` для этого уже есть и ждёт.
 *
 * ПОЧЕМУ ВООБЩЕ КАРТИНКА. Список из восьми строк без них читается как таблица.
 * Клиент смотрит подборку с телефона и запоминает вузы в лицо — разный цвет и
 * буквы дают это почти бесплатно.
 *
 * Цвет считается из названия, а не выбирается случайно: один и тот же вуз
 * всегда одного цвета, и на двух разных экранах он узнаётся.
 */

/**
 * Буквы для знака.
 *
 * Сначала ищем аббревиатуру — «RWTH», «TUM», «МГУ». Если вуз сам себя так
 * называет, именно её человек и узнаёт; собранные из первых букв «TM» и «MU»
 * не говорят ему ничего.
 */
export function буквыВуза(название: string): string {
  // Разбираем на слова, а не ищем регулярным выражением с `\b`: в JavaScript
  // это граница ASCII-слова, и «МГУ» она не находит. Те же грабли уже ловили
  // в разборе уровня программы — здесь они повторились бы молча.
  const токены = название.split(/[\s,—–()\-]+/).filter(Boolean)
  const аббревиатура = токены.find((т) => т.length >= 2 && т.length <= 4 && т === т.toUpperCase() && /\p{L}/u.test(т))
  if (аббревиатура) return аббревиатура

  const общие = new Set([
    'university', 'universität', 'universitat', 'université', 'università',
    'technical', 'technische', 'hochschule', 'college', 'institute', 'school',
    'the', 'of', 'and', 'für', 'des', 'der', 'van', 'di', 'da',
    'университет', 'университета', 'институт', 'академия', 'имени',
  ])

  const слова = название
    .replace(/\([^)]*\)/g, ' ')
    .split(/[\s,—–-]+/)
    .map((с) => с.replace(/[^\p{L}]/gu, ''))
    .filter((с) => с.length > 1 && !общие.has(с.toLowerCase()))

  if (!слова.length) return название.slice(0, 2).toUpperCase()
  if (слова.length === 1) return слова[0].slice(0, 2).toUpperCase()
  return (слова[0][0] + слова[1][0]).toUpperCase()
}

/**
 * Цвет знака — из названия, устойчиво.
 *
 * Берём оттенок из простого хэша и держим насыщенность и светлоту в узком
 * диапазоне: иначе часть вузов получит кислотный цвет, а часть — серый, и
 * список развалится на глаз.
 */
export function цветВуза(название: string): string {
  let хэш = 0
  for (const знак of название) хэш = (хэш * 31 + знак.codePointAt(0)!) % 360
  return `hsl(${хэш} 42% 46%)`
}
