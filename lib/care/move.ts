/**
 * Переезд контура на боевой адрес — решение «можно ли переключать».
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНО ОТ СКРИПТА. Правило здесь одно, и ошибка в нём не
 * заметна: переключив адреса до того, как боевая выкладка ожила, мы получаем
 * расписание, которое зовёт несуществующий адрес, и Телеграм, который шлёт
 * события в пустоту. Ошибок не будет ни одной — просто перестанут приходить
 * сообщения и готовиться напоминания. На сутки это выглядит как спокойный день.
 *
 * Поэтому правило проверяется тестом, а не глазами при каждом переезде.
 */
export const БОЕВОЙ = 'https://crm.goandstudy.com'
export const ПРЕВЬЮ =
  'https://goandstudy-crm-git-feat-curator-v2-pkhakhalov-pngs-projects.vercel.app'

/** Указывает ли адрес на боевой сайт. */
export function наБою(адрес: string | null | undefined): boolean {
  return Boolean(адрес && адрес.startsWith(БОЕВОЙ))
}

export type РешениеПереезда = { можно: true } | { можно: false; почему: string }

/**
 * Можно ли переключать адреса на бой.
 *
 * Возврат на превью разрешён всегда: он не делает хуже, а чинит. Переезд
 * вперёд — только когда бой отвечает и все переменные контура на месте.
 */
export function можноПереключать(
  боевойОтвечает: boolean,
  нехватаетПеременных: string[],
  обратно = false
): РешениеПереезда {
  if (обратно) return { можно: true }

  if (!боевойОтвечает) {
    return {
      можно: false,
      почему:
        'боевой адрес не отвечает на /api/care/health — кода контура там нет. ' +
        'Сначала мерж в main и выкладка, потом адреса.',
    }
  }
  if (нехватаетПеременных.length) {
    return {
      можно: false,
      почему:
        `на бою не хватает переменных: ${нехватаетПеременных.join(', ')}. ` +
        'Без них контур ответит, но работать не сможет.',
    }
  }
  return { можно: true }
}

/** Адреса воркера и вебхука для стороны переезда. */
export function адресаДля(обратно: boolean, обход?: string | null): { tick: string; вебхук: string } {
  const куда = обратно ? ПРЕВЬЮ : БОЕВОЙ
  // Обход защиты Vercel нужен только превью: на бою его нет и быть не должно —
  // подставленный туда, он остался бы в адресе, который видит Телеграм.
  const хвост = обратно && обход ? `?x-vercel-protection-bypass=${обход}` : ''
  return {
    tick: `${куда}/api/care/tick${хвост}`,
    вебхук: `${куда}/api/care/webhooks/telegram${хвост}`,
  }
}
