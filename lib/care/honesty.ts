/**
 * Пустое «что проверить» — это утверждение, а не отсутствие сведений.
 *
 * ЧТО ВИДИТ КЛИЕНТ. На странице подборки под каждой программой есть строка
 * «Уточняем: …». Когда её нет, человек читает это как «здесь всё проверено» —
 * и строит на этом планы: подаёт документы, считает деньги, отказывается от
 * других вариантов.
 *
 * КОГДА ЭТО НЕПРАВДА. Строка попадает в подборку с пустым списком, если модель
 * при поиске не назвала, что осталось выяснить. Проверка требований при этом не
 * запускалась ни разу, в `care.program_requirements` по этой программе нет ни
 * одной подтверждённой записи — и клиенту всё равно показывается чистая
 * карточка. Это худший вид ошибки в контуре: она не ломается, она врёт.
 *
 * ПОЧЕМУ ЧИНИМ, А НЕ ЗАПРЕЩАЕМ. Отказать в публикации значит оставить куратора
 * перед запертой дверью: подборка собрана, клиент ждёт, а кнопка не работает и
 * сделать с этим нечего. Поэтому недостающая пометка дописывается, а куратору
 * говорится, у скольких программ и почему. Он решает, публиковать так или
 * сперва запустить проверку требований.
 *
 * ПОЧЕМУ ПЕРЕД ПУБЛИКАЦИЕЙ, А НЕ ПРИ СБОРКЕ. При сборке проверка требований
 * ещё не проходила ни у кого — все строки выглядели бы непроверенными, и
 * пометка перестала бы что-либо значить. Публикация — момент, когда список
 * уходит человеку, и ровно тогда утверждение должно быть обеспечено.
 */
import { базаCare } from './db'

/** Что дописываем, когда подтвердить нечем. */
export const ПОМЕТКА = 'требования не проверены'

export type ИтогСверки = {
  /** Сколько строк заявляли «всё проверено», не имея на это оснований. */
  исправлено: number
  названия: string[]
}

/**
 * Проверить и дописать пометку там, где она должна быть.
 *
 * Свежесть проверки здесь не смотрим: устаревшая запись — это всё-таки
 * проверка, и отдельный разговор. Здесь ловится другое — её полное отсутствие.
 */
export async function обеспечитьЧестность(shortlistId: string): Promise<ИтогСверки> {
  const итог: ИтогСверки = { исправлено: 0, названия: [] }

  const { data: строки } = await базаCare()
    .from('shortlist_items')
    .select('id, program_ref, unresolved, status')
    .eq('shortlist_id', shortlistId)

  // Убранные клиенту не показываются — про них врать некому.
  const живые = (строки ?? []).filter((с) => с.status !== 'removed')
  const подозрительные = живые.filter((с) => !((с.unresolved ?? []) as string[]).length)
  if (!подозрительные.length) return итог

  for (const с of подозрительные) {
    const ref = (с.program_ref ?? {}) as Record<string, string>
    const ссылка = ref.ссылка

    // Без ссылки проверять было нечего по определению: страницу программы мы
    // не открывали, и утверждать, что всё выяснено, тем более нельзя.
    let подтверждено = 0
    if (ссылка) {
      const { count } = await базаCare()
        .from('program_requirements')
        .select('*', { count: 'exact', head: true })
        .contains('program_ref', { ссылка })
        .eq('status', 'confirmed')
      подтверждено = count ?? 0
    }

    if (подтверждено > 0) continue

    await базаCare().from('shortlist_items').update({ unresolved: [ПОМЕТКА] }).eq('id', с.id)
    итог.исправлено += 1
    итог.названия.push(`${ref.вуз ?? ''} — ${ref.программа ?? ''}`.trim())
  }

  return итог
}
