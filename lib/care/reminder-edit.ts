/**
 * Правка текста напоминания перед отправкой.
 *
 * ЗАЧЕМ. До сих пор у куратора было два ответа: отправить как есть или
 * пропустить с причиной. Если в тексте одно слово не то — «справка» вместо
 * «справки о доходах», обращение на «ты» вместо «вы», — выбор между «отправить
 * неточное» и «не отправить ничего». На практике выбирают второе и пишут сами,
 * а тогда весь контур перестаёт экономить время, ради чего он и строится.
 *
 * ПОЧЕМУ ЭТО НЕ ОСЛАБЛЯЕТ ПРАВИЛО. Правило звучит «модель предлагает, человек
 * решает». Исправленный человеком текст — это и есть его решение, причём более
 * полное, чем кнопка «отправить». Ослабляло бы обратное: отправка того, чего
 * человек не писал и поправить не мог.
 *
 * ЧТО ПРАВКА НЕ МЕНЯЕТ. Получателя. Он берётся из `care.contacts` дела в
 * момент отправки и в тексте не живёт вовсе — ни подменить его правкой, ни
 * «дописать адрес» нельзя (на этом стоит T19).
 *
 * ЗАЧЕМ ХРАНИМ ПРЕЖНИЙ ТЕКСТ. Правки — это единственная обратная связь о
 * шаблонах. Через месяц видно: правят обращение — значит шаблон не тот; правят
 * название документа — значит задача названа неудачно. Без прежнего текста
 * сравнивать не с чем.
 */
import { createHash } from 'crypto'
import { базаCare } from './db'

/** Напоминание — короткое сообщение, а не письмо. */
const ПРЕДЕЛ = 1000

export type ИтогПравки = { ok: true; текст: string } | { ok: false; ошибка: string }

export async function исправитьТекст(
  proposalId: string,
  новый: string,
  участникId: string
): Promise<ИтогПравки> {
  const текст = новый.trim()
  if (!текст) return { ok: false, ошибка: 'Пустой текст отправлять нечего' }
  if (текст.length > ПРЕДЕЛ) {
    return { ok: false, ошибка: `Длиннее ${ПРЕДЕЛ} знаков — напоминание должно читаться с экрана телефона` }
  }

  const { data: предложение } = await базаCare()
    .from('proposals')
    .select('id, case_id, kind, payload, status')
    .eq('id', proposalId)
    .maybeSingle()

  if (!предложение) return { ok: false, ошибка: 'Предложение не найдено' }
  if (предложение.kind !== 'reminder') return { ok: false, ошибка: 'Это не напоминание' }
  // Решённое не правим: отправленное уже у человека, отклонённое решено.
  if (предложение.status !== 'pending') {
    return { ok: false, ошибка: 'По этому напоминанию уже приняли решение' }
  }

  const payload = (предложение.payload ?? {}) as Record<string, unknown>
  const прежний = String(payload.текст ?? '')
  if (прежний === текст) return { ok: true, текст }

  const { error } = await базаCare()
    .from('proposals')
    .update({
      payload: { ...payload, текст, правлено_человеком: true },
      // Хэш описывает payload, и оставить прежний значило бы соврать о нём.
      payload_hash: createHash('sha256').update(текст).digest('hex').slice(0, 32),
    })
    .eq('id', proposalId)
    .eq('status', 'pending')
  if (error) return { ok: false, ошибка: `Не сохранилось: ${error.message}` }

  await базаCare().from('events').insert({
    actor_kind: 'member',
    actor_id: участникId,
    case_id: предложение.case_id,
    action: 'reminder_edited',
    before: { текст: прежний },
    after: { текст },
    source: { lib: 'lib/care/reminder-edit.ts' },
    reason: 'куратор поправил текст перед отправкой',
  })

  return { ok: true, текст }
}
