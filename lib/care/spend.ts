/**
 * Что контур потратил на модель — в кабинете, а не в терминале.
 *
 * ЗАЧЕМ. Первый вопрос к системе, которая зовёт модель, — «сколько это стоит».
 * Ответа в кабинете не было вовсе: расход лежит в `care.ai_spend`, потолки в
 * `care.job_kinds_budget`, и посмотреть на них мог только тот, у кого есть
 * терминал и ключ. А когда потолок срабатывает, куратор видит «потолок
 * исчерпан» и не видит ни картины, ни того, что именно его съело.
 *
 * ПОЧЕМУ РЯДОМ С ПОТОЛКАМИ. Сумма без потолка ничего не говорит: восемь
 * долларов — это много или нормально? Рядом с потолком это ответ.
 *
 * ПОЧЕМУ РАСХОД ПРОВЕРОК ОТДЕЛЬНО. Деньги настоящие, и прятать их нельзя. Но
 * смешивать с рабочим тоже нельзя: прогон проверок однажды съел дневной потолок
 * подбора, и именно поэтому счета теперь два. Экран должен показывать то же
 * разделение, иначе он снова сложит одно с другим.
 *
 * ПОЧЕМУ КРУПНЫЕ ВЫЗОВЫ ПОИМЁННО. «Девять долларов за сутки» не говорит, что
 * делать. «Подбор по трём делам — семь долларов» говорит.
 */
import { базаCare } from './db'

export type ВидРасхода = {
  вид: string
  сегодня: number
  неделя: number
  потолок: number
  /** Доля потолка, съеденная сегодня: 0.8 и выше стоит показать цветом. */
  доля: number
}

export type КрупныйВызов = {
  когда: string
  вид: string
  сумма: number
  пометка: string | null
  проверка: boolean
}

export type КартинаРасхода = {
  виды: ВидРасхода[]
  проверки: { сегодня: number; неделя: number; потолок: number }
  поДням: { день: string; сумма: number; проверки: number }[]
  крупные: КрупныйВызов[]
  /** Строк больше, чем прочитали: суммы за неделю занижены. */
  обрезано: boolean
}

/** Сколько строк расхода читаем за раз. */
const ПОТОЛОК_СТРОК = 2000

function день(когда: string): string {
  return когда.slice(0, 10)
}

export async function картинаРасхода(дней = 7): Promise<КартинаРасхода> {
  const граница = new Date(Date.now() - дней * 86_400_000).toISOString()
  const сегодня = new Date().toISOString().slice(0, 10)

  const [{ data: потолки }, { data: строки }] = await Promise.all([
    базаCare().from('job_kinds_budget').select('kind, daily_budget_usd').order('kind'),
    базаCare()
      .from('ai_spend')
      .select('kind, usd, note, created_at, is_test')
      .gte('created_at', граница)
      .order('created_at', { ascending: false })
      .limit(ПОТОЛОК_СТРОК),
  ])

  const все = (строки ?? []) as {
    kind: string
    usd: number
    note: string | null
    created_at: string
    is_test: boolean
  }[]

  const поВиду = new Map<string, { сегодня: number; неделя: number }>()
  const поДням = new Map<string, { сумма: number; проверки: number }>()
  let проверкиСегодня = 0
  let проверкиНеделя = 0

  for (const с of все) {
    const д = день(с.created_at)
    const сумма = Number(с.usd)
    const запись = поДням.get(д) ?? { сумма: 0, проверки: 0 }

    if (с.is_test) {
      проверкиНеделя += сумма
      if (д === сегодня) проверкиСегодня += сумма
      запись.проверки += сумма
    } else {
      const в = поВиду.get(с.kind) ?? { сегодня: 0, неделя: 0 }
      в.неделя += сумма
      if (д === сегодня) в.сегодня += сумма
      поВиду.set(с.kind, в)
      запись.сумма += сумма
    }
    поДням.set(д, запись)
  }

  const потолокПоВиду = new Map(
    (потолки ?? []).map((п) => [п.kind as string, Number(п.daily_budget_usd)])
  )

  // Виды берём из потолков, а не из расхода: вид, по которому сегодня не
  // потратили ничего, должен быть виден — иначе «нет строки» читается как
  // «такого вида нет», а не как «сегодня не тратили».
  const виды: ВидРасхода[] = [...потолокПоВиду.keys()]
    .filter((в) => в !== 'tests')
    .map((вид) => {
      const в = поВиду.get(вид) ?? { сегодня: 0, неделя: 0 }
      const потолок = потолокПоВиду.get(вид) ?? 0
      return {
        вид,
        сегодня: в.сегодня,
        неделя: в.неделя,
        потолок,
        доля: потолок > 0 ? в.сегодня / потолок : 0,
      }
    })
    .sort((а, б) => б.сегодня - а.сегодня || а.вид.localeCompare(б.вид))

  const крупные = все
    .slice()
    .sort((а, б) => Number(б.usd) - Number(а.usd))
    .slice(0, 10)
    .map((с) => ({
      когда: с.created_at,
      вид: с.kind,
      сумма: Number(с.usd),
      пометка: с.note,
      проверка: с.is_test === true,
    }))

  return {
    виды,
    проверки: {
      сегодня: проверкиСегодня,
      неделя: проверкиНеделя,
      потолок: потолокПоВиду.get('tests') ?? 0,
    },
    поДням: [...поДням.entries()]
      .map(([день, з]) => ({ день, ...з }))
      .sort((а, б) => б.день.localeCompare(а.день)),
    крупные,
    // Честно говорим, что сумма занижена: молчаливо обрезанный итог хуже
    // отсутствующего — по нему принимают решение.
    обрезано: все.length >= ПОТОЛОК_СТРОК,
  }
}
