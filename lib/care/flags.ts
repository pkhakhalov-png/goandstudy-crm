/**
 * Что кому включено.
 *
 * Четыре независимых переключателя, три уровня области. Ближайший найденный
 * побеждает: запись для клиента сильнее записи для куратора, та — сильнее
 * общей. **Отсутствие записи означает «выключено».**
 *
 * Почему умолчание именно такое. Обратное — «нет записи, значит можно» —
 * означает, что забытая строка открывает функцию, а не закрывает. Забывают
 * одинаково часто в обе стороны, но цена ошибки разная: здесь это либо
 * «кабинет не открылся, пошли разбираться», либо «сообщение ушло клиенту,
 * которого никто не собирался подключать».
 *
 * Почему таблица, а не переменная окружения. Переменную нельзя включить
 * одному куратору и не включить другому, а весь смысл пилота — в том, чтобы
 * начать с одного клиента.
 */
import { базаCare } from './db'

export type Флаг = 'ui' | 'ai' | 'autowrite' | 'outbound'
export type ОбластьФлага = 'client' | 'curator' | 'all'

type Запись = {
  scope: ОбластьФлага
  scope_id: string | null
  flag: Флаг
  enabled: boolean
}

/** Кому задаём вопрос: конкретный клиент, конкретный сотрудник, или ни то ни другое. */
export type Кому = {
  clientId?: number | string | null
  memberId?: string | null
}

/**
 * Включён ли флаг.
 *
 * Один запрос на все уровни, разбор в коде: три отдельных обращения к базе
 * ради одного ответа на каждой странице — это три задержки сети там, где
 * достаточно одной.
 */
export async function флагВключён(флаг: Флаг, кому: Кому = {}): Promise<boolean> {
  const { data, error } = await базаCare()
    .from('feature_flags')
    .select('scope, scope_id, flag, enabled')
    .eq('flag', флаг)

  if (error) {
    // Не прочитали — считаем выключенным. Это единственное безопасное
    // поведение: «база недоступна, поэтому открываем всем» — не рассуждение.
    console.warn(`[care flags] не прочитали флаг ${флаг}: ${error.message}`)
    return false
  }

  const записи = (data ?? []) as Запись[]
  const клиент = кому.clientId != null ? String(кому.clientId) : null
  const сотрудник = кому.memberId ?? null

  // Порядок именно такой: ближайший побеждает.
  const поКлиенту = клиент
    ? записи.find((з) => з.scope === 'client' && з.scope_id === клиент)
    : undefined
  if (поКлиенту) return поКлиенту.enabled

  const поСотруднику = сотрудник
    ? записи.find((з) => з.scope === 'curator' && з.scope_id === сотрудник)
    : undefined
  if (поСотруднику) return поСотруднику.enabled

  const общий = записи.find((з) => з.scope === 'all')
  if (общий) return общий.enabled

  return false
}

/**
 * Несколько флагов разом — для страниц, которым нужно знать больше одного.
 */
export async function флаги(кому: Кому, какие: Флаг[]): Promise<Record<Флаг, boolean>> {
  const пары = await Promise.all(какие.map(async (ф) => [ф, await флагВключён(ф, кому)] as const))
  return Object.fromEntries(пары) as Record<Флаг, boolean>
}

/**
 * Разрешено ли отправлять наружу этому клиенту.
 *
 * Флаг здесь — только половина ответа. Вторая половина — отпечаток режима в
 * базе (`care.env_marker.external_sends`), и он сильнее: пока там `false`,
 * никакой флаг отправку не откроет. Полная проверка со всеми пятью условиями
 * появится в `lib/care/gate/outbound.ts` на этапе 3; эта функция — её часть,
 * а не замена.
 */
export async function отправкаРазрешенаФлагом(clientId: number | string): Promise<boolean> {
  return флагВключён('outbound', { clientId })
}
