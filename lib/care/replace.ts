/**
 * «Найти замену»: подборка собрана при одном бюджете, а бюджет стал другим.
 *
 * ЧТО ПРОИСХОДИТ В ЖИЗНИ. Куратор собрал десять программ под двенадцать тысяч
 * евро. Через месяц родители говорят «девять, больше не вытянем». Половина
 * списка уже не подходит — но выглядит он ровно так же, как вчера, и куратор
 * отдаёт его клиенту, не пересчитывая. Клиент влюбляется в программу, которую
 * семья не потянет.
 *
 * ПОЧЕМУ НЕ ПЕРЕСОБИРАЕМ АВТОМАТИЧЕСКИ. В подборке лежит работа куратора: он
 * убрал лишнее, поставил вперёд главное, что-то отметил выбором клиента.
 * Пересборка по изменившемуся факту стёрла бы это молча — и человек узнал бы
 * об этом, только не найдя на месте того, что помнил. Поэтому расхождение
 * показывается, а нажимает человек.
 *
 * ЧТО ДЕЛАЕТ ЗАМЕНА. Убирает то, что перестало подходить, с причиной; ищет
 * столько же новых под новое основание; всё остальное оставляет как было —
 * вместе с порядком. Выбранное клиентом не трогает никогда: отменить чужой
 * выбор может только человек, который с этим клиентом разговаривает.
 */
import { базаCare } from './db'
import { основаниеПодбора, кодыСтран, type ОснованиеПодбора } from './jobs/shortlist'
import { искатьПрограммы } from './programs'
import { искатьВВебе } from './ai/search'
import { можноТратить, записатьРасход } from './ai/budget'
import { суммаИВалюта } from './fit'

export type Расхождение = {
  поле: string
  было: string
  стало: string
}

export type СостояниеОснования = {
  shortlistId: string | null
  расхождения: Расхождение[]
  основание: ОснованиеПодбора
}

const ПОДПИСЬ: Record<string, string> = {
  страна: 'страна',
  направление: 'направление',
  уровень: 'уровень поступления',
  бюджет: 'бюджет на обучение',
}

function какТекст(значение: unknown, валюта?: string | null): string {
  if (значение === null || значение === undefined || значение === '') return 'не указано'
  return валюта ? `${значение} ${валюта}` : String(значение)
}

/**
 * Разошлось ли основание подборки с сегодняшними решениями клиента.
 *
 * Сравниваем со снимком, сделанным при сборке, а не со ссылками на факты: факт
 * правится на месте, и по ссылке всегда видно сегодняшнее значение — то есть
 * расхождения не видно вовсе.
 */
export async function состояниеОснования(caseId: string): Promise<СостояниеОснования> {
  const основание = await основаниеПодбора(caseId)

  const { data: подборки } = await базаCare()
    .from('shortlists')
    .select('id, basis')
    .eq('case_id', caseId)
    .order('version', { ascending: false })
    .limit(1)

  const подборка = (подборки ?? [])[0]
  if (!подборка) return { shortlistId: null, расхождения: [], основание }

  const было = (подборка.basis ?? {}) as Record<string, unknown>
  // Подборки, собранные до появления снимка, сравнивать не с чем. Молчим:
  // предупреждение «основание изменилось» без «на что» хуже молчания.
  if (!Object.keys(было).length) {
    return { shortlistId: подборка.id as string, расхождения: [], основание }
  }

  const расхождения: Расхождение[] = []
  const пары: [string, unknown, unknown][] = [
    ['страна', было.страна, основание.страна],
    ['направление', было.направление, основание.направление],
    ['уровень', было.уровень, основание.уровень],
    ['бюджет', было.бюджет, основание.бюджет],
  ]

  for (const [поле, старое, новое] of пары) {
    const одно = String(старое ?? '').trim()
    const другое = String(новое ?? '').trim()
    if (одно === другое) continue
    // Пустое «стало» — это не изменение решения, а стёртый факт. Звать на
    // замену по нему нельзя: подбирать было бы не по чему.
    if (!другое) continue
    расхождения.push({
      поле: ПОДПИСЬ[поле] ?? поле,
      было: какТекст(старое, поле === 'бюджет' ? (было.валюта as string) : null),
      стало: какТекст(новое, поле === 'бюджет' ? основание.валюта : null),
    })
  }

  return { shortlistId: подборка.id as string, расхождения, основание }
}

/** Укладывается ли строка в новый бюджет. Валюты не пересчитываем. */
function поБюджету(
  сумма: number | null,
  валютаСтроки: string | null,
  основание: ОснованиеПодбора
): { подходит: boolean; почему: string | null } {
  if (основание.бюджет === null) return { подходит: true, почему: null }
  if (сумма === null) {
    // Неизвестная стоимость — не повод выбрасывать: у немецких
    // государственных её часто просто нет. Это повод проверить.
    return { подходит: true, почему: null }
  }
  if (основание.валюта && валютаСтроки && основание.валюта !== валютаСтроки) {
    // Курс мы не знаем и выдумывать не станем: решение о такой строке
    // принимает человек.
    return { подходит: true, почему: null }
  }
  if (сумма <= основание.бюджет) return { подходит: true, почему: null }
  return {
    подходит: false,
    почему: `дороже нового бюджета: ${сумма} ${валютаСтроки ?? ''} при ${основание.бюджет} ${основание.валюта ?? ''}`.trim(),
  }
}

/** Подходит ли страна строки под сегодняшнее решение. */
function поСтране(страна: string | null, основание: ОснованиеПодбора): boolean {
  if (!основание.страна) return true
  const нужные = кодыСтран(основание.страна)
  if (!нужные.length) return true
  const своя = кодыСтран(страна ?? '')
  // Страну строки не распознали — не выбрасываем: это наша слепота, а не
  // несоответствие.
  if (!своя.length) return true
  return своя.some((к) => нужные.includes(к))
}

export type ИтогЗамены = {
  убрано: number
  добавлено: number
  долларов: number
  причины: string[]
}

/**
 * Заменить то, что перестало подходить.
 *
 * Сколько убрали — столько и ищем. Приносить больше значит незаметно менять
 * размер подборки, которую куратор уже выверил.
 */
export async function найтиЗамену(caseId: string): Promise<ИтогЗамены> {
  const итог: ИтогЗамены = { убрано: 0, добавлено: 0, долларов: 0, причины: [] }

  const состояние = await состояниеОснования(caseId)
  if (!состояние.shortlistId) {
    итог.причины.push('подборки по делу ещё нет — заменять нечего')
    return итог
  }
  const основание = состояние.основание
  if (основание.нет.length || основание.намерения.length) {
    итог.причины.push('страна или направление не решены — подбирать не по чему')
    return итог
  }

  const { data: строки } = await базаCare()
    .from('shortlist_items')
    .select('id, program_ref, tuition_amount, currency, status')
    .eq('shortlist_id', состояние.shortlistId)
    .order('position')
    .order('created_at')

  const живые = (строки ?? []).filter((с) => с.status === 'active')
  const негодные: { id: string; почему: string; подпись: string }[] = []

  for (const с of живые) {
    const ref = (с.program_ref ?? {}) as Record<string, string>
    const подпись = `${ref.вуз ?? ''} — ${ref.программа ?? ''}`.trim()

    if (!поСтране(ref.страна ?? null, основание)) {
      негодные.push({ id: с.id as string, почему: `страна больше не та: ${основание.страна}`, подпись })
      continue
    }

    const { сумма, валюта } = с.tuition_amount
      ? { сумма: Number(с.tuition_amount), валюта: (с.currency as string | null) ?? null }
      : суммаИВалюта(null)
    const бюджет = поБюджету(сумма, валюта, основание)
    if (!бюджет.подходит) {
      негодные.push({ id: с.id as string, почему: бюджет.почему!, подпись })
    }
  }

  if (!негодные.length) {
    итог.причины.push('всё в подборке по-прежнему подходит — заменять нечего')
    return итог
  }

  for (const н of негодные) {
    await базаCare()
      .from('shortlist_items')
      .update({ status: 'removed', removed_reason: н.почему })
      .eq('id', н.id)
    итог.убрано += 1
  }

  // Ищем ровно столько, сколько убрали.
  const коды = кодыСтран(основание.страна)
  const { data: оставшиеся } = await базаCare()
    .from('shortlist_items')
    .select('program_ref')
    .eq('shortlist_id', состояние.shortlistId)
    .eq('status', 'active')

  const уже = new Set(
    (оставшиеся ?? []).map((с) => {
      const r = (с.program_ref ?? {}) as Record<string, string>
      return `${r.вуз ?? ''}|${r.программа ?? ''}`.toLowerCase()
    })
  )

  const изБазы = await искатьПрограммы({
    страны: коды,
    бюджет: основание.бюджет,
    направление: основание.направление.split(/[\s,;]+/)[0] ?? '',
    сколько: негодные.length * 2,
  }).catch(() => ({ программы: [], всего: 0, непроверено: [] }))

  const новые: {
    program_ref: Record<string, unknown>
    tuition_amount: number | null
    currency: string | null
    fit_notes: Record<string, unknown>
    unresolved: string[]
  }[] = []

  for (const п of изБазы.программы) {
    if (новые.length >= негодные.length) break
    const ключ = `${п.вуз}|${п.название}`.toLowerCase()
    if (уже.has(ключ)) continue
    уже.add(ключ)
    новые.push({
      program_ref: {
        вуз: п.вуз,
        программа: п.название,
        страна: п.страна,
        город: п.город ?? null,
        ссылка: п.ссылка ?? null,
        добавлено: new Date().toISOString().slice(0, 10),
      },
      tuition_amount: п.стоимость ?? null,
      currency: п.валюта ?? null,
      fit_notes: { почему: 'замена под новое основание' },
      unresolved: ['требования не проверены'],
    })
  }

  // Базы не хватило — идём в веб. Не наоборот: веб стоит денег, справочник нет.
  if (новые.length < негодные.length) {
    const потолок = await можноТратить('research')
    if (!потолок.можно) {
      итог.причины.push(`в вебе не искал: ${потолок.почему}`)
    } else {
      const веб = await искатьВВебе({
        страны: основание.страна,
        направление: основание.направление,
        уровень: основание.уровень,
        бюджетВГод: основание.бюджет ? `${основание.бюджет} ${основание.валюта ?? ''}`.trim() : 'не задан',
        оКлиенте: {},
        сколько: негодные.length - новые.length,
      })
      if (веб.расход) {
        await записатьРасход('research', веб.расход, { caseId, пометка: 'замена в подборке' })
        итог.долларов += веб.расход.долларов
      }
      if (веб.ошибка) итог.причины.push(`поиск в вебе: ${веб.ошибка}`)
      for (const п of веб.программы) {
        if (новые.length >= негодные.length) break
        const ключ = `${п.вуз}|${п.программа}`.toLowerCase()
        if (уже.has(ключ)) continue
        уже.add(ключ)
        новые.push({
          program_ref: {
            вуз: п.вуз,
            программа: п.программа,
            страна: п.страна,
            город: п.город ?? null,
            ссылка: п.ссылка,
            добавлено: new Date().toISOString().slice(0, 10),
          },
          tuition_amount: п.стоимость_в_год ?? null,
          currency: п.валюта ?? null,
          fit_notes: { почему: п.почему_подходит },
          unresolved: п.что_проверить?.length ? п.что_проверить : ['требования не проверены'],
        })
      }
    }
  }

  if (новые.length) {
    const { error } = await базаCare()
      .from('shortlist_items')
      .insert(
        новые.map((н) => ({
          shortlist_id: состояние.shortlistId,
          // Место назначает база: вставок несколько, и считать максимум здесь
          // значит снова получить две программы на одном месте.
          position: null,
          status: 'active',
          ...н,
        }))
      )
    if (error) итог.причины.push(`замены не записались: ${error.message}`)
    else итог.добавлено = новые.length
  }

  if (итог.добавлено < итог.убрано) {
    // Молчать нельзя: подборка стала короче, и это должно быть сказано, а не
    // обнаружено пересчётом карточек.
    итог.причины.push(
      `убрано ${итог.убрано}, найдено на замену ${итог.добавлено} — ` +
        'под новое основание больше ничего не нашлось'
    )
  }

  await базаCare().from('events').insert({
    actor_kind: 'member',
    case_id: caseId,
    action: 'shortlist_replaced',
    after: { убрано: итог.убрано, добавлено: итог.добавлено },
    source: { lib: 'lib/care/replace.ts' },
    reason: состояние.расхождения.map((р) => `${р.поле}: ${р.было} → ${р.стало}`).join('; '),
  })

  return итог
}
