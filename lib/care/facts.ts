/**
 * Разбор значения, которое куратор вписал руками.
 *
 * Вынесено из серверного действия отдельно, потому что это единственное место
 * в правке факта, где можно ошибиться молча. Остальное — запись в базу под
 * ограничениями, которые сами себя защищают; а вот «6 000», «6000 EUR» и
 * «6.000» человек напишет обязательно, и ответить на это надо понятной
 * фразой, а не отказом ограничения базы.
 */

/** Поля, где значение — сумма. Валюта для них обязательна ограничением базы. */
export function этоДеньги(поле: string): boolean {
  return поле.startsWith('budget.')
}

/** Поля, где значение — число, но не деньги. Год набора, например. */
function этоЧисло(поле: string): boolean {
  return этоДеньги(поле) || поле.endsWith('.year')
}

export type РазборЗначения =
  | { ok: true; значение: string | number; валюта: string | null }
  | { ok: false; почему: string }

/**
 * Привести введённое к тому виду, в котором факт ляжет в базу.
 *
 * Числа чистим от пробелов, неразрывных пробелов и знаков валюты: человек
 * пишет «6 000 €», и это ровно та же сумма. Запятую считаем десятичной —
 * в русской записи она ей и является.
 *
 * Чего здесь намеренно нет: угадывания валюты по символу. «€» в сумме мог
 * оказаться случайно, а валюта решает, 6000 это годовой бюджет в Европе или
 * в рублях на месяц. Валюта приходит отдельным полем, и пустой она быть не
 * может.
 */
export function разобратьЗначение(
  поле: string,
  введено: string,
  валюта: string | null
): РазборЗначения {
  const строка = введено.trim()
  if (!строка) return { ok: false, почему: 'Пустое значение — нечего записывать' }

  const код = (валюта ?? '').trim().toUpperCase() || null

  if (!этоЧисло(поле)) return { ok: true, значение: строка, валюта: код }

  const очищено = строка
    .replace(/[\s ]/g, '')
    .replace(',', '.')
    .replace(/[^\d.-]/g, '')
  const число = Number(очищено)

  if (!очищено || !Number.isFinite(число)) {
    return { ok: false, почему: `«${строка}» — не число. Для этого поля нужна сумма, валюта отдельным полем.` }
  }
  if (число < 0) {
    return { ok: false, почему: 'Сумма не может быть отрицательной' }
  }

  // Ограничение базы: деньги без валюты — не сумма, а число. Ловим здесь,
  // чтобы человек увидел свою ошибку, а не текст про constraint.
  if (этоДеньги(поле) && !код) {
    return { ok: false, почему: 'Для суммы нужна валюта — EUR, USD, RUB' }
  }

  return { ok: true, значение: число, валюта: код }
}
