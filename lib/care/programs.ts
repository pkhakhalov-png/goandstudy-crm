/**
 * Поиск программ в базе вузов.
 *
 * Отдельная база (проект парсера), только чтение, свой анонимный ключ. Это не
 * обход границ контура: `lib/care/db.ts` — вход в **рабочую** базу, а здесь
 * справочник, в который контур ничего не пишет и писать не может.
 *
 * ЧТО В ЭТОЙ БАЗЕ ЕСТЬ НА САМОМ ДЕЛЕ — и почему подбор устроен именно так.
 * Программ 80 995, и у всех заполнена стоимость. А вот уровень заполнен у
 * четырёх записей, язык и даты набора — у четырёхсот с небольшим, то есть у
 * полупроцента. Фильтровать по ним нельзя: фильтр по полю, которого нет,
 * молча выкинет всё.
 *
 * Поэтому отбор идёт по тому, что действительно есть: страна (через вуз),
 * стоимость и совпадение в названии. Уровень определяется **из названия** —
 * «Bachelor of…», «MSc», «Магистратура», — и это честная догадка, которую мы
 * помечаем как догадку, а не выдаём за данные.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ БЕЗ ПРОВЕРКИ. Требований к поступающим, сроков
 * подачи и языка обучения. Их нет в базе, и придумывать их нельзя: цена
 * ошибки — клиент готовит документы не туда. Это следующий шаг этапа 5 —
 * проверка требований на сайте вуза с сохранением ссылки и даты.
 */
import { createClient, type SupabaseClient } from '@supabase/supabase-js'
import { требуется } from './env'

let клиент: SupabaseClient | null = null

function базаВузов(): SupabaseClient {
  if (!клиент) {
    клиент = createClient(
      требуется('NEXT_PUBLIC_PARSER_SUPABASE_URL'),
      требуется('NEXT_PUBLIC_PARSER_SUPABASE_ANON_KEY'),
      { auth: { persistSession: false } }
    )
  }
  return клиент
}

export type Уровень = 'бакалавриат' | 'магистратура' | 'подготовка' | 'неизвестно'

/**
 * Уровень по названию программы.
 *
 * Догадка, а не данные: в базе поле уровня пустое почти везде. Зато названия
 * почти всегда начинаются со степени — на английском, немецком или русском.
 * Всё, что не опознано, остаётся «неизвестно» и не выдаёт себя за знание.
 */
export function уровеньПоНазванию(название: string): Уровень {
  const т = название.toLowerCase()

  // Латиница и кириллица проверяются отдельно: `\b` в JavaScript — граница
  // ASCII-слова, и перед «магистратура» она не срабатывает. Один общий шаблон
  // выглядел бы работающим и молча не опознавал бы всё русское.
  const магистр = /\b(master|msc|m\.sc|ma\b|mba|magister)/.test(т) || /(магистр|мастер)/.test(т)
  if (магистр) return 'магистратура'

  const бакалавр = /\b(bachelor|bsc|b\.sc|ba\b|beng)/.test(т) || /бакалавр/.test(т)
  if (бакалавр) return 'бакалавриат'

  if (/(foundation|pathway|pre-?master)/.test(т) || /(подготовит|языков)/.test(т)) return 'подготовка'
  return 'неизвестно'
}

export type Программа = {
  id: number
  название: string
  вуз: string
  город: string | null
  страна: string | null
  стоимость: number | null
  валюта: string | null
  уровень: Уровень
  ссылка: string | null
}

export type ЗапросПодбора = {
  /** Коды стран: de, at, it, es, hu. Пусто — без ограничения по стране. */
  страны?: string[]
  /** Потолок стоимости за год. Программы дороже не берём. */
  бюджет?: number | null
  /** Слова из направления: «биолог», «molecular», «маркетинг». */
  направление?: string | null
  уровень?: Уровень | null
  сколько?: number
}

export type ИтогПодбора = {
  программы: Программа[]
  /** Сколько всего нашлось до обрезки — чтобы не выдавать десять за всё. */
  всего: number
  /** Чего мы не проверяли, потому что этого нет в базе. Показывается человеку. */
  непроверено: string[]
}

/**
 * Найти программы под запрос.
 *
 * Отбор механический: никакой модели здесь нет и быть не должно. Модель
 * объясняет выбор, но не делает его — иначе в подборке окажется вуз, которого
 * в базе не существует, и проверять это придётся человеку по одному.
 */
export async function искатьПрограммы(з: ЗапросПодбора): Promise<ИтогПодбора> {
  const сколько = Math.min(Math.max(з.сколько ?? 12, 1), 40)

  // Сначала вузы: страна лежит у них, а не у программы.
  let вузы = базаВузов().from('schools').select('id, name, city, country_code, currency, website')
  if (з.страны?.length) вузы = вузы.in('country_code', з.страны.map((с) => с.toLowerCase()))
  const { data: списокВузов, error: ошибкаВузов } = await вузы.limit(2000)
  if (ошибкаВузов) throw new Error(`база вузов недоступна: ${ошибкаВузов.message}`)

  const поId = new Map((списокВузов ?? []).map((ш) => [ш.id as number, ш]))
  if (!поId.size) return { программы: [], всего: 0, непроверено: [] }

  let запрос = базаВузов()
    .from('programs')
    .select('id, name, tuition, school_id', { count: 'exact' })
    .in('school_id', [...поId.keys()])

  if (з.бюджет) запрос = запрос.lte('tuition', з.бюджет)
  if (з.направление?.trim()) запрос = запрос.ilike('name', `%${з.направление.trim()}%`)

  // Дешёвые вперёд: при равном соответствии дешевле — лучше, а дорогие
  // клиент и так увидит, если попросит.
  const { data, count, error } = await запрос.order('tuition', { ascending: true }).limit(сколько * 4)
  if (error) throw new Error(`поиск программ не прошёл: ${error.message}`)

  let программы: Программа[] = (data ?? []).map((п) => {
    const ш = поId.get(п.school_id as number)
    return {
      id: п.id as number,
      название: п.name as string,
      вуз: (ш?.name as string) ?? 'вуз не найден',
      город: (ш?.city as string | null) ?? null,
      страна: (ш?.country_code as string | null)?.toUpperCase() ?? null,
      стоимость: (п.tuition as number | null) ?? null,
      валюта: (ш?.currency as string | null) ?? null,
      уровень: уровеньПоНазванию(п.name as string),
      ссылка: (ш?.website as string | null) ?? null,
    }
  })

  // Уровень фильтруем уже здесь: в базе его нет, он выведен из названия.
  // Неизвестный уровень не выбрасываем — иначе отсеется почти всё.
  if (з.уровень && з.уровень !== 'неизвестно') {
    программы = программы.filter((п) => п.уровень === з.уровень || п.уровень === 'неизвестно')
  }

  return {
    программы: программы.slice(0, сколько),
    всего: count ?? программы.length,
    непроверено: [
      'язык обучения — в базе не заполнен почти нигде',
      'сроки подачи и даты набора — тоже',
      'требования к поступающим — их в базе нет вовсе',
    ],
  }
}
