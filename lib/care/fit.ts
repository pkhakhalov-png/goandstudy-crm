/**
 * Применимость: сходится ли проверенное требование с тем, что мы знаем о клиенте.
 *
 * ПОЧЕМУ ЭТО КОД, А НЕ МОДЕЛЬ. Сравнить «обучение на чешском» с «английский
 * B2» — не задача, где есть что решать. Это арифметика, и у неё должен быть
 * один и тот же ответ каждый раз. Модель здесь добавила бы только возможность
 * ошибиться по-новому.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. Проверка требований ставит галочку «язык обучения:
 * чешский» — она означает «проверено», а читается как «подходит». Программа
 * по молекулярной биологии, идеально ложащаяся на запрос, оказалась на
 * чешском у клиента с английским B2: без сверки она дошла бы до клиента в
 * подборке, и выяснилось бы это при подаче.
 *
 * ТРИ ОТВЕТА, И ТРЕТИЙ НЕ ХУЖЕ ДРУГИХ. «Подходит», «не подходит» и «неясно».
 * Последний — честный результат там, где данных не хватает: выдать «подходит»
 * при неизвестном бюджете значит соврать уверенно.
 */

export type Вывод = 'подходит' | 'не подходит' | 'неясно'

export type Сверка = {
  вид: string
  вывод: Вывод
  объяснение: string
}

/** Что мы знаем о клиенте — только подтверждённое, без намерений. */
export type ФактыКлиента = {
  бюджетВГод: number | null
  валютаБюджета: string | null
  английский: string | null
  немецкий: string | null
  /** Прочие языки, какие подтверждены: ключ — язык строкой из подписи поля. */
  языки: Record<string, string>
}

const УРОВНИ = ['a1', 'a2', 'b1', 'b2', 'c1', 'c2'] as const

/** Уровень из свободного текста: «B2 – готовится к IELTS» → b2. */
export function уровеньЯзыка(текст: string | null): string | null {
  if (!текст) return null
  const м = текст.toLowerCase().match(/\b([abc][12])\b/)
  return м ? м[1] : null
}

/** Не ниже ли уровень клиента требуемого. */
function достаточенУровень(у: string | null, нужен: string | null): boolean | null {
  if (!у || !нужен) return null
  const а = УРОВНИ.indexOf(у as (typeof УРОВНИ)[number])
  const б = УРОВНИ.indexOf(нужен as (typeof УРОВНИ)[number])
  if (а < 0 || б < 0) return null
  return а >= б
}

/**
 * Сумма и валюта из того, как написано на странице вуза.
 *
 * «€3,000 per academic year», «3 000 EUR в год», «2000 EUR» — одно и то же.
 * Разделители разрядов убираем, десятичные дроби в стоимости обучения не
 * встречаются и не разбираются намеренно: «3.000» в Европе это три тысячи.
 */
export function суммаИВалюта(текст: string | null): { сумма: number | null; валюта: string | null } {
  if (!текст) return { сумма: null, валюта: null }

  const валюта = текст.includes('€') || /\beur\b/i.test(текст)
    ? 'EUR'
    : текст.includes('$') || /\busd\b/i.test(текст)
      ? 'USD'
      : /\bczk\b|\bкрон/i.test(текст)
        ? 'CZK'
        : /\bgbp\b|£/.test(текст)
          ? 'GBP'
          : null

  // Берём первое число длиной от трёх знаков: «3,000», «3 000», «3.000», «2000».
  const м = текст.match(/\d[\d  .,]{2,}\d|\d{3,}/)
  if (!м) return { сумма: null, валюта }

  const число = Number(м[0].replace(/[  .,]/g, ''))
  return { сумма: Number.isFinite(число) ? число : null, валюта }
}

/** Язык обучения из текста требования: «English», «Чешский», «Czech». */
export function языкОбучения(текст: string | null): 'английский' | 'немецкий' | 'другой' | null {
  if (!текст) return null
  const т = текст.toLowerCase()
  if (/англ|english/.test(т)) return 'английский'
  if (/нем|герман|german|deutsch/.test(т)) return 'немецкий'
  if (/чешск|czech|итальянск|italian|испанск|spanish|французск|french|польск|polish|венгерск|hungarian/.test(т)) {
    return 'другой'
  }
  return null
}

/** Дата из срока подачи, если её удалось узнать однозначно. */
export function срокПодачи(текст: string | null): Date | null {
  if (!текст) return null

  // 28/2/2026, 28.02.2026, 28-02-2026
  const цифрами = текст.match(/\b(\d{1,2})[./-](\d{1,2})[./-](\d{4})\b/)
  if (цифрами) {
    const [, д, м, г] = цифрами
    const дата = new Date(Number(г), Number(м) - 1, Number(д))
    return Number.isNaN(дата.getTime()) ? null : дата
  }

  // 28 February 2026 / 28 февраля 2026
  const месяцы: Record<string, number> = {
    jan: 0, feb: 1, mar: 2, apr: 3, may: 4, jun: 5, jul: 6, aug: 7, sep: 8, oct: 9, nov: 10, dec: 11,
    янв: 0, фев: 1, мар: 2, апр: 3, ма: 4, июн: 5, июл: 6, авг: 7, сен: 8, окт: 9, ноя: 10, дек: 11,
  }
  const словами = текст.toLowerCase().match(/\b(\d{1,2})\s+([a-zа-яё]{3,})\s+(\d{4})\b/)
  if (словами) {
    const [, д, м, г] = словами
    const ключ = Object.keys(месяцы).find((к) => м.startsWith(к))
    if (ключ !== undefined) {
      const дата = new Date(Number(г), месяцы[ключ], Number(д))
      return Number.isNaN(дата.getTime()) ? null : дата
    }
  }

  return null
}

export type ТребованиеДляСверки = { вид: string; значение: string }

/**
 * Сверить одно требование с фактами клиента.
 *
 * Сверяются только те виды, где сравнение однозначно: язык обучения,
 * стоимость, языковой сертификат, срок подачи. Документы и вступительные
 * испытания остаются сведениями — по ним решение принимает человек, и
 * притворяться, что код умеет его принять, было бы хуже молчания.
 */
export function сверить(
  т: ТребованиеДляСверки,
  ф: ФактыКлиента,
  сегодня: Date = new Date()
): Сверка | null {
  switch (т.вид) {
    case 'language_of_instruction': {
      const язык = языкОбучения(т.значение)
      if (!язык) return null

      if (язык === 'английский') {
        const у = уровеньЯзыка(ф.английский)
        if (!у) return { вид: т.вид, вывод: 'неясно', объяснение: 'обучение на английском, уровень клиента не подтверждён' }
        const хватает = достаточенУровень(у, 'b2')
        return хватает
          ? { вид: т.вид, вывод: 'подходит', объяснение: `обучение на английском, у клиента ${у.toUpperCase()}` }
          : { вид: т.вид, вывод: 'не подходит', объяснение: `обучение на английском, у клиента только ${у.toUpperCase()}` }
      }

      if (язык === 'немецкий') {
        const у = уровеньЯзыка(ф.немецкий)
        return у
          ? { вид: т.вид, вывод: 'подходит', объяснение: `обучение на немецком, у клиента ${у.toUpperCase()}` }
          : { вид: т.вид, вывод: 'не подходит', объяснение: 'обучение на немецком, немецкий у клиента не подтверждён' }
      }

      // Язык, которого у нас нет в фактах вовсе. Самый частый и самый дорогой
      // случай: программа идеально подходит по направлению и читается на чешском.
      return {
        вид: т.вид,
        вывод: 'не подходит',
        объяснение: `обучение не на английском и не на немецком: ${т.значение}`,
      }
    }

    case 'tuition_per_year': {
      if (!ф.бюджетВГод) return { вид: т.вид, вывод: 'неясно', объяснение: 'бюджет клиента не подтверждён' }
      const { сумма, валюта } = суммаИВалюта(т.значение)
      if (сумма == null) return { вид: т.вид, вывод: 'неясно', объяснение: 'со страницы не вышло прочитать сумму' }
      if (валюта && ф.валютаБюджета && валюта !== ф.валютаБюджета) {
        // Курсы мы не считаем: пересчёт по неизвестному курсу — это выдумка
        // с точностью до десятков процентов.
        return { вид: т.вид, вывод: 'неясно', объяснение: `стоимость в ${валюта}, бюджет в ${ф.валютаБюджета}` }
      }
      return сумма <= ф.бюджетВГод
        ? { вид: т.вид, вывод: 'подходит', объяснение: `${сумма} ${валюта ?? ''} против бюджета ${ф.бюджетВГод}`.trim() }
        : {
            вид: т.вид,
            вывод: 'не подходит',
            объяснение: `дороже бюджета: ${сумма} ${валюта ?? ''} против ${ф.бюджетВГод}`.trim(),
          }
    }

    case 'language_certificate': {
      const нужен = уровеньЯзыка(т.значение)
      if (!нужен) return null
      const у = уровеньЯзыка(ф.английский)
      if (!у) return { вид: т.вид, вывод: 'неясно', объяснение: `нужен ${нужен.toUpperCase()}, уровень клиента не подтверждён` }
      const хватает = достаточенУровень(у, нужен)
      return хватает
        ? { вид: т.вид, вывод: 'подходит', объяснение: `нужен ${нужен.toUpperCase()}, у клиента ${у.toUpperCase()}` }
        : { вид: т.вид, вывод: 'не подходит', объяснение: `нужен ${нужен.toUpperCase()}, у клиента ${у.toUpperCase()}` }
    }

    case 'application_deadline': {
      const дата = срокПодачи(т.значение)
      if (!дата) return null
      if (дата < сегодня) {
        // Сроки на странице часто от прошлого набора: вуз ещё не опубликовал
        // новые. Это не ошибка проверки, но куратор должен это видеть.
        return {
          вид: т.вид,
          вывод: 'неясно',
          объяснение: `срок на странице уже прошёл (${дата.toLocaleDateString('ru-RU')}) — вуз, вероятно, ещё не опубликовал новый`,
        }
      }
      const дней = Math.round((дата.getTime() - сегодня.getTime()) / 86_400_000)
      return { вид: т.вид, вывод: 'подходит', объяснение: `подача до ${дата.toLocaleDateString('ru-RU')}, осталось ${дней} дн.` }
    }

    default:
      return null
  }
}

/** Сверить всё, что проверено по программе. */
export function сверитьВсё(
  требования: ТребованиеДляСверки[],
  ф: ФактыКлиента,
  сегодня: Date = new Date()
): Сверка[] {
  return требования.map((т) => сверить(т, ф, сегодня)).filter((с): с is Сверка => с !== null)
}
