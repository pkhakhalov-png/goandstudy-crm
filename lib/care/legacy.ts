/**
 * Правки в прежнем кабинете по переведённому клиенту.
 *
 * ЗАЧЕМ. Клиента перевели на новый кабинет, но прежний его показывать не
 * перестал: мы его не меняли, и запрет там — дисциплина, а не замок. Куратор по
 * привычке правит этап или дорожную карту в старом окне, новый кабинет об этом
 * не знает и продолжает работать на своих сведениях. Две системы расходятся, и
 * заметно это становится, когда клиент говорит «я же вам писал».
 *
 * ПОЧЕМУ ОТПЕЧАТОК, А НЕ ВРЕМЯ ПРАВКИ. План предлагал сравнивать
 * `clients.updated_at` со временем перевода. Такого столбца в таблице нет
 * вовсе. Отпечаток значений отвечает на тот же вопрос и ещё на один — что
 * именно изменили.
 *
 * ПОЧЕМУ ХЭШИ, А НЕ ЗНАЧЕНИЯ. `roadmap_data` и `project_data` — большие
 * документы. Держать их копию в контуре значит хранить рабочие данные там, где
 * они не нужны; хэша хватает, чтобы заметить изменение.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Любой записи в прежний кабинет. Это чтение и сравнение;
 * решать, чьи сведения верны, будет человек.
 */
import { createHash } from 'crypto'
import { базаCare, базаPublic } from './db'

/**
 * Поля, правка которых означает работу в прежнем кабинете.
 *
 * Не все подряд: `created_at` и служебное меняются сами, и шум от них
 * заглушил бы настоящие расхождения.
 */
export const ПОЛЯ: { поле: string; подпись: string }[] = [
  { поле: 'current_stage_code', подпись: 'этап' },
  { поле: 'status', подпись: 'статус' },
  { поле: 'curator_id', подпись: 'куратор' },
  { поле: 'university', подпись: 'вуз' },
  { поле: 'country', подпись: 'страна' },
  { поле: 'months', подпись: 'срок' },
  { поле: 'service_type', подпись: 'вид услуги' },
  { поле: 'roadmap_data', подпись: 'дорожная карта' },
  { поле: 'project_data', подпись: 'данные проекта' },
]

export type Отпечаток = Record<string, string>

/** Хэш значения: пустое и отсутствующее должны давать одно и то же. */
function хэш(значение: unknown): string {
  const текст =
    значение === null || значение === undefined
      ? ''
      : typeof значение === 'object'
        ? JSON.stringify(значение)
        : String(значение)
  return createHash('sha256').update(текст).digest('hex').slice(0, 16)
}

export function отпечаток(клиент: Record<string, unknown>): Отпечаток {
  const о: Отпечаток = {}
  for (const { поле } of ПОЛЯ) о[поле] = хэш(клиент[поле])
  return о
}

/** Что разошлось между двумя отпечатками — подписями, а не именами столбцов. */
export function чтоИзменилось(было: Отпечаток | null, стало: Отпечаток): string[] {
  if (!было) return []
  const список: string[] = []
  for (const { поле, подпись } of ПОЛЯ) {
    // Поле, которого не было в прежнем отпечатке, изменением не считаем:
    // это мы расширили список, а не куратор что-то поправил.
    if (было[поле] === undefined) continue
    if (было[поле] !== стало[поле]) список.push(подпись)
  }
  return список
}

export type ИтогСверки = {
  сверено: number
  расхождений: number
  впервые: number
  причины: string[]
}

/**
 * Сверить переведённых клиентов с прежним кабинетом.
 *
 * Первая сверка по делу расхождения не утверждает: сравнивать не с чем.
 * Запоминаем отпечаток и ждём следующего раза — иначе в день включения все
 * дела разом объявились бы изменёнными.
 */
export async function сверитьПрежнийКабинет(): Promise<ИтогСверки> {
  const итог: ИтогСверки = { сверено: 0, расхождений: 0, впервые: 0, причины: [] }

  const { data: дела } = await базаCare()
    .from('cases')
    .select('id, client_id, is_synthetic, legacy_fingerprint')
    .eq('automation_owner', 'v2')
    .eq('status', 'active')

  // Тестовые дела в прежнем кабинете не существуют: у них выдуманный клиент.
  const свои = (дела ?? []).filter((д) => !д.is_synthetic)
  if (!свои.length) {
    итог.причины.push('переведённых настоящих клиентов нет')
    return итог
  }

  // Список полей собирается строкой: он задан в одном месте выше, и
  // перечислять его второй раз в типе значило бы завести вторую правду.
  const поля = ПОЛЯ.map((п) => п.поле).join(', ')
  const { data: клиенты, error } = await базаPublic()
    .from('clients')
    .select(`id, ${поля}`)
    .in('id', свои.map((д) => д.client_id))

  if (error) {
    итог.причины.push(`прежний кабинет не читается: ${error.message}`)
    return итог
  }

  // Приведение через unknown: список полей собран строкой, и вывести его тип
  // клиент базы не может — он знает только то, что написано буквами в запросе.
  const строки = (клиенты ?? []) as unknown as Record<string, unknown>[]
  const поId = new Map(строки.map((к) => [Number(к.id), к]))

  for (const дело of свои) {
    const клиент = поId.get(Number(дело.client_id))
    if (!клиент) {
      итог.причины.push(`клиент #${дело.client_id}: в прежнем кабинете не нашёлся`)
      continue
    }

    итог.сверено += 1
    const сейчас = отпечаток(клиент)
    const было = (дело.legacy_fingerprint as Отпечаток | null) ?? null
    const изменилось = чтоИзменилось(было, сейчас)

    if (!было) итог.впервые += 1

    await базаCare()
      .from('cases')
      .update({ legacy_fingerprint: сейчас, legacy_checked_at: new Date().toISOString() })
      .eq('id', дело.id)

    if (!изменилось.length) continue

    итог.расхождений += 1
    итог.причины.push(`клиент #${дело.client_id}: правили ${изменилось.join(', ')}`)

    await базаCare().from('events').insert({
      actor_kind: 'system',
      case_id: дело.id,
      action: 'legacy_write_detected',
      after: { поля: изменилось },
      source: { lib: 'lib/care/legacy.ts' },
      reason: 'в прежнем кабинете изменили сведения по переведённому клиенту',
    })
  }

  return итог
}

/**
 * Дела, по которым недавно правили в прежнем кабинете, — для ленты внимания.
 *
 * Неделя: позже этого разбираться уже поздно, а строка в ленте, висящая
 * месяцами, перестаёт читаться.
 */
export async function недавниеПравки(дела: string[], дней = 7): Promise<Map<string, string[]>> {
  const по = new Map<string, string[]>()
  if (!дела.length) return по

  const граница = new Date(Date.now() - дней * 86_400_000).toISOString()
  const { data } = await базаCare()
    .from('events')
    .select('case_id, after, created_at')
    .in('case_id', дела)
    .eq('action', 'legacy_write_detected')
    .gte('created_at', граница)
    .order('created_at', { ascending: false })

  for (const с of data ?? []) {
    const id = с.case_id as string
    if (по.has(id)) continue
    const поля = ((с.after ?? {}) as { поля?: string[] }).поля ?? []
    по.set(id, поля)
  }
  return по
}
