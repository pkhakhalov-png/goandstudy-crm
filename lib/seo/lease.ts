/**
 * Аренда задачи: подтверждение жизни и защита от воскресших исполнителей.
 *
 * Зачем это вообще. Очередь возвращала в работу всё, что провисело в `running`
 * дольше десяти минут, потому что иначе умерший воркер держал бы задачу вечно.
 * Но десять минут — это не признак смерти, а признак долгого шага: черновик
 * статьи пишется три минуты, проверки с починкой три с половиной. Отличить одно
 * от другого можно только если исполнитель сам говорит, что жив.
 *
 * Отсюда два механизма, и они работают в паре:
 *
 *   heartbeat — «я ещё тут», продлевает аренду;
 *   fencing   — номер выдачи, который растёт при каждой выдаче задачи.
 *
 * Одного heartbeat мало. Воркер может замереть (пауза сборщика мусора, потеря
 * сети, спящий ноутбук), аренду отберут, задачу отдадут другому — а потом
 * первый оживёт и допишет свой результат поверх чужого. Это тот самый дубль,
 * который MVP обязан исключить. Поэтому результат принимается только с текущим
 * номером выдачи: у воскресшего он старый, и запись отклоняется базой.
 */

/** Как часто стучать. Аренда 900 c, запас 120 c — раз в 30 c с большим зазором. */
const BEAT_MS = 30_000

export type Leased = {
  id: number
  fencing_token?: number | null
}

/**
 * Выполнить работу, подтверждая жизнь, пока она идёт.
 *
 * Если аренду отобрали, `lost` станет true. Прервать чужой `await` мы не можем
 * и не пытаемся — остановка на полуслове оставила бы половину работы. Вместо
 * этого шаг доработает, а записать результат ему не даст fencing в базе.
 */
export async function withHeartbeat<T>(
  seo: any,
  job: Leased,
  handlerVersion: string,
  work: () => Promise<T>,
): Promise<{ value: T; lost: boolean }> {
  // Задачи, выданные до миграции аренды, номера не имеют. Для них стучать
  // некуда и нечем — работаем как раньше, без подтверждений.
  if (job.fencing_token == null) {
    return { value: await work(), lost: false }
  }

  let lost = false
  const beat = setInterval(async () => {
    try {
      const { data, error } = await seo.rpc('heartbeat_job', {
        p_job_id: job.id,
        p_fencing_token: job.fencing_token,
        p_handler_version: handlerVersion,
      })
      // Функции ещё нет в базе — миграция не применена. Это не потеря аренды,
      // и объявлять её потерянной нельзя: так мы остановили бы рабочий конвейер
      // из-за неприменённой миграции.
      if (error) return
      if (data === false) {
        lost = true
        clearInterval(beat)
        console.error(`  ⚠ аренда задачи #${job.id} отобрана — результат записан не будет`)
      }
    } catch { /* сеть моргнула: следующий удар через полминуты */ }
  }, BEAT_MS)

  try {
    return { value: await work(), lost }
  } finally {
    clearInterval(beat)
  }
}
