/**
 * Кому мы пишем и что этих людей останавливает.
 *
 * Взято из маркетинговой стратегии: четыре сегмента и одиннадцать возражений,
 * собранных на живых консультациях. Это ценнее любой частотности — возражение
 * «а вдруг не поступлю» приводит клиентов лучше, чем частотный запрос ни о чём.
 *
 * ВАЖНО, ЧТО ИМЕННО ОТСЮДА БЕРЁТСЯ. Только смысл: кто читатель, чего боится,
 * что его убеждает. Скрипты продаж содержат цифры вроде «в 98% случаев дают
 * визу» — это слова для разговора, а не проверенный факт, и в статью они
 * попасть не должны. Поэтому числа из скриптов вырезаются механически, а не
 * оставляются на усмотрение модели.
 */
import fs from 'fs'
import path from 'path'

export type Segment = {
  id: number
  кто: string
  возраст: string
  ктоРешает: string
  портрет: string
  потребности: string
  чтоУбеждает: string
}

export type Objection = { возражение: string; цель: string; скрипт: string }

let cache: { сегменты: Segment[]; возражения: Objection[] } | null = null

function load(): { сегменты: Segment[]; возражения: Objection[] } {
  if (cache) return cache
  try {
    const file = path.join(process.cwd(), 'data', 'audience.json')
    cache = JSON.parse(fs.readFileSync(file, 'utf8'))
  } catch {
    cache = { сегменты: [], возражения: [] }
  }
  return cache!
}

/** Убрать всё, что похоже на статистику: проценты, доли, количества клиентов. */
function stripNumbers(text: string): string {
  return text
    .replace(/\b\d+[\d\s.,]*\s*%/g, 'некоторой доли')
    .replace(/\b\d[\d\s.,]{2,}\b/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim()
}

export function segments(): Segment[] { return load().сегменты }
export function objections(): Objection[] { return load().возражения }

/**
 * Блок для подсказки модели. Короткий намеренно: длинный контекст размывает
 * внимание, а нам нужно, чтобы модель держала в голове читателя и его страх,
 * а не пересказывала маркетинговый документ.
 */
export function audienceBlock(topic: string): string {
  const { сегменты, возражения } = load()
  if (!сегменты.length) return ''

  const t = topic.toLowerCase()
  // Родительские темы звучат иначе, чем студенческие: у родителя первый вопрос
  // про безопасность, у абитуриента — про поступление
  const forParents = /(школ|9 класс|11 класс|ребен|ребён|подрост)/.test(t)
  const chosen = forParents ? сегменты.filter((s) => /родител/i.test(s.кто)) : сегменты.filter((s) => !/родител/i.test(s.кто))
  const list = (chosen.length ? chosen : сегменты).slice(0, 2)

  const parts = [
    'КОМУ ПИШЕМ',
    ...list.map((s) => [
      `— ${s.кто} (${s.возраст}). Решение принимает: ${s.ктоРешает.replace(/\n/g, ', ')}.`,
      s.потребности ? `  Чего хочет: ${stripNumbers(s.потребности).replace(/\n/g, '; ').slice(0, 220)}` : '',
      s.чтоУбеждает ? `  Что убеждает: ${stripNumbers(s.чтоУбеждает).replace(/\n/g, '; ').slice(0, 220)}` : '',
    ].filter(Boolean).join('\n')),
    '',
    'ЧТО ОСТАНАВЛИВАЕТ ЭТИХ ЛЮДЕЙ (снимать по ходу текста, не выносить в рекламу)',
    ...возражения.slice(0, 8).map((o) => `— ${o.возражение}`),
    '',
    'Цифры из скриптов продаж — не факты. Доли поступивших, проценты одобренных виз,',
    'сроки рассрочки в статье не упоминать: их нет в реестре подтверждённых фактов.',
  ]

  return parts.join('\n')
}

/** Возражения как темы: у каждого есть поисковый спрос. */
