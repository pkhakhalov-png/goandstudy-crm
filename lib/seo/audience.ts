    'Не дадут визу': ['отказ в студенческой визе что делать', 'как получить студенческую визу'],
    'Мне интересно только бесплатное образование': ['бесплатное обучение за границей для русских', 'где можно учиться бесплатно за рубежом'],
    'Небезопасно отпускать одного': ['безопасно ли отправлять ребенка учиться за границу', 'как живут студенты за границей общежитие'],
