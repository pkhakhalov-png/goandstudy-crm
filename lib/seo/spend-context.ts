/**
 * Контекст задачи для учёта расходов.
 *
 * Зачем он вообще. Учёт требует знать, к какой задаче и статье отнести вызов.
 * Писателю это знание передают параметром: у него один вход, и контекст идёт
 * через GenContext. У эмбеддингов, схем и картинок входов много — `embed`
 * зовут из восьми мест, включая соседние модули, — и протаскивать контекст
 * через каждую сигнатуру значило бы переписать половину конвейера ради учёта.
 *
 * Поэтому контекст живёт в хранилище асинхронного вызова: воркер объявляет его
 * один раз на задачу, а платный вызов забирает сам, где бы он ни случился.
 * Это не глобальная переменная: параллельные задачи не видят чужой контекст,
 * потому что AsyncLocalStorage хранит своё значение для каждой цепочки вызовов.
 *
 * Контекста может не быть — так работают скрипты и ручные прогоны. Тогда вызов
 * просто не учитывается: молча тратить нельзя, но и падать из-за учёта тоже.
 */
import { AsyncLocalStorage } from 'node:async_hooks'

export type SpendJobContext = {
  seo: any
  jobId?: number | null
  articleId?: number | null
  traceId?: string | null
}

const storage = new AsyncLocalStorage<SpendJobContext>()

/** Выполнить работу задачи так, чтобы платные вызовы внутри знали, чьи они. */
export function runWithSpendContext<T>(ctx: SpendJobContext, fn: () => Promise<T>): Promise<T> {
  return storage.run(ctx, fn)
}

/** Контекст текущей задачи, если он объявлен. */
export function currentSpendContext(): SpendJobContext | undefined {
  return storage.getStore()
}
