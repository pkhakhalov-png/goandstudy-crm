/**
 * Читаемый текст статьи и карта смещений обратно в тело.
 *
 * Разметку выбрасываем, но помним, где стоял каждый уцелевший символ: без этого
 * находка укажет на позицию в очищенном тексте, а человек будет искать её в теле
 * статьи и не найдёт.
 *
 * Экспортируется: тем же способом ревизия архива (E3) ищет позиции для находок
 * по числам. Две разные карты позиций для одного и того же текста разошлись бы
 * при первой же правке.
 */
export function toPlain(body: string): { text: string; map: number[] } {
  const chars: string[] = []
  const map: number[] = []
  let i = 0
  let lastWasSpace = false

  while (i < body.length) {
    if (body.startsWith('<!--', i)) {
      const end = body.indexOf('-->', i)
      i = end === -1 ? body.length : end + 3
      pushBreak()
      continue
    }
    if (body[i] === '<') {
      const end = body.indexOf('>', i)
      const tag = body.slice(i + 1, end === -1 ? body.length : end)
      i = end === -1 ? body.length : end + 1
      // Заголовок, абзац и пункт списка кончаются без точки. Без разрыва
      // заголовок склеивался бы с первой фразой раздела, и сторож отрицания
      // из одной ловил бы утверждение из другой.
      if (BLOCK_TAGS.test(tag)) pushBreak()
      else pushSpace()
      continue
    }
    if (body[i] === '&') {
      const end = body.indexOf(';', i)
      const entity = end !== -1 && end - i <= 8 ? body.slice(i, end + 1) : null
      if (entity) {
        const decoded = ENTITIES[entity.toLowerCase()] ?? ' '
        push(decoded, i)
        i = end + 1
        continue
      }
    }
    push(body[i], i)
    i++
  }

  function push(ch: string, at: number) {
    const space = /\s/.test(ch)
    if (space) { pushSpace(); return }
    chars.push(ch)
    map.push(at)
    lastWasSpace = false
  }
  function pushSpace() {
    if (lastWasSpace || !chars.length) return
    chars.push(' ')
    map.push(i)
    lastWasSpace = true
  }
  /** Конец блока — конец предложения, даже если точки не было. */
  function pushBreak() {
    if (!chars.length) return
    if (chars[chars.length - 1] === '\n') return
    if (lastWasSpace) { chars.pop(); map.pop() }
    chars.push('\n')
    map.push(i)
    lastWasSpace = true
  }

  return { text: chars.join(''), map }
}

/** Теги, которые заканчивают мысль: абзац, заголовок, пункт, ячейка. */
const BLOCK_TAGS = /^\/?(?:p|div|h[1-6]|li|ul|ol|tr|td|th|table|section|article|blockquote|br|figure|figcaption|header|footer)\b/i

const ENTITIES: Record<string, string> = {
  '&nbsp;': ' ', '&mdash;': '—', '&ndash;': '–', '&laquo;': '«', '&raquo;': '»',
  '&quot;': '"', '&amp;': '&', '&lt;': '<', '&gt;': '>', '&#039;': "'", '&hellip;': '…',
}

/** Предложения с их смещением в читаемом тексте. */
function sentences(text: string): { text: string; at: number }[] {
  const out: { text: string; at: number }[] = []
  let start = 0
  const re = /[.!?…]+(?:\s+|$)|\n+/g
  let m: RegExpExecArray | null
  while ((m = re.exec(text))) {
    const end = m.index + m[0].length
    const piece = text.slice(start, end).trim()
    if (piece) out.push({ text: piece, at: text.indexOf(piece, start) })
    start = end
  }
  const tail = text.slice(start).trim()
  if (tail) out.push({ text: tail, at: text.indexOf(tail, start) })
  return out
}

/**
 * Найти в теле статьи рискованные утверждения без чисел.
 *
 * Работает по предложениям: и сторож отрицания, и оговорка действуют ровно в той
 * фразе, где стоят. Проверять их по всей статье нельзя — одно «мы не гарантируем
 * результат» во введении погасило бы обещание в середине текста.
 */
export function findSemanticClaims(body: string): SemanticFinding[] {
  const { text, map } = toPlain(body)
  const out: SemanticFinding[] = []
  const seen = new Set<string>()

  for (const s of sentences(text)) {
    if (REFUTATIONS.some((re) => re.test(s.text))) continue

    for (const rule of RULES) {
      if (rule.safe.some((re) => re.test(s.text))) continue
      if (rule.hedgeable && HEDGES.some((re) => re.test(s.text))) continue

      for (const re of rule.hit) {
        const m = re.exec(s.text)
        if (!m) continue

        const inPlain = s.at + m.index
        const key = `${rule.category}:${inPlain}`
        if (seen.has(key)) break
        seen.add(key)

        out.push({
          category: rule.category,
          kind: rule.kind,
          trigger: m[0].trim(),
          quote: s.text.length > 300 ? `${s.text.slice(0, 300).trim()}…` : s.text,
          offset: map[inPlain] ?? 0,
          why: rule.why,
        })
        break   // одной находки на категорию в предложении довольно
      }
    }
  }

  return out.sort((a, b) => a.offset - b.offset)
}
