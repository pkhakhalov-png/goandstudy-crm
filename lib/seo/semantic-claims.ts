/**
 * Рискованные утверждения без чисел (PRD E2.9).
 *
 * Сверка цифр ловит выдуманную сумму и несуществующий дедлайн, но самое
 * дорогое враньё в наших статьях — не число, а формулировка. «Виза не нужна»,
 * «гарантированное поступление», «можно работать без ограничений», «диплом
 * признаётся автоматически» — ни в одной из этих фраз нет цифры, которую можно
 * сверить с реестром, а читателю такая фраза стоит года жизни или отказа в визе.
 *
 * Что здесь есть и чего здесь нет. Это поиск по формулировкам, а не понимание
 * смысла: модуль не решает, правда ли «виза не нужна» — он находит место, где
 * статья это утверждает, и требует подтверждения так же, как для числа.
 * Решение остаётся за человеком, поэтому находка обязана нести дословную цитату
 * и смещение: редактор должен увидеть место, а не мнение.
 *
 * Про ложные срабатывания. Они здесь дороже пропуска: редактор, которому дважды
 * показали правильную фразу как ошибку, перестанет читать замечания вовсе.
 * Поэтому «виза нужна», «мы не гарантируем поступление», «гарантий никто не
 * даёт» отсекаются явными сторожами, а фразы с оговоркой («зависит от
 * гражданства», «как правило», «уточняйте») не считаются утверждением там, где
 * оговорка действительно снимает категоричность.
 */

/** Категории, с которых начинаем. Первые три названы в PRD прямо. */
export type SemanticCategory = 'visa' | 'guarantee' | 'work_rights' | 'recognition' | 'about_us'

export type SemanticFinding = {
  category: SemanticCategory
  /** Вид утверждения из словаря claim_policy — по нему гейт решает, блокировать ли. */
  kind: string
  /** Дословная фраза, которая сработала. */
  trigger: string
  /** Предложение целиком — то, что редактор увидит в замечании. */
  quote: string
  /** Смещение сработавшей фразы в исходном теле статьи. */
  offset: number
  why: string
}

type Rule = {
  category: SemanticCategory
  kind: string
  why: string
  hit: RegExp[]
  /** Формулировки, при которых находки нет: отрицание или прямое опровержение. */
  safe: RegExp[]
  /** Снимает ли оговорка категоричность. Для обещаний и рассказов о себе — нет. */
  hedgeable: boolean
}

