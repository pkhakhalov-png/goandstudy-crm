/**
 * Общий секрет вебхука: сравнение и проверка годности.
 *
 * Вынесено отдельно, потому что нужно в двух несвязанных местах: клиентским
 * чатам CRM и публикующему боту контент-машины. Общий код здесь уместен —
 * это не бизнес-логика, а одно правило сравнения строк, которое одинаково
 * важно для обоих.
 */
import crypto from 'node:crypto'

/**
 * Сравнение постоянным временем.
 *
 * Обычное `===` выходит на первом несовпавшем знаке, и по времени ответа
 * секрет подбирается посимвольно. Речь о миллисекундах, но подбор
 * автоматический, и времени у него много.
 */
export function секретыСовпали(a: string | null | undefined, b: string | null | undefined): boolean {
  if (!a || !b) return false
  const бa = Buffer.from(a), бb = Buffer.from(b)
  // Длины сравниваем отдельно: timingSafeEqual падает на разных длинах.
  // Утечка длины секрета безобидна, утечка содержимого — нет.
  if (бa.length !== бb.length) return false
  return crypto.timingSafeEqual(бa, бb)
}

/**
 * Годится ли секрет для заголовка.
 *
 * Телеграм передаёт секрет заголовком, а в заголовок HTTP нельзя положить
 * ничего, кроме однобайтовых знаков. Секрет с русскими буквами — естественная
 * вещь в русскоязычном проекте — не отправится вовсе, и ошибка будет
 * невнятной: «Cannot convert argument to a ByteString» вместо «секрет не тот».
 *
 * Документация разрешает A-Z, a-z, 0-9, подчёркивание и дефис, длиной 1–256.
 */
export function секретГодится(s: string | null | undefined): { ok: boolean; почему?: string } {
  if (!s) return { ok: false, почему: 'секрет не задан' }
  if (s.length > 256) return { ok: false, почему: 'длиннее 256 знаков' }
  if (!/^[A-Za-z0-9_-]+$/.test(s)) {
    return {
      ok: false,
      почему: 'разрешены только латиница, цифры, подчёркивание и дефис: секрет уходит '
        + 'заголовком HTTP, а туда кириллица не помещается',
    }
  }
  return { ok: true }
}
