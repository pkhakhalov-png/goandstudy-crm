/**
 * Тестовые клиенты и отчёты.
 *
 * Тестовые учётки живут в боевой базе: на них проверяют кабинет куратора и
 * кабинет клиента, и отдельной базы под это нет. Отличались они только словом
 * «ТЕСТ» в имени — соглашением, о котором отчёты не знали. Три таких клиента,
 * заведённых 25 сентября, добавили в статистику 920 000 ₽ договоров и
 * 152 166 ₽ «оплаченного», и владелец увидел это на экране платежей.
 *
 * Теперь признак — колонка `clients.is_test`, а не договорённость. Здесь
 * лежит одна функция, через которую отчёты её читают: так место фильтрации
 * видно поиском по `безТестовых`, и забыть его в новом отчёте труднее, чем
 * вспомнить про `.eq('is_test', false)`.
 *
 * Где фильтровать, а где нет. Правило простое: в ЦИФРАХ — да, в РАБОТЕ — нет.
 * Сводка, аналитика, выручка, нагрузка кураторов считаются без тестовых.
 * Списки, карточки и экраны, на которых с клиентом работают, показывают всех:
 * иначе тестового клиента нельзя будет открыть, а он для того и заведён.
 */

/** Запрос только по настоящим клиентам. Для сводок, аналитики и выручки. */
export function безТестовых<T>(q: T): T {
  return (q as any).eq('is_test', false) as T
}

/**
 * Отсеять платежи тестовых клиентов.
 *
 * Платежи приезжают отдельным запросом из `payments_view` и сшиваются с
 * клиентами в коде, поэтому фильтр по клиентам до них сам не доходит.
 */
export function платежиБезТестовых<P extends { client_id: number | null }>(
  платежи: P[],
  настоящие: { id: number }[],
): P[] {
  const свои = new Set(настоящие.map((c) => c.id))
  return платежи.filter((p) => p.client_id != null && свои.has(p.client_id))
}
