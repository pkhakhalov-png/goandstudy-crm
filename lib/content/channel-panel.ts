/**
 * Панель каналов: что видно сразу и что спрятано внутрь.
 *
 * Экран каналов легко превратить в стену цифр — публикации, охваты, переходы,
 * заявки, стоимость, лимиты, токены, — после чего человек перестанет на него
 * смотреть. Поэтому здесь сознательно разделено: наверху у каждого канала одна
 * строка состояния и пять чисел, всё остальное живёт внутри карточки.
 *
 * Правила, без которых панель начнёт врать:
 *
 *   Ноль и «нет данных» — разное. Площадка не отдала охваты — это `null` и слово
 *     «нет данных», а не 0. Ноль означает «показали ноль раз», и на экране эти
 *     два случая обязаны выглядеть по-разному.
 *   Переходы приписываются публикации только при кликабельной ссылке. Если
 *     площадка ссылку переписала или не отдала, приписывать ей переходы — значит
 *     выдумывать результат.
 *   Два источника правды не складываются. Охваты приходят от площадки, переходы
 *     и заявки — из CRM по меткам. Это разные измерения разных вещей, и общая
 *     сумма из них не получается.
 */

export type Доставка = 'api' | 'ssh' | 'manual'

export type Состояние =
  /** Публикует и публикуется. */
  | 'работает'
  /** Есть открытая проблема: неизвестный исход, отзыв токена, зависшая ручная выкладка. */
  | 'требует_внимания'
  /** Канал заведён, но ни одной публикации не было. */
  | 'нет_публикаций'
  /** Приостановлен человеком: материал готовится, наружу не уходит. */
  | 'приостановлен'
  /** Остановлен: обычно после отзыва доступа. */
  | 'выключен'

/** Число, которого может не быть. `null` — не ноль, а «не знаем». */
export type Мера = { n: number | null; почему?: string }

export type Карточка = {
  id: number
  платформа: string
  аккаунт: string
  название: string
  доставка: Доставка
  режим: string
  состояние: Состояние
  /** Одна строка, объясняющая состояние человеческим языком. */
  строка: string
  вышло7: number
  вышло30: number
  вПлане7: number
  заблокировано: number
  ждутРук: number
  переходы30: Мера
  заявки30: Мера
  проблем: number
  зона: string
  темп: string
}

const дней = (n: number) => new Date(Date.now() - n * 86_400_000).toISOString()

/** «1 публикация», «2 публикации», «5 публикаций» — экран читают люди. */
export function скл(n: number, формы: [string, string, string]): string {
  const сотня = n % 100, десяток = n % 10
  const форма = сотня >= 11 && сотня <= 14 ? формы[2]
    : десяток === 1 ? формы[0]
      : десяток >= 2 && десяток <= 4 ? формы[1]
        : формы[2]
  return `${n} ${форма}`
}

const ПУБЛИКАЦИЯ: [string, string, string] = ['публикация', 'публикации', 'публикаций']

export const ДОСТАВКА_RU: Record<Доставка, string> = {
  api: 'по API — публикует сама',
  ssh: 'по SSH — кладёт на свой сервер',
  manual: 'руками — готовит машина, публикует человек',
}

export const СОСТОЯНИЕ_RU: Record<Состояние, string> = {
  работает: 'работает',
  требует_внимания: 'требует внимания',
  нет_публикаций: 'нет публикаций',
  приостановлен: 'приостановлен',
  выключен: 'выключен',
}

/** Вышедшие: публикация считается вышедшей, когда её исход подтверждён. */
const ВЫШЛО = ['published', 'verified']

export async function карточкиКаналов(content: any, seo: any): Promise<Карточка[]> {
  const { data: каналы } = await content.from('channels')
    .select('id, platform, account_external_id, title, timezone, mode, delivery, daily_cap, max_catch_up')
    .order('id')
  if (!каналы?.length) return []

  const ids = (каналы as any[]).map((c) => c.id)

  const [{ data: публикации }, { data: внимание }] = await Promise.all([
    content.from('publications')
      .select('id, channel_id, status, scheduled_at, created_at, link_clickable, remote_url')
      .in('channel_id', ids),
    content.from('attention_items')
      .select('id, entity_type, entity_id, severity, reason_code')
      .is('resolved_at', null),
  ])

  const сейчас = Date.now()
  const порог7 = дней(7)
  const порог30 = дней(30)
  const через7 = new Date(сейчас + 7 * 86_400_000).toISOString()

  // Переходы из CRM: метка utm_content хранит идентификатор публикации (E5.2).
  const { data: переходы } = await seo.from('attribution_events')
    .select('utm, created_at').gte('created_at', порог30).not('utm', 'is', null)
  const { data: заявки } = await seo.from('lead_identities')
    .select('last_touch_utm, lead_at').gte('lead_at', порог30)

  const поПубликации = (строки: any[] | null, поле: string) => {
    const счёт = new Map<string, number>()
    for (const r of строки ?? []) {
      const id = (r[поле] ?? {})?.utm_content
      if (!id) continue
      счёт.set(String(id), (счёт.get(String(id)) ?? 0) + 1)
    }
    return счёт
  }
  const переходовПо = поПубликации(переходы, 'utm')
  const заявокПо = поПубликации(заявки, 'last_touch_utm')

  return (каналы as any[]).map((c) => {
    const свои = (публикации ?? []).filter((p: any) => p.channel_id === c.id)
    const вышедшие = свои.filter((p: any) => ВЫШЛО.includes(p.status))

    const вышло7 = вышедшие.filter((p: any) => (p.scheduled_at ?? p.created_at) >= порог7).length
    const вышло30 = вышедшие.filter((p: any) => (p.scheduled_at ?? p.created_at) >= порог30).length
    const вПлане7 = свои.filter((p: any) =>
      p.status === 'scheduled' && p.scheduled_at > new Date(сейчас).toISOString() && p.scheduled_at <= через7).length
    const заблокировано = свои.filter((p: any) => p.status === 'blocked').length
    const неизвестных = свои.filter((p: any) => p.status === 'unknown').length

    // Ручной канал: материал готов и ждёт человека. Это не ошибка машины, но и
    // не «опубликовано»: пока человек не выложил, поста нет.
    const ждутРук = c.delivery === 'manual'
      ? свои.filter((p: any) => p.status === 'scheduled' && p.scheduled_at <= new Date(сейчас).toISOString()).length
      : 0

    const мои = (внимание ?? []).filter((a: any) =>
      a.entity_type === 'publication' && свои.some((p: any) => p.id === a.entity_id))
    const проблем = мои.length + (c.mode === 'stopped' ? 1 : 0)

    // Переходы считаем только у публикаций с кликабельной ссылкой. Пустое
    // link_clickable — это «не знаем», и приписывать по нему переходы нельзя.
    const считаемые = вышедшие.filter((p: any) => p.link_clickable === true)
    const некликабельных = вышедшие.length - считаемые.length
    const сумма = (счёт: Map<string, number>) =>
      считаемые.reduce((s: number, p: any) => s + (счёт.get(String(p.id)) ?? 0), 0)

    const мераПереходов: Мера = вышедшие.length === 0
      ? { n: null, почему: 'публикаций ещё не было' }
      : считаемые.length === 0
        ? { n: null, почему: `ни у одной публикации не подтверждена кликабельная ссылка (${скл(некликабельных, ПУБЛИКАЦИЯ)})` }
        : {
            n: сумма(переходовПо),
            почему: некликабельных ? `${скл(некликабельных, ПУБЛИКАЦИЯ)} не в счёте: ссылка не подтверждена` : undefined,
          }

    const мераЗаявок: Мера = мераПереходов.n === null
      ? { n: null, почему: мераПереходов.почему }
      : { n: сумма(заявокПо) }

    const состояние: Состояние =
      c.mode === 'stopped' ? 'выключен'
        : проблем > 0 || неизвестных > 0 || заблокировано > 0 ? 'требует_внимания'
          : вышедшие.length === 0 ? 'нет_публикаций'
            : c.mode === 'paused' ? 'приостановлен'
              : 'работает'

    const строка =
      состояние === 'выключен' ? 'Канал остановлен — обычно так бывает после отзыва доступа'
        : состояние === 'требует_внимания'
          ? [
              неизвестных ? `${скл(неизвестных, ПУБЛИКАЦИЯ)} с неизвестным исходом` : '',
              заблокировано ? `${заблокировано} заблокировано из-за изменившегося факта` : '',
              мои.length ? `${скл(мои.length, ['пункт', 'пункта', 'пунктов'])} в очереди внимания` : '',
            ].filter(Boolean).join(' · ')
          : состояние === 'нет_публикаций'
            ? 'Канал заведён, публикаций ещё не было'
            : состояние === 'приостановлен'
              ? 'Материал готовится, наружу не уходит — включение отдельным решением'
              : ждутРук
                ? `${скл(ждутРук, ['материал ждёт', 'материала ждут', 'материалов ждут'])} ручной публикации`
                : 'Публикует по расписанию'

    return {
      id: c.id,
      платформа: c.platform,
      аккаунт: c.account_external_id,
      название: c.title || c.account_external_id,
      доставка: (c.delivery ?? 'manual') as Доставка,
      режим: c.mode,
      состояние,
      строка,
      вышло7, вышло30, вПлане7, заблокировано, ждутРук,
      переходы30: мераПереходов,
      заявки30: мераЗаявок,
      проблем,
      зона: c.timezone,
      темп: `${c.daily_cap ?? 1} в день`,
    }
  })
}

/** Сводка над карточками: одна строка про весь раздел. */
export function сводка(карточки: Карточка[]): string {
  if (!карточки.length) return 'каналов нет'
  const по = (s: Состояние) => карточки.filter((k) => k.состояние === s).length
  return [
    `${карточки.length} подключено`,
    по('работает') ? `${по('работает')} работают` : '',
    по('требует_внимания') ? `${по('требует_внимания')} требуют внимания` : '',
    по('нет_публикаций') ? `${по('нет_публикаций')} без публикаций` : '',
    по('приостановлен') ? `${по('приостановлен')} приостановлены` : '',
    по('выключен') ? `${по('выключен')} выключены` : '',
  ].filter(Boolean).join(' · ')
}
