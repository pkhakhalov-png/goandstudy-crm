/**
 * Проверка подключения: что площадка отвечает на самом деле.
 *
 * Экран подключений без этой проверки показывал бы ровно одно — заданы ли
 * переменные окружения. Это не то, что нужно знать перед первой публикацией:
 * токен бывает рабочим, но не тем; бывает тем, но без прав на канал; бывает
 * отозванным вчера. Все три случая с виду одинаковы, и различает их только
 * живой вызов.
 *
 * Чего проверка не делает: не публикует. Право публикации доказывается правами
 * бота в канале, а не тестовым постом в рабочем канале — пост потом придётся
 * удалять, а подписчики его уже увидели. Там, где права по API не узнать
 * (VK), проверка честно возвращает «доступ есть, публикация не доказана» и не
 * выдаёт одно за другое.
 *
 * Секрет наружу не уходит: ни в результат, ни в журнал, ни в сообщение об
 * ошибке. Токен Telegram стоит в самом адресе запроса, поэтому адрес в след
 * никогда не пишется целиком.
 */
import { ПУБЛИКАЦИЯ, type Площадка } from './platforms'

export type Итог = {
  ок: boolean
  /** Доказанные действия — уходят в `connector_capabilities.verified_actions`. */
  действия: string[]
  /** След проверки: что именно ответил сервер. Уходит в `proof_ref`. */
  след: string
  /** Построчно для экрана: что проверяли и что вышло. */
  подробно: string[]
}

const ТАЙМАУТ = 10_000

async function запрос(url: string, чтоЭто: string): Promise<{ ok: boolean; json: any; статус: number; ошибка?: string }> {
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(ТАЙМАУТ), cache: 'no-store' })
    const json = await res.json().catch(() => null)
    return { ok: res.ok, json, статус: res.status }
  } catch (e: any) {
    // В сообщении об ошибке fetch адрес может приехать целиком — вместе с
    // токеном. Поэтому наружу отдаём название шага, а не текст исключения.
    const причина = e?.name === 'TimeoutError' ? `${чтоЭто}: не ответил за ${ТАЙМАУТ / 1000} с` : `${чтоЭто}: сеть недоступна`
    return { ok: false, json: null, статус: 0, ошибка: причина }
  }
}

/**
 * Telegram: два вопроса подряд.
 *
 * Первый — жив ли токен (`getMe`). Второй, по каждому заведённому каналу, —
 * админ ли бот в этом канале и есть ли у него право писать
 * (`getChatMember`). Второй без первого бессмыслен, первый без второго
 * недостаточен: у рабочего бота может не быть прав ровно в нашем канале.
 */
async function телеграм(токен: string, аккаунты: string[]): Promise<Итог> {
  const подробно: string[] = []
  const me = await запрос(`https://api.telegram.org/bot${токен}/getMe`, 'getMe')
  if (!me.ok || !me.json?.ok) {
    const почему = me.ошибка ?? `getMe вернул ${me.статус}${me.json?.description ? `: ${me.json.description}` : ''}`
    return { ок: false, действия: [], след: почему, подробно: [`✗ ${почему}`] }
  }
  const бот = me.json.result
  подробно.push(`✓ токен рабочий: бот @${бот.username} (id ${бот.id})`)

  if (!аккаунты.length) {
    return {
      ок: true,
      действия: ['auth'],
      след: `getMe ok, бот @${бот.username}; каналов не заведено — право публикации проверять негде`,
      подробно: [...подробно, '— каналов на площадке нет: завести канал, тогда проверятся и права'],
    }
  }

  let гдеМожно = 0
  for (const чат of аккаунты) {
    const chatId = чат.startsWith('@') || /^-?\d+$/.test(чат) ? чат : `@${чат}`
    const m = await запрос(
      `https://api.telegram.org/bot${токен}/getChatMember?chat_id=${encodeURIComponent(chatId)}&user_id=${бот.id}`,
      'getChatMember',
    )
    if (!m.ok || !m.json?.ok) {
      подробно.push(`✗ ${chatId}: ${m.ошибка ?? m.json?.description ?? `ответ ${m.статус}`}`)
      continue
    }
    const член = m.json.result
    const админ = член?.status === 'administrator' || член?.status === 'creator'
    const можетПисать = член?.status === 'creator' || член?.can_post_messages === true
    if (админ && можетПисать) {
      гдеМожно++
      подробно.push(`✓ ${chatId}: бот администратор с правом публикации`)
    } else if (админ) {
      подробно.push(`✗ ${chatId}: бот администратор, но без права публикации — включить «Публикация сообщений»`)
    } else {
      подробно.push(`✗ ${chatId}: бот не администратор канала (статус «${член?.status ?? 'неизвестен'}»)`)
    }
  }

  return {
    ок: гдеМожно > 0,
    действия: гдеМожно > 0 ? ['auth', ПУБЛИКАЦИЯ] : ['auth'],
    след: гдеМожно > 0
      ? `getMe ok (@${бот.username}); getChatMember подтвердил право публикации в ${гдеМожно} из ${аккаунты.length}`
      : `getMe ok (@${бот.username}), но права публикации нет ни в одном из ${аккаунты.length} каналов`,
    подробно,
  }
}

/**
 * VK: проверяем токен и сообщество, право wall не проверяем.
 *
 * Права ключа сообщества по API не спросить: `account.getAppPermissions`
 * работает для пользовательских токенов, а не для ключей сообщества. Значит
 * единственное доказательство права wall — публикация, а публиковать на
 * проверке подключения мы не будем. Поэтому итог здесь всегда «доступ есть,
 * публикация не доказана» — и экран говорит это словами, а не выдаёт за
 * подключение.
 */
async function вк(токен: string, аккаунты: string[]): Promise<Итог> {
  const группа = аккаунты[0]?.replace(/^-/, '') ?? ''
  const базовый = `https://api.vk.com/method/groups.getById?v=5.199&access_token=${токен}`
  const url = группа ? `${базовый}&group_id=${encodeURIComponent(группа)}` : базовый
  const r = await запрос(url, 'groups.getById')

  if (r.ошибка) return { ок: false, действия: [], след: r.ошибка, подробно: [`✗ ${r.ошибка}`] }
  if (r.json?.error) {
    const почему = `groups.getById: ошибка ${r.json.error.error_code} — ${r.json.error.error_msg}`
    return { ок: false, действия: [], след: почему, подробно: [`✗ ${почему}`] }
  }

  const первая = r.json?.response?.groups?.[0] ?? r.json?.response?.[0] ?? null
  const имя = первая?.name ?? первая?.screen_name ?? 'сообщество'
  return {
    ок: true,
    действия: ['auth'],
    след: `groups.getById ok: «${имя}». Право wall по API не проверяется — только тестовой публикацией`,
    подробно: [
      `✓ токен рабочий, сообщество отвечает: «${имя}»`,
      '— право wall этим вызовом не доказано: у ключа сообщества права не спросить,',
      '  доказательством будет первая тестовая публикация',
    ],
  }
}

/** Проверить площадку. Секрет передаётся сюда, но наружу не возвращается. */
export async function проверить(
  п: Площадка,
  вход: { секрет: string | null; аккаунты: string[] },
): Promise<Итог> {
  if (п.путь === 'нет') {
    return {
      ок: false,
      действия: [],
      след: 'интерфейса публикации у площадки нет — проверять нечего',
      подробно: [`✗ ${п.почему ?? 'Интерфейса публикации нет.'} Ни токен, ни коннектор этого не меняют.`],
    }
  }
  if (п.путь === 'rss') {
    return {
      ок: true,
      действия: [],
      след: 'площадка забирает материал из ленты сама — подключение проверяется её кабинетом',
      подробно: [`— ${п.почему ?? 'Площадка забирает материал из ленты.'}`,
        '— проверить можно одним способом: дождаться, когда она заберёт очередную статью'],
    }
  }
  if (п.доставка === 'ssh') {
    return {
      ок: true,
      действия: [],
      след: 'доставка по SSH — проверяется публикацией статьи, а не этим экраном',
      подробно: ['— сайт публикуется агентом на своём сервере; отдельной проверки токена здесь нет'],
    }
  }
  if (!вход.секрет) {
    const почему = `секрет не задан (${п.секреты.join(' или ')})`
    return { ок: false, действия: [], след: почему, подробно: [`✗ ${почему}`] }
  }
  if (п.код === 'telegram') return телеграм(вход.секрет, вход.аккаунты)
  if (п.код === 'vk') return вк(вход.секрет, вход.аккаунты)
  return {
    ок: false,
    действия: [],
    след: `проверка для площадки «${п.код}» не написана`,
    подробно: [`✗ проверять «${п.код}» пока нечем: коннектора нет`],
  }
}

/** Первый заданный секрет площадки. Порядок в реестре — это и есть приоритет. */
export function секретДля(п: Площадка, env: Record<string, string | undefined> = process.env as any): string | null {
  for (const имя of п.секреты) {
    const v = env[имя]
    if (typeof v === 'string' && v.trim()) return v.trim()
  }
  return null
}
