/**
 * Свежесть фактов: следствия наблюдения (E6.1, E6.2, E6.7).
 *
 * Наблюдение уже умеет честно назвать исход (`observe.ts`). Этот слой отвечает
 * на следующий вопрос: что из исхода следует. Ответ не сводится к «страница
 * изменилась — блокируем», и вот почему.
 *
 * Страница вуза меняется почти каждый день: новости в боковом блоке, баннер
 * про cookie, номер набора в подвале. Если считать любое изменение хеша
 * изменением факта, машина будет блокировать выпуск ежедневно и по пустякам, а
 * человек через неделю перестанет читать её сообщения — и пропустит то одно,
 * которое было настоящим. Поэтому изменение страницы здесь только повод
 * перепроверить факт по тексту: цена на месте — факт стоит, цены больше нет —
 * вот это событие.
 *
 * Обратная ошибка дороже. Пробел наблюдения — таймаут, 403, три 404 подряд —
 * нельзя превращать в «изменений нет»: первое видно в отчёте как пробел, а
 * второе молча продлевает годность факта, которого никто не проверял.
 *
 * И отдельно про правку вышедшего. Снять или поправить пост на площадке наш
 * коннектор не умеет вовсе — в контракте нет такой операции (см. E5.10). У обеих
 * площадок методы правки в API есть, но мы их ни разу не вызывали, поэтому план
 * правки называет их «не проверяли», а не «можно». Записать непроверенную
 * возможность как доступную — значит пообещать человеку кнопку, которой нет.
 */
import { ПРОБЕЛ, выводИзИстории, type Исход, type Вывод } from './observe'

/* ── Расписание ─────────────────────────────────────────────────────────── */

/** Критичный источник — визы, дедлайны, стоимость: смотрим четыре раза в сутки. */
export const ЧАСЫ_КРИТИЧНЫЕ = 6
/** Прочие — раз в неделю: описание кампуса не меняется к утру. */
export const ЧАСЫ_ПРОЧИЕ = 168

/**
 * Через сколько часов смотреть источник заново.
 *
 * Те же числа стоят в `seo.sources_due`, и это сознательное дублирование: в SQL
 * оно нужно очереди, здесь — предварительному расчёту и проверкам. Расхождение
 * двух мест ловится проверкой `scripts/content-freshness-test.ts`, которая
 * сравнивает расчёт с тем, что вернула база.
 */
export function часыПерепроверки(критичный: boolean, задано?: number | null): number {
  if (задано != null && задано > 0) return задано
  return критичный ? ЧАСЫ_КРИТИЧНЫЕ : ЧАСЫ_ПРОЧИЕ
}

/** Пора ли смотреть: ни разу не смотрели — значит пора. */
export function пораСмотреть(
  последнее: string | Date | null | undefined,
  критичный: boolean,
  задано?: number | null,
  сейчас = new Date(),
): { пора: boolean; просрочкаЧасов: number } {
  if (!последнее) return { пора: true, просрочкаЧасов: Infinity }
  const прошло = (сейчас.getTime() - new Date(последнее).getTime()) / 3_600_000
  return { пора: прошло >= часыПерепроверки(критичный, задано), просрочкаЧасов: Math.round(прошло * 10) / 10 }
}

/* ── История наблюдений из строк базы ───────────────────────────────────── */

export type СтрокаСнимка = {
  outcome?: string | null
  http_status?: number | null
  fetch_error?: string | null
  changed?: boolean | null
}

/**
 * Какой исход стоит за строкой снимка.
 *
 * У строк, снятых до миграции свежести, имени исхода нет — его приходится
 * восстанавливать по статусу и ошибке. Восстанавливается не всё: ответ 304 в
 * старых строках неотличим от обычного успеха, потому что условных заголовков
 * мы тогда не посылали и 304 прийти не мог. Это единственное место, где мы
 * гадаем, и гадаем в безопасную сторону: неизвестное считается пробелом, а не
 * подтверждением.
 */
export function видИзСтроки(row: СтрокаСнимка): Исход['вид'] {
  const имя = (row.outcome ?? '').trim()
  if (имя) return имя as Исход['вид']

  const s = row.http_status ?? null
  const err = row.fetch_error ?? null
  if (s === 404 || s === 410) return 'не_найдено'
  if (s === 403 || s === 401) return 'запрещено_сервером'
  if (err && /abort|timeout|таймаут/i.test(err)) return 'таймаут'
  if (err) return 'недоступно'
  if (s != null && s >= 200 && s < 300) {
    if (row.changed === false) return 'не_изменилось'
    if (row.changed === true) return 'изменилось'
    return 'впервые'
  }
  return 'недоступно'
}

/** История видов от новой строки к старой — в том порядке, какой ждёт `выводИзИстории`. */
export function историяВидов(строки: СтрокаСнимка[]): Исход['вид'][] {
  return строки.map(видИзСтроки)
}

/* ── Что делать с исходом ───────────────────────────────────────────────── */

export type Следствие = {
  /** Прибавить к счётчику подряд или обнулить его. */
  пробелов: (было: number) => number
  /** Нужно ли перепроверять факты по новому тексту. */
  перепроверитьФакты: boolean
  /** Вывод из истории: жив, исчез, наблюдение прервано. */
  вывод: Вывод
  /** Короткая причина для журнала и для человека. */
  почему: string
}

export function следствия(исход: Исход, историяДо: Исход['вид'][]): Следствие {
  const пробел = ПРОБЕЛ.has(исход.вид)
  const вывод = выводИзИстории([исход.вид, ...историяДо])

  const почему = пробел
    ? `${исход.вид}: мы не узнали, что с источником. Это пробел наблюдения, а не «изменений нет»`
    : исход.вид === 'не_изменилось'
      ? `не изменилось (${(исход as any).как === 'по_ответу_304' ? 'ответ 304' : 'совпал хеш'}) — факт подтверждён`
      : `${исход.вид}: текст страницы другой, факты надо перепроверить по нему`

  return {
    пробелов: (было) => (пробел ? было + 1 : 0),
    перепроверитьФакты: исход.вид === 'изменилось' || исход.вид === 'впервые',
    вывод,
    почему,
  }
}

/**
 * Надо ли звать человека.
 *
 * Пробел сам по себе не повод: сайт лежал минуту — это шум. Поводом становится
 * вывод из истории, то есть несколько наблюдений подряд без ответа. Для
 * критичного источника порог тот же, а вес — выше: неделя молчания страницы
 * визовых правил и неделя молчания страницы про столовую стоят разного.
 */
export function нуженЧеловек(вывод: Вывод, критичный: boolean): { нужен: boolean; вес: 'low' | 'medium' | 'high'; текст: string } {
  if (вывод.что === 'источник_жив' || вывод.что === 'ждём') {
    return { нужен: false, вес: 'low', текст: вывод.что === 'ждём' ? вывод.почему : 'источник отвечает' }
  }
  const вес = критичный ? 'high' : 'medium'
  if (вывод.что === 'источник_исчез') {
    return {
      нужен: true, вес,
      текст: `Страница отдаёт ${вывод.статус} ${вывод.подряд} наблюдения подряд. Скорее всего, переехала: `
        + 'найти новый адрес и заменить источник. Факты пока не подтверждены и не опровергнуты.',
    }
  }
  if (вывод.что === 'источник_закрылся') {
    return {
      нужен: true, вес,
      текст: `Источник закрылся от нас ${вывод.подряд} наблюдения подряд (403 или robots.txt). Страница, скорее всего, `
        + 'на месте — нас на неё не пускают. Решить: другой источник или ручная выписка.',
    }
  }
  return {
    нужен: true, вес,
    текст: `Источник недоступен ${вывод.подряд} наблюдения подряд. Это пробел наблюдения, а НЕ «изменений нет»: `
      + 'факты на нём не подтверждены и не опровергнуты.',
  }
}

/* ── Правка вышедшего ───────────────────────────────────────────────────── */

export type ПравкаНаПлощадке = {
  платформа: string
  /** Метод площадки, которым правка делается. Из документации. */
  метод: string | null
  /** Вызывали ли мы его хоть раз. */
  доверие: 'проверено' | 'не_проверяли'
  примечание: string
}

/**
 * Можно ли поправить вышедший пост.
 *
 * Отвечаем «не проверяли» и для Telegram, и для VK, хотя методы в документации
 * у обоих есть. Разведка E5.8 показала, почему на документацию тут нельзя
 * опираться: она описывает намерение авторов площадки, а не поведение
 * конкретного аккаунта с конкретным токеном. У правки к тому же есть окна по
 * времени и по типу вложения, и узнать их настоящие границы можно только
 * вызовом. Пока вызова не было, план правки честно говорит: руками.
 */
export function правкаНаПлощадке(платформа: string | null): ПравкаНаПлощадке {
  const p = (платформа ?? '').toLowerCase()
  if (p === 'telegram') {
    return {
      платформа: 'telegram', метод: 'editMessageText', доверие: 'не_проверяли',
      примечание: 'правка ограничена окном по времени и типом вложения; границы не проверяли вызовом',
    }
  }
  if (p === 'vk') {
    return {
      платформа: 'vk', метод: 'wall.edit', доверие: 'не_проверяли',
      примечание: 'правка поста сообщества требует прав wall и своего окна; вызовом не проверяли',
    }
  }
  return {
    платформа: p || 'неизвестна', метод: null, доверие: 'не_проверяли',
    примечание: 'площадка не опознана — способ правки неизвестен',
  }
}

/* ── План правки ────────────────────────────────────────────────────────── */

export type ПланВход = {
  факт: {
    id: number
    kind: string
    statement: string
    /** Чем факт подтверждался раньше — дословная выдержка из прежнего снимка. */
    было: string | null
    /** Нашлось ли подтверждение в новом тексте страницы. */
    подтверждаетсяСейчас: boolean
    /** Что на странице стоит вместо прежнего — если нашли. */
    стало: string | null
  }
  источник: { url: string | null; наблюдёнВ: string }
  публикация: {
    id: number
    статус: string
    платформа: string | null
    адрес: string | null
  } | null
  вариант: { версияId: number; пакетId: number | null } | null
}

export type Действие = { что: string; доступно: 'да' | 'нет' | 'не_проверяли'; почему: string }

export type План = {
  вес: 'low' | 'medium' | 'high'
  действия: Действие[]
  текст: string
}

/**
 * План правки: что именно изменилось, где это стоит и что с этим можно сделать.
 *
 * План не решает за человека. Его задача — чтобы решение не требовало
 * раскопок: адрес поста, прежняя выдержка, нынешнее состояние страницы и
 * перечень доступных действий с честной пометкой, какое из них мы умеем.
 */
export function планПравки(вход: ПланВход): План {
  const { факт, источник, публикация, вариант } = вход
  const вышло = публикация?.статус === 'published'

  const действия: Действие[] = []
  if (вышло) {
    const пр = правкаНаПлощадке(публикация!.платформа)
    действия.push({
      что: `поправить текст поста на площадке (${пр.метод ?? 'способ неизвестен'})`,
      доступно: пр.метод ? 'не_проверяли' : 'нет',
      почему: пр.примечание,
    })
    действия.push({
      что: 'снять пост',
      доступно: 'не_проверяли',
      почему: 'удаление в контракте коннектора не реализовано — руками через интерфейс площадки',
    })
    действия.push({
      что: 'оставить пост и дать оговорку отдельной публикацией',
      доступно: 'да',
      почему: 'обычная публикация тем же путём, что и все остальные',
    })
  } else {
    действия.push({
      что: 'поправить вариант и перепланировать выпуск',
      доступно: 'да',
      почему: 'публикация заблокирована и наружу не ушла',
    })
    действия.push({
      что: 'отменить публикацию',
      доступно: 'да',
      почему: 'отмена — решение человека, статус ставится вручную',
    })
  }

  const состояние = факт.подтверждаетсяСейчас
    ? `на странице формулировка ещё есть: ${обрезать(факт.стало)}`
    : факт.стало
      ? `на странице теперь: ${обрезать(факт.стало)}`
      : 'прежней формулировки на странице больше нет, замену автоматически не нашли'

  const строки = [
    `Факт #${факт.id} (${факт.kind}): ${факт.statement}`,
    `Было подтверждено выдержкой: ${обрезать(факт.было) || 'выдержка не сохранилась'}`,
    `Сейчас — ${состояние}`,
    `Источник: ${источник.url ?? 'адрес неизвестен'}, наблюдён ${источник.наблюдёнВ}`,
    вышло
      ? `Пост уже вышел: ${публикация!.адрес ?? 'ссылки нет'} (${публикация!.платформа ?? 'площадка неизвестна'})`
      : публикация
        ? `Публикация #${публикация.id} заблокирована до правки, наружу не ушла`
        : `Затронут неопубликованный вариант${вариант ? ` (версия #${вариант.версияId})` : ''}`,
    'Что можно сделать:',
    ...действия.map((д) => `  — ${д.что}: ${д.доступно === 'да' ? 'умеем' : д.доступно === 'нет' ? 'нельзя' : 'не проверяли'} — ${д.почему}`),
  ]

  return {
    // Вышедший пост с изменившимся фактом читают прямо сейчас — это высокий вес
    // независимо от типа факта. Заблокированный не читает никто.
    вес: вышло ? 'high' : 'medium',
    действия,
    текст: строки.join('\n'),
  }
}

function обрезать(s: string | null | undefined, n = 180): string {
  if (!s) return ''
  const t = s.replace(/\s+/g, ' ').trim()
  return t.length > n ? t.slice(0, n) + '…' : t
}
