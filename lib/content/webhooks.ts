/**
 * Приём вебхуков от площадок (E5.13).
 *
 * Три защиты, и они закрывают разные дыры — ни одна не заменяет другую.
 *
 *   Подпись отвечает на вопрос «это вообще от площадки». Без неё любой, кто
 *     знает адрес, шлёт нам события от её имени.
 *   Срок отвечает на «это не старое». Подписанное событие остаётся подписанным
 *     навсегда; перехваченный и повторённый через сутки запрос пройдёт проверку
 *     подписи безупречно.
 *   Уникальность отвечает на «это не то же самое». Площадки повторяют доставку
 *     при отсутствии ответа — это их штатное поведение, а не сбой.
 *
 * Про срок есть неприятная правда, которую нельзя замазать: не всякое событие
 * несёт своё время. У телеграма время есть у сообщений и нет у некоторых
 * других обновлений; у VK Callback API времени нет вовсе. Там, где времени
 * нет, защита по сроку не работает — и притворяться, что работает, значит
 * иметь дыру и думать, что её нет. Поэтому функция возвращает `срок: 'нечем'`,
 * а не молча пропускает.
 */
import crypto from 'node:crypto'

export type Платформа = 'telegram' | 'vk'

export type ПроверкаВебхука =
  | { ok: true; eventId: string; срок: 'свежее' | 'нечем'; возраст: number | null }
  | { ok: false; причина: string; статус: 401 | 400 | 409 }

/** Окно свежести. Больше суток — уже не «доставка подзадержалась». */
export const ОКНО_СВЕЖЕСТИ_СЕК = 300

/**
 * Сравнение секретов постоянным временем.
 *
 * Обычное `===` выходит из сравнения на первом несовпавшем знаке, и по
 * времени ответа секрет подбирается по одному символу. Речь о миллисекундах,
 * но подбор автоматический, и времени у него много.
 */
export function секретыСовпали(a: string | null | undefined, b: string | null | undefined): boolean {
  if (!a || !b) return false
  const бa = Buffer.from(a), бb = Buffer.from(b)
  // Длины сравниваем отдельно: timingSafeEqual падает на разных длинах.
  // Утечка длины секрета безобидна, утечка его содержимого — нет.
  if (бa.length !== бb.length) return false
  return crypto.timingSafeEqual(бa, бb)
}

/**
 * Годится ли секрет для заголовка.
 *
 * Телеграм передаёт секрет заголовком, а в заголовок HTTP нельзя положить
 * ничего, кроме однобайтовых знаков. Секрет с русскими буквами — естественная
 * вещь в русскоязычном проекте — не отправится вовсе, и ошибка будет невнятной:
 * «Cannot convert argument to a ByteString» вместо «секрет не тот».
 *
 * Документация телеграма разрешает только A-Z, a-z, 0-9, подчёркивание и
 * дефис, длиной 1–256. Проверяем на старте, а не в момент первого вебхука.
 */
export function секретГодится(s: string | null | undefined): { ok: boolean; почему?: string } {
  if (!s) return { ok: false, почему: 'секрет не задан' }
  if (s.length > 256) return { ok: false, почему: 'длиннее 256 знаков' }
  if (!/^[A-Za-z0-9_-]+$/.test(s)) {
    return { ok: false, почему: 'разрешены только латиница, цифры, подчёркивание и дефис: секрет уходит заголовком HTTP, а туда кириллица не помещается' }
  }
  return { ok: true }
}

/** Идентификатор события в форме uuid — под ключ таблицы расписок. */
export function ключСобытия(платформа: Платформа, eventId: string): string {
  const h = crypto.createHash('md5').update(`${платформа}|${eventId}`).digest('hex')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`
}

/**
 * Разобрать событие телеграма.
 *
 * Подпись — заголовок `X-Telegram-Bot-Api-Secret-Token`, который площадка
 * возвращает тем же значением, что задано при setWebhook. Это не подпись тела,
 * а общий секрет: тело подделать нельзя только в том смысле, что без секрета
 * запрос не примут.
 */
export function разобратьTelegram(
  headers: Headers,
  body: any,
  секрет: string | null,
  сейчас = new Date(),
): ПроверкаВебхука {
  if (!секретыСовпали(headers.get('x-telegram-bot-api-secret-token'), секрет)) {
    return { ok: false, причина: 'подпись не сошлась', статус: 401 }
  }

  const updateId = body?.update_id
  if (updateId == null) return { ok: false, причина: 'нет update_id', статус: 400 }

  // Время есть у сообщений и постов канала. У остальных обновлений его нет.
  const дата = body?.message?.date ?? body?.channel_post?.date ?? body?.edited_channel_post?.date ?? null
  if (дата == null) {
    return { ok: true, eventId: String(updateId), срок: 'нечем', возраст: null }
  }

  const возраст = Math.floor(сейчас.getTime() / 1000) - Number(дата)
  if (возраст > ОКНО_СВЕЖЕСТИ_СЕК) {
    return { ok: false, причина: `событие старше ${ОКНО_СВЕЖЕСТИ_СЕК} с (${возраст} с)`, статус: 400 }
  }
  // Отрицательный возраст — часы разошлись. Это не повод отказывать: наши
  // часы могут быть неправы ровно так же, как чужие.
  return { ok: true, eventId: String(updateId), срок: 'свежее', возраст }
}

/**
 * Разобрать событие VK.
 *
 * У VK Callback API нет ни подписи тела, ни времени события. Есть общий
 * секрет в теле и `event_id` для дедупликации — и всё. Значит защита по сроку
 * там невозможна в принципе, и единственное, что стоит между нами и повтором
 * суточной давности, — уникальность `event_id`.
 */
export function разобратьVk(
  body: any,
  секрет: string | null,
  ожидаемаяГруппа: number | string | null,
): ПроверкаВебхука {
  if (!секретыСовпали(body?.secret, секрет)) {
    return { ok: false, причина: 'подпись не сошлась', статус: 401 }
  }
  // Чужая группа с нашим секретом — значит секрет утёк или его переиспользуют.
  // Проверять дёшево, а не проверять значит принимать события неизвестно о чём.
  if (ожидаемаяГруппа != null && String(body?.group_id) !== String(ожидаемаяГруппа)) {
    return { ok: false, причина: 'событие не от нашей группы', статус: 401 }
  }
  const eventId = body?.event_id
  if (!eventId) return { ok: false, причина: 'нет event_id', статус: 400 }

  return { ok: true, eventId: String(eventId), срок: 'нечем', возраст: null }
}

/**
 * Записать, что событие обработано. `false` — уже обрабатывали.
 *
 * Уникальность держит первичный ключ таблицы, а не проверка перед вставкой:
 * между проверкой и вставкой успевает вторая доставка того же события, и
 * площадки повторяют доставку именно пачками.
 */
export async function принятьОдинРаз(
  content: any,
  платформа: Платформа,
  eventId: string,
): Promise<boolean> {
  const { error } = await content.from('event_receipts').insert({
    consumer: `webhook:${платформа}`,
    event_id: ключСобытия(платформа, eventId),
  })
  if (!error) return true
  if (String(error.code) === '23505') return false
  throw new Error(`расписка о событии не записалась: ${error.message}`)
}

/**
 * Что делать с исходом отправки.
 *
 * Отдельно от коннектора намеренно: политика повторов — решение системы, а не
 * площадки. Площадка сообщает, что случилось; сколько раз пробовать и когда
 * сдаться, решаем мы.
 */
export const МАКС_ПОПЫТОК = 5

export type Решение =
  | { что: 'готово' }
  | { что: 'повторить'; черезСек: number }
  | { что: 'сдаться'; почему: string }
  | { что: 'остановить_канал'; почему: string }
  | { что: 'разобрать_вручную'; почему: string }

export function решитьПоИсходу(
  исход: { kind: string; reason?: string; retryAfterSec?: number },
  попытка: number,
): Решение {
  switch (исход.kind) {
    case 'опубликовано':
      return { что: 'готово' }

    case 'отказано':
      // Повтор того же даст то же самое. Пробовать пять раз, чтобы пять раз
      // получить «слишком длинно», — это не настойчивость, а трата слота.
      return { что: 'сдаться', почему: исход.reason ?? 'площадка отказала' }

    case 'нужна_авторизация':
      // Не повторяем и не сдаёмся: чинится человеком, и до починки все
      // попытки на этом канале бессмысленны.
      return { что: 'остановить_канал', почему: исход.reason ?? 'токен не принят' }

    case 'повторить_позже': {
      if (попытка >= МАКС_ПОПЫТОК) {
        return { что: 'сдаться', почему: `${МАКС_ПОПЫТОК} попыток подряд: ${исход.reason ?? ''}`.trim() }
      }
      // Срок от площадки главнее нашей оценки: она знает, когда снимет
      // ограничение, а мы гадаем. Если срока нет — растущая задержка.
      const свой = Math.min(60 * 2 ** (попытка - 1), 3600)
      return { что: 'повторить', черезСек: исход.retryAfterSec ?? свой }
    }

    case 'исход_неизвестен':
      // Единственное, чего здесь делать нельзя, — повторять. Слепой повтор
      // при неизвестном исходе даёт второй пост.
      return {
        что: 'разобрать_вручную',
        почему: исход.reason
          ? `исход неизвестен: ${исход.reason}. Повторять нельзя — можно получить второй пост`
          : 'исход неизвестен; повторять нельзя — можно получить второй пост',
      }

    default:
      return { что: 'разобрать_вручную', почему: `неизвестный исход «${исход.kind}»` }
  }
}
