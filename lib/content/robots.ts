/**
 * robots.txt: что нам запрещено запрашивать (E6.4).
 *
 * Правило здесь жёстче, чем кажется на первый взгляд. Запрещённый путь не
 * просто не сохраняется — он НЕ ЗАПРАШИВАЕТСЯ. Разница видна с той стороны:
 * запрос в журнале чужого сервера есть независимо от того, что мы сделали с
 * ответом. «Скачали, но не сохранили» — это всё равно скачали.
 *
 * Разбор намеренно простой и осторожный. Стандарт robots.txt допускает
 * толкования, а в спорном случае мы выбираем «не ходить»: пропущенная страница
 * стоит нам одного факта, а проигнорированный запрет — репутации домена,
 * который нас же и подтверждает.
 */
import { safeFetch } from '../seo/safe-fetch'

export type Правила = {
  /** Пути, запрещённые для нашего агента или для всех. */
  запрещено: string[]
  /** Явно разрешённые — они сильнее запрета, если длиннее. */
  разрешено: string[]
  /** Задержка между запросами, если указана. */
  задержкаСек: number | null
  /** Откуда взяли: сам файл, отсутствие файла или ошибка. */
  источник: 'файл' | 'нет_файла' | 'не_прочитали'
  /**
   * Почему не прочитали. Нужно, чтобы не выдать защиту от приватных адресов
   * за правило robots.txt: отказать правильно и соврать о причине — значит
   * отправить человека искать несуществующее правило.
   */
  причина?: string
  прочитано: string
}

const КЭШ = new Map<string, { правила: Правила; до: number }>()
const ЖИЗНЬ_МС = 6 * 3600_000

/**
 * Разобрать текст robots.txt для конкретного агента.
 *
 * Берутся две группы: наша по имени и общая со звёздочкой. Наша не отменяет
 * общую целиком — мы складываем обе, потому что складывать безопаснее, чем
 * угадывать, какую имел в виду автор файла.
 */
export function разобратьRobots(текст: string, агент: string): Omit<Правила, 'источник' | 'прочитано'> {
  const строки = текст.split(/\r?\n/).map((s) => s.replace(/#.*$/, '').trim()).filter(Boolean)
  const запрещено: string[] = []
  const разрешено: string[] = []
  let задержкаСек: number | null = null

  let насКасается = false
  let былаГруппа = false

  for (const строка of строки) {
    const m = строка.match(/^([A-Za-z-]+)\s*:\s*(.*)$/)
    if (!m) continue
    const ключ = m[1].toLowerCase()
    const знач = m[2].trim()

    if (ключ === 'user-agent') {
      // Подряд идущие User-agent относятся к одной группе.
      if (!былаГруппа) насКасается = false
      былаГруппа = true
      if (знач === '*' || агент.toLowerCase().includes(знач.toLowerCase()) && знач !== '') насКасается = true
      continue
    }
    былаГруппа = false
    if (!насКасается) continue

    if (ключ === 'disallow' && знач) запрещено.push(знач)
    else if (ключ === 'allow' && знач) разрешено.push(знач)
    else if (ключ === 'crawl-delay') {
      const n = Number(знач)
      if (Number.isFinite(n) && n > 0) задержкаСек = n
    }
  }
  return { запрещено, разрешено, задержкаСек }
}

/** Подходит ли путь под правило. `*` и `$` — единственное, что поддерживаем. */
function подходит(путь: string, правило: string): boolean {
  const конецЖёсткий = правило.endsWith('$')
  const шаблон = (конецЖёсткий ? правило.slice(0, -1) : правило)
    .replace(/[.+^${}()|[\]\\]/g, '\\$&')
    .replace(/\*/g, '.*')
  return new RegExp(`^${шаблон}${конецЖёсткий ? '$' : ''}`).test(путь)
}

/**
 * Можно ли идти по этому адресу.
 *
 * Более длинное правило сильнее короткого — так разрешают исключения внутри
 * запрещённого раздела. При равной длине побеждает разрешение: запрет,
 * совпадающий с разрешением, означает, что автор файла имел в виду именно
 * исключение.
 */
export function путьРазрешён(путь: string, правила: Pick<Правила, 'запрещено' | 'разрешено'>): boolean {
  let запрет = -1, разрешение = -1
  for (const п of правила.запрещено) if (подходит(путь, п) && п.length > запрет) запрет = п.length
  for (const п of правила.разрешено) if (подходит(путь, п) && п.length > разрешение) разрешение = п.length
  if (запрет < 0) return true
  return разрешение >= запрет
}

/** Правила для домена. Кэш на шесть часов: файл меняется редко, а запрос стоит. */
export async function правилаДомена(origin: string, агент = 'goandstudy-seo-bot'): Promise<Правила> {
  const ключ = `${origin}|${агент}`
  const есть = КЭШ.get(ключ)
  if (есть && есть.до > Date.now()) return есть.правила

  const res = await safeFetch(`${origin.replace(/\/$/, '')}/robots.txt`, агент)
  let правила: Правила
  if (res.ok) {
    правила = {
      ...разобратьRobots(res.body.toString('utf8'), агент),
      источник: 'файл', прочитано: new Date().toISOString(),
    }
  } else if (res.status === 404) {
    // Нет файла — значит ограничений нет. Это единственный случай, когда
    // отсутствие ответа толкуется в нашу пользу, и он прямо описан стандартом.
    правила = { запрещено: [], разрешено: [], задержкаСек: null, источник: 'нет_файла', прочитано: new Date().toISOString() }
  } else {
    // Файл не прочитался. Не знаем, что запрещено, — значит не ходим никуда,
    // кроме корня. Обратное решение («не прочитали, значит можно») однажды
    // приведёт нас туда, куда просили не ходить.
    правила = {
      запрещено: ['/'], разрешено: [], задержкаСек: null,
      источник: 'не_прочитали', причина: res.reason, прочитано: new Date().toISOString(),
    }
  }

  КЭШ.set(ключ, { правила, до: Date.now() + ЖИЗНЬ_МС })
  return правила
}

/** Только для тестов: забыть прочитанное. */
export function __сброситьКэшRobots() { КЭШ.clear() }
