/**
 * Наблюдение за источником: что с ним стало (E6.5).
 *
 * Задача этого слоя — не «скачать страницу», а честно назвать исход. Сегодня
 * любая неудача выглядит одинаково: `ok: false` со строкой причины. Для
 * свежести фактов этого мало, потому что разные неудачи означают разное:
 *
 *   404 — страницы нет ПО ЭТОМУ АДРЕСУ СЕЙЧАС. Это не «факт отменён»: сайты
 *     переезжают, разделы перестраивают, вуз меняет CMS. Одиночный 404 —
 *     наблюдение, а не вывод.
 *   403 — нас не пустили. Страница, скорее всего, на месте, просто не для нас.
 *     Считать её исчезнувшей значит выбросить подтверждение из-за чужого
 *     фильтра ботов.
 *   таймаут — мы ничего не узнали. Ни «изменилось», ни «не изменилось».
 *   304 и совпадение хеша — «не изменилось». Это ЕДИНСТВЕННЫЙ случай, когда
 *     можно сказать, что факт всё ещё подтверждён.
 *
 * Главное правило этапа: недоступность источника — пробел наблюдения, а не
 * «изменений нет». Разница в том, что первое видно в отчёте как пробел, а
 * второе молча продлевает годность факта, которого никто не проверял.
 */
import crypto from 'node:crypto'
import { safeFetch } from '../seo/safe-fetch'
import { правилаДомена, путьРазрешён } from './robots'

export type Исход =
  | { вид: 'впервые'; хеш: string; текст: string; статус: number; финальныйАдрес: string; etag: string | null; изменено: string | null }
  | { вид: 'изменилось'; хеш: string; текст: string; статус: number; финальныйАдрес: string; etag: string | null; изменено: string | null }
  | { вид: 'не_изменилось'; хеш: string; как: 'по_ответу_304' | 'по_хешу'; статус: number }
  | { вид: 'не_найдено'; статус: number }
  | { вид: 'запрещено_сервером'; статус: number }
  | { вид: 'запрещено_robots'; правило: string }
  | { вид: 'таймаут' }
  | { вид: 'недоступно'; причина: string; статус: number | null }

/** Пробел наблюдения: мы НЕ знаем, что с источником. */
export const ПРОБЕЛ: ReadonlySet<Исход['вид']> = new Set([
  'не_найдено', 'запрещено_сервером', 'запрещено_robots', 'таймаут', 'недоступно',
])

/** Подтверждает ли исход, что факт всё ещё на месте. */
export function подтверждает(и: Исход): boolean {
  return и.вид === 'не_изменилось' || и.вид === 'впервые' || и.вид === 'изменилось'
}

const хешТекста = (s: string) => crypto.createHash('sha256').update(s).digest('hex')

export type Прошлое = {
  хеш?: string | null
  etag?: string | null
  /** Значение Last-Modified из прошлого ответа. */
  изменено?: string | null
}

/**
 * Посмотреть, что стало с адресом.
 *
 * `извлечь` передаётся снаружи, чтобы этот слой не знал про HTML: его дело —
 * исход, а не разбор разметки.
 */
export async function наблюдать(
  url: string,
  прошлое: Прошлое = {},
  извлечь: (html: string) => string = (s) => s,
  агент = 'goandstudy-seo-bot',
): Promise<Исход> {
  let u: URL
  try { u = new URL(url) } catch { return { вид: 'недоступно', причина: 'адрес не разобрался', статус: null } }

  // robots.txt — ДО запроса. Запрещённый путь не запрашивается вовсе:
  // «скачали, но не сохранили» — это всё равно скачали, и в журнале чужого
  // сервера наш запрос будет стоять.
  const правила = await правилаДомена(u.origin, агент)

  // Если robots.txt не прочитался потому, что сам хост заблокирован защитой
  // от приватных адресов, — это недоступность, а не запрет robots. Назвать
  // одно другим значит отправить человека искать правило, которого нет.
  if (правила.источник === 'не_прочитали' && /blocked (host|protocol)/i.test(правила.причина ?? '')) {
    return { вид: 'недоступно', причина: правила.причина ?? 'хост заблокирован', статус: null }
  }

  if (!путьРазрешён(u.pathname, правила)) {
    const правило = правила.запрещено.find((p) => u.pathname.startsWith(p.replace(/\*.*$/, ''))) ?? '/'
    return {
      вид: 'запрещено_robots',
      правило: правила.источник === 'не_прочитали'
        ? `robots.txt не прочитался (${правила.причина ?? 'причина неизвестна'}) — не ходим никуда`
        : `${правило} (${правила.источник})`,
    }
  }

  // Условные заголовки: если ничего не изменилось, источник ответит 304 и не
  // пришлёт тело. Экономит не столько наш трафик, сколько чужой.
  const заголовки: Record<string, string> = {}
  if (прошлое.etag) заголовки['If-None-Match'] = прошлое.etag
  if (прошлое.изменено) заголовки['If-Modified-Since'] = прошлое.изменено

  const res = await safeFetch(url, агент, заголовки)

  if (!res.ok) {
    if (res.status === 304) return { вид: 'не_изменилось', хеш: прошлое.хеш ?? '', как: 'по_ответу_304', статус: 304 }
    if (res.status === 404 || res.status === 410) return { вид: 'не_найдено', статус: res.status }
    if (res.status === 403 || res.status === 401) return { вид: 'запрещено_сервером', статус: res.status }
    if (/abort|timeout/i.test(res.reason)) return { вид: 'таймаут' }
    return { вид: 'недоступно', причина: res.reason, статус: res.status ?? null }
  }

  const текст = извлечь(res.body.toString('utf8'))
  const хеш = хешТекста(текст)

  if (!прошлое.хеш) {
    return { вид: 'впервые', хеш, текст, статус: res.status, финальныйАдрес: res.finalUrl, etag: null, изменено: null }
  }
  if (хеш === прошлое.хеш) {
    return { вид: 'не_изменилось', хеш, как: 'по_хешу', статус: res.status }
  }
  return { вид: 'изменилось', хеш, текст, статус: res.status, финальныйАдрес: res.finalUrl, etag: null, изменено: null }
}

/* ── Одиночный сбой против настоящего исчезновения ─────────────────────── */

/** Сколько подряд неудач подряд считать исчезновением, а не сбоем. */
export const ПОДРЯД_ДЛЯ_ВЫВОДА = 3

export type Вывод =
  | { что: 'источник_жив' }
  | { что: 'источник_исчез'; подряд: number; статус: number }
  | { что: 'источник_закрылся'; подряд: number }
  | { что: 'наблюдение_прервано'; подряд: number; почему: string }
  | { что: 'ждём'; подряд: number; почему: string }

/**
 * Что следует из истории наблюдений.
 *
 * Правило PRD: одиночный 404 не равен удалению. Сайты переезжают, и страница,
 * вернувшая 404 в пятницу, в понедельник стоит на новом адресе. Вывод об
 * исчезновении делается только после нескольких подряд — и всё равно остаётся
 * поводом посмотреть человеку, а не стереть факт.
 *
 * История передаётся от новой к старой.
 */
export function выводИзИстории(история: Исход['вид'][]): Вывод {
  if (!история.length) return { что: 'ждём', подряд: 0, почему: 'наблюдений ещё не было' }
  if (!ПРОБЕЛ.has(история[0])) return { что: 'источник_жив' }

  let подряд = 0
  for (const в of история) { if (ПРОБЕЛ.has(в)) подряд++; else break }

  const вид = история[0]
  if (подряд < ПОДРЯД_ДЛЯ_ВЫВОДА) {
    return {
      что: 'ждём', подряд,
      почему: вид === 'не_найдено'
        ? `404 подряд ${подряд} раз из ${ПОДРЯД_ДЛЯ_ВЫВОДА} — сайты переезжают, одиночный 404 это не удаление`
        : `${подряд} неудач подряд из ${ПОДРЯД_ДЛЯ_ВЫВОДА}`,
    }
  }

  if (вид === 'не_найдено') return { что: 'источник_исчез', подряд, статус: 404 }
  if (вид === 'запрещено_сервером' || вид === 'запрещено_robots') return { что: 'источник_закрылся', подряд }
  return {
    что: 'наблюдение_прервано', подряд,
    почему: 'источник недоступен несколько попыток подряд. Это пробел наблюдения, а НЕ «изменений нет»: '
      + 'факт не подтверждён и не опровергнут',
  }
}
