export type Состояние =
  /** Живой вызов доказал право публикации. Единственное честное «подключено». */
  | 'подключено'
  /** Вызов прошёл, но право публикации им не доказано. */
  | 'частично'
  /** Секрет задан, но вызова не было: рабочий он или нет — неизвестно. */
  | 'не_проверено'
  /** Секрета нет. Подключать нечем. */
  | 'нет_секрета'
  /** Проверка была и не прошла: токен не тот, прав нет, доступ отозван. */
  | 'нет_доступа'
  /** Ручная площадка: подключения не бывает, бывает человек. */
  | 'руками'
  /** Доставка по SSH: проверяется выходом статьи, а не токеном на этом экране. */
  | 'по_ssh'

