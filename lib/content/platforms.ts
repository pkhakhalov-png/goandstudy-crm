/**
 * Действие, доказывающее, что публиковать мы правда можем.
 *
 * Отдельная константа, а не строка в трёх местах: «доступ есть» и «можно
 * публиковать» — разные утверждения, и площадки различаются именно этим. Токен
 * VK читает сообщество любым ключом, а право wall даёт не любой.
 */
export const ПУБЛИКАЦИЯ = 'post_text'

export type КарточкаПодключения = {
  площадка: Площадка
  состояние: Состояние
  /** Одна строка человеческим языком: что именно происходит. */
  строка: string
  /** Чего не хватает, чтобы площадка заработала. Пусто — всё на месте. */
  требуется: string[]
  каналов: number
  активных: number
  /** Какие секреты заданы. Только имена и факт, никогда значения. */
  секретЗадан: Record<string, boolean>
  проверено: string | null
  доказательство: string | null
}

/** Задан ли хоть один из секретов площадки. Пустой список секретов — считаем «да». */
export function естьСекрет(п: Площадка, env: Record<string, string | undefined>): boolean {
  if (!п.секреты.length) return true
  return п.секреты.some((имя) => {
    const v = env[имя]
    return typeof v === 'string' && v.trim().length > 0
  })
}

/**
 * Провалившаяся проверка отличается от успешной не отсутствием записи, а её
 * содержимым: `checked_at` стоит, а подтверждённых действий нет. Иначе неудачу
 * пришлось бы хранить отдельной таблицей либо не хранить вовсе — и тогда экран
 * после неудачной проверки выглядел бы точно так же, как до неё.
 */
export function состояниеПо(
  п: Площадка,
  вход: { секретЕсть: boolean; проверено: string | null; действия: string[] },
): Состояние {
  if (п.доставка === 'manual') return 'руками'
  // Сайт не «не проверен»: проверять токен здесь нечем и незачем — доказательством
  // служит вышедшая статья, а не вызов с этого экрана.
  if (п.доставка === 'ssh') return 'по_ssh'
  if (!вход.секретЕсть) return 'нет_секрета'
  if (!вход.проверено) return 'не_проверено'
  if (вход.действия.includes(ПУБЛИКАЦИЯ)) return 'подключено'
  return вход.действия.length ? 'частично' : 'нет_доступа'
}

export function строкаПо(к: Omit<КарточкаПодключения, 'строка'>): string {
  const п = к.площадка
  const каналы = к.каналов === 0
    ? 'каналов не заведено'
    : `${к.каналов} ${к.каналов === 1 ? 'канал' : 'каналов'}, активных ${к.активных}`

  switch (к.состояние) {
    case 'руками':
      return `${п.почемуРуками ?? 'API на публикацию нет.'} ${каналы}.`
    case 'по_ssh':
      return 'Статьи выкладывает агент на сервере сайта. Доказательство выхода — сама статья: '
        + 'проверка индексации и чтение страницы, а не токен на этом экране.'
    case 'нет_секрета':
      return `Секрет не задан (${п.секреты.join(' или ')}) — отправить пост нечем. ${каналы}.`
    case 'не_проверено':
      return `Секрет задан, живого вызова не было: рабочий он или нет — неизвестно. ${каналы}.`
    case 'нет_доступа':
      return `Проверка не прошла: ${к.доказательство ?? 'причина не записана'}. ${каналы}.`
    case 'частично':
      return `Доступ есть, право публикации не доказано: ${к.доказательство ?? 'след не записан'}. ${каналы}.`
    case 'подключено':
      return `Проверено вызовом${к.проверено ? ` ${датаКоротко(к.проверено)}` : ''}. ${каналы}.`
  }
}

function датаКоротко(iso: string): string {
  const d = new Date(iso)
  return Number.isNaN(d.getTime())
    ? iso
    : d.toLocaleString('ru-RU', { day: 'numeric', month: 'long', hour: '2-digit', minute: '2-digit' })
}

/** Чего не хватает. Для ручной площадки не хватает человека, а не токена. */
export function требуетсяДля(п: Площадка, с: Состояние, каналов: number): string[] {
  // У сайта канала в этом смысле не бывает: он публикуется агентом, и требовать
  // от человека «завести канал» значит требовать несуществующего действия.
  if (с === 'по_ssh') return []
  const out: string[] = []
  if (с === 'нет_секрета') out.push(`Задать ${п.секреты.join(' или ')}`)
  if (с === 'не_проверено') out.push('Нажать «Проверить» — до этого подключением это не считается')
  if (с === 'нет_доступа') out.push('Разобраться с доступом и проверить снова')
  if (с === 'частично') out.push('Доказать публикацию: тестовый пост в канал, который не стыдно удалить')
  if (!каналов) out.push('Завести канал — планировать выпуск некуда, пока его нет')
  return out
}

/**
 * Собрать экран.
 *
 * Два запроса на весь список, а не по два на площадку: строк здесь десяток, и
 * запрос в цикле превратил бы экран в двадцать обращений к базе ради таблицы,
 * которая целиком влезает в память.
 */
export async function подключения(
  content: any,
  env: Record<string, string | undefined> = process.env as any,
): Promise<КарточкаПодключения[]> {
  const { data: каналы, error: e1 } = await content
    .from('channels').select('id, platform, mode, delivery')
  if (e1) throw new Error(`каналы: ${e1.message}`)

  const { data: проверки, error: e2 } = await content
    .from('connector_capabilities').select('platform, verified_actions, checked_at, proof_ref')
  if (e2) throw new Error(`проверки коннекторов: ${e2.message}`)

  return ПЛОЩАДКИ.map((п) => {
    const свои = (каналы ?? []).filter((к: any) => к.platform === п.код)
    // Проверок на площадку может быть несколько — по аккаунтам. Берём самую
    // свежую: экран отвечает на вопрос «доступ есть сейчас», а не «был когда-то».
    const проверка = (проверки ?? [])
      .filter((p: any) => p.platform === п.код)
      .sort((a: any, b: any) => String(b.checked_at ?? '').localeCompare(String(a.checked_at ?? '')))[0] ?? null

    const секретЕсть = естьСекрет(п, env)
    const состояние = состояниеПо(п, {
      секретЕсть,
      проверено: проверка?.checked_at ?? null,
      действия: проверка?.verified_actions ?? [],
    })

    const основа = {
      площадка: п,
      состояние,
      требуется: требуетсяДля(п, состояние, свои.length),
      каналов: свои.length,
      активных: свои.filter((к: any) => к.mode === 'active').length,
      секретЗадан: Object.fromEntries(п.секреты.map((имя) => [имя, Boolean(env[имя]?.trim())])),
      проверено: проверка?.checked_at ?? null,
      доказательство: проверка?.proof_ref ?? null,
    }
    return { ...основа, строка: строкаПо(основа) }
  })
}

/** Сводка наверху экрана. Считает по способу доставки, а не по числу строк. */
export function сводкаПодключений(карточки: КарточкаПодключения[]): string {
  const апи = карточки.filter((к) => к.площадка.доставка !== 'manual')
  const готовы = апи.filter((к) => к.состояние === 'подключено').length
  const руками = карточки.filter((к) => к.состояние === 'руками').length
  const каналов = карточки.reduce((s, к) => s + к.каналов, 0)
  return `${готовы} из ${апи.length} автоматических площадок подключены, `
    + `${руками} выкладываются руками, каналов заведено ${каналов}`
}
