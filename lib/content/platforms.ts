/**
 * Реестр площадок: каким путём подключаемся и что для этого нужно.
 *
 * Установка владельца: руками не публикуем нигде. Значит вопрос к каждой
 * площадке ровно один — есть ли у неё путь, по которому наш код положит туда
 * пост сам. Путей ровно три, и четвёртого не существует:
 *
 *   api  — у площадки есть пригодный интерфейс публикации. Пишем коннектор,
 *          человек один раз заводит приложение и отдаёт токен.
 *   rss  — площадка забирает материал из нашей ленты сама. Мы не публикуем, мы
 *          отдаём; момент выхода решает площадка, и это не одно и то же.
 *   нет  — интерфейса публикации не существует. Не «мы не дописали», а
 *          «дописывать нечего»: писать туда нечем ни нам, ни кому-либо.
 *
 * Чего здесь сознательно нет. Браузерной автоматизации вместо API, парольных
 * сессий и прочих обходов: для площадки это нарушение её правил, для нас —
 * канал, который ломается от любой перерисовки чужой вёрстки и молча перестаёт
 * публиковать. Инвариант 10 плана запрещает это прямым текстом.
 *
 * MCP в этом списке не фигурирует, и это не упущение. MCP — способ модели
 * позвать наш инструмент; за инструментом всё равно стоит либо API площадки,
 * либо браузер. Где API есть, коннектор пишется и без MCP; где API нет, MCP его
 * не создаёт.
 *
 * Три правила, без которых экран начнёт врать.
 *
 *   «Токен задан» и «подключено» — разное. Переменная в окружении означает, что
 *     строка есть, а не что она рабочая и что у неё есть права на наш аккаунт.
 *     Подключением считается только успешный живой вызов с сохранённым следом.
 *   «Коннектора нет» и «токена нет» — разное. Токен добывается за вечер, и он
 *     ничего не меняет, пока писать в площадку нечем.
 *   Секрет в интерфейс не попадает. На экран уходит имя переменной и факт
 *     «задана или нет», никогда значение.
 */

export type Доставка = 'api' | 'ssh' | 'manual'

