/**
 * Ручная выкладка: площадок много, API у них нет.
 *
 * Telegram и VK — исключение, а не правило: у большинства мест, где выходят наши
 * материалы, публикация через API либо не предусмотрена, либо не выдаётся под
 * наши задачи. Писать интеграцию под каждую — работа без конца, и после каждой
 * новой площадки пришлось бы ждать релиз.
 *
 * Поэтому общий путь другой: машина готовит материал целиком — текст под
 * площадку, ссылку с метками, картинку, — человек публикует и возвращает адрес
 * поста. Дальше всё как у автоматических каналов: проверка выхода, метрики,
 * переходы, заявки. Новая площадка при этом добавляется настройкой, а не кодом.
 *
 * Два места, где здесь легко соврать, и как мы этого не делаем.
 *
 *   «Отметил опубликованным» — это слова человека, а не факт. Поэтому после
 *     отметки пост читается по ссылке, и результат чтения записывается отдельно
 *     от самой отметки. Не прочитали — так и пишем; это не «не вышло».
 *   «Ссылка в посте» — не то же самое, что «ссылка кликабельна». Площадка могла
 *     обрезать хвост с метками или подменить ссылку своим переходником. Первое
 *     ломает учёт переходов навсегда, второе — нет, потому что метка доезжает до
 *     нашего сайта вместе с переходом. Поэтому ищем в посте именно метку
 *     публикации, а не адрес.
 */
import { safeFetch } from '../seo/safe-fetch'

/** Метки кампании: по ним переход связывается с тем, что его породило (E5.2). */
export function метки(input: {
  платформа: string
  публикацияId: number
  пакетId?: number | null
}): Record<string, string> {
  return {
    utm_source: input.платформа,
    utm_medium: 'social',
    ...(input.пакетId ? { utm_campaign: String(input.пакетId) } : {}),
    utm_content: String(input.публикацияId),
  }
}

/** Целевая ссылка с метками. Без меток переход не приписать никому. */
export function ссылкаДляПоста(целевой: string, m: Record<string, string>): string {
  try {
    const u = new URL(целевой)
    for (const [k, v] of Object.entries(m)) if (v) u.searchParams.set(k, v)
    return u.toString()
  } catch {
    return целевой
  }
}

/**
 * Текст, готовый к вставке.
 *
 * Ссылку в тексте пересобираем здесь, а не при сборке поста, по простой причине:
 * при сборке публикации ещё нет, а метка `utm_content` — это её номер. Без
 * пересборки переход будет виден как «пришёл с этой площадки», но не от какого
 * поста, и сравнивать посты между собой станет нечем.
 */
export function подготовить(input: {
  текст: string
  платформа: string
  публикацияId: number
  пакетId?: number | null
}): { текст: string; ссылка: string | null } {
  const m = метки(input)
  const найдено = input.текст.match(/https?:\/\/[^\s<>»"]+/)
  if (!найдено) return { текст: input.текст, ссылка: null }

  const было = найдено[0].replace(/[.,;:)]+$/, '')
  const стало = ссылкаДляПоста(было, m)
  return { текст: input.текст.replace(было, стало), ссылка: стало }
}

export type Выход =
  /** Пост прочитан, и в нём стоит метка этой публикации. */
  | { вид: 'виден_с_меткой'; адрес: string }
  /** Пост прочитан, метки в нём нет: переходы приписать нечем. */
  | { вид: 'виден_без_метки'; почему: string }
  /** Страница не прочиталась. Это НЕ «пост не вышел». */
  | { вид: 'не_проверить'; почему: string }

/**
 * Проверка выхода для ручной площадки.
 *
 * Ищем в опубликованной странице метку `utm_content` с номером публикации.
 * Именно метку, а не адрес сайта: площадка может завернуть ссылку в свой
 * переходник — тогда адреса в HTML не будет, а метка останется и доедет до нас
 * вместе с переходом. Для учёта важна она.
 */
export async function проверитьВыход(адрес: string, публикацияId: number): Promise<Выход> {
  const res = await safeFetch(адрес, process.env.SEO_CRAWL_USER_AGENT || 'goandstudy-seo-bot')
  if (!res.ok) {
    return {
      вид: 'не_проверить',
      почему: res.status === 403 || res.status === 401
        ? `площадка не пустила нас на страницу поста (${res.status}) — это не «поста нет»`
        : `страница не прочиталась: ${res.reason}`,
    }
  }

  const html = res.body.toString('utf8')
  const метка = `utm_content=${публикацияId}`
  // Площадки экранируют амперсанд и режут кавычки по-разному, поэтому ищем
  // подстроку, а не разбираем ссылки: разбор здесь дал бы больше промахов.
  if (html.includes(метка) || html.includes(encodeURIComponent(метка))) {
    return { вид: 'виден_с_меткой', адрес: res.finalUrl }
  }
  return {
    вид: 'виден_без_метки',
    почему: 'страница поста прочиталась, но метки этой публикации в ней нет — '
      + 'скорее всего, ссылку вставили без хвоста с метками. Переходы приписать нечем.',
  }
}

/** Что записать в публикацию по итогу проверки. */
export function следствиеВыхода(в: Выход): {
  link_clickable: boolean | null
  last_verified_at: string | null
  пояснение: string
} {
  const сейчас = new Date().toISOString()
  if (в.вид === 'виден_с_меткой') {
    return { link_clickable: true, last_verified_at: сейчас, пояснение: 'пост прочитан, метка на месте — переходы считаются' }
  }
  if (в.вид === 'виден_без_метки') {
    return { link_clickable: false, last_verified_at: сейчас, пояснение: в.почему }
  }
  // Не прочитали — не трогаем ни кликабельность, ни отметку проверки: пустое
  // значение означает «не знаем», и это честнее, чем записать «нет».
  return { link_clickable: null, last_verified_at: null, пояснение: в.почему }
}
