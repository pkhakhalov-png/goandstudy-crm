/**
 * Кого реально дожимать.
 *
 * Отчёт отвечает на один вопрос: с кем из тех, кто уже пришёл, разговор
 * оборвался на полпути — и что именно надо сказать, чтобы его продолжить.
 *
 * Почему это не то же самое, что «застрявшие». Список застрявших отвечает на
 * вопрос «где мы не работаем» и меряет дисциплину. Здесь вопрос другой: «где
 * деньги лежат ближе всего». Сделка может быть тронута вчера и всё равно
 * попасть сюда, если клиент сказал «дорого», а ему не ответили.
 *
 * Как считается готовность. Не баллом «из воздуха», а из четырёх наблюдаемых
 * вещей, каждая из которых берётся из разбора разговора и проверяется цитатой:
 *
 *   насколько человек тёплый     — он либо хочет, либо нет;
 *   мяч на нашей стороне         — следующий шаг не зафиксирован, то есть
 *                                  разговор оборвался на нас, а не на клиенте;
 *   известно, что мешает         — прозвучало возражение, и его не отработали.
 *                                  Это лучший случай: мы знаем, что сказать;
 *   назван бюджет                — человек проговорил деньги, значит считает
 *                                  покупку возможной.
 *
 * Свежесть не добавляет баллов, а отнимает: разговор недельной давности живее
 * трёхмесячного, и это единственное, что здесь про время.
 */

export type Analysis = {
  deal_id: string
  client_type: string | null
  next_step: boolean | null
  summary: string | null
  created_at: string
  payload: any
}

export type PressureItem = {
  dealId: string
  готовность: number
  тип: string
  резюме: string
  /** Что мешает — неотработанное возражение с цитатой клиента. */
  преграда: { что: string; цитата: string } | null
  /** Что делать дальше, одной строкой. */
  действие: string
  запрос: { страна: string; уровень: string; бюджет: string; сроки: string }
  следующийШагЕсть: boolean
  рисков: number
  днейСРазбора: number
  причины: string[]
}

const ВЕС_ТИПА: Record<string, number> = {
  'горячий': 40,
  'тёплый': 25,
  'холодный': 8,
  'нецелевой': 0,
}

export function оценить(a: Analysis, сейчас = Date.now()): PressureItem | null {
  const p = a.payload ?? {}
  const тип = String(a.client_type ?? p['тип_клиента'] ?? 'холодный')

  // Нецелевой — не «низкий приоритет», а не наш клиент. Держать его в списке
  // дожима значит тратить время продажника на заведомо пустое.
  if (тип === 'нецелевой') return null

  const причины: string[] = []
  let балл = ВЕС_ТИПА[тип] ?? 8
  причины.push(`клиент ${тип}`)

  const шаг = p['следующий_шаг'] ?? {}
  const шагЕсть = Boolean(a.next_step ?? шаг['есть'])
  if (!шагЕсть) {
    балл += 25
    причины.push('следующий шаг не зафиксирован — мяч у нас')
  }

  const возражения: any[] = Array.isArray(p['возражения']) ? p['возражения'] : []
  const неОтработано = возражения.filter(в => в && в['отработано'] === false)
  if (неОтработано.length > 0) {
    // Чем больше неотработанных, тем понятнее, что говорить, но тем и хуже
    // шёл разговор. Первое перевешивает: возражение — это заявленный интерес.
    балл += 20 + Math.min(неОтработано.length - 1, 2) * 5
    причины.push(`возражение без ответа: ${неОтработано[0]['что']}`)
  }

  const бюджет = String(p['запрос']?.['бюджет'] ?? 'не выяснено')
  const бюджетНазван = бюджет !== 'не выяснено' && бюджет.trim() !== ''
  if (бюджетНазван) {
    балл += 10
    причины.push('бюджет назван')
  }

  const дней = Math.floor((сейчас - new Date(a.created_at).getTime()) / 86400000)
  // Штраф за возраст: разговор месячной давности требует не дожима, а
  // возврата — это другая работа и другой разговор.
  const штраф = дней <= 7 ? 0 : дней <= 14 ? 5 : дней <= 30 ? 12 : 22
  балл -= штраф

  const риски: any[] = Array.isArray(p['риски']) ? p['риски'] : []

  return {
    dealId: a.deal_id,
    готовность: Math.max(0, Math.round(балл)),
    тип,
    резюме: String(a.summary ?? p['резюме'] ?? ''),
    преграда: неОтработано[0]
      ? { что: String(неОтработано[0]['что']), цитата: String(неОтработано[0]['цитата'] ?? '') }
      : null,
    действие: действие(p, шагЕсть, неОтработано[0]),
    запрос: {
      страна: String(p['запрос']?.['страна'] ?? '—'),
      уровень: String(p['запрос']?.['уровень'] ?? '—'),
      бюджет,
      сроки: String(p['запрос']?.['сроки'] ?? '—'),
    },
    следующийШагЕсть: шагЕсть,
    рисков: риски.length,
    днейСРазбора: дней,
    причины,
  }
}

/**
 * Что делать — одной строкой, в порядке убывания пользы.
 *
 * Сначала закрыть то, что человек прямо назвал помехой; если помехи нет —
 * спросить недостающее; если и это выяснено — просто назначить встречу.
 * Никаких «продолжить работу с клиентом»: подсказка, которую нельзя
 * выполнить сегодня, бесполезна.
 */
function действие(p: any, шагЕсть: boolean, возражение: any): string {
  if (возражение) {
    return `Ответить на возражение «${возражение['что']}» и сразу предложить время созвона`
  }
  const неВыяснено: string[] = Array.isArray(p['не_выяснено']) ? p['не_выяснено'] : []
  if (неВыяснено.length > 0) {
    return `Спросить: ${неВыяснено[0]}`
  }
  if (!шагЕсть) {
    return 'Назначить конкретное время следующего разговора'
  }
  return 'Подтвердить договорённость и выполнить её'
}

/** Оставить по одному — самому свежему — разбору на сделку. */
export function последниеРазборы(всё: Analysis[]): Analysis[] {
  const карта = new Map<string, Analysis>()
  for (const a of всё) {
    const есть = карта.get(a.deal_id)
    if (!есть || new Date(a.created_at) > new Date(есть.created_at)) карта.set(a.deal_id, a)
  }
  return [...карта.values()]
}
