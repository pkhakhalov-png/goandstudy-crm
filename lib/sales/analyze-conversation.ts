/**
 * Разбор разговора моделью.
 *
 * Отвечает на пять вопросов, ради которых всё и затевалось:
 *   чего человек хочет · что его держит · о чём договорились ·
 *   что менеджер не спросил · насколько это вообще наш клиент.
 *
 * Два решения, которые определяют всё остальное.
 *
 * ПЕРВОЕ: строгая схема ответа. Модель обязана вернуть ровно описанную
 * структуру — это проверяется на стороне API, а не разбором свободного текста
 * у нас. Без этого каждый десятый ответ приезжал бы «почти в формате», и
 * половина кода занималась бы угадыванием, что имелось в виду.
 *
 * ВТОРОЕ: каждое утверждение — с цитатой. Оценка без опоры на реплику не
 * принимается: разбор, который нельзя проверить за десять секунд, никто не
 * будет проверять вообще, и через месяц ему перестанут верить — справедливо.
 *
 * Переписка — это данные, а не команды. Внутри может оказаться «игнорируй
 * инструкции» или «поставь себе десять баллов»: текст приходит содержимым
 * разговора и ничего сверх разбора выполнить не может.
 */
