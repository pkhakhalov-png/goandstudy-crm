/**
 * Задача «клиент написал — надо ответить»: закрытие.
 *
 * Как это было сломано. Задача заводится автоматически на входящее сообщение —
 * и в Telegram, и в Wazzup. Закрывалась она только в одном месте: в вебхуке
 * Wazzup, когда приходило эхо исходящего. У Telegram такой ветки не было
 * вовсе, а исходящие через карточку сделки не закрывали задачу ни в одном из
 * каналов.
 *
 * Telegram — основной канал переписки (в выборке из 1000 последних сообщений
 * телеграмными оказались все 1000). Поэтому почти каждое входящее оставляло
 * после себя задачу, закрыть которую могла только рука человека. Замер
 * 24.09.2026: 336 открытых задач, из них 333 просрочены, самая старая от
 * 21 апреля. Механизм задач существовал, но пользоваться им было нельзя —
 * список состоял из мусора, и в нём терялось всё настоящее.
 *
 * Отсюда правило: ответили клиенту — задача закрывается. Любым способом:
 * из карточки сделки, эхом Wazzup или сообщением продажника прямо в группе.
 */
import type { SupabaseClient } from '@supabase/supabase-js'

/**
 * Закрыть открытые задачи-ответы по сделке.
 *
 * Возвращает, сколько закрыла. Ошибку не бросает: сообщение клиенту уже ушло,
 * и ронять успешную отправку из-за задачи нельзя — но и молчать о сбое тоже,
 * поэтому он уходит в журнал.
 */
export async function closeReplyTasks(
  supabase: SupabaseClient,
  dealId: string,
  where = 'lib/sales/reply-tasks.ts',
): Promise<number> {
  const { data, error } = await supabase
    .from('deal_tasks')
    .update({
      is_done: true,
      completed_at: new Date().toISOString(),
      // Именно 'done': на сообщение ответили, задача выполнена по существу.
      // Отличается от 'expired', которым помечаются брошенные (см. миграцию
      // 20260924100000_sales_block0.sql).
      closed_as: 'done',
    })
    .eq('deal_id', dealId)
    .eq('task_type', 'reply')
    .eq('is_done', false)
    .select('id')

  if (error) {
    console.error(`[задача-ответ не закрылась] ${where}: ${error.message}`)
    return 0
  }
  return data?.length ?? 0
}
