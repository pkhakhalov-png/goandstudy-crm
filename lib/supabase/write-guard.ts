/**
 * Проверка результата записи в базу.
 *
 * Supabase не бросает исключение при неудаче: он возвращает `{ error }`. Если
 * его не прочитать, код спокойно идёт дальше и отчитывается об успехе. Это
 * худший вид ошибки — её никто не видит: ни пользователь, ни разработчик.
 *
 * ПОЧЕМУ НЕ ПРОСТО `.throwOnError()`. Записи бывают двух сортов, и обращаться
 * с ними одинаково нельзя. Смена этапа сделки должна падать громко: если она не
 * прошла, дальше делать нечего. А запись в журнал действий — нет: сделка уже
 * перемещена, и ронять из-за журнала целиком удавшуюся операцию значит
 * показать человеку ошибку там, где всё получилось.
 *
 * Поэтому здесь два инструмента:
 *   · `.throwOnError()` (свой, из supabase-js) — там, где продолжать нельзя.
 *     Так сделано во всём конвейере статей.
 *   · `warnOnError` — там, где продолжать можно, но молчать нельзя. Ошибка
 *     попадает в журнал сервера, где её видно в логах Vercel.
 *
 * Общее у них одно: результат записи больше нигде не остаётся непрочитанным.
 */

export type WriteResult = { error: unknown | null }

/**
 * Прочитать результат записи и сообщить о неудаче, не прерывая работу.
 *
 *   await supabase.from('deal_activities').insert(row).then(warnOnError('журнал действий'))
 *
 * @param what что именно писали — это попадёт в сообщение, поэтому пишите так,
 *             чтобы по логу было понятно место, а не только таблица.
 */
export function warnOnError<T extends WriteResult>(what: string): (r: T) => T {
  return (r: T): T => {
    if (r?.error) {
      const message = (r.error as any)?.message ?? String(r.error)
      console.error(`[запись не прошла] ${what}: ${message}`)
    }
    return r
  }
}
