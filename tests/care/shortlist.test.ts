/**
 * Подбор программ и стратегия: что пропускаем, а что выбрасываем.
 *
 * Модель здесь не вызывается — подбор ищет в вебе и стоит около доллара за
 * прогон. Проверяются правила, по которым найденное принимается: они не
 * зависят от того, что поиск выдал сегодня.
 *
 * Главная проверка подбора — ссылка. Она здесь то же, чем цитата была при
 * разборе переписки: единственное, что отличает найденное от придуманного.
 * Главная проверка стратегии — выдуманная дата: клиент строит по ней планы,
 * и ошибка стоит года.
 */
import { describe, it, expect } from 'vitest'
import { проверитьПрограмму, type НайденнаяПрограмма } from '@/lib/care/ai/search'
import { проверитьСтратегию, type ДанныеСтратегии } from '@/lib/care/ai/strategy'
import { кодыСтран } from '@/lib/care/jobs/shortlist'
import { уровеньПоНазванию } from '@/lib/care/programs'

const программа = (п: Partial<НайденнаяПрограмма> = {}): НайденнаяПрограмма => ({
  вуз: 'Masaryk University',
  город: 'Брно',
  страна: 'Чехия',
  программа: 'Biology and Biochemistry',
  уровень: 'бакалавриат',
  язык: 'английский',
  стоимость_в_год: 4500,
  валюта: 'EUR',
  ссылка: 'https://www.muni.cz/en/bachelors-and-masters-study-programmes/27005-biology',
  почему_подходит: 'Продолжает два года биологии, преподавание на английском.',
  что_проверить: ['сроки подачи'],
  ...п,
})

describe('программа принимается, только если её можно открыть', () => {
  it('ссылка на сайт вуза проходит', () => {
    expect(проверитьПрограмму(программа()).ok).toBe(true)
  })

  it('без ссылки не проходит', () => {
    const итог = проверитьПрограмму(программа({ ссылка: '' }))
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('ссылки')
  })

  it('ссылка на агрегатор не проходит', () => {
    // Куратору нужна страница программы, а не ещё один список, который надо
    // разбирать самому.
    for (const адрес of [
      'https://www.mastersportal.com/studies/12345/biology.html',
      'https://www.bachelorsportal.com/studies/999/x.html',
      'https://www.topuniversities.com/universities/masaryk-university',
    ]) {
      const итог = проверитьПрограмму(программа({ ссылка: адрес }))
      expect(итог.ok).toBe(false)
      if (!итог.ok) expect(итог.почему).toContain('посредника')
    }
  })

  it('ссылка на поисковую выдачу не проходит', () => {
    const итог = проверитьПрограмму(программа({ ссылка: 'https://www.google.com/search?q=biology+brno' }))
    expect(итог.ok).toBe(false)
  })

  it('сумма без валюты не проходит', () => {
    const итог = проверитьПрограмму(программа({ валюта: null }))
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('валют')
  })

  it('неизвестная стоимость — это нормально', () => {
    // Честное «не нашли» лучше выдуманного числа: по стоимости клиент считает
    // бюджет на три года вперёд.
    expect(проверитьПрограмму(программа({ стоимость_в_год: null, валюта: null })).ok).toBe(true)
  })
})

const данные: ДанныеСтратегии = {
  клиент: 'Даниил Герман',
  факты: [{ поле: 'Год поступления', значение: 'осень 2027', намерение: false }],
  задачи: [{ название: 'Перевод диплома', срок: '2027-03-01', ждём: 'клиента', статус: 'ждём' }],
  подборка: [],
  изПереписки: [],
}

describe('стратегия не выдумывает сроков', () => {
  const годный =
    'Даниил, цель — поступление осенью 2027 года на биологическое направление в Европе. ' +
    'Сейчас подтверждены направление и год набора, английский на уровне B2. ' +
    'Не хватает перевода диплома, он нужен к марту 2027 года. ' +
    'В ближайший месяц: собрать документы об образовании и уточнить требования выбранных вузов, ' +
    'после чего вернуться к подборке программ и сузить её до трёх вариантов.'

  it('текст по данным дела проходит', () => {
    expect(проверитьСтратегию(годный, данные).ok).toBe(true)
  })

  it('выдуманный год не проходит', () => {
    const итог = проверитьСтратегию(годный.replace('осенью 2027', 'осенью 2026'), данные)
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('2026')
  })

  it('разметка не проходит', () => {
    const итог = проверитьСтратегию(`## Стратегия\n\n${годный}`, данные)
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('разметка')
  })

  it('слишком короткий текст не проходит', () => {
    expect(проверитьСтратегию('Поступаем в 2027.', данные).ok).toBe(false)
  })
})

describe('страна словами превращается в коды', () => {
  it('названия стран опознаются', () => {
    expect(кодыСтран('Германия, Италия').sort()).toEqual(['de', 'it'])
    expect(кодыСтран('США')).toEqual(['us'])
  })

  it('«Европа» без уточнения — это те страны, куда возят чаще всего', () => {
    // Пустой список означал бы «искать везде», а это не подбор, а рулетка.
    const коды = кодыСтран('Европа')
    expect(коды.length).toBeGreaterThan(3)
    expect(коды).toContain('de')
  })

  it('непонятное не превращается в случайные страны', () => {
    expect(кодыСтран('пока не решили')).toEqual([])
  })
})

describe('уровень по названию программы', () => {
  it('степень в названии опознаётся', () => {
    expect(уровеньПоНазванию('Bachelor of Science - Biology')).toBe('бакалавриат')
    expect(уровеньПоНазванию('MSc Molecular Biology')).toBe('магистратура')
    expect(уровеньПоНазванию('Магистратура по биохимии')).toBe('магистратура')
  })

  it('без степени в названии — честное «неизвестно»', () => {
    // В базе поле уровня пустое почти везде, поэтому догадка по названию — это
    // догадка, и она должна уметь признаваться.
    expect(уровеньПоНазванию('Инженерия')).toBe('неизвестно')
  })
})
