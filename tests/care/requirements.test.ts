/**
 * Проверка требований на сайте вуза: что считается проверенным.
 *
 * Эти записи закрывают строки «что проверить» в подборке — то есть превращают
 * «не знаем» в «знаем». Поэтому планка выше, чем у подбора: мало ссылки,
 * нужна дословная цитата со страницы.
 *
 * Модель не вызывается — чтение шести вопросов по странице стоит денег и
 * каждый раз даёт чуть разный ответ. Проверяются правила приёмки.
 */
import { describe, it, expect } from 'vitest'
import {
  проверитьТребование,
  ВИДЫ_ТРЕБОВАНИЙ,
  ПОДПИСЬ_ТРЕБОВАНИЯ,
  type НайденноеТребование,
} from '@/lib/care/ai/requirements'

const требование = (п: Partial<НайденноеТребование> = {}): НайденноеТребование => ({
  requirement_type: 'tuition_per_year',
  value: '2000 EUR в год',
  excerpt: 'Tuition fee for international students is 2000 EUR per academic year.',
  source_url: 'https://www.muni.cz/en/programmes/27005/fees',
  found: true,
  ...п,
})

describe('требование принимается, только если его можно перепроверить', () => {
  it('значение с цитатой и адресом проходит', () => {
    expect(проверитьТребование(требование()).ok).toBe(true)
  })

  it('«не нашлось» — полноценный ответ, цитата ему не нужна', () => {
    // Это не пустота, а результат: куратор не пойдёт искать второй раз.
    const итог = проверитьТребование(
      требование({ found: false, value: '', excerpt: '', source_url: '' })
    )
    expect(итог.ok).toBe(true)
  })

  it('найденное без цитаты не проходит', () => {
    const итог = проверитьТребование(требование({ excerpt: '' }))
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('цитата')
  })

  it('цитата в три слова не проходит', () => {
    // По такой совпадёт что угодно, а проверять потом куратору.
    const итог = проверитьТребование(требование({ excerpt: '2000 EUR' }))
    expect(итог.ok).toBe(false)
  })

  it('найденное без адреса источника не проходит', () => {
    const итог = проверитьТребование(требование({ source_url: '' }))
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('адрес')
  })

  it('адрес не на http не проходит', () => {
    expect(проверитьТребование(требование({ source_url: 'javascript:alert(1)' })).ok).toBe(false)
  })

  it('вид не из словаря не проходит', () => {
    const итог = проверитьТребование(требование({ requirement_type: 'стипендии' as never }))
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('словар')
  })

  it('пустое значение при found = true не проходит', () => {
    expect(проверитьТребование(требование({ value: '  ' })).ok).toBe(false)
  })
})

describe('словарь требований', () => {
  it('у каждого вида есть человеческая подпись', () => {
    // Вид без подписи попадёт на экран кодом вроде language_of_instruction —
    // куратор ведёт клиентов, а не читает схему базы.
    for (const вид of ВИДЫ_ТРЕБОВАНИЙ) {
      expect(ПОДПИСЬ_ТРЕБОВАНИЯ[вид], вид).toBeTruthy()
      expect(ПОДПИСЬ_ТРЕБОВАНИЯ[вид]).not.toMatch(/[a-z]_[a-z]/)
    }
  })

  it('спрашиваем ровно то, чего не хватало в подборке', () => {
    // Список закрыт намеренно: открытый набор вопросов даёт разные ответы на
    // разных страницах, и сложить их потом невозможно.
    expect([...ВИДЫ_ТРЕБОВАНИЙ].sort()).toEqual([
      'application_deadline',
      'documents',
      'entrance_exam',
      'language_certificate',
      'language_of_instruction',
      'tuition_per_year',
    ])
  })
})
