/**
 * Сверка требований с фактами клиента.
 *
 * Это арифметика, а не суждение, поэтому проверяется полностью и без модели.
 * Каждый случай здесь встречался на настоящих страницах вузов — в том числе
 * тот, ради которого всё это и написано: программа по молекулярной биологии,
 * идеально подходящая по направлению, читается на чешском.
 */
import { describe, it, expect } from 'vitest'
import {
  сверить,
  сверитьВсё,
  суммаИВалюта,
  уровеньЯзыка,
  языкОбучения,
  срокПодачи,
  type ФактыКлиента,
} from '@/lib/care/fit'

const даниил: ФактыКлиента = {
  бюджетВГод: 6000,
  валютаБюджета: 'EUR',
  английский: 'B2 – готовится к IELTS',
  немецкий: null,
  языки: {},
}

const сегодня = new Date('2026-10-01')

describe('язык обучения', () => {
  it('английский при B2 у клиента — подходит', () => {
    const с = сверить({ вид: 'language_of_instruction', значение: 'English' }, даниил, сегодня)
    expect(с?.вывод).toBe('подходит')
  })

  it('чешский — не подходит, и это главная находка проверки', () => {
    // Настоящий случай: Masaryk «Experimental and Molecular Biology». По
    // названию и направлению идеальна, читается на чешском. Без сверки дошла
    // бы до клиента в подборке.
    const с = сверить({ вид: 'language_of_instruction', значение: 'Чешский' }, даниил, сегодня)
    expect(с?.вывод).toBe('не подходит')
    expect(с?.объяснение).toContain('не на английском')
  })

  it('немецкий без подтверждённого немецкого — не подходит', () => {
    const с = сверить({ вид: 'language_of_instruction', значение: 'German (Deutsch)' }, даниил, сегодня)
    expect(с?.вывод).toBe('не подходит')
  })

  it('английский при неизвестном уровне — неясно, а не «подходит»', () => {
    const с = сверить(
      { вид: 'language_of_instruction', значение: 'English' },
      { ...даниил, английский: null },
      сегодня
    )
    expect(с?.вывод).toBe('неясно')
  })

  it('английский при A2 — не подходит', () => {
    const с = сверить(
      { вид: 'language_of_instruction', значение: 'English' },
      { ...даниил, английский: 'A2 – в процессе' },
      сегодня
    )
    expect(с?.вывод).toBe('не подходит')
  })
})

describe('стоимость', () => {
  it('в бюджет — подходит', () => {
    const с = сверить({ вид: 'tuition_per_year', значение: '€3,000 per academic year' }, даниил, сегодня)
    expect(с?.вывод).toBe('подходит')
  })

  it('дороже бюджета — не подходит, с числами в объяснении', () => {
    const с = сверить({ вид: 'tuition_per_year', значение: '7000 EUR в год' }, даниил, сегодня)
    expect(с?.вывод).toBe('не подходит')
    expect(с?.объяснение).toContain('7000')
    expect(с?.объяснение).toContain('6000')
  })

  it('другая валюта — неясно, курс не выдумываем', () => {
    // Пересчёт по неизвестному курсу врёт на десятки процентов, а выглядит
    // как точный ответ.
    const с = сверить({ вид: 'tuition_per_year', значение: '45000 CZK' }, даниил, сегодня)
    expect(с?.вывод).toBe('неясно')
    expect(с?.объяснение).toContain('CZK')
  })

  it('без подтверждённого бюджета — неясно', () => {
    const с = сверить(
      { вид: 'tuition_per_year', значение: '€3,000' },
      { ...даниил, бюджетВГод: null },
      сегодня
    )
    expect(с?.вывод).toBe('неясно')
  })
})

describe('языковой сертификат', () => {
  it('нужен B2, у клиента B2 — подходит', () => {
    const с = сверить({ вид: 'language_certificate', значение: 'B2 (or higher) English' }, даниил, сегодня)
    expect(с?.вывод).toBe('подходит')
  })

  it('нужен C1, у клиента B2 — не подходит', () => {
    const с = сверить({ вид: 'language_certificate', значение: 'C1 English required' }, даниил, сегодня)
    expect(с?.вывод).toBe('не подходит')
  })

  it('уровень не назван — не сверяем вовсе', () => {
    // «Документ об уровне английского, конкретный уровень не требуется» —
    // настоящая формулировка Masaryk. Сверять тут нечего, и выдумывать вывод
    // хуже, чем промолчать.
    const с = сверить(
      { вид: 'language_certificate', значение: 'Документ об уровне английского; уровень не требуется' },
      даниил,
      сегодня
    )
    expect(с).toBeNull()
  })
})

describe('срок подачи', () => {
  it('будущая дата — подходит, с остатком дней', () => {
    const с = сверить({ вид: 'application_deadline', значение: 'до полуночи 28/2/2027' }, даниил, сегодня)
    expect(с?.вывод).toBe('подходит')
    expect(с?.объяснение).toContain('осталось')
  })

  it('прошедшая дата — неясно, а не «не подходит»', () => {
    // Настоящий случай Болоньи: на странице сроки прошлого набора, потому что
    // новых вуз ещё не опубликовал. Это не «нам не подходит».
    const с = сверить({ вид: 'application_deadline', значение: 'до 05/05/2025 13:00' }, даниил, сегодня)
    expect(с?.вывод).toBe('неясно')
    expect(с?.объяснение).toContain('ещё не опубликовал')
  })

  it('дата словами разбирается', () => {
    const с = сверить({ вид: 'application_deadline', значение: 'until midnight 28 February 2027' }, даниил, сегодня)
    expect(с?.вывод).toBe('подходит')
  })
})

describe('что не сверяется вовсе', () => {
  it('документы и испытания остаются сведениями', () => {
    // По ним решает человек. Код, притворяющийся, что умеет это решить,
    // хуже молчания.
    expect(сверить({ вид: 'documents', значение: 'Мотивационное письмо' }, даниил, сегодня)).toBeNull()
    expect(сверить({ вид: 'entrance_exam', значение: 'Онлайн-тест' }, даниил, сегодня)).toBeNull()
  })
})

describe('разбор строк со страниц вузов', () => {
  it('суммы в разных записях читаются одинаково', () => {
    for (const текст of ['€3,000 per academic year', '3 000 EUR в год', '3.000 EUR', '3000 EUR']) {
      expect(суммаИВалюта(текст).сумма, текст).toBe(3000)
    }
  })

  it('уровень языка выдёргивается из свободного текста', () => {
    expect(уровеньЯзыка('B2 – готовится к IELTS')).toBe('b2')
    expect(уровеньЯзыка('сертификата пока нет, ближе к B2')).toBe('b2')
    expect(уровеньЯзыка('в процессе')).toBeNull()
  })

  it('язык обучения опознаётся на обоих языках', () => {
    expect(языкОбучения('English')).toBe('английский')
    expect(языкОбучения('Чешский')).toBe('другой')
    expect(языкОбучения('Deutsch')).toBe('немецкий')
    expect(языкОбучения('по договорённости')).toBeNull()
  })

  it('дата разбирается в обоих видах, а неразбираемая даёт null', () => {
    expect(срокПодачи('28/2/2026')?.getFullYear()).toBe(2026)
    expect(срокПодачи('28 February 2026')?.getMonth()).toBe(1)
    expect(срокПодачи('ближе к весне')).toBeNull()
  })
})

describe('сверка всей программы', () => {
  it('несверяемое не попадает в итог', () => {
    const выводы = сверитьВсё(
      [
        { вид: 'language_of_instruction', значение: 'English' },
        { вид: 'documents', значение: 'Мотивационное письмо' },
        { вид: 'tuition_per_year', значение: '€3,000' },
      ],
      даниил,
      сегодня
    )
    expect(выводы).toHaveLength(2)
    expect(выводы.every((с) => с.вывод === 'подходит')).toBe(true)
  })
})
