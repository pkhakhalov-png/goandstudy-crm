/**
 * Что контур потратил на модель — картина для экрана.
 *
 * ЗАЧЕМ. Первый вопрос к системе, которая зовёт модель, — «сколько это стоит».
 * Ответа в кабинете не было: расход лежит в таблице, потолки в другой, и
 * посмотреть мог только тот, у кого терминал и ключ.
 *
 * ЧТО ЗАЩИЩАЕМ. Три вещи, каждая из которых молча врала бы:
 *
 *   — расход проверок не должен складываться с рабочим. Он настоящий и
 *     показывается, но отдельно: один прогон уже съедал дневной потолок
 *     подбора, и смешанная сумма скрыла бы причину;
 *   — вид, по которому сегодня не тратили, обязан быть виден. «Нет строки»
 *     читается как «такого вида нет», а не как «сегодня не звали»;
 *   — обрезанная выборка должна называть себя обрезанной. Молчаливо занижённый
 *     итог хуже отсутствующего: по нему принимают решение.
 */
import { describe, it, expect, afterEach } from 'vitest'
import { базаCare } from '@/lib/care/db'
import { картинаРасхода } from '@/lib/care/spend'

const ПОМЕТКА = 'ТЕСТ картины расхода'
const свои: string[] = []

async function расход(ч: { вид: string; сумма: number; проверка?: boolean; дней?: number }) {
  const { data, error } = await базаCare()
    .from('ai_spend')
    .insert({
      kind: ч.вид,
      model: 'тест',
      tokens_in: 1,
      tokens_out: 1,
      usd: ч.сумма,
      is_test: ч.проверка === true,
      note: ПОМЕТКА,
      created_at: new Date(Date.now() - (ч.дней ?? 0) * 86_400_000).toISOString(),
    })
    .select('id')
    .single()
  if (error) throw new Error(error.message)
  свои.push(data!.id as string)
}

afterEach(async () => {
  for (const id of свои.splice(0)) await базаCare().from('ai_spend').delete().eq('id', id)
})

describe('картина расхода', () => {
  it('рабочий расход попадает в свой вид', async () => {
    const до = (await картинаРасхода()).виды.find((в) => в.вид === 'research')!.сегодня
    await расход({ вид: 'research', сумма: 1.25 })

    const после = (await картинаРасхода()).виды.find((в) => в.вид === 'research')!
    expect(после.сегодня).toBeCloseTo(до + 1.25, 2)
  })

  it('расход проверок в рабочий счёт не попадает', async () => {
    // Иначе повторяется то, ради чего счета разделили: прогон съедает потолок
    // подбора, а по экрану этого не понять.
    const до = await картинаРасхода()
    const былоРабочих = до.виды.find((в) => в.вид === 'research')!.сегодня
    const былоПроверок = до.проверки.сегодня

    await расход({ вид: 'research', сумма: 2.5, проверка: true })

    const после = await картинаРасхода()
    expect(после.виды.find((в) => в.вид === 'research')!.сегодня).toBeCloseTo(былоРабочих, 2)
    expect(после.проверки.сегодня).toBeCloseTo(былоПроверок + 2.5, 2)
  })

  it('вид без расхода сегодня всё равно виден', async () => {
    // «Нет строки» читается как «такого вида нет», а не как «сегодня не звали».
    const к = await картинаРасхода()
    for (const вид of ['outbound', 'extraction', 'research', 'review']) {
      expect(к.виды.find((в) => в.вид === вид), `вида «${вид}» нет на экране`).toBeTruthy()
    }
  })

  it('вид проверок среди рабочих не показывается', async () => {
    // У него своя строка и свой смысл; в ряду рабочих он читался бы как ещё
    // один вид работы с клиентами.
    const к = await картинаРасхода()
    expect(к.виды.find((в) => в.вид === 'tests')).toBeUndefined()
  })

  it('доля считается от потолка и не превышает единицу на экране', async () => {
    const к = await картинаРасхода()
    for (const в of к.виды) {
      expect(в.доля).toBeGreaterThanOrEqual(0)
      // Сама доля может быть больше единицы — потолок бывает перебран; экран
      // ограничивает ширину полосы, а число остаётся правдой.
      expect(Number.isFinite(в.доля)).toBe(true)
    }
  })

  it('вчерашний расход в «сегодня» не входит, а в неделю входит', async () => {
    const до = await картинаРасхода()
    const былоСегодня = до.виды.find((в) => в.вид === 'review')!.сегодня
    const былоЗаНеделю = до.виды.find((в) => в.вид === 'review')!.неделя

    await расход({ вид: 'review', сумма: 0.75, дней: 2 })

    const после = (await картинаРасхода()).виды.find((в) => в.вид === 'review')!
    expect(после.сегодня).toBeCloseTo(былоСегодня, 2)
    expect(после.неделя).toBeCloseTo(былоЗаНеделю + 0.75, 2)
  })

  it('крупный вызов попадает в список самых дорогих с пометкой', async () => {
    // «Девять долларов за сутки» не говорит, что делать; «подбор по трём
    // делам — семь долларов» говорит.
    await расход({ вид: 'research', сумма: 99.5 })

    const к = await картинаРасхода()
    expect(к.крупные[0].сумма).toBeCloseTo(99.5, 2)
    expect(к.крупные[0].пометка).toBe(ПОМЕТКА)
  })

  it('по дням расход разложен и проверки в нём отдельно', async () => {
    await расход({ вид: 'outbound', сумма: 0.4 })
    await расход({ вид: 'outbound', сумма: 0.6, проверка: true })

    const сегодня = new Date().toISOString().slice(0, 10)
    const день = (await картинаРасхода()).поДням.find((д) => д.день === сегодня)

    expect(день).toBeTruthy()
    expect(день!.сумма).toBeGreaterThanOrEqual(0.4)
    expect(день!.проверки).toBeGreaterThanOrEqual(0.6)
  })
})
