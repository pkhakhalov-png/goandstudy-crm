/**
 * Проверки, которые без настоящего вызова модели ничего не значат.
 *
 * ЗАЧЕМ. Потолок прогона может быть исчерпан — например, предыдущими
 * прогонами за те же сутки. Тогда `можноТратить` отказывает, вызов не идёт, а
 * проверка всё равно зеленеет: она ведь ждала текст, а текст пришёл — отказом.
 *
 * Такое зелёное хуже красного: оно утверждает, что путь проверен, хотя путь не
 * исполнялся. Поэтому вызов, без которого проверка бессмысленна, объявляется
 * обязательным явно.
 */
export function требуетсяВызов(расход: unknown, что: string): void {
  if (расход) return
  throw new Error(
    `Проверка «${что}» не выполнена: модель не звали. ` +
      'Скорее всего исчерпан дневной потолок прогона проверок — ' +
      'посмотрите care.job_kinds_budget (вид tests) и spent_today_test(). ' +
      'Зелёный прогон без этого вызова ничего бы не значил.'
  )
}
