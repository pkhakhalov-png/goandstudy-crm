/**
 * Страница подборки для клиента.
 *
 * Эту страницу открывает человек вне компании, по ссылке, которую могут
 * переслать. Поэтому проверяется не вёрстка, а два свойства: на ней нет
 * ничего, кроме подборки, и чужой текст не может в неё ничего внедрить.
 *
 * Содержимое строк приходит из веб-поиска — то есть в конечном счёте с
 * чужих сайтов. Экранирование здесь не формальность.
 */
import { describe, it, expect } from 'vitest'
import { собратьСтраницу, новыйТокен, type СтраницаПодборки } from '@/lib/care/share'
import { проверитьВступление } from '@/lib/care/ai/intro'

const страница = (п: Partial<СтраницаПодборки> = {}): СтраницаПодборки => ({
  intro: 'Список собран по подтверждённым направлению и бюджету. Стоимость и требования уточняем.',
  собрана: '2026-10-01T10:00:00Z',
  строки: [
    {
      вуз: 'Masaryk University',
      программа: 'Biology and Biochemistry',
      город: 'Брно',
      страна: 'Чехия',
      ссылка: 'https://www.muni.cz/en/programmes/27005',
      стоимость: '4500 EUR',
      проверить: ['сроки подачи', 'признание аттестата'],
    },
  ],
  ...п,
})

describe('страница показывает подборку и больше ничего', () => {
  it('программа, вуз, стоимость и ссылка на месте', () => {
    const html = собратьСтраницу(страница())
    expect(html).toContain('Biology and Biochemistry')
    expect(html).toContain('Masaryk University')
    expect(html).toContain('4500 EUR')
    expect(html).toContain('https://www.muni.cz/en/programmes/27005')
  })

  it('непроверенное показывается, а не прячется', () => {
    // Это главная честность страницы: клиент должен видеть, что сроки и
    // требования ещё не подтверждены, а не узнать это через месяц.
    const html = собратьСтраницу(страница())
    expect(html).toContain('сроки подачи')
    expect(html).toContain('признание аттестата')
  })

  it('страница ничего не грузит снаружи', () => {
    // Ни шрифтов, ни скриптов, ни картинок: страницу открывают с телефона в
    // мессенджере, иногда сохраняют, и она должна открываться всегда.
    const html = собратьСтраницу(страница())
    expect(html).not.toMatch(/<script/i)
    expect(html).not.toMatch(/<link[^>]+href=/i)
    expect(html).not.toMatch(/src=["']https?:/i)
  })

  it('поисковикам страница закрыта', () => {
    expect(собратьСтраницу(страница())).toContain('noindex')
  })
})

describe('чужой текст не ломает страницу', () => {
  it('разметка в названии программы экранируется', () => {
    const html = собратьСтраницу(
      страница({
        строки: [
          {
            вуз: '<script>alert(1)</script>',
            программа: 'Biology "расширенная" & прочее',
            город: null,
            страна: null,
            ссылка: null,
            стоимость: null,
            проверить: ['<img onerror=alert(2)>'],
          },
        ],
      })
    )
    expect(html).not.toContain('<script>alert(1)</script>')
    expect(html).toContain('&lt;script&gt;')
    expect(html).toContain('&amp;')
    expect(html).not.toContain('<img onerror')
  })

  it('ссылка не на http выбрасывается целиком', () => {
    // `javascript:` в href — классический способ превратить страницу в
    // чужой инструмент. Такую ссылку не чиним, а не выводим вовсе.
    const html = собратьСтраницу(
      страница({
        строки: [{ ...страница().строки[0], ссылка: 'javascript:alert(1)' }],
      })
    )
    expect(html).not.toContain('javascript:')
    expect(html).not.toContain('Страница программы')
  })
})

describe('секрет в адресе', () => {
  it('длинный и каждый раз разный', () => {
    const а = новыйТокен()
    const б = новыйТокен()
    expect(а.length).toBeGreaterThan(24)
    expect(а).not.toBe(б)
    // Только то, что переживает копирование из мессенджера и обратно.
    expect(а).toMatch(/^[A-Za-z0-9_-]+$/)
  })
})

describe('вступление ничего не обещает', () => {
  const годное =
    'Список собран по направлению и бюджету, о которых мы договорились. ' +
    'Стоимость и требования к поступающим уточняются на сайтах вузов — что именно, ' +
    'написано под каждой программой.'

  it('нормальное вступление проходит', () => {
    expect(проверитьВступление(годное).ok).toBe(true)
  })

  it('обещание поступления не проходит', () => {
    const итог = проверитьВступление(`${годное} Гарантируем поступление в один из них.`)
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('обещание')
  })

  it('числа во вступлении не проходят', () => {
    // Цена уже есть в карточке. Два места с одним числом однажды разойдутся,
    // и клиент поверит тому, что прочитал первым.
    const итог = проверитьВступление(`${годное} Все варианты укладываются в 6000 евро.`)
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('числа')
  })

  it('ссылка во вступлении не проходит', () => {
    expect(проверитьВступление(`${годное} Подробнее: https://example.com`).ok).toBe(false)
  })
})
