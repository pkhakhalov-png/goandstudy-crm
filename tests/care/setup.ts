/**
 * Подготовка окружения тестов.
 *
 * Тесты ходят в настоящую базу под ролью care_app, а ключ лежит в `.env.local`.
 * Vite сам его не читает: переменные без префикса `VITE_` он в `process.env`
 * не кладёт — и правильно делает, иначе секреты утекали бы в браузерную сборку.
 * Здесь мы в Node, поэтому читаем файл явно.
 *
 * Если ключа нет — падаем сразу и с внятным текстом. Тест, который молча
 * работает без ключа, проверяет не то, что написано в его названии.
 *
 * ПРО РАСХОД. Здесь же выставляется признак прогона проверок: вызовы модели из
 * тестов настоящие и стоят настоящих денег, но считаться они должны отдельно.
 * Один прогон однажды израсходовал дневной потолок подбора целиком — и до
 * полуночи куратор не мог собрать ни одной подборки. Проверки сломали работу,
 * которую должны защищать.
 */
import { config } from 'dotenv'
import path from 'path'

config({ path: path.resolve(process.cwd(), '.env.local') })

// Признак читается на сервере, где исполняется вызов модели; подделать его
// из браузера нельзя. Выставляется только отсюда — из конфигурации проверок.
process.env.CARE_TEST_RUN = '1'

const обязательные = ['NEXT_PUBLIC_SUPABASE_URL', 'NEXT_PUBLIC_SUPABASE_ANON_KEY', 'CARE_DB_KEY']
const нет = обязательные.filter((имя) => !process.env[имя]?.trim())

if (нет.length) {
  throw new Error(
    `Нет переменных для тестов: ${нет.join(', ')}. ` +
      `Ожидаются в .env.local. CARE_DB_KEY выпускается через scripts/care/mint-key.ts.`
  )
}
