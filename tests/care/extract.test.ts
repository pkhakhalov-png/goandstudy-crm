/**
 * Проверка фактов, извлечённых из переписки.
 *
 * Модель здесь не вызывается: разбор сотни сообщений стоит около десяти
 * центов и каждый раз даёт чуть разный ответ. Проверяем правила, по которым
 * извлечённое принимается или выбрасывается, — они одни и те же независимо от
 * того, что модель придумала сегодня.
 *
 * Главное правило — цитата обязана найтись в переписке дословно. Это
 * единственная защита, ловящая выдумку: перефразировать можно что угодно,
 * а процитировать — только то, что было написано.
 */
import { describe, it, expect } from 'vitest'
import { проверитьФакт, ПОЛЯ_ИЗВЛЕЧЕНИЯ, type Сообщение } from '@/lib/care/ai/extract'

const переписка: Сообщение[] = [
  {
    message_id: 'm1',
    created_at: '2026-05-20T10:00:00Z',
    sender_name: 'Анастасия',
    content: 'Здравствуйте! Бюджет на обучение у нас до 6000 евро в год, больше не потянем.',
  },
  {
    message_id: 'm2',
    created_at: '2026-05-21T10:00:00Z',
    sender_name: 'Милена (куратор)',
    content: 'Поняла вас. Тогда смотрим Германию и Чехию — там есть варианты в этом бюджете.',
  },
  {
    message_id: 'm3',
    created_at: '2026-05-22T10:00:00Z',
    sender_name: 'Анастасия',
    content: 'Немецкий я только начала учить, пока уровень A1. Планирую к лету сдать B1.',
  },
]

const факт = (п: Partial<Parameters<typeof проверитьФакт>[0]> = {}) => ({
  field: 'budget.tuition.max',
  value: 6000,
  currency: 'EUR',
  speaker: 'student' as const,
  quote: 'Бюджет на обучение у нас до 6000 евро в год',
  is_plan: false,
  ...п,
})

describe('факт принимается, только если его можно проверить', () => {
  it('дословная цитата находится и даёт источник', () => {
    const итог = проверитьФакт(факт(), переписка)
    expect(итог.ok).toBe(true)
    // Источник — конкретное сообщение, а не «переписка вообще».
    if (итог.ok) expect(итог.messageId).toBe('m1')
  })

  it('цитата с другими кавычками и лишними пробелами всё равно находится', () => {
    // Нормальное цитирование, а не выдумка: выбрасывать такое значит терять
    // годные факты.
    const итог = проверитьФакт(факт({ quote: '«Бюджет   на обучение у нас до 6000 евро  в год»' }), переписка)
    expect(итог.ok).toBe(true)
  })

  it('пересказанная цитата не проходит', () => {
    // Смысл тот же, слов таких не было. Ровно то, ради чего проверка и есть.
    const итог = проверитьФакт(факт({ quote: 'Клиент сказал, что готов платить около шести тысяч евро' }), переписка)
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('дословно')
  })

  it('выдуманная цитата не проходит', () => {
    const итог = проверитьФакт(факт({ value: 20000, quote: 'Бюджет до 20000 евро в год' }), переписка)
    expect(итог.ok).toBe(false)
  })

  it('поле не из словаря не проходит', () => {
    // Иначе рядом с budget.tuition.max заведётся «бюджет_обучения», и
    // половина фактов станет невидимой для остального кода.
    const итог = проверитьФакт(факт({ field: 'бюджет_обучения' }), переписка)
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('словар')
  })

  it('сумма без валюты не проходит', () => {
    const итог = проверитьФакт(факт({ currency: null }), переписка)
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('валют')
  })

  it('слишком короткая цитата не проходит', () => {
    // По трём словам совпадёт что угодно — проверять таким нечего.
    const итог = проверитьФакт(факт({ quote: 'до 6000' }), переписка)
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('коротк')
  })

  it('пустое значение не проходит', () => {
    const итог = проверитьФакт(факт({ field: 'program.field', value: '   ', currency: null }), переписка)
    expect(итог.ok).toBe(false)
  })

  it('намерение остаётся намерением', () => {
    // «Планирую сдать B1» не должно попадать в поле текущего уровня как факт.
    const итог = проверитьФакт(
      факт({
        field: 'language.german.level',
        value: 'B1',
        currency: null,
        is_plan: true,
        quote: 'Планирую к лету сдать B1',
      }),
      переписка
    )
    expect(итог.ok).toBe(true)
    if (итог.ok) expect(итог.факт.is_plan).toBe(true)
  })
})

describe('словарь полей', () => {
  it('в нём нет свободных текстовых свалок', () => {
    // profile.notes и подобное — место, куда стекается всё неразобранное.
    // Извлекать туда значит копить мусор, который никто не читает.
    expect(ПОЛЯ_ИЗВЛЕЧЕНИЯ).not.toContain('profile.notes')
    expect(ПОЛЯ_ИЗВЛЕЧЕНИЯ).not.toContain('profile.budget_text')
  })

  it('деньги в словаре есть, и их несколько видов', () => {
    expect(ПОЛЯ_ИЗВЛЕЧЕНИЯ).toContain('budget.tuition.max')
    expect(ПОЛЯ_ИЗВЛЕЧЕНИЯ).toContain('budget.living.max')
  })
})
