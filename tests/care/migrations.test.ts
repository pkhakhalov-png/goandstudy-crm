/**
 * Реестр миграций сходится с репозиторием.
 *
 * `docs/care/MIGRATIONS.md` — журнал, по которому отвечают на вопрос «что в
 * базе». Он ведётся руками и поэтому отстаёт: к двадцать первой миграции в нём
 * не хватало четырёх записей, а у трёх строк потерялась замыкающая черта —
 * разметка ломалась молча, и таблица переставала быть таблицей.
 *
 * Журнал, которому нельзя верить, хуже отсутствующего: на него ссылаются как
 * на источник правды. Поэтому расхождение теперь роняет тесты, а не ждёт,
 * пока кто-нибудь заметит.
 */
import { describe, it, expect } from 'vitest'
import { execFileSync } from 'child_process'

describe('реестр миграций', () => {
  it('у каждой миграции есть откат, запись в реестре и верная сумма', () => {
    // Проверку делает тот же скрипт, которым пользуются руками: две копии
    // одной логики разъезжаются, и расходится обычно та, которую не запускают.
    let вывод = ''
    let упало = false
    try {
      вывод = execFileSync('npx', ['tsx', 'scripts/care/check-migrations.ts'], {
        encoding: 'utf8',
        stdio: 'pipe',
      })
    } catch (e) {
      упало = true
      const о = e as { stdout?: string; stderr?: string }
      вывод = `${о.stdout ?? ''}${о.stderr ?? ''}`
    }

    expect(упало, вывод).toBe(false)
    expect(вывод).toContain('Реестр сходится')
  })
})
