/**
 * Потолки расхода: заведены ли они для всех видов работы, где зовут модель.
 *
 * ПОЧЕМУ ЭТОТ ТЕСТ СУЩЕСТВУЕТ. Потолки заводились тремя миграциями подряд, и
 * на третьей я пропустил `review` — тот самый вид, на котором висят стратегия
 * и вступление к подборке. Стратегия отказывала словами, вступление молча не
 * писалось. Поймала это не проверка кода, а взгляд в таблицу.
 *
 * Поэтому проверка смотрит в базу, а не в миграции: правда о потолках — то,
 * что в ней сейчас, а не то, что когда-то применяли.
 *
 * ЧЕГО ОНА НЕ ПРОВЕРЯЕТ. Что потолки не исчерпаны сегодня. Это состояние дня,
 * а не свойство кода, и падать от него проверка не должна.
 */
import { describe, it, expect } from 'vitest'
import { базаCare } from '@/lib/care/db'
import { можноТратить } from '@/lib/care/ai/budget'

/** Виды работы, на которых контур действительно зовёт модель. */
const ВИДЫ = ['outbound', 'extraction', 'research', 'review'] as const

describe('потолки расхода заведены для всего, что зовёт модель', () => {
  it('у каждого вида работы потолок больше нуля', async () => {
    const { data, error } = await базаCare()
      .from('job_kinds_budget')
      .select('kind, daily_budget_usd')
      .in('kind', [...ВИДЫ])

    expect(error).toBeNull()
    const поВиду = new Map((data ?? []).map((с) => [с.kind as string, Number(с.daily_budget_usd)]))

    for (const вид of ВИДЫ) {
      // Ноль означает «не расходовать»: вызов откажется, и узнает об этом
      // куратор в тот момент, когда нажал кнопку.
      expect(поВиду.get(вид), `потолок вида «${вид}»`).toBeGreaterThan(0)
    }
  })

  it('проверка перед вызовом отвечает по каждому виду, и отказ — только по исчерпанию', async () => {
    // Не то же самое, что строка в таблице: между ней и разрешением стоит
    // `spent_today` и чтение настроек, и сломаться может любое из них.
    //
    // ПОЧЕМУ НЕ ТРЕБУЕМ «МОЖНО». Сначала требовали, и проверка покраснела в
    // день, когда подбор честно израсходовал дневной потолок. Красное от
    // нормальной работы хуже отсутствующей проверки: к нему привыкают и
    // перестают смотреть. Исчерпанный потолок — это рабочее состояние, а не
    // дефект; дефект — когда вид не заведён или чтение расхода падает.
    for (const вид of ВИДЫ) {
      const решение = await можноТратить(вид)
      if (решение.можно) continue
      expect(решение.почему, `${вид}: отказ не по исчерпанию`).toContain('потолок')
      expect(решение.почему, `${вид}: вид не заведён`).not.toContain('не заведён')
    }
  })

  it('неизвестный вид работы не пропускается', async () => {
    // Опечатка в названии вида не должна открывать расход без потолка.
    const решение = await можноТратить('выдуманный_вид')
    expect(решение.можно).toBe(false)
    if (!решение.можно) expect(решение.почему).toContain('не заведён')
  })
})
