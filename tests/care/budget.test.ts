/**
 * Потолки расхода: заведены ли они для всех видов работы, где зовут модель.
 *
 * ПОЧЕМУ ЭТОТ ТЕСТ СУЩЕСТВУЕТ. Потолки заводились тремя миграциями подряд, и
 * на третьей я пропустил `review` — тот самый вид, на котором висят стратегия
 * и вступление к подборке. Стратегия отказывала словами, вступление молча не
 * писалось. Поймала это не проверка кода, а взгляд в таблицу.
 *
 * Поэтому проверка смотрит в базу, а не в миграции: правда о потолках — то,
 * что в ней сейчас, а не то, что когда-то применяли.
 *
 * ЧЕГО ОНА НЕ ПРОВЕРЯЕТ. Что потолки не исчерпаны сегодня. Это состояние дня,
 * а не свойство кода, и падать от него проверка не должна.
 *
 * ПРО СОБСТВЕННЫЙ РАСХОД. Эти проверки зовут модель по-настоящему, и однажды
 * прогон съел дневной потолок подбора целиком: до полуночи куратор не мог
 * собрать ни одной подборки. Теперь расход прогона помечается `is_test` и в
 * рабочий счёт не входит — ниже это и проверяется, потому что молчаливый
 * возврат к общему счёту заметен только по сломанной кнопке у куратора.
 */
import { describe, it, expect } from 'vitest'
import { базаCare } from '@/lib/care/db'
import { можноТратить } from '@/lib/care/ai/budget'

/** Виды работы, на которых контур действительно зовёт модель. */
const ВИДЫ = ['outbound', 'extraction', 'research', 'review'] as const

describe('потолки расхода заведены для всего, что зовёт модель', () => {
  it('у каждого вида работы потолок больше нуля', async () => {
    const { data, error } = await базаCare()
      .from('job_kinds_budget')
      .select('kind, daily_budget_usd')
      .in('kind', [...ВИДЫ])

    expect(error).toBeNull()
    const поВиду = new Map((data ?? []).map((с) => [с.kind as string, Number(с.daily_budget_usd)]))

    for (const вид of ВИДЫ) {
      // Ноль означает «не расходовать»: вызов откажется, и узнает об этом
      // куратор в тот момент, когда нажал кнопку.
      expect(поВиду.get(вид), `потолок вида «${вид}»`).toBeGreaterThan(0)
    }
  })

  it('счёт расхода считается по каждому виду и отвечает числом', async () => {
    // Не то же самое, что строка в таблице: между ней и разрешением стоит
    // `spent_today`, и сломаться может он. Зовём его прямо, потому что
    // `можноТратить` в прогоне проверок смотрит на свой счёт, а здесь нужно
    // убедиться, что работает счёт рабочих видов.
    for (const вид of ВИДЫ) {
      const { data, error } = await базаCare().rpc('spent_today', { p_kind: вид })
      expect(error, `${вид}: счёт расхода не читается`).toBeNull()
      expect(Number.isFinite(Number(data ?? 0)), `${вид}: счёт вернул не число`).toBe(true)
    }
  })

  it('расход прогона проверок не входит в рабочий счёт', async () => {
    // Иначе повторяется то, ради чего всё это: проверки съедают потолок
    // подбора, и куратор до полуночи не может собрать подборку. Заметно это
    // было бы только по сломанной кнопке.
    const { data: до } = await базаCare().rpc('spent_today', { p_kind: 'research' })

    const { data: строка, error } = await базаCare()
      .from('ai_spend')
      .insert({
        kind: 'research',
        model: 'тест',
        tokens_in: 1,
        tokens_out: 1,
        usd: 9.99,
        is_test: true,
        note: 'проверка отдельного счёта',
      })
      .select('id')
      .single()
    expect(error).toBeNull()

    try {
      const { data: после } = await базаCare().rpc('spent_today', { p_kind: 'research' })
      expect(Number(после ?? 0)).toBeCloseTo(Number(до ?? 0), 2)

      // А в своём счёте — виден: деньги потрачены настоящие, и не видеть их
      // хуже всего.
      const { data: свой } = await базаCare().rpc('spent_today_test')
      expect(Number(свой ?? 0)).toBeGreaterThanOrEqual(9.99)
    } finally {
      await базаCare().from('ai_spend').delete().eq('id', строка!.id)
    }
  })

  it('у прогона проверок есть свой потолок', async () => {
    // Без него зацикленная проверка тратила бы без ограничения вовсе — а
    // именно от этого потолки и существуют.
    const { data } = await базаCare()
      .from('job_kinds_budget')
      .select('daily_budget_usd')
      .eq('kind', 'tests')
      .maybeSingle()

    expect(data, 'вид «tests» не заведён в потолках').toBeTruthy()
    expect(Number(data!.daily_budget_usd)).toBeGreaterThan(0)
  })

  it('неизвестный вид работы не пропускается', async () => {
    // Опечатка в названии вида не должна открывать расход без потолка.
    const решение = await можноТратить('выдуманный_вид')
    expect(решение.можно).toBe(false)
    if (!решение.можно) expect(решение.почему).toContain('не заведён')
  })
})

describe('подмена счёта не ослабляет словарь видов', () => {
  it('опечатка в виде работы отвергается и в прогоне проверок', async () => {
    // Первая версия подменяла вид целиком — и в прогоне проверок любое
    // выдуманное название проходило: расход открыт, потолка нет. В бою защита
    // при этом работала, то есть проверка перестала бы ловить именно то, ради
    // чего написана.
    const решение = await можноТратить('выдуманный_вид')
    expect(решение.можно).toBe(false)
    if (!решение.можно) expect(решение.почему).toContain('не заведён')
  })

  it('нулевой потолок остаётся запретом и для проверок', async () => {
    // «Ноль» означает «не расходовать вовсе». Если бы проверки его обходили,
    // они ходили бы туда, куда работе ходить запрещено, — и молчаливо
    // подтверждали бы работоспособность того, что отключено.
    const { data: было } = await базаCare()
      .from('job_kinds_budget')
      .select('daily_budget_usd')
      .eq('kind', 'review')
      .single()

    await базаCare().from('job_kinds_budget').update({ daily_budget_usd: 0 }).eq('kind', 'review')
    try {
      const решение = await можноТратить('review')
      expect(решение.можно).toBe(false)
      if (!решение.можно) expect(решение.почему).toContain('ноль')
    } finally {
      await базаCare()
        .from('job_kinds_budget')
        .update({ daily_budget_usd: было!.daily_budget_usd })
        .eq('kind', 'review')
    }
  })
})
