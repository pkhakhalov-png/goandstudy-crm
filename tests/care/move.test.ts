/**
 * Переезд контура на боевой адрес.
 *
 * ЗАЧЕМ ПРОВЕРЯТЬ ПРАВИЛО, А НЕ СКРИПТ. Ошибка здесь не заметна ниоткуда:
 * переключив адреса до того, как боевая выкладка ожила, мы получаем
 * расписание, которое зовёт несуществующий адрес, и Телеграм, который шлёт
 * события в пустоту. Ни одной ошибки — просто перестают приходить сообщения и
 * готовиться напоминания. На сутки это выглядит как спокойный день, и так и
 * узнают: через сутки.
 *
 * ПОЧЕМУ ВОЗВРАТ РАЗРЕШЁН ВСЕГДА. Он не делает хуже, а чинит. Запрет на
 * возврат означал бы, что из неудачного переезда нет выхода, — а это худшее,
 * что можно сделать с процедурой переезда.
 */
import { describe, it, expect } from 'vitest'
import { наБою, можноПереключать, адресаДля, БОЕВОЙ, ПРЕВЬЮ } from '@/lib/care/move'

describe('какой это адрес', () => {
  it('боевой узнаётся', () => {
    expect(наБою(`${БОЕВОЙ}/api/care/tick`)).toBe(true)
  })

  it('превью боевым не считается', () => {
    expect(наБою(`${ПРЕВЬЮ}/api/care/tick`)).toBe(false)
  })

  it('пустого адреса достаточно, чтобы не считать его боевым', () => {
    // Иначе ненастроенный вебхук прошёл бы как «уже на бою».
    expect(наБою('')).toBe(false)
    expect(наБою(null)).toBe(false)
    expect(наБою(undefined)).toBe(false)
  })
})

describe('можно ли переключать', () => {
  it('боевой не отвечает — нельзя, и сказано почему', () => {
    const р = можноПереключать(false, [])
    expect(р.можно).toBe(false)
    if (!р.можно) expect(р.почему).toContain('мерж в main')
  })

  it('отвечает, но переменных не хватает — нельзя', () => {
    // Контур ответит и будет выглядеть живым, а работать не сможет: без ключа
    // базы или токена бота он молча ничего не делает.
    const р = можноПереключать(true, ['CARE_DB_KEY'])
    expect(р.можно).toBe(false)
    if (!р.можно) expect(р.почему).toContain('CARE_DB_KEY')
  })

  it('всё на месте — можно', () => {
    expect(можноПереключать(true, []).можно).toBe(true)
  })

  it('возврат на превью разрешён даже когда бой лежит', () => {
    // Это и есть выход из неудачного переезда.
    expect(можноПереключать(false, ['CARE_DB_KEY'], true).можно).toBe(true)
  })
})

describe('адреса для переключения', () => {
  it('боевые идут без обхода защиты', () => {
    // Обход нужен только превью. Подставленный в боевой адрес, он остался бы
    // в том, что видит Телеграм, — и жил бы там, пока кто-нибудь не заметит.
    const а = адресаДля(false, 'секретный-обход')
    expect(а.tick).toBe(`${БОЕВОЙ}/api/care/tick`)
    expect(а.вебхук).not.toContain('bypass')
  })

  it('адреса превью несут обход, иначе Vercel их не пустит', () => {
    const а = адресаДля(true, 'секретный-обход')
    expect(а.tick).toContain(ПРЕВЬЮ)
    expect(а.tick).toContain('x-vercel-protection-bypass=секретный-обход')
    expect(а.вебхук).toContain('x-vercel-protection-bypass=секретный-обход')
  })

  it('без обхода адреса превью всё равно собираются', () => {
    // Нет переменной — не повод падать: адрес нужен, а защиту можно снять
    // руками в Vercel.
    const а = адресаДля(true, null)
    expect(а.tick).toBe(`${ПРЕВЬЮ}/api/care/tick`)
  })

  it('пути совпадают с настоящими маршрутами контура', () => {
    // Опечатка в пути дала бы 404 на каждом тике — и ни одной ошибки в
    // журнале контура, потому что до него дело не дошло бы.
    const а = адресаДля(false)
    expect(а.tick.endsWith('/api/care/tick')).toBe(true)
    expect(а.вебхук.endsWith('/api/care/webhooks/telegram')).toBe(true)
  })
})
