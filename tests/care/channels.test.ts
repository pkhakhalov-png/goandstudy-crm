/**
 * Можем ли мы написать клиенту — разбор ответов Bot API.
 *
 * ОТКУДА ЭТО. Проверка 02.10.2026 показала, что care-бот не состоит ни в одной
 * группе клиентов: все одиннадцать привязанных чатов отвечают «chat not found».
 * Он отдельный от прежнего бота, а чек-лист перевода проверял только, что поле
 * `tg_chat_id` заполнено. Первое живое напоминание не дошло бы ни до кого, и
 * выяснилось бы это в день, когда у клиента прошёл срок.
 *
 * ЧТО ПРОВЕРЯЕМ ЗДЕСЬ. Разбор ответов, а не сеть. Ответы Bot API известны и
 * воспроизводятся строкой; гонять ради них настоящие запросы значит платить
 * временем и зависеть от чужой доступности за ту же проверку.
 *
 * ГЛАВНОЕ РАЗЛИЧЕНИЕ — «нельзя писать» и «не знаем». Оборванная сеть не должна
 * помечать дело сломанным: по первому куратор пойдёт добавлять бота в группу,
 * где он и так есть.
 */
import { describe, it, expect } from 'vitest'
import { выводОЧате } from '@/lib/care/channels'

const группа = { ok: true, result: { id: -100, type: 'group', title: 'Группа клиента' } }
const участник = (status: string, can?: boolean) => ({
  ok: true,
  result: { status, ...(can === undefined ? {} : { can_send_messages: can }) },
})

describe('вывод о чате', () => {
  it('бот в группе — писать можно', () => {
    const в = выводОЧате(группа, участник('member'))
    expect(в.можемПисать).toBe(true)
    expect(в.название).toBe('Группа клиента')
  })

  it('администратор тоже пишет', () => {
    // У обычных участников и администраторов `can_send_messages` не приходит
    // вовсе. Считать его отсутствие запретом значило бы объявить недоступными
    // все группы разом.
    expect(выводОЧате(группа, участник('administrator')).можемПисать).toBe(true)
  })

  it('чата нет — писать нельзя, и так и сказано', () => {
    // Именно этот ответ пришёл по всем одиннадцати чатам: бота в них нет.
    const в = выводОЧате({ ok: false, description: 'Bad Request: chat not found' }, участник('member'))
    expect(в.можемПисать).toBe(false)
    expect(в.почему).toContain('chat not found')
  })

  it('бота удалили из группы', () => {
    const в = выводОЧате(группа, участник('kicked'))
    expect(в.можемПисать).toBe(false)
    expect(в.почему).toContain('удалили')
  })

  it('бот вышел из группы', () => {
    expect(выводОЧате(группа, участник('left')).можемПисать).toBe(false)
  })

  it('боту запрещено писать', () => {
    const в = выводОЧате(группа, участник('restricted', false))
    expect(в.можемПисать).toBe(false)
    expect(в.почему).toContain('запрещено')
  })

  it('ограничен, но писать может — значит может', () => {
    expect(выводОЧате(группа, участник('restricted', true)).можемПисать).toBe(true)
  })

  it('группу переделали в канал — туда писать нельзя', () => {
    const в = выводОЧате(
      { ok: true, result: { id: -100, type: 'channel', title: 'Канал' } },
      участник('administrator')
    )
    expect(в.можемПисать).toBe(false)
    expect(в.почему).toContain('channel')
  })

  it('личная переписка годится', () => {
    const в = выводОЧате({ ok: true, result: { id: 5, type: 'private' } }, участник('member'))
    expect(в.можемПисать).toBe(true)
  })

  it('оборванная сеть названа сетью, а не удалением из группы', () => {
    // Иначе куратор пойдёт добавлять бота в группу, где он и так есть, —
    // а настоящая причина (связь) останется ненайденной.
    const в = выводОЧате({ ok: false, description: 'сеть: таймаут' }, участник('member'))
    expect(в.можемПисать).toBe(false)
    expect(в.почему).toContain('сеть')
  })

  it('название чата доходит до вывода даже при отказе по членству', () => {
    // Куратору нужно узнать группу: «Иванов (магистратура)» понятнее, чем
    // минусовое число в пятнадцать цифр.
    const в = выводОЧате(группа, { ok: false, description: 'бота в чате нет' })
    expect(в.название).toBe('Группа клиента')
  })
})
