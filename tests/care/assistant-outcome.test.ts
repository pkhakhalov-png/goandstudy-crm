/**
 * Что куратор видит по итогам разговора с помощником.
 *
 * ПОЧЕМУ ЭТОТ ТЕСТ ЕСТЬ. Помощник правит подборку, и на просьбе из трёх правок
 * он упёрся в потолок шагов: Саарланд уже убрал, Дортмунд добавить не успел, а
 * куратору показалось «Помощник вернул пустой ответ». Самый дурной исход из
 * возможных — данные изменились, человеку сказали «ничего». Отказ был бы лучше.
 *
 * Проверяем чистой функцией, а не вызовом модели: подвести живой разговор к
 * потолку стоит доллар и выходит по-разному каждый раз, а развилок всего три и
 * ошибается именно развилка.
 */
import { describe, it, expect } from 'vitest'
import { итогРазговора, type СледРазговора } from '@/lib/care/ai/assistant'

function след(ч: Partial<СледРазговора>): СледРазговора {
  return { последний: null, шагов: 1, сделано: [], расходы: [], итогоДолларов: 0, ...ч }
}

const текстом = (т: string) => ({ content: [{ type: 'text', text: т }], stop_reason: 'end_turn' })

describe('итог разговора с помощником', () => {
  it('обычный ответ отдаётся как есть', () => {
    const и = итогРазговора(след({ последний: текстом('Три задачи, ближайшая 12 октября.') }))
    expect(и.текст).toBe('Три задачи, ближайшая 12 октября.')
    expect(и.оборван).toBeUndefined()
    expect(и.отказ).toBe(false)
  })

  it('обрыв на потолке назван обрывом, а не пустым ответом', () => {
    const и = итогРазговора(
      след({
        шагов: 18,
        сделано: ['поправил строку подборки'],
        последний: { stop_reason: 'tool_use', content: [{ type: 'tool_use' }] as never },
      })
    )
    expect(и.оборван).toBe(true)
    expect(и.текст).not.toContain('пустой ответ')
    // Главное: названо и что оборвалось, и что при этом уже изменилось.
    expect(и.текст).toContain('потолок шагов (18)')
    expect(и.текст).toContain('поправил строку подборки')
  })

  it('обрыв без единой правки прямо говорит, что ничего не изменилось', () => {
    // Иначе куратор пойдёт проверять карточку на всякий случай — а там нечего.
    const и = итогРазговора(
      след({ шагов: 18, последний: { stop_reason: 'tool_use', content: [] } })
    )
    expect(и.текст).toContain('Изменить ничего не успел')
  })

  it('текст, сказанный до обрыва, не теряется', () => {
    // Модель часто успевает сказать «убрал Саарланд, теперь ищу Дортмунд».
    // Выбросить это и оставить одну жалобу на потолок — потерять отчёт.
    const и = итогРазговора(
      след({
        шагов: 18,
        сделано: ['добавил программу в подборку'],
        последний: {
          stop_reason: 'tool_use',
          content: [{ type: 'text', text: 'Саарланд убрал, ищу Дортмунд.' }, { type: 'tool_use' } as never],
        },
      })
    )
    expect(и.текст).toContain('Саарланд убрал')
    expect(и.текст).toContain('потолок шагов')
  })

  it('отказ модели не выдаётся за ответ', () => {
    const и = итогРазговора(след({ последний: { stop_reason: 'refusal', content: [] } }))
    expect(и.отказ).toBe(true)
    expect(и.текст).toContain('отказался')
  })

  it('молчание не выдаётся за обрыв: это разные беды и разные действия', () => {
    // Нет ответа — повторить. Обрыв — продолжить. Путать их значит советовать
    // куратору не то.
    const молчание = итогРазговора(след({ последний: null }))
    expect(молчание.оборван).toBeUndefined()
    expect(молчание.текст).toContain('не ответил')

    const пусто = итогРазговора(след({ последний: { stop_reason: 'end_turn', content: [] } }))
    expect(пусто.оборван).toBeUndefined()
    expect(пусто.текст).toContain('пустой ответ')
  })
})
