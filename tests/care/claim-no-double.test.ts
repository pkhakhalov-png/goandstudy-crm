/**
 * Два воркера не берут одно задание.
 *
 * Почему это не очевидно и требует теста. Воркер зовётся расписанием раз в
 * минуту, а работа может идти дольше минуты — значит два запуска пересекаются
 * по времени регулярно, а не в исключительном случае. Если выдача не
 * атомарна, клиент получит два одинаковых сообщения, и это заметит он, а не мы.
 *
 * Проверяется на настоящей базе намеренно: гонку двух транзакций нельзя
 * воспроизвести подделкой клиента — она либо есть в SQL, либо нет.
 *
 * ПОЧЕМУ ЗДЕСЬ ЕСТЬ ВОЗВРАТ ЧУЖИХ ЗАДАНИЙ. `claim_jobs` выдаёт задания по
 * приоритету и времени, а не по виду: отобрать «только свои» она не умеет и
 * не должна — воркеру в работе это не нужно. Значит тест, который просит
 * десять заданий, забирает вместе со своими и настоящие, а взятое задание
 * висит до истечения аренды.
 *
 * Пока расписание было выключено, это ничего не стоило: в очереди лежали
 * только тестовые задания. С 30.09.2026 расписание работает, и прогон тестов
 * успел украсть настоящую дневную подготовку напоминаний — она осталась в
 * `running` с чужим воркером. Аренда через пять минут вернула бы её сама, но
 * тест, который тихо крадёт работу у боевого контура, чинить надо, а не
 * объяснять.
 *
 * Поэтому всё чужое, взятое за компанию, возвращается в очередь сразу же — и
 * счётчик попыток возвращается тоже: мы взяли по ошибке, попытка не считается.
 */
import { describe, it, expect, afterAll } from 'vitest'
import { базаCare } from '@/lib/care/db'
import { взятьЗадания, закрытьЗадание, type Задание } from '@/lib/care/jobs/claim'

const МЕТКА = `test_claim_${Date.now()}`
const СКОЛЬКО = 6

afterAll(async () => {
  await базаCare().from('jobs').delete().eq('kind', МЕТКА)
})

/**
 * Вернуть в очередь всё, что тест взял не своё.
 *
 * Попытку тоже отдаём назад: `claim_jobs` увеличила счётчик, а работы не было.
 * Оставить счётчик выросшим значит отнять у настоящего задания одну из трёх
 * попыток — тихо и в самый неподходящий момент.
 */
async function вернутьЧужие(...наборы: Задание[][]): Promise<void> {
  const чужие = наборы.flat().filter((з) => з.kind !== МЕТКА)
  for (const з of чужие) {
    await базаCare()
      .from('jobs')
      .update({
        status: 'queued',
        claimed_by: null,
        lease_until: null,
        attempts: Math.max(0, з.attempts - 1),
      })
      .eq('id', з.id)
  }
  if (чужие.length) {
    console.warn(`[тест выдачи] вернул в очередь чужие задания: ${чужие.map((з) => з.kind).join(', ')}`)
  }
}

async function завестиЗадания(n: number) {
  const строки = Array.from({ length: n }, (_, i) => ({
    kind: МЕТКА,
    payload: { n: i },
    priority: 10,
  }))
  const { error } = await базаCare().from('jobs').insert(строки)
  expect(error).toBeNull()
}

describe('выдача заданий', () => {
  it('два параллельных вызова дают непересекающиеся наборы', async () => {
    await завестиЗадания(СКОЛЬКО)

    const [первый, второй] = await Promise.all([
      взятьЗадания('воркер-А', СКОЛЬКО),
      взятьЗадания('воркер-Б', СКОЛЬКО),
    ])

    await вернутьЧужие(первый, второй)

    const А = new Set(первый.filter((з) => з.kind === МЕТКА).map((з) => з.id))
    const Б = new Set(второй.filter((з) => з.kind === МЕТКА).map((з) => з.id))

    const общие = [...А].filter((id) => Б.has(id))
    expect(общие).toHaveLength(0)
    // Вместе они должны разобрать всё: если сумма меньше, часть заданий
    // потерялась — это другая беда, но тоже беда.
    expect(А.size + Б.size).toBe(СКОЛЬКО)
  })

  it('взятое задание не выдаётся третьему', async () => {
    await завестиЗадания(1)
    const первые = await взятьЗадания('воркер-В', 10)
    const вторые = await взятьЗадания('воркер-Г', 10)
    await вернутьЧужие(первые, вторые)

    const моё = первые.find((з) => з.kind === МЕТКА)
    expect(моё).toBeDefined()
    expect(вторые.map((з) => з.id)).not.toContain(моё?.id)
  })

  it('результат от чужого воркера не принимается', async () => {
    await завестиЗадания(1)
    const взятые = await взятьЗадания('воркер-Д', 10)
    await вернутьЧужие(взятые)
    const моё = взятые.find((з) => з.kind === МЕТКА)
    expect(моё).toBeDefined()

    // Чужое имя — задание не его, закрыть не может. Это то, что защищает
    // результат опоздавшего воркера от записи поверх актуального.
    const чужой = await закрытьЗадание(моё!.id, 'воркер-Е', true, { чужой: true })
    expect(чужой).toBe(false)

    const свой = await закрытьЗадание(моё!.id, 'воркер-Д', true, { свой: true })
    expect(свой).toBe(true)
  })
})
