/**
 * Знак вуза: буквы и цвет.
 *
 * Мелочь, но видимая: знак стоит у каждой программы в подборке, которую
 * открывает клиент. Ошибка здесь не ломает ничего, зато бросается в глаза —
 * «UN» у шести вузов подряд или кислотный цвет у одного из восьми.
 */
import { describe, it, expect } from 'vitest'
import { буквыВуза, цветВуза } from '@/lib/care/herb'

describe('буквы знака', () => {
  it('аббревиатура вуза важнее собранных букв', () => {
    // Вуз, который сам себя зовёт RWTH или TUM, человек узнаёт именно так.
    // Собранные из первых букв «RA» и «TM» не говорят ему ничего.
    expect(буквыВуза('RWTH Aachen University')).toBe('RWTH')
    expect(буквыВуза('Technical University of Munich (TUM)')).toBe('TUM')
  })

  it('без аббревиатуры берутся значимые слова, а не «University»', () => {
    // Иначе половина подборки — одинаковые «UN».
    expect(буквыВуза('Universität des Saarlandes')).toBe('SA')
    expect(буквыВуза('Universität Mannheim')).toBe('MA')
    expect(буквыВуза('Eberhard Karls Universität Tübingen')).toBe('EK')
  })

  it('кириллица не ломается', () => {
    expect(буквыВуза('Московский государственный университет')).toBe('МГ')
    expect(буквыВуза('МГУ имени Ломоносова')).toBe('МГУ')
  })

  it('пустое или странное название не роняет', () => {
    expect(буквыВуза('…')).toBeTruthy()
    expect(буквыВуза('X')).toBeTruthy()
  })
})

describe('цвет знака', () => {
  it('у одного вуза всегда один цвет', () => {
    // На карточке и на странице клиента это должен быть один и тот же вуз.
    expect(цветВуза('RWTH Aachen University')).toBe(цветВуза('RWTH Aachen University'))
  })

  it('разные вузы различаются', () => {
    expect(цветВуза('RWTH Aachen')).not.toBe(цветВуза('TU München'))
  })

  it('цвет всегда в читаемом диапазоне', () => {
    // Насыщенность и светлота закреплены: иначе один вуз выйдет кислотным,
    // другой серым, и список развалится на глаз.
    for (const имя of ['A', 'Universität Tübingen', 'Масарикув университет', 'Sapienza']) {
      expect(цветВуза(имя)).toMatch(/^hsl\(\d{1,3} 42% 46%\)$/)
    }
  })
})
