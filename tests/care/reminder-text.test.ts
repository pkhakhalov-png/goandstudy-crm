/**
 * Проверка текста, написанного моделью, перед тем как показать его куратору.
 *
 * Эти проверки — единственное, что стоит между формулировкой модели и живым
 * человеком. Куратор смотрит следом, но смотрит он бегло: текст всегда
 * выглядит прилично, и именно поэтому подмену даты глазами не ловят.
 *
 * Модель здесь не вызывается: тест про правила, а не про её сегодняшнее
 * настроение. Вызов стоит денег и даёт разный ответ на один и тот же вход —
 * такому в наборе тестов делать нечего.
 */
import { describe, it, expect } from 'vitest'
import { проверитьТекст, type ДелоДляНапоминания } from '@/lib/care/ai/reminder'

const дело: ДелоДляНапоминания = {
  имя: 'Иван Тестов',
  документ: 'перевод диплома',
  датаСловами: '15 января',
  просрочено: false,
  напоминалиРаз: 0,
  оКлиенте: { Страна: 'Германия' },
}

const годный =
  'Иван, добрый день. Напоминаю про перевод диплома — он нужен до 15 января, ' +
  'чтобы мы успели подать документы вовремя. Если что-то мешает, скажите, разберёмся вместе.'

describe('текст напоминания — что пропускаем', () => {
  it('нормальное сообщение проходит', () => {
    const итог = проверитьТекст(годный, дело)
    expect(итог.ok).toBe(true)
  })

  it('перенос строки и обращение через запятую не мешают', () => {
    const итог = проверитьТекст(
      'Иван, здравствуйте!\n\nЖдём перевод диплома до 15 января. Подскажите, всё ли понятно по списку?',
      дело
    )
    expect(итог.ok).toBe(true)
  })
})

describe('текст напоминания — что не пропускаем', () => {
  it('чужая дата не проходит', () => {
    // Самая дорогая ошибка: клиент поверит тексту, а не задаче в CRM, и
    // сдвинет себе дедлайн на пять дней.
    const итог = проверитьТекст(
      'Иван, напоминаю про перевод диплома до 15 января. Лучше прислать до 10 января, чтобы был запас.',
      дело
    )
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('чужая дата')
  })

  it('дата цифрами тоже считается чужой', () => {
    const итог = проверитьТекст(
      'Иван, напоминаю про перевод диплома до 15 января. Крайний срок подачи 20.01.',
      дело
    )
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('чужая дата')
  })

  it('без срока не проходит', () => {
    const итог = проверитьТекст('Иван, напоминаю про перевод диплома. Пришлите, пожалуйста.', дело)
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('срок')
  })

  it('без имени не проходит', () => {
    const итог = проверитьТекст(
      'Добрый день! Напоминаем про перевод диплома — он нужен до 15 января, будем ждать.',
      дело
    )
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('имен')
  })

  it('незаполненный плейсхолдер не проходит', () => {
    // Значит модель повторила шаблон вместо того, чтобы написать.
    const итог = проверитьТекст('Иван, напоминаем про {документ} до 15 января, пожалуйста.', дело)
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('{документ}')
  })

  it('ссылка не проходит', () => {
    // Наших адресов модель не знает и придумает их уверенно.
    const итог = проверитьТекст(
      'Иван, загрузите перевод диплома до 15 января вот здесь: https://goandstudy.example/upload',
      дело
    )
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('ссылка')
  })

  it('разметка Markdown не проходит', () => {
    // Панель и Телеграм покажут звёздочки как есть.
    const итог = проверитьТекст(
      'Иван, напоминаю про **перевод диплома** — нужен до 15 января, пришлите когда сможете.',
      дело
    )
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('разметка')
  })

  it('слишком короткое не проходит', () => {
    const итог = проверитьТекст('Иван, 15 января.', дело)
    expect(итог.ok).toBe(false)
    if (!итог.ok) expect(итог.почему).toContain('коротко')
  })

  it('пустой ответ не проходит', () => {
    const итог = проверитьТекст('   ', дело)
    expect(итог.ok).toBe(false)
  })
})
