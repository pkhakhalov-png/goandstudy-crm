-- Вид утверждения для чисел, найденных в тексте статьи.
--
-- Зачем отдельный вид. Проверка находит в статье число, за которым не стоит ни
-- один факт реестра, и раньше на этом всё кончалось: замечание в отчёте и
-- статья, стоящая до тех пор, пока человек не заведёт утверждение руками. Так
-- две недели простояли стипендии CSC. Теперь ненайденное заводится в реестр
-- само, и часовой шаг claims_autoverify идёт за источником.
--
-- Почему не класть находки в существующие виды. tuition_fee, deadline,
-- eligibility и прочие входят в CRITICAL_KINDS: неподтверждённое утверждение
-- такого вида блокирует выпуск. Заводи мы найденное число ценой, каждая статья
-- немедленно блокировала бы сама себя собственными цифрами, и конвейер встал
-- бы наглухо вместо того, чтобы ускориться. observed_number не блокирует
-- ничего: находка лишь встаёт в очередь на проверку, а подтвердившись,
-- перестаёт быть «числом без основания». Повысить вид до материального может
-- человек — это решение редакции, а не регулярного выражения.
--
-- autopilot_ok = false, как у всех остальных: флаг нигде не читается кодом и
-- остаётся декларацией о намерениях, и заявлять для находок больше доверия,
-- чем для фактов, заведённых редакцией, было бы странно.

begin;

insert into seo.claim_policy (kind, required_kinds, preferred_kinds, default_ttl, autopilot_ok)
values (
  'observed_number',
  array['official_gov', 'official_org', 'university_program', 'university_general', 'ministry'],
  array['official_gov', 'university_program'],
  '180 days',
  false
)
on conflict (kind) do nothing;

commit;
