-- Признак тестового клиента.
--
-- Зачем. Тестовые учётки заводятся в боевой базе и ничем не отличаются от
-- настоящих, кроме слова «ТЕСТ» в имени. Отчёты про это соглашение не знают, и
-- три тестовых клиента, заведённых 25 сентября, добавили в статистику 920 000 ₽
-- договоров и 152 166 ₽ «оплаченного». Владелец увидел это на экране платежей.
--
-- Уборка по именам не работает: `scripts/clean-test-data.ts` прибит к клиентам
-- #50 и #58, которых давно нет, то есть сломан с тех пор, как номера сменились.
-- Соглашение, о котором знает только человек, рано или поздно забывается —
-- поэтому признак становится колонкой, а не договорённостью.
--
-- Почему флаг, а не удаление. Тестовые клиенты нужны: на них проверяют кабинет
-- куратора и кабинет клиента. Флаг позволяет держать их сколько угодно — они
-- просто не попадают в цифры.

alter table public.clients
  add column if not exists is_test boolean not null default false;

comment on column public.clients.is_test is
  'Тестовый клиент: виден в рабочих списках, но исключён из отчётов и статистики.';

-- Отметить то, что уже заведено. Дальше ставится при создании.
update public.clients set is_test = true where name ~* '(тест|test)' and is_test = false;
