-- Тик SEO-очереди раз в десять минут вместо раза в минуту.
--
-- 9 октября база легла: сервер Nano с процессором на кредитах, а кредиты
-- съедает постоянная фоновая работа. Тик был её заметной частью: за двое суток
-- 2789 вызовов на ~400 задач, то есть почти каждый будил воркер впустую.
--
-- Чем платим: задача ждёт тика до десяти минут, статья проходит конвейер за
-- час-полтора вместо получаса. При ритме «статья в день» это ничего не меняет.
-- Сторож (lib/seo/alerts.ts) считает зависшей задачу через 30 минут, а очередь
-- отбирает её через 10 и следующий тик — так что ложных тревог не будет.
begin;

create or replace function seo.schedule_all()
returns void language plpgsql as $$
begin
  -- Единственное расписание: тик раз в десять минут. Что и когда ставить в
  -- очередь, решает сам тик — там это видно в коде, а не размазано по крону.
  perform cron.unschedule(jobname) from cron.job where jobname = 'seo_tick';
  perform cron.schedule('seo_tick', '*/10 * * * *', $q$ select seo.dispatch_tick(); $q$);
end $$;

select cron.alter_job(jobid, schedule := '*/10 * * * *') from cron.job where jobname = 'seo_tick';

commit;
