-- Утверждения из архива: повторный импорт должен проходить (E3.2).
--
-- Ревизия завела уникальный индекс с условием — `where page_id is not null`.
-- Условие по смыслу верное: ключ «страница × вид × смещение» имеет смысл только
-- для находок из архива, а у утверждений из источников страницы нет вовсе.
--
-- Но частичный индекс нельзя вывести из `ON CONFLICT (колонки)`: Postgres требует
-- повторить в запросе то же условие, а PostgREST такого синтаксиса не даёт. В
-- итоге импорт 685 находок падал на «no unique or exclusion constraint matching
-- the ON CONFLICT specification», и в базе оставалось пусто при готовом отчёте.
--
-- Поэтому индекс становится полным. Ограничение от этого не слабеет: у строк без
-- страницы page_id равен null, а null в уникальном индексе Postgres считает
-- отличным от любого другого null — такие строки как не конфликтовали друг с
-- другом, так и не будут.

begin;

drop index if exists seo.claims_from_page_unique;

create unique index if not exists claims_from_page_unique
  on seo.claims (page_id, kind, body_offset);

comment on index seo.claims_from_page_unique is
  'Повторная ревизия не плодит дубли: ключ — страница, вид утверждения и место в '
  'тексте. Индекс полный, а не частичный, потому что частичный не выводится из '
  'ON CONFLICT, и импорт через PostgREST по нему не проходит.';

commit;
