-- Кабинет куратора v2, миграция 036: след клиента в прежнем кабинете.
--
-- ЗАЧЕМ. Переведённого на новый кабинет клиента прежний кабинет не перестаёт
-- показывать: мы его не меняли, и запрет там — дисциплина, а не замок
-- (раздел 5 плана, пункт 6). Куратор по привычке правит этап или дорожную
-- карту в старом окне, а новый кабинет об этом не знает и продолжает работать
-- на своих сведениях. Две системы расходятся молча.
--
-- ЧЕГО НЕ ХВАТИЛО ДЛЯ ПЛАНОВОГО СПОСОБА. План предлагал сравнивать
-- `clients.updated_at` с `cases.switched_at`. Такого столбца в `public.clients`
-- нет вовсе — проверено 02.10.2026. Поэтому вместо отметки времени храним
-- отпечаток значений: по нему видно не только что правили, но и что именно.
--
-- ПОЧЕМУ ПО ПОЛЯМ, А НЕ ОДНОЙ СТРОКОЙ. «Что-то изменилось» не говорит, куда
-- смотреть. «Изменили этап и дорожную карту» — говорит. Разница между
-- сообщением, по которому идут проверять, и сообщением, которое закрывают.
--
-- ПОЧЕМУ ХЭШИ, А НЕ ЗНАЧЕНИЯ. `roadmap_data` и `project_data` — большие
-- документы, и держать их копию в контуре значит хранить рабочие данные
-- клиента там, где они не нужны. Хэша достаточно, чтобы заметить изменение.
--
-- Откат: supabase/migrations/care/036_legacy_fingerprint.rollback.sql

begin;

alter table care.cases
  add column if not exists legacy_fingerprint jsonb null,
  add column if not exists legacy_checked_at timestamptz null;

comment on column care.cases.legacy_fingerprint is
  'Хэши значимых полей клиента в прежнем кабинете на момент последней сверки: {поле: хэш}';
comment on column care.cases.legacy_checked_at is
  'Когда сверяли последний раз. Пусто — ни разу: расхождение по такому делу не утверждаем.';

commit;
