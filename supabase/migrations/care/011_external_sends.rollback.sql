-- Откат 011. Закрывает рубильник отправок.
--
-- После этого ворота отказывают на первой же проверке с причиной
-- `sends_disabled`, а отказ виден куратору на экране очереди. Уже отправленные
-- сообщения остаются фактом — их не отменить, и откат этого не обещает.

begin;

update care.env_marker
   set external_sends = false,
       note = 'Отправки выключены откатом 011. Наружу не отправляется ничего.',
       updated_at = now()
 where id = true;

commit;
