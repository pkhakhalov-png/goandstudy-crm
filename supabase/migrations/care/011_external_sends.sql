-- Кабинет куратора v2, миграция 011: разрешить отправки наружу.
--
-- Что меняет. Один признак: `care.env_marker.external_sends` переводится в
-- `true`. Ни таблиц, ни колонок, ни прав — только рубильник.
--
-- ПОЧЕМУ ЭТО МИГРАЦИЯ, А НЕ ПЕРЕМЕННАЯ ОКРУЖЕНИЯ. Переменную можно переставить
-- деплоем и не заметить; строку в базе — нет. Включение отправок наружу должно
-- оставлять след в истории репозитория с датой и причиной, потому что это
-- единственное изменение во всём контуре, после которого ошибка видна живому
-- клиенту.
--
-- ЧТО ЭТО НЕ ВКЛЮЧАЕТ. Само по себе — ничего не отправляет. Ворота
-- `lib/care/gate/outbound.ts` проверяют пять условий, и рубильник только
-- первое. Чтобы сообщение ушло, нужно ещё: флаг `outbound` у конкретного
-- клиента (по умолчанию выключен у всех), совпадение слепка данных, рабочее
-- время и получатель в `care.contacts` дела. И главное — нажатие куратора:
-- предложение без решения человека в очередь отправки не попадает.
--
-- Решение владельца от 30.09.2026.
--
-- Откат: supabase/migrations/care/011_external_sends.rollback.sql

begin;

update care.env_marker
   set external_sends = true,
       note = 'Пилот. Отправки разрешены владельцем 30.09.2026. Наружу уходит только принятое куратором и только по клиентам с флагом outbound.',
       updated_at = now()
 where id = true;

commit;
