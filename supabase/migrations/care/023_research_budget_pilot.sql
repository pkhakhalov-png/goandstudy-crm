-- Кабинет куратора v2, миграция 023: потолок подбора под живую работу.
--
-- ПОЧЕМУ МЕНЯЕМ. Пять долларов в день на `research` упёрлись за один день
-- пилота. Это не утечка: один подбор с проверкой требований по пяти страницам
-- вузов стоит около доллара с небольшим, и пяти долларов хватает на три-четыре
-- запуска. Куратор, который за день разобрал четыре дела, на пятом получает
-- отказ — и это выглядит как поломка, а не как предохранитель.
--
-- Пятнадцать: десяток подборок в день. Для пилота с одним куратором это
-- заведомо больше, чем он успеет, то есть потолок остаётся предохранителем от
-- зацикливания, а не нормой расхода.
--
-- Потолок не снимаем и не поднимаем «с запасом»: его задача — поймать цикл,
-- который сам себя кормит. Чем он выше, тем дольше такой цикл живёт.
--
-- Откат: supabase/migrations/care/023_research_budget_pilot.rollback.sql

begin;

update care.job_kinds_budget
   set daily_budget_usd = 15.00, updated_at = now()
 where kind = 'research';

commit;
