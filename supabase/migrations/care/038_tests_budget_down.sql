-- Кабинет куратора v2, миграция 038: потолок проверок с двадцати до пяти.
--
-- ЧТО ПОКАЗАЛИ ДВОЕ СУТОК. Прогон проверок истратил 16.58 $ на одной
-- проверке — она искала замену программ в вебе по-настоящему, тридцать центов
-- за прогон, а прогон шёл каждый час. Все 51 вызова помечены `is_test`: ни
-- одного по настоящей работе.
--
-- Сама причина устранена в коде: проверка больше в веб не ходит. Но потолок,
-- при котором такое вообще стало возможным, был выбран неверно. Двадцать
-- долларов в сутки — это не предохранитель, это разрешение: прогон, которому
-- их не хватает, перестал быть проверкой и стал производством.
--
-- Пять: полный прогон после правок стоит центы, и пяти хватит на сотню
-- прогонов в сутки. Если он снова упрётся — значит что-то опять ходит в веб или
-- зациклилось, и остановиться надо на пятом долларе, а не на двадцатом.
--
-- Откат: supabase/migrations/care/038_tests_budget_down.rollback.sql

begin;

update care.job_kinds_budget
   set daily_budget_usd = 5.00, updated_at = now()
 where kind = 'tests';

commit;
