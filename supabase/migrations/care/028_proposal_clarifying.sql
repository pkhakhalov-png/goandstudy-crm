-- Кабинет куратора v2, миграция 028: состояние «ушло в уточнение».
--
-- ЧТО НЕ ХВАТАЛО. У предложения было пять состояний: ждёт, принято, отклонено,
-- на доработку, устарело. А у куратора есть шестой ответ, и самый частый из
-- честных: «ни то ни другое, спрошу у клиента».
--
-- Положить его в существующие нельзя. `rejected` врёт: мы не отвергли слова
-- клиента, мы их проверяем. `rework` врёт тоже: дорабатывать нечего, вопрос не
-- к нам. `pending` оставляет вопрос в очереди, и куратор видит его каждый день,
-- пока клиент не ответит, — а очередь, где лежит неотвечаемое, перестают
-- читать целиком.
--
-- ЧТО ПРОИСХОДИТ ПРИ ЭТОМ. Заводится задача «ждём клиента» со сроком — по ней
-- готовятся напоминания, и у вопроса появляется то, чего у предложения нет:
-- срок, который сам о себе напомнит.
--
-- НАЙДЕНО ТЕСТОМ, И НЕ ТОЛЬКО ЭТО. Первая версия экрана писала `done` и
-- `skipped` — таких состояний нет, обновление отвергалось ограничением, а
-- действие отвечало «Принято». Куратор видел бы подтверждение, которого не
-- было. Проверка ошибок в коде добавлена тем же выпуском.
--
-- Откат: supabase/migrations/care/028_proposal_clarifying.rollback.sql

begin;

alter table care.proposals drop constraint if exists proposals_status_check;

alter table care.proposals
  add constraint proposals_status_check
  check (status in ('pending', 'accepted', 'rejected', 'rework', 'expired', 'clarifying'));

commit;
