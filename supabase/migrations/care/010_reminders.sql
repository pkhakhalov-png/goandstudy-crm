-- Кабинет куратора v2, миграция 010: напоминания.
--
-- Что добавляет. Причину отмены у отправки, шаблоны и настройки напоминаний
-- в care.settings. Новых таблиц нет: предложения и отправки уже заведены
-- миграцией 005, здесь только то, чего им не хватало.
--
-- ПОЧЕМУ ШАБЛОНЫ, А НЕ СВОБОДНАЯ ГЕНЕРАЦИЯ. Напоминание уходит клиенту от
-- имени компании. Текст, который каждый раз пишется заново, каждый раз может
-- оказаться другим — вежливее, резче, с выдуманной подробностью. Куратор
-- проверяет предложения десятками и перестанет вчитываться на третьем.
-- Шаблон делает проверку быстрой: смотреть надо на подстановки, а не на весь
-- текст.
--
-- ПОЧЕМУ ПРИЧИНА ОТМЕНЫ ОТДЕЛЬНОЙ КОЛОНКОЙ. `last_error` — про сбой. Отказ
-- ворот отправки сбоем не является: это штатное «нельзя», и показывать его
-- человеку как ошибку значит учить не доверять сообщениям об ошибках.
--
-- Откат: supabase/migrations/care/010_reminders.rollback.sql

begin;

alter table care.outbound_actions
  add column if not exists cancel_reason text;

comment on column care.outbound_actions.cancel_reason is
  'Почему отправка не состоялась: sends_disabled, flag_off, stale_data, quiet_hours, no_recipient. Не ошибка, а штатный отказ.';

-- ── Настройки напоминаний ───────────────────────────────────────────────────
--
-- Значения по умолчанию рабочие, но **требуют утверждения владельцем**:
-- тексты уходят живым клиентам. Меняются правкой строки в care.settings, без
-- выката кода.

insert into care.settings (key, value) values
  (
    'reminder_window_days',
    to_jsonb(3)
  ),
  (
    'reminder_repeat_days',
    to_jsonb(4)
  ),
  (
    'reminder_pause_hours',
    to_jsonb(48)
  ),
  (
    'templates',
    '{
      "document_due": {
        "название": "Напоминание о документе",
        "текст": "{имя}, напоминаем про {документ} — он нужен до {дата}. Если что-то мешает или нужна помощь, напишите, разберёмся.",
        "подстановки": ["имя", "документ", "дата"]
      },
      "document_overdue": {
        "название": "Напоминание о просроченном документе",
        "текст": "{имя}, срок по {документ} был {дата}. Подскажите, пожалуйста, как продвигается — если нужна помощь, мы на связи.",
        "подстановки": ["имя", "документ", "дата"]
      }
    }'::jsonb
  )
on conflict (key) do nothing;

-- ── Порядок разбора напоминаний ─────────────────────────────────────────────
--
-- Индекс под экран проверки: предложения одного вида, ждущие решения,
-- в порядке появления. Очередь «1 из N» читает ровно это.

create index if not exists care_proposals_reminders_idx
  on care.proposals (kind, created_at)
  where status = 'pending';

commit;
