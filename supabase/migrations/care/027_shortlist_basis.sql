-- Кабинет куратора v2, миграция 027: на чём собрана подборка.
--
-- ЗАЧЕМ. Подборка стоит на четырёх решениях клиента: страна, направление,
-- уровень и бюджет. Любое из них меняется — «клиент снизил бюджет до девяти
-- тысяч», «родители против Германии» — и половина программ в подборке уже не
-- подходит. Сейчас об этом знает только тот, кто помнит, при каком бюджете её
-- собирали; через месяц не помнит никто, а список выглядит действующим.
--
-- ЧТО КЛАДЁМ. Снимок решений на момент сборки. По нему видно расхождение с
-- сегодняшними фактами — и его можно назвать словами: «собрана при бюджете
-- 12 000 EUR, сейчас 9 000 EUR».
--
-- ПОЧЕМУ СНИМОК, А НЕ ССЫЛКИ НА ФАКТЫ. Факт правится на месте: тот же
-- идентификатор, другое значение. Ссылка показала бы сегодняшнее значение и
-- расхождения не было бы видно вовсе — именно того, ради чего всё затевается.
--
-- ПОЧЕМУ НЕ ПЕРЕСОБИРАЕМ САМИ. В подборке лежит работа куратора: он убрал
-- лишнее и поставил вперёд главное. Пересборка по изменившемуся факту стёрла
-- бы это молча. Поэтому расхождение показывается, а решение — за человеком.
--
-- Откат: supabase/migrations/care/027_shortlist_basis.rollback.sql

begin;

