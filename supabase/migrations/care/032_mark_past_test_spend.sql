-- Кабинет куратора v2, миграция 032: пометить расход, который был проверками.
--
-- ЗАЧЕМ. Миграция 031 завела признак `is_test`, но строки, записанные до неё,
-- признака не имеют — и дневной потолок подбора остаётся исчерпанным: 15.09 из
-- 15. До полуночи куратор не соберёт ни одной подборки, хотя израсходовали его
-- проверки, а не работа.
--
-- ПОЧЕМУ ИМЕННО ЭТИ СТРОКИ. Помечаем только расход с пометкой «замена в
-- подборке» и без привязки к делу. Это вызовы `найтиЗамену`, и доказательств
-- два: за сутки нет ни одного события `shortlist_replace_requested` — то есть
-- кнопку никто не нажимал; и дела, к которым эти вызовы относились, уже
-- удалены — так убирает за собой только прогон проверок.
--
-- ЧЕГО НЕ ТРОГАЕМ. «Поиск программ из помощника» — там есть настоящая работа
-- куратора в тот же день, и отделить её от проверок нечем. Записи остаются как
-- есть: лучше оставить лишнее в рабочем счёте, чем списать настоящий расход на
-- проверки и перестать его видеть.
--
-- Это разовая поправка истории, а не правило. Дальше признак ставит код в
-- момент записи.
--
-- Откат: supabase/migrations/care/032_mark_past_test_spend.rollback.sql

begin;

update care.ai_spend
   set is_test = true
 where kind = 'research'
   and note = 'замена в подборке'
   and case_id is null
   and not is_test;

commit;
