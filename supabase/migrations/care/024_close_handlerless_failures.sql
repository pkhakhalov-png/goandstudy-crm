-- Кабинет куратора v2, миграция 024: закрыть падения «нет обработчика».
--
-- ЧТО ЭТО ЗА СТРОКИ. `care.enqueue_due_jobs` ставит задание в очередь, а
-- обработчик для его вида появляется в коде отдельным выпуском. В промежутке
-- задание падает трижды с «нет обработчика для вида …» и остаётся `failed`
-- навсегда. Одно такое висит с 30.09: обработчик напоминаний завезли через
-- час после того, как расписание впервые его поставило.
--
-- ПОЧЕМУ ЕГО НАДО ЗАКРЫТЬ, А НЕ ОСТАВИТЬ. В сводке состояния оно выглядит
-- ровно как свежая поломка. Пока оно там, каждая проверка начинается с
-- «а, это то старое» — и ровно так перестают замечать настоящее.
--
-- ПОЧЕМУ `cancelled`, А НЕ УДАЛЕНИЕ. Падение было настоящим: расписание
-- опередило код, и это стоит помнить. `cancelled` с причиной сохраняет запись
-- и убирает её из красного.
--
-- ПОЧЕМУ НЕ ПЕРЕЗАПУСКАЕМ. Напоминание готовилось на вчерашний день. Сегодня
-- расписание поставит новое, по сегодняшним срокам; вчерашнее исполнять
-- незачем, а исполнить его значит написать клиенту про просроченное.
--
-- Условие по тексту ошибки, а не по идентификатору: это признак класса —
-- «код отстал от расписания», — и завтра он может повториться с другим видом.
--
-- Откат: supabase/migrations/care/024_close_handlerless_failures.rollback.sql

begin;

update care.jobs
   set status = 'cancelled',
       last_error = last_error || ' · закрыто миграцией 024: обработчик завезли позже'
 where status = 'failed'
   and last_error like 'нет обработчика для вида%';

commit;
