-- Кабинет куратора v2, миграция 033: состояние по каждому чату, а не вообще.
--
-- ЗАЧЕМ. Перед первым живым напоминанием надо знать не «работает ли Телеграм»,
-- а «можем ли мы написать вот этому клиенту». Бота могли удалить из группы,
-- группу — переделать в канал, права — урезать. Узнать об этом в момент
-- отправки значит узнать слишком поздно: напоминание со сроком не уходит, и
-- заметно это станет, когда срок пройдёт.
--
-- Таблица `care.connections` для этого и заведена («чтобы тихо ничего не
-- приходит отличалось от всё хорошо, событий нет»), но в неё никто не писал, и
-- она пуста с самого начала. Поле `scope` принимает `{case_id, chat_id}` —
-- отдельной таблицы не нужно.
--
-- ПОЧЕМУ УНИКАЛЬНЫЙ КЛЮЧ. Проверка идёт по расписанию, и без него каждый прогон
-- добавлял бы новую строку на тот же чат: через месяц в таблице тридцать
-- записей об одном и том же, и «последнее состояние» приходится угадывать по
-- времени. Ключ по виду и чату делает запись обновлением, а не накоплением.
--
-- Откат: supabase/migrations/care/033_connections_per_chat.rollback.sql

begin;

-- Выражение, а не столбец: chat_id живёт в scope, и выносить его отдельно
-- значило бы держать одно и то же в двух местах.
create unique index if not exists care_connections_chat_idx
  on care.connections (kind, (scope ->> 'chat_id'))
  where scope ? 'chat_id';

comment on index care.care_connections_chat_idx is
  'Одна строка состояния на чат: проверка обновляет её, а не копит историю';

commit;
