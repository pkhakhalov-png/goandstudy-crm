-- Кабинет куратора v2, миграция 022: подборку можно править, а не только читать.
--
-- ЗАЧЕМ. Подборка приходит списком из восьми программ, и половина из них —
-- не то. Куратор должен убрать лишнее и поставить вперёд главное, прежде чем
-- отдавать клиенту: список, который начинается с четвёртого по важности
-- варианта, читается как «нам всё равно».
--
-- ПОЧЕМУ «УБРАНО», А НЕ УДАЛЕНИЕ. Через месяц возникает вопрос «а почему мы
-- не рассматривали Мюнхен» — и ответ «его убрали тогда-то и вот почему»
-- лучше, чем отсутствие строки. Убранное не показывается ни куратору в
-- подборке, ни клиенту, но остаётся в деле.
--
-- ЧТО ЗАКЛАДЫВАЕТСЯ НА ВПЕРЁД. `chosen` — клиент выбрал этот вариант. Пока
-- отмечает куратор со слов клиента, а когда появится кабинет клиента, отмечать
-- будет он сам: поле уже есть, и переносить ничего не придётся.
--
-- Картинка хранится ссылкой, а не файлом: это логотип или фото кампуса с сайта
-- вуза, своего хранилища для них заводить незачем, а чужие картинки мы и так
-- не контролируем.
--
-- Откат: supabase/migrations/care/022_shortlist_items_editable.rollback.sql

begin;

alter table care.shortlist_items
  add column if not exists status text not null default 'active'
    check (status in ('active', 'removed', 'chosen')),
  add column if not exists removed_reason text null,
  add column if not exists image_url text null;

comment on column care.shortlist_items.status is
  'active — в подборке; removed — убрана куратором, остаётся в деле ради вопроса «почему не рассматривали»; chosen — клиент выбрал.';
comment on column care.shortlist_items.image_url is
  'Логотип или фото кампуса со страницы вуза. Ссылкой: своё хранилище под чужие картинки заводить незачем.';

create index if not exists care_shortlist_items_active_idx
  on care.shortlist_items (shortlist_id, position) where status <> 'removed';

commit;
