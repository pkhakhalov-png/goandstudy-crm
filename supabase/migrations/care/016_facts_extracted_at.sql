-- Кабинет куратора v2, миграция 016: отметка о разборе переписки.
--
-- ЗАЧЕМ. Разбор переписки стоит около десяти центов на дело: модель читает
-- сотню сообщений целиком. Повторять его каждый тик значит платить за одно и
-- то же по сто раз в сутки и каждый раз заново предлагать куратору те же
-- факты.
--
-- Отметка отвечает на один вопрос: до какого момента переписка уже разобрана.
-- Следующий разбор берёт только то, что пришло позже. Пусто — значит дело не
-- разбиралось ни разу, и читать надо всё.
--
-- ПОЧЕМУ КОЛОНКА В ДЕЛЕ, А НЕ ЗАПИСЬ В ОЧЕРЕДИ. Очередь чистится, задания
-- удаляются, а вопрос «разобрано ли это дело» переживает и то, и другое.
--
-- Откат: supabase/migrations/care/016_facts_extracted_at.rollback.sql

begin;

alter table care.cases
  add column if not exists facts_extracted_at timestamptz null;

comment on column care.cases.facts_extracted_at is
  'До какого момента переписка разобрана в факты. Пусто — не разбиралась ни разу.';

create index if not exists care_cases_extract_idx
  on care.cases (facts_extracted_at) where automation_owner = 'v2';

commit;
