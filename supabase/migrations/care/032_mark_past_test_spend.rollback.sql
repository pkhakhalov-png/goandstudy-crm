-- Откат 032. Возвращает помеченные строки в рабочий счёт.
--
-- После отката дневной потолок подбора снова будет считать расход проверок
-- своим — и может оказаться исчерпанным без единой подборки для клиента.

begin;

update care.ai_spend
   set is_test = false
 where kind = 'research'
   and note = 'замена в подборке'
   and case_id is null
   and is_test;

commit;
