-- Кабинет куратора v2, миграция 039: у помощника появляется потолок.
--
-- ЧТО ВЫЯСНИЛОСЬ. Расход помощника не попадал в `care.ai_spend` вовсе: он
-- писался в `assignments.cost_ledger` — рядом с ответом, для истории, — и
-- поэтому не был виден ни потолку, ни экрану расхода. А это самый дорогой
-- вызов в кабинете: один вопрос с подбором программ стоил 0.37 $, и ничто его
-- не ограничивало.
--
-- То есть на вопрос «сколько тратит кабинет» оба журнала отвечали меньше
-- правды — ровно про ту часть, которая дороже всех.
--
-- ПОЧЕМУ ДЕСЯТЬ. Обычный вопрос стоит центы, вопрос с подбором — до
-- полудоллара. Десять долларов — это два-три десятка тяжёлых вопросов в сутки,
-- больше, чем куратор успевает задать. Потолок здесь предохранитель от
-- зацикливания, а не бюджет на работу.
--
-- Откат: supabase/migrations/care/039_assistant_budget.rollback.sql

begin;

insert into care.job_kinds_budget (kind, daily_budget_usd)
values ('assistant', 10.00)
on conflict (kind) do update set daily_budget_usd = 10.00, updated_at = now();

commit;
