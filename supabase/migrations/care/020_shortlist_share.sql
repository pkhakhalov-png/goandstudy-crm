-- Кабинет куратора v2, миграция 020: подборка становится страницей для клиента.
--
-- ЗАЧЕМ. Принятую подборку куратор пересылает клиенту — сейчас руками, копируя
-- в гуглдок. Страница по ссылке решает то же самое, но без копирования: правка
-- подборки меняет то, что видит клиент, и не возникает двух расходящихся
-- версий одного списка.
--
-- ПОЧЕМУ ССЫЛКА СЕКРЕТНАЯ, А НЕ ЗА ВХОДОМ. Клиент в кабинете не заведён — по
-- плану его туда и не заводят на пилоте. Просить человека завести учётную
-- запись, чтобы посмотреть список вузов, значит не показать список.
-- Неугадываемый адрес — обычное решение для такого: ссылка знает, кому её
-- дали, и отзывается одной строкой в базе.
--
-- ЧТО ЭТО ЗНАЧИТ ЧЕСТНО. У кого есть ссылка — тот видит страницу. Поэтому на
-- ней только подборка: вузы, программы, стоимость, ссылки. Ни имени клиента,
-- ни бюджета, ни переписки, ни чего бы то ни было из дела.
--
-- Откат: supabase/migrations/care/020_shortlist_share.rollback.sql

begin;

alter table care.shortlists
  add column if not exists share_token text null,
  add column if not exists published_at timestamptz null,
  add column if not exists intro text null;

comment on column care.shortlists.share_token is
  'Секрет в адресе страницы для клиента. Отзывается обнулением: ссылка перестаёт работать сразу.';
comment on column care.shortlists.intro is
  'Вступление к подборке, написанное помощником и утверждённое куратором. Названия и цены в страницу подставляются из строк, а не отсюда.';

create unique index if not exists care_shortlists_token_uniq
  on care.shortlists (share_token) where share_token is not null;

commit;
