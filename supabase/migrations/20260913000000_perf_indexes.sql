-- Индексов на deals, clients, payments, expenses. В deals сейчас 1046 строк,
-- в остальных — сотни. Полный проход по такой таблице Postgres делает за
-- доли миллисекунды, и замер это подтвердил: медленными были не они, а число
-- обращений к базе и объём выдачи. Это исправлено в коде.
