-- Индексы под запросы, которые остались тяжёлыми после правок в коде.
--
-- ВАЖНО: этот файл не применён. Прямого доступа к DDL из кода нет, поэтому
-- выполните его вручную в SQL-редакторе Supabase (проект pxtwaxhmygnssyyowrgr),
-- а потом повторите замер: `npx tsx scripts/perf-audit.ts --steps`.
--
-- Почему индексов так мало. Индекс помогает там, где строк много и запрос
-- отбирает из них малую часть. На таблицах в сотню строк — а это почти вся
-- база CRM — он не даст ничего, только замедлит запись. Поэтому ниже только
-- те места, где замер показал настоящую цену.
--
-- CREATE INDEX CONCURRENTLY не блокирует запись, но не работает внутри
-- транзакции. Supabase выполняет содержимое редактора одной транзакцией,
-- поэтому выполняйте команды по одной, каждую отдельным запуском.

-- ── 1. Запросная статистика: отбор по дате ───────────────────────────────────
-- seo.gsc_daily — 190 тысяч строк и растёт на полторы тысячи в сутки.
-- Шаги topics_from_gsc и article_autostart читают её за последние 90 дней:
-- сейчас это 140 обращений по тысяче строк, каждое отбирает по дате без
-- индекса. Замер: шаг целиком около 5 секунд при бюджете в 30.
create index concurrently if not exists gsc_daily_date_idx
  on seo.gsc_daily (date);

-- ── 2. Дневная статистика страниц ────────────────────────────────────────────
-- seo.gsc_page_daily — 18 тысяч строк. Экраны «Обзор» и «Страницы» больше её
-- не читают (берут готовый снимок), но «Эффект» и «Индексация» отбирают окно
-- по дате при каждом открытии.
create index concurrently if not exists gsc_page_daily_date_idx
  on seo.gsc_page_daily (date);

-- ── 3. Переписка по сделкам ──────────────────────────────────────────────────
-- public.deal_messages — 23 тысячи строк. Экраны РОПа раскладывают её по
-- сделкам и ищут последнее сообщение каждой. Индекс по (сделка, время) даёт
-- это без полного прохода.
create index concurrently if not exists deal_messages_deal_created_idx
  on public.deal_messages (deal_id, created_at);

-- ── 4. Действия по сделкам ───────────────────────────────────────────────────
-- public.deal_activities — 25 тысяч строк. Экран аналитики отбирает из них
-- только смены этапа: сейчас их 1106 из 25 386, то есть 4% таблицы.
create index concurrently if not exists deal_activities_type_idx
  on public.deal_activities (activity_type, deal_id);

