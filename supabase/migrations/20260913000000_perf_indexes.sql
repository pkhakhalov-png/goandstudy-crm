-- Индексы под запросы, которые остались тяжёлыми после правок в коде.
--
-- ПРИМЕНЕНО 30 сентября 2026 — кроме пункта 3, см. пометку в нём.
--
-- До этого дня файл пролежал неприменённым две недели, и это стоило дорого:
-- код 13 сентября переписали под чтение по одному дню за запрос, рассчитывая
-- на индекс по дате, а индекс не приехал. Получилось хуже, чем было — 147
-- последовательных проходов по всей таблице вместо одного. Отдельный запрос
-- на день шёл 1593 мс, из них 105 762 строки отбрасывались фильтром, и время
-- от времени он не укладывался в предел: шаги article_fix падали с
-- «canceling statement due to statement timeout».
--
-- После применения тот же запрос идёт 10,4 мс — Bitmap Index Scan вместо
-- Parallel Seq Scan, 296 страниц вместо 6389. Чтение целиком по живым ключам
-- статей: 12,9 с → 3,3 с, 17,1 с → 1,2 с, 5,1 с → 1,6 с, 5,0 с → 1,9 с.
--
-- Применяется так: npx tsx scripts/apply-sql.ts <файл с одной командой>.
-- CREATE INDEX CONCURRENTLY не работает внутри транзакции, а Management API
-- шлёт файл целиком, поэтому команды выполняются по одной за запуск.
--
-- Почему индексов так мало. Индекс помогает там, где строк много и запрос
-- отбирает из них малую часть. На таблицах в сотню строк — а это почти вся
-- база CRM — он не даст ничего, только замедлит запись. Поэтому ниже только
-- те места, где замер показал настоящую цену.

-- ── 1. Запросная статистика: отбор по дате ───────────────────────────────────
-- seo.gsc_daily — 193 тысячи строк и растёт на полторы тысячи в сутки.
-- Из всех индексов ниже этот единственный по-настоящему нужен, и с 13 сентября
-- он нужен сильнее, чем был.
--
-- Что изменилось. Шаги article_brief, topics_from_gsc и article_autostart
-- раньше читали таблицу страницами со смещением. Смещение Postgres честно
-- прокручивает: страница со смещением 100 000 отдавалась 1847 мс против 343 мс
-- у первой. Теперь чтение идёт по одному дню за запрос (lib/supabase/read-all.ts,
-- readAllByDay) — смещений нет вовсе, и шаги ускорились вдвое-вчетверо без
-- всякой миграции.
--
-- Но каждый такой запрос отбирает `where date = ...`, а индекса на дату нет:
-- значит каждый из 190 запросов проходит всю таблицу целиком. Видно по замеру —
-- отдельный запрос на день стоит 450–840 мс вместо ~100 мс, которые занимает
-- сама дорога до базы. Этот индекс превращает проход в чтение нужного куска.
--
-- Ожидание: article_brief 5,8 с → около 2 с, topics_from_gsc 5,2 с → около 2 с,
-- article_autostart 3,3 с → около 1,5 с. Проверить после применения:
-- npx tsx scripts/perf-audit.ts --steps
create index concurrently if not exists gsc_daily_date_idx
  on seo.gsc_daily (date);

-- ── 2. Дневная статистика страниц ────────────────────────────────────────────
-- seo.gsc_page_daily — 18 тысяч строк. Экраны «Обзор» и «Страницы» больше её
-- не читают (берут готовый снимок), но «Эффект» и «Индексация» отбирают окно
-- по дате при каждом открытии.
create index concurrently if not exists gsc_page_daily_date_idx
  on seo.gsc_page_daily (date);

-- ── 3. Переписка по сделкам ── НЕ ПРИМЕНЕНО, и намеренно ─────────────────────
