-- 20260923000000_vk_autopost.sql — самостоятельный выпуск в VK.
--
-- Зачем отдельная таблица под фотографии, а не поле у статьи.
--
-- VK не даёт загрузить фотографию ключом сообщества (ошибка 27), а ключ
-- пользователя живёт сутки — для автопостинга он не годится. Разведка
-- (docs/spikes/vk.md) показала единственный рабочий порядок: фотографии
-- грузятся партией заранее, человеком, и получают постоянные идентификаторы.
-- Публиковать их потом умеет вечный ключ сообщества.
--
-- Отсюда таблица: это запас, который тратится. У запаса есть остаток, и когда
-- он кончается, поток встаёт — значит остаток надо видеть и о нём предупреждать
-- заранее, а не обнаруживать по молчанию ленты.

create table if not exists seo.vk_photo_pool (
  id            bigserial primary key,
  -- Слаг статьи, под которую заготовлена фотография. Один к одному:
  -- ссылка в посте ведёт на эту же статью.
  slug          text not null unique,
  article_url   text not null,
  title         text not null,
  -- Описание статьи. Лежит здесь, а не берётся из seo.articles: восемьдесят
  -- девять статей блога писал не конвейер, и в его таблицах их нет.
  description   text,
  -- Идентификатор уже загруженной фотографии: photo{owner}_{id}.
  -- Именно он уходит в attachments у wall.post.
  attachment    text not null,
  kb            int,
  -- Потрачена или ещё в запасе. NULL — в запасе; порядок выдачи по id.
  used_at       timestamptz,
  -- Что из неё вышло. Пусто при used_at — публикация не удалась,
  -- и это видно, а не теряется.
  remote_post_id text,
  remote_url    text,
  created_at    timestamptz not null default now()
);

comment on table seo.vk_photo_pool is
  'Запас фотографий для постов в VK. Грузится партией вручную: ключ сообщества '
  'загружать фотографии не умеет, а ключ пользователя живёт сутки. См. docs/spikes/vk.md';
comment on column seo.vk_photo_pool.used_at is
  'Потрачена. NULL — в запасе. Остаток запаса = число строк с NULL, по нему поднимается тревога.';
comment on column seo.vk_photo_pool.remote_post_id is
  'Пусто при заполненном used_at означает, что публикация не удалась. Это не то же самое, '
  'что «не использована»: фотографию уже не переиспользуешь, а поста нет.';

-- Выдача очередной: первая непотраченная по порядку загрузки.
create index if not exists vk_photo_pool_free
  on seo.vk_photo_pool (id) where used_at is null;

-- Когда была последняя публикация — по ней шаг решает, вышла ли пауза.
create index if not exists vk_photo_pool_used
  on seo.vk_photo_pool (used_at desc nulls last);
