-- Вес замечаний о числах в сохранённых отчётах проверки.
--
-- Код исправлен коммитом «предупреждение о числах перестало запрещать выпуск»:
-- проверка «числа подтверждены реестром» заведена как level 'W', то есть
-- предупреждение, но замечание из неё выходило с весом major, а ворота выпуска
-- блокируют всё, что не minor. Правило противоречило само себе.
--
-- Эта миграция догоняет данные. Отчёты, записанные прежней версией кода, лежат
-- в article_versions.qa_report и ворота читают именно их — без правки данных
-- статьи остались бы заблокированы навсегда: переписывать отчёт имеет право
-- только шаг починки, а он после первой попытки справедливо отказывается это
-- делать.
--
-- Тронуты ровно замечания вида «число … не подтверждено реестром фактов».
-- Находки модели не тронуты: их вес она выносит сама, по смыслу, и понижать
-- его скопом было бы подменой её суждения.
--
-- Применено к боевой базе 30 сентября 2026. Предпросмотром затронуто 13 версий
-- у 6 статей, текущей среди них была одна — версия 115 статьи #28.
--
-- Отката нет намеренно: вернуть major значило бы заново заблокировать статьи
-- правилом, которое признано ошибочным.

update seo.article_versions v
set qa_report = jsonb_set(
  v.qa_report,
  '{issues}',
  (select jsonb_agg(
     case when i->>'kind' = 'facts'
           and i->>'severity' = 'major'
           and i->>'why' like 'число %'
          then jsonb_set(i, '{severity}', '"minor"')
          else i end)
   from jsonb_array_elements(v.qa_report->'issues') i)
)
where v.qa_report ? 'issues'
  and exists (select 1 from jsonb_array_elements(v.qa_report->'issues') i
              where i->>'kind'='facts' and i->>'severity'='major' and i->>'why' like 'число %');
